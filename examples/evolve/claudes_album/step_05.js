samples('shabda/speech/fr-FR/m:souviens_toi,oubli,reviens')

setcps(100/60/4)

$: note("g2 ~ bb2 ~ c3 d3 eb3 ~ f2 ~ g2 ~ ab2 g2 f2 ~")
  .sound("sawtooth")
  .lpf(cosine.range(300, 1800).slow(4))
  .lpq(6)
  .gain(0.6)
  .shape(0.8)
  .detune(12)
  .juxBy(0.6, x => x.octave(1).delay(0.35).dt(0.5))

$: stack(
  s("bd").euclid(7, 12).gain(0.85),
  s("~ ~ sn ~ ~ sn").room(0.5).size(0.7).gain(0.75),
  s("oh*8").degradeBy(0.4).velocity(rand.range(0.2, 0.6)).lpf(3000).gain(0.4),
  s("rim").euclid(3, 8).late(0.125).gain(0.4).delay(0.4).dt(0.25)
)

$: note("<[g2,d3,f3,bb3] [ab2,eb3,g3,c4] [f2,c3,eb3,ab3] [eb2,bb2,d3,g3]>")
  .sound("sine")
  .fm(4)
  .fmh(2.5)
  .attack(0.02)
  .decay(0.6)
  .sustain(0.1)
  .release(0.8)
  .gain(0.35)
  .room(0.6)
  .size(0.8)
  .jux(x => x.late(0.375).transpose(-12))

$: note("bb4 ~ d5 eb5 ~ ~ g5 ~ ab5 ~ ~ bb5 ~ d6 ~ ~")
  .sound("triangle")
  .lpf(perlin.range(600, 3500).slow(8))
  .lpq(3)
  .attack(0.08)
  .decay(0.25)
  .sustain(0.15)
  .release(0.4)
  .gain(0.18)
  .delay(0.7)
  .dt(0.5)
  .delayfeedback(0.7)
  .pan(sine.range(0.3, 0.7).slow(6))

$: s("reviens*3")
  .chop(24)
  .speed(rand.range(0.6, 1.4))
  .every(3, x => x.rev())
  .juxBy(0.4, x => x.hurry(1.5).lpf(2000))
  .gain(0.45)
  .room(0.9)
  .delay(0.5)
  .dt(0.75)

$: note("<g3 ~ ab3 ~> <~ d4 ~ eb4>")
  .sound("pulse")
  .fm(1.5)
  .fmh(3)
  .lpf(1200)
  .attack(0.15)
  .decay(0.3)
  .sustain(0.4)
  .release(0.6)
  .gain(0.12)
  .tremolo(0.6)
  .tremolosync(3)
  .room(0.7)