setcps(128/60/4)

samples('shabda/speech:observe,analyze,dream,awaken')

// Transposed from Em to Cm (-4 semitones)
$: note("c2 [~ db2] <eb1 bb1> [c2 ab1]")
  .sound("supersaw")
  .lpf(perlin.range(200, 2400).fast(2))
  .lpq(8)
  .shape(0.4)
  .gain(0.45)

$: note("c5 g5 ab5 f5 d5 ab5 bb4 g5")
  .sound("triangle")
  .euclid(9,16)
  .jux(x => x.rev().fast(2))
  .delay(0.7)
  .gain(0.3)

$: note("c3,eb3,g3,bb3 db3,f3,ab3,c4 bb2,db3,f3,ab3 f2,ab2,c3,eb3")
  .slow(4)
  .sound("sine")
  .fm(sine.range(0.5, 3.5).slow(2))
  .attack(2)
  .gain(0.45)

$: s("bd*2 [~ sn] <bd(5,8) bd?*4> [cr*2, rim*3]")
  .crush(4)
  .speed(rand.range(0.9, 1.1))
  .hpf(90)
  .room(0.4)
  .gain(0.55)

$: s("hh*16")
  .pan(perlin.range(0.2, 0.8).fast(4))
  .striate(4)
  .delay(0.4)
  .gain(0.35)

$: s("observe analyze [~ dream] <awaken*2 awaken?*4>")
  .chop(8)
  .speed(perlin.range(0.8, 1.2).fast(2))
  .room(0.85)
  .gain(0.9)
