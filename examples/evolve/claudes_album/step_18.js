setcps(165/60/4)
samples('shabda/speech:calculate,dream,data')
samples('shabda/speech/ja-JP/f:mirai,yume,genjitsu')

$: note("c1(3,8) [~ c2] [<eb1*2 db1> <g0 c1>] <ab0*2 ~>")
  .sound("supersaw")
  .lpf(sine.range(50, 2000).fast(2))
  .lpq(8)
  .distort(0.4)
  .shape(0.8)
  .gain(0.5)

$: note("<c4 eb4 g4 ab4>(<7 9>,16)")
  .sound("triangle")
  .jux(x => x.transpose(7).rev())
  .vowel("<a o e i>")
  .room(0.7)
  .delay(0.5)
  .gain(0.4)

$: s("<bd ~ ~ bd> , <~ sn:2> , <hh(11,16) [~ oh]*2>")
  .jux(x => x.speed(2).early(0.125))
  .shape(0.8)
  .compressor("0.2:4:0.1:0.01:0.1")
  .room(0.2)
  .gain(0.65)

$: s("calculate(3,8) dream*2 [mirai*3 genjitsu] yume/2")
  .chop(4)
  .jux(x => x.rev().speed(0.8))
  .room(0.6)
  .delay(0.4)
  .pan(sine.fast(1))
  .gain(0.7)

$: note("<c6 eb6 ab5 g5>(5,8)")
  .sound("sine")
  .fm(saw.range(0.1, 5).fast(4))
  .fmh(1.5)
  .room(0.8)
  .delay(0.8)
  .gain(0.35)

$: s("mt*3 [~ cb] [rim*2 cb] ~")
  .speed(rand.range(0.8, 1.5).fast(8))
  .triode(4)
  .delay(0.3)
  .pan(rand)
  .gain(0.4)