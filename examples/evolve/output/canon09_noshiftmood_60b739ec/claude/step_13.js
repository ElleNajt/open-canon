// BWV 1087 Canon 10 - The Gathering Storm (Variation: Confession in Fragments)

// The mirror doesn't crack — it multiplies.
// Each reflection speaks a different truth, none complete.
// The accused becomes the accuser becomes the witness.

let shatteredVoice = x => x
  .sound("sine")
  .gain(0.15)
  .attack(0.001)
  .decay(0.8)
  .sustain(0.02)
  .release(2.2)
  .lpf(sine.range(1200, 3800).slow(12))
  .room(0.8)
  .delay(0.6)
  .delaytime(0.333)
  .delayfeedback(0.6)

let accusation = x => x
  .sound("pulse")
  .gain(0.12)
  .attack(0.002)
  .decay(0.4)
  .sustain(0.08)
  .release(0.9)
  .lpf(2200)
  .room(0.5)

setcps(108/60/4)

// Track 1 - The fanfare now INTERROGATES — questions without answers
$: note("d4 ~ ~ eb4 g3 ~ ~ ~ ab3 ~ d4 ~ ~ ~ ~ eb4")
  .slow(5)
  .apply(shatteredVoice)
  .pan(0.25)
  .juxBy(0.6, x => x.transpose(-5).gain(0.1).late(0.4))

$: note("g3 ~ ab3 ~ ~ d4 ~ eb4 ~ ~ ~ g3 ~ ~ ab3 ~")
  .slow(5)
  .apply(shatteredVoice)
  .gain(0.1)
  .pan(0.75)
  .late(0.2)

// Track 2 - Hail becomes MORSE CODE — urgent, encrypted
$: note("g6 g6 ~ fs6 ~ ~ e6 e6 e6 ~ eb6 ~ ~ d6 ~ ~")
  .slow(2.5)
  .apply(accusation)
  .pan(0.2)
  .every(3, x => x.rev().transpose(2))

$: note("~ ~ b5 ~ bb5 bb5 ~ ~ a5 ~ ~ gs5 gs5 ~ g5 ~")
  .slow(2.5)
  .apply(accusation)
  .gain(0.08)
  .pan(0.8)
  .late(0.125)

// Track 3 - Drone splits into ARGUING FIFTHS
$: note("[g1 d2] ~ ~ [fs1 cs2] ~ ~ [g1 d2] ~ ~ [ab1 eb2] ~ ~ [g1 d2] ~ ~ ~")
  .slow(10)
  .sound("sawtooth")
  .gain(0.12)
  .attack(2.0)
  .decay(1.2)
  .sustain(0.45)
  .release(3.0)
  .lpf(cosine.range(70, 200).slow(12))
  .lpq(6)
  .pan(0.5)
  .room(0.6)

// Track 4 - DROPPED stuttering, replaced with GALLOPING ESCAPE ATTEMPT
$: note("d4 ~ g4 d4 ~ g4 a4 ~ d4 ~ b4 ~ ~ c5 ~ ~")
  .slow(3)
  .sound("triangle")
  .gain(0.11)
  .attack(0.005)
  .decay(0.12)
  .sustain(0.2)
  .release(0.3)
  .lpf(1800)
  .room(0.35)
  .pan(0.45)
  .sometimes(x => x.transpose(7).gain(0.07))

// Track 5 - Bass now LIMPS — wounded, asymmetric
$: note("g2 ~ ~ a2 bb2 ~ g2 ~ ~ ~ fs2 ~ g2 ~ ~ ~")
  .slow(6)
  .sound("sawtooth")
  .gain(0.13)
  .attack(0.03)
  .decay(0.25)
  .sustain(0.3)
  .release(0.5)
  .lpf(480)
  .lpq(3)
  .pan(0.52)
  .room(0.25)

// Track 6 - DROPPED whispers, replaced with TOLLING VERDICT
$: note("g3 ~ ~ ~ g3 ~ ~ ~ g3 ~ ~ ~ fs3 ~ ~ ~")
  .slow(8)
  .sound("sine")
  .gain(0.14)
  .attack(0.01)
  .decay(0.6)
  .sustain(0.1)
  .release(1.5)
  .lpf(400)
  .room(0.9)
  .delay(0.5)
  .delaytime(0.75)
  .delayfeedback(0.5)
  .pan(0.5)

// Track 7 - Heartbeat becomes ARRHYTHMIC — panic setting in
$: note("g1 ~ g1 ~ ~ g1 g1 ~ ~ ~ ~ g1 ~ g1 g1 ~")
  .slow(3)
  .sound("sine")
  .gain(0.16)
  .attack(0.006)
  .decay(0.2)
  .sustain(0.06)
  .release(0.15)
  .lpf(110)
  .room(0.2)
  .pan(0.5)

// Track 8 - Chords become SUSPENDED — never resolving
$: note("<g3 c4 d4> ~ ~ ~ <g3 b3 eb4> ~ ~ <g3 bb3 d4> ~ ~ ~ <fs3 a3 d4> ~ ~ ~")
  .slow(6)
  .sound("sawtooth")
  .gain(0.09)
  .attack(0.02)
  .decay(0.5)
  .sustain(0.2)
  .release(0.7)
  .lpf(900)
  .lpq(5)
  .room(0.6)
  .pan(0.5)
  .juxBy(0.5, x => x.late(0.125).transpose(12).gain(0.05))

// Track 9 - DROPPED descending alarm, replaced with CIRCLING VULTURES
$: note("d5 ~ eb5 ~ d5 ~ cs5 ~ d5 ~ eb5 ~ e5 ~ eb5 ~ d5 ~")
  .slow(4)
  .sound("square")
  .gain(0.06)
  .attack(0.1)
  .decay(0.15)
  .sustain(0.03)
  .release(0.6)
  .lpf(2800)
  .hpf(1400)
  .room(0.7)
  .pan(cosine.range(0.2, 0.8).slow(4))

// Track 10 - Canon becomes ECHO CHAMBER — words returning distorted
$: note("g4 b4 ~ d5 ~ ~ g5 ~ fs5 ~ ~ e5 d5 ~ ~ b4")
  .slow(6)
  .sound("sine")
  .gain(0.09)
  .attack(0.1)
  .decay(0.4)
  .sustain(0.2)
  .release(1.5)
  .lpf(2000)
  .room(0.8)
  .pan(0.4)
  .off(0.5, x => x.transpose(-12).gain(0.06).pan(0.6))
  .off(1, x => x.transpose(-5).gain(0.05).pan(0.7))

// Track 11 - The question INVERTS — now descending into silence
$: note("g5 ~ fs5 ~ e5 ~ d5 ~ c5 ~ b4 ~ a4 ~ g4 ~")
  .slow(16)
  .sound("triangle")
  .gain(0.07)
  .attack(0.6)
  .decay(0.4)
  .sustain(0.35)
  .release(2.5)
  .lpf(sine.range(500, 1400).slow(16))
  .room(0.9)
  .pan(0.5)
  .off(2, x => x.transpose(-12).gain(0.04))