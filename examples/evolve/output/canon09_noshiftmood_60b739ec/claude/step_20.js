// BWV 1087 Canon 11 - The Shattered Mirror (Variation: Cathedral of Fireflies)

// What if joy could glow? The garden at twilight.
// Points of light drift through the ruins — not restoration, but transformation.
// The walking bass becomes a procession. Birdsong becomes bells calling across water.
// A new voice enters: a solo violin remembering everything, forgiving everything.

let fireflyVoice = x => x
  .sound("triangle")
  .gain(0.12)
  .attack(0.001)
  .decay(0.3)
  .sustain(0.15)
  .release(2.2)
  .lpf(sine.range(1200, 3200).slow(7))
