// BWV 1087 Canon 10 - The Scattering (Variation: Rebirth Through Dissonance)

// The diaspora finds new harmonic language.
// What scattered now recombines in unexpected intervals.
// Minor seconds and tritones — the friction of reunion.

let glassVoice = x => x
  .sound("sine")
  .gain(0.17)
  .attack(0.002)
  .decay(1.0)
  .sustain(0.03)
  .release(1.8)
  .lpf(sine.range(1800, 4500).slow(10))
  .room(0.75)
  .delay(0.5)
  .delaytime(0.25)
  .delayfeedback(0.55)

let scatterVoice = x => x
  .sound("triangle")
  .gain(0.12)
  .attack(0.001)
  .decay(0.15)
  .sustain(0.1)
  .release(0.4)
  .lpf(1800)
  .room(0.4)

let deepVoice = x => x
  .sound("sawtooth")
  .gain(0.14)
  .attack(0.8)
  .decay(0.5)
  .sustain(0.5)
  .release(1.5)
  .lpf(400)
  .lpq(4)
  .room(0.6)

setcps(92/60/4)

// Track 1 - The fanfare inverted and transposed — ascent becomes descent
$: note("g3 ~ ~ ~ ~ ~ d5 ~ ~ ~ ~ ab3 ~ ~ ~ ~ ~ ~ ~ ~ f4 ~ ~ ~ ~ ~ ~ ~ db4 ~ ~ ~")
  .slow(16)
  .apply(glassVoice)
  .pan(sine.range(0.2, 0.8).slow(8))
  .juxBy(0.6, x => x.transpose(17).gain(0.1).late(0.25))

// Track 2 - Rain becomes TRITONE hail — tension incarnate
$: note("[g5 cs5] ~ [c5 fs5] ~ [e5 bb5] ~ [f5 b5]")
  .slow(2)
  .apply(scatterVoice)
  .pan(rand.range(0.1, 0.9))
  .degradeBy(0.25)
  .every(3, x => x.transpose(-7))

// Track 3 - Drone now in minor seconds — the discomfort of closeness
$: note("g1 ~ ~ ~ ~ ~ ~ ~ fs1 ~ ~ ~ ~ ~ ~ ~")
  .slow(8)
  .sound("sawtooth")
  .gain(0.12)
  .attack(3)
  .decay(2)
  .sustain(0.5)
  .release(4)
  .lpf(cosine.range(80, 200).slow(14))
  .lpq(3)
  .pan(0.15)
  .room(0.65)

$: note("~ ~ ~ ~ ab1 ~ ~ ~ ~ ~ ~ ~ g1 ~ ~ ~")
  .slow(8)
  .sound("sawtooth")
  .gain(0.12)
  .attack(3)
  .decay(2)
  .sustain(0.5)
  .release(4)
  .lpf(cosine.range(100, 250).slow(11))
  .lpq(3)
  .pan(0.85)
  .room(0.65)

// Track 4 - DROPPED clusters, replaced with pulsing fifths — the skeleton revealed
$: note("g2 ~ d3 ~ g2 ~ d3 ~ g2 ~ d3 ~ g2 ~ d3 ~")
  .slow(4)
  .sound("pulse")
  .gain(0.13)
  .attack(0.01)
  .decay(0.2)
  .sustain(0.3)
  .release(0.4)
  .lpf(sine.range(300, 800).slow(7))
  .room(0.4)
  .pan(0.5)

// Track 5 - Bass now AUGMENTED — stretching time, widening the gap
$: note("fs2 ~ ~ ~ bb2 ~ ~ ~ d2 ~ ~ ~ a1 ~ ~ ~")
  .slow(8)
  .sound("triangle")
  .gain(0.16)
  .attack(0.02)
  .decay(0.3)
  .sustain(0.2)
  .release(0.6)
  .lpf(550)
  .pan(0.4)
  .room(0.3)

// Track 6 - Counter-melody now in WHOLE TONES — floating, unmoored
$: note("g5 ~ ~ a5 ~ ~ b5 ~ ~ ~ cs6 ~ ~ ~ ~ ~ ~ ~ eb5 ~ ~ f5 ~ ~ g5 ~ ~ ~ ~ ~ ~ ~")
  .slow(16)
  .sound("sine")
  .gain(0.13)
  .attack(0.2)
  .decay(0.6)
  .sustain(0.3)
  .release(1.2)
  .lpf(2000)
  .room(0.85)
  .delay(0.6)
  .delaytime(0.666)
  .delayfeedback(0.55)
  .pan(0.6)
  .echo(3, 0.333, 0.4)

// Track 7 - Heartbeat becomes POLYRHYTHM — two hearts, out of sync
$: note("g1 ~ g1 ~ ~ g1 ~ ~ ~ g1 ~ ~ ~ ~ ~ ~")
  .slow(8)
  .sound("sine")
  .gain(0.16)
  .attack(0.01)
  .decay(0.35)
  .sustain(0.08)
  .release(0.25)
  .lpf(140)
  .room(0.35)
  .pan(0.4)

$: note("~ d2 ~ ~ d2 ~ ~ ~ d2 ~ ~ ~ ~ d2 ~ ~")
  .slow(8)
  .sound("sine")
  .gain(0.14)
  .attack(0.01)
  .decay(0.35)
  .sustain(0.08)
  .release(0.25)
  .lpf(160)
  .room(0.35)
  .pan(0.6)

// Track 8 - Arpeggios now ASCENDING — seeds rising, not falling
$: note("d5 f5 a5 d6 ~ ~ e5 gs5 b5 e6 ~ ~ fs5 a5 cs6 fs6 ~ ~ g5 b5 d6 g6 ~ ~")
  .slow(12)
  .sound("sine")
  .gain(0.09)
  .attack(0.001)
  .decay(0.8)
  .sustain(0)
  .release(1.5)
  .lpf(4000)
  .room(0.8)
  .delay(0.5)
  .delaytime(0.375)
  .delayfeedback(0.5)
  .pan(saw.range(0.3, 0.7).slow(6))

// Track 9 - NEW: Bell choir — the scattered voices calling across valleys
$: note("<g5 b5 d6> <d5 fs5 a5> ~ <c5 e5 g5> ~ ~ <eb5 g5 bb5> ~")
  .slow(4)
  .sound("sine")
  .gain(0.1)
  .attack(0.001)
  .decay(1.5)
  .sustain(0)
  .release(2)
  .lpf(3500)
  .room(0.9)
  .delay(0.6)
  .delaytime(0.5)
  .delayfeedback(0.6)
  .pan(tri.range(0.2, 0.8).slow(5))