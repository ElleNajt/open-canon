// BWV 1087 Canon 10 - The Gathering Storm (Variation: Fractured Reunion)

// They have found each other, but recognition is uncertain.
// Familiar melodies return wearing stranger's clothes.
// The heartbeat falters — skips — then races.

let glassVoice = x => x
  .sound("sine")
  .gain(0.17)
  .attack(0.002)
  .decay(1.0)
  .sustain(0.03)
  .release(1.8)
  .lpf(sine.range(1800, 4500).slow(10))
  .room(0.75)
  .delay(0.5)
  .delaytime(0.25)
  .delayfeedback(0.55)

let scatterVoice = x => x
  .sound("triangle")
  .gain(0.12)
  .attack(0.001)
  .decay(0.15)
  .sustain(0.1)
  .release(0.4)
  .lpf(1800)
  .room(0.4)

let choirVoice = x => x
  .sound("sawtooth")
  .gain(0.08)
  .attack(0.4)
  .decay(0.3)
  .sustain(0.6)
  .release(1.2)
  .lpf(900)
  .lpq(2)
  .room(0.7)

setcps(96/60/4)

// Track 1 - The fanfare INVERTED — what rose now falls, questioning
$: note("d4 ~ ~ g3 ~ ~ ~ eb4 ~ ~ ~ ab3 ~ ~ ~ ~ ~")
  .slow(8)
  .apply(glassVoice)
  .pan(0.3)
  .juxBy(0.7, x => x.transpose(-12).gain(0.12).late(0.5))

$: note("~ ~ d3 ~ ~ ~ g2 ~ ~ eb3 ~ ~ ~ ~ ab2 ~")
  .slow(8)
  .apply(glassVoice)
  .gain(0.12)
  .pan(0.7)

// Track 2 - Rain becomes HAIL — sharp, staccato, insistent
$: note("g5 g5 ~ fs5 fs5 ~ c5 ~ e5 e5 ~ ~ f5 f5 ~ ~")
