$: note("g5 ~ ~ b5 ~ ~ d6 ~ ~ ~ ~ ~ ~ ~ ~ ~")
  .slow(16)
  .sound("sine")
  .gain(0.07)
  .attack(0.3)
  .decay(0.2)
