// BWV 1087 Canon 10 - The Gathering Storm (Variation: The Verdict Arrives)

// The tribunal has spoken. Not with words, but with weight.
// Every voice now carries the same terrible knowledge.
// What was fragmented coalesces into grim certainty.

let condemnedVoice = x => x
  .sound("sine")
  .gain(0.14)
  .attack(0.002)
  .decay(1.2)
  .sustain(0.01)
  .release(3.0)
  .lpf(sine.range(800, 2400).slow(16))
  .room(0.85)
  .delay(0.7)
  .delaytime(0.5)
  .delayfeedback(0.55)

let gavel = x => x
  .sound("square")
  .gain(0.11)
  .attack(0.001)
  .decay(0.2)
  .sustain(0.05)
  .release(0.4)
  .lpf(1600)
  .room(0.4)

setcps(92/60/4)

// Track 1 - The fanfare becomes DIRGE — slow, inevitable descent
$: note("g4 ~ fs4 ~ ~ f4 ~ ~ e4 ~ ~ eb4 ~ ~ d4 ~")
  .slow(8)
  .apply(condemnedVoice)
  .pan(0.3)
  .juxBy(0.5, x => x.transpose(-12).gain(0.08).late(0.5))

$: note("d4 ~ ~ cs4 ~ c4 ~ ~ b3 ~ ~ bb3 ~ ~ a3 ~")
  .slow(8)
  .apply(condemnedVoice)
  .gain(0.1)
  .pan(0.7)
  .late(0.25)

// Track 2 - Morse code becomes SINGLE REPEATED SENTENCE
$: note("g5 ~ g5 ~ ~ ~ g5 ~ ~ ~ ~ ~ g5 ~ ~ ~")
  .slow(4)
  .apply(gavel)
  .pan(0.5)
  .every(4, x => x.transpose(-5))

// Track 3 - Drone collapses to UNISON — all dissent silenced
$: note("g1 ~ ~ ~ ~ ~ ~ ~ g1 ~ ~ ~ ~ ~ ~ ~")
  .slow(16)
  .sound("sawtooth")
  .gain(0.14)
  .attack(3.0)
  .decay(2.0)
  .sustain(0.5)
  .release(4.0)
  .lpf(cosine.range(50, 150).slow(16))
  .lpq(4)
  .pan(0.5)
  .room(0.7)

// Track 4 - Galloping stops — FROZEN IN PLACE
$: note("d4 ~ ~ ~ ~ ~ ~ ~ a3 ~ ~ ~ ~ ~ ~ ~")
  .slow(8)
  .sound("triangle")
  .gain(0.1)
  .attack(0.01)
  .decay(0.8)
  .sustain(0.15)
