// BWV 1087 Canon 10 - The Gathering Storm (Variation: The Mirror Cracks)

// Recognition arrives like lightning — sudden, blinding, then dark again.
// The mirror shows two faces, neither quite right.
// One voice tries to complete the other's sentence, always wrong.

let glassVoice = x => x
  .sound("sine")
  .gain(0.17)
  .attack(0.002)
  .decay(1.0)
  .sustain(0.03)
  .release(1.8)
  .lpf(sine.range(1800, 4500).slow(10))
  .room(0.75)
  .delay(0.5)
  .delaytime(0.25)
  .delayfeedback(0.55)

let brokenBell = x => x
  .sound("triangle")
  .gain(0.11)
  .attack(0.001)
  .decay(0.6)
  .sustain(0.05)
  .release(1.2)
  .lpf(2800)
  .room(0.65)

setcps(104/60/4)

// Track 1 - The fanfare FRAGMENTED — words cut mid-syllable
$: note("d4 ~ eb4 ~ ~ g3 ~ ~ ab3 ~ ~ ~ d4 eb4 ~ ~")
  .slow(6)
  .apply(glassVoice)
  .pan(0.3)
  .juxBy(0.7, x => x.transpose(-12).gain(0.12).late(0.33))

$: note("~ g3 ~ ab3 ~ ~ ~ eb4 ~ d4 ~ ~ ~ g3 ab3 ~")
  .slow(6)
  .apply(glassVoice)
  .gain(0.12)
  .pan(0.7)

// Track 2 - Hail becomes BROKEN GLASS — cascading, glittering, dangerous
$: note("g6 ~ fs6 ~ ~ e6 ~ ~ eb6 ~ d6 ~ ~ cs6 ~ c6")
  .slow(3)
  .apply(brokenBell)
  .pan(0.25)
  .every(4, x => x.rev())

$: note("~ b5 ~ bb5 ~ ~ a5 ~ ~ gs5 ~ g5 ~ ~ fs5 ~")
  .slow(3)
  .apply(brokenBell)
  .gain(0.09)
  .pan(0.75)
  .late(0.166)

// Track 3 - Drone OSCILLATES — can't decide where to land
$: note("g1 ~ ~ fs1 ~ ~ g1 ~ ~ ab1 ~ ~ g1 ~ fs1 ~")
  .slow(8)
  .sound("sawtooth")
  .gain(0.14)
  .attack(1.5)
  .decay(1.0)
  .sustain(0.5)
  .release(2.5)
  .lpf(cosine.range(90, 240).slow(10))
  .lpq(5)
  .pan(0.5)
  .room(0.55)

// Track 4 - DROPPED: Running eighths — replaced with STUTTERING CONFESSION
$: note("d4 d4 ~ e4 ~ ~ d4 ~ fs4 ~ ~ ~ g4 ~ ~ ~")
  .slow(4)
  .sound("pulse")
  .gain(0.13)
  .attack(0.003)
  .decay(0.08)
  .sustain(0.15)
  .release(0.2)
  .lpf(1400)
  .room(0.4)
  .pan(0.4)
  .sometimesBy(0.3, x => x.transpose(12).gain(0.08))

// Track 5 - Bass now WALKS IN CIRCLES — obsessive, trapped
$: note("g2 a2 bb2 a2 g2 fs2 g2 ~ g2 ab2 a2 ab2 g2 fs2 g2 ~")
  .slow(8)
  .sound("triangle")
  .gain(0.14)
  .attack(0.02)
  .decay(0.2)
  .sustain(0.35)
  .release(0.4)
  .lpf(550)
  .pan(0.48)
  .room(0.3)

// Track 6 - Whispers become ACCUSATIONS — sharper, closer
$: note("eb6 ~ d6 ~ ~ ~ cs6 ~ ~ d6 ~ ~ eb6 ~ ~ ~")
  .slow(8)
  .sound("square")
  .gain(0.06)
  .attack(0.15)
  .decay(0.1)
  .sustain(0.05)
  .release(1.8)
  .lpf(1800)
  .hpf(1200)
  .room(0.9)
  .delay(0.7)
  .delaytime(0.5)
  .delayfeedback(0.65)
  .pan(sine.range(0.15, 0.85).slow(7))

// Track 7 - Heartbeat STOPS then RESTARTS — the moment of recognition
$: note("g1 ~ ~ ~ ~ ~ ~ ~ ~ ~ g1 g1 g1 g1 g1 g1")
  .slow(4)
  .sound("sine")
  .gain(0.18)
  .attack(0.008)
  .decay(0.25)
  .sustain(0.08)
  .release(0.12)
  .lpf(130)
  .room(0.25)
  .pan(0.5)

// Track 8 - Chords INVERT and CLASH — wrong answers to right questions
$: note("<b3 d4 g4> ~ ~ <bb3 db4 gb4> ~ <a3 c4 f4> ~ ~ <ab3 b3 eb4> ~ ~ ~")
  .slow(4)
  .sound("sawtooth")
  .gain(0.1)
  .attack(0.01)
  .decay(0.35)
  .sustain(0.15)
  .release(0.5)
  .lpf(1000)
  .lpq(4)
  .room(0.55)
  .pan(0.5)
  .juxBy(0.4, x => x.late(0.0625).transpose(-7).gain(0.07))

// Track 9 - Alarm DESCENDS — hope draining away
$: note("eb6 d6 cs6 c6 b5 bb5 a5 ab5 g5 fs5 f5 e5 eb5 d5 cs5 c5")
  .slow(8)
  .sound("triangle")
  .gain(0.07)
  .attack(0.002)
  .decay(0.2)
  .sustain(0)
  .release(0.4)
  .lpf(3200)
  .room(0.5)
  .delay(0.35)
  .delaytime(0.1875)
  .delayfeedback(0.25)
  .pan(0.55)

// Track 10 - The canon ARGUES WITH ITSELF — same notes, wrong timing
$: note("g4 ~ b4 ~ d5 ~ g5 ~ ~ fs5 ~ e5 ~ d5 ~ b4")
  .slow(8)
  .sound("sine")
  .gain(0.1)
  .attack(0.08)
  .decay(0.35)
  .sustain(0.25)
  .release(1.3)
  .lpf(2200)
  .room(0.75)
  .pan(0.35)
  .off(0.375, x => x.transpose(0).gain(0.08).pan(0.65).late(0.0625))

// Track 11 - NEW: The question that cannot be answered — rising, always rising
$: note("g3 ~ a3 ~ b3 ~ c4 ~ d4 ~ e4 ~ fs4 ~ g4 ~")
  .slow(16)
  .sound("sine")
  .gain(0.08)
  .attack(0.5)
  .decay(0.3)
  .sustain(0.4)
  .release(2.0)
  .lpf(sine.range(600, 1600).slow(16))
  .room(0.85)
  .pan(0.5)
  .off(4, x => x.transpose(12).gain(0.05))