// BWV 1087 Canon 10 - The Gathering Storm (Variation: The Defiant Ember)

// But in the ashes of verdict, something stirs.
// One voice refuses the sentence. A single flame
// that will not be extinguished by consensus.

let condemnedVoice = x => x
  .sound("sine")
  .gain(0.14)
  .attack(0.002)
  .decay(1.2)
  .sustain(0.01)
  .release(3.0)
  .lpf(sine.range(800, 2400).slow(16))
  .room(0.85)
  .delay(0.7)
  .delaytime(0.5)
  .delayfeedback(0.55)

let defiantVoice = x => x
  .sound("sawtooth")
  .gain(0.12)
  .attack(0.01)
  .decay(0.3)
  .sustain(0.6)
  .release(0.5)
  .lpf(2200)
  .distort(0.15)
  .room(0.4)

setcps(100/60/4)

// Track 1 - The dirge INTERRUPTED — ascending phrase breaks through
$: note("g4 ~ a4 ~ ~ bb4 ~ ~ c5 ~ ~ d5 ~ ~ eb5 ~")
  .slow(8)
  .apply(condemnedVoice)
  .pan(0.3)
  .juxBy(0.5, x => x.transpose(-12).gain(0.08).late(0.5))

$: note("d4 ~ eb4 ~ f4 ~ ~ g4 ~ ~ a4 ~ ~ bb4 ~")
  .slow(8)
  .apply(condemnedVoice)
  .gain(0.1)
  .pan(0.7)
  .late(0.25)

