// BWV 1087 Canon 10 - The Gathering Storm (Variation: Convergence)

// The scattered begin to return.
// Dissonance resolves not to consonance, but to new questions.
// Rhythms align then splinter — the dance of almost-meeting.

let glassVoice = x => x
  .sound("sine")
  .gain(0.17)
  .attack(0.002)
  .decay(1.0)
  .sustain(0.03)
  .release(1.8)
  .lpf(sine.range(1800, 4500).slow(10))
  .room(0.75)
  .delay(0.5)
  .delaytime(0.25)
  .delayfeedback(0.55)

let scatterVoice = x => x
  .sound("triangle")
  .gain(0.12)
  .attack(0.001)
  .decay(0.15)
  .sustain(0.1)
  .release(0.4)
  .lpf(1800)
  .room(0.4)

let choirVoice = x => x
  .sound("sawtooth")
  .gain(0.08)
  .attack(0.4)
  .decay(0.3)
  .sustain(0.6)
  .release(1.2)
  .lpf(900)
  .lpq(2)
  .room(0.7)

setcps(96/60/4)

// Track 1 - The fanfare ANSWERS ITSELF — call and response across octaves
$: note("g3 ~ ~ d4 ~ ~ ~ ab3 ~ ~ ~ eb4 ~ ~ ~ ~ ~")
  .slow(8)
  .apply(glassVoice)
  .pan(0.3)
  .juxBy(0.7, x => x.transpose(12).gain(0.12).late(0.5))

$: note("~ ~ g4 ~ ~ ~ d5 ~ ~ ab4 ~ ~ ~ ~ eb5 ~")
  .slow(8)
  .apply(glassVoice)
  .gain(0.12)
  .pan(0.7)

// Track 2 - Rain now INTERLOCKING — two hands reaching
$: note("g5 ~ fs5 ~ ~ c5 ~ ~ e5 ~ ~ ~ f5 ~ ~ ~")
  .slow(4)
  .apply(scatterVoice)
  .pan(0.35)
  .every(4, x => x.transpose(5))

$: note("~ cs5 ~ ~ b4 ~ ~ bb4 ~ ~ a4 ~ ~ ~ g4 ~")
  .slow(4)
  .apply(scatterVoice)
  .pan(0.65)
  .every(4, x => x.transpose(-3))

// Track 3 - Drone RESOLVES to perfect fifth — brief peace
$: note("g1 ~ ~ ~ ~ ~ ~ ~ d2 ~ ~ ~ ~ ~ ~ ~")
  .slow(8)
  .sound("sawtooth")
  .gain(0.13)
  .attack(2.5)
  .decay(1.5)
  .sustain(0.6)
  .release(3)
  .lpf(cosine.range(100, 280).slow(12))
  .lpq(4)
  .pan(0.5)
  .room(0.6)

// Track 4 - Pulsing fifths become RUNNING EIGHTHS — urgency enters
$: note("g2 a2 b2 d3 g2 fs2 e2 d2 g2 a2 b2 c3 d3 e3 d3 ~")
  .slow(4)
  .sound("pulse")
  .gain(0.11)
  .attack(0.008)
  .decay(0.15)
  .sustain(0.2)
  .release(0.3)
  .lpf(sine.range(400, 1200).slow(6))
  .room(0.35)
  .pan(tri.range(0.3, 0.7).slow(3))

// Track 5 - Bass WALKS — purposeful, directed
$: note("g2 a2 b2 c3 d3 ~ e3 ~ fs3 ~ g3 ~ ~ ~ ~ ~")
  .slow(8)
  .sound("triangle")
  .gain(0.15)
  .attack(0.015)
  .decay(0.25)
  .sustain(0.3)
  .release(0.5)
  .lpf(600)
  .pan(0.45)
  .room(0.25)

// Track 6 - Counter-melody DESCENDS — what rose now falls to meet
$: note("g6 ~ fs6 ~ e6 ~ ~ d6 ~ c6 ~ ~ b5 ~ ~ a5 ~ ~ ~ g5 ~ ~ ~ ~ ~ ~ ~ ~ ~ ~ ~")
  .slow(16)
  .sound("sine")
  .gain(0.12)
  .attack(0.15)
  .decay(0.5)
  .sustain(0.35)
  .release(1.0)
  .lpf(2200)
  .room(0.8)
  .delay(0.55)
  .delaytime(0.5)
  .delayfeedback(0.5)
  .pan(0.55)

// Track 7 - Heartbeats SYNCHRONIZE briefly — then drift
$: note("g1 ~ ~ g1 ~ ~ g1 ~ g1 ~ ~ ~ g1 ~ ~ ~")
  .slow(8)
  .sound("sine")
  .gain(0.15)
  .attack(0.01)
  .decay(0.3)
  .sustain(0.1)
  .release(0.2)
  .lpf(150)
  .room(0.3)
  .pan(0.45)

$: note("g1 ~ ~ g1 ~ ~ g1 ~ ~ g1 ~ ~ ~ g1 ~ ~")
  .slow(8)
  .sound("sine")
  .gain(0.13)
  .attack(0.01)
  .decay(0.3)
  .sustain(0.1)
  .release(0.2)
  .lpf(170)
  .room(0.3)
  .pan(0.55)

// Track 8 - DROPPED arpeggios — replaced with CHOIR SWELLS
$: note("<g3 b3 d4 g4> ~ ~ ~ <d3 fs3 a3 d4> ~ ~ ~ <c3 e3 g3 c4> ~ ~ ~ <eb3 g3 bb3 eb4> ~ ~ ~")
  .slow(8)
  .apply(choirVoice)
  .pan(0.5)
  .jux(x => x.transpose(12).gain(0.06))

// Track 9 - Bell choir becomes MORSE CODE — messages across distance
$: note("g6 g6 ~ g6 ~ ~ ~ ~ d6 ~ d6 d6 ~ ~ ~ ~")
  .slow(4)
  .sound("sine")
  .gain(0.09)
  .attack(0.001)
  .decay(0.8)
  .sustain(0)
  .release(1.5)
  .lpf(4000)
  .room(0.85)
  .delay(0.7)
  .delaytime(0.333)
  .delayfeedback(0.55)
  .pan(0.7)

// Track 10 - NEW: Trembling high strings — anticipation
$: note("d7 ~ ~ ~ ~ ~ ~ ~ ~ ~ ~ ~ ~ ~ ~ ~")
  .slow(16)
  .sound("sawtooth")
  .gain(0.06)
  .attack(1)
  .decay(0.5)
  .sustain(0.7)
  .release(2)
  .lpf(sine.range(1500, 3000).slow(4))
  .tremolo(0.8)
  .tremolosync(8)
  .room(0.9)
  .pan(0.5)