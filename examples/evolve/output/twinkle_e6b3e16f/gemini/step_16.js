setcps(120/60/4)

$: n("0 2 3 5 7 5 3 2").scale("g:minor")
  .s("pulse")
  .shape(0.2)
  .slow(4)
  .release(0.25)
  .sustain(0)
  .lpf(700)
  .lpq(10)
  .lpenv(6000)
  .lpdecay(0.1)
  .pan(sine.range(0.1, 0.9).slow(4))
  .delay(0.5)
  .dfb(0.6)
  .dt("[3/16 1/8]*2")
  .room(0.4)
  .gain(0.5)

$: n("0 ~ 0 0 ~ 3 ~ <0 -2>").scale("g:minor").octave(2)
  .s("square")
  .slow(2)
  .lpf(400)
  .lpq(4)
  .lpenv(200)
  .lpdecay(0.1)
  .attack(0.01)
  .release(0.3)
  .crush(5)
  .gain(0.7)

$: stack(
  s("bd ~ bd ~"),
  s("~ sn ~ [sn/2 sn/2]"),
  s("hh*8")
    .hpf(1500)
    .velocity(perlin.range(0.6, 1).slow(2))
    .lpf(12000)
    .gain(0.6)
).compressor()