setcps(125/60/4)

$: n("[0 2]/2 3 [~ 5] 7 [5 3] 2").scale("g:minor").iter(1)
  .s("pulse")
  .shape(sine.range(0.2, 0.8).slow(6))
  .slow(4)
  .release(0.2)
  .sustain(0)
  .lpf(1000)
  .lpq(8)
  .lpenv(4000)
  .lpdecay(0.15)
  .pan(sine.range(0.2, 0.8).slow(8))
  .delay(0.4)
  .dfb(0.6)
  .dt(3/8)
  .room(0.2)
  .gain(0.55)

$: n("0*3 ~ 3*2 2*2").scale("g:minor").octave(2)
  .s("square")
  .slow(2)
  .lpf(sine.range(300, 900).slow(8))
  .lpq(5)
  .attack(0.01)
  .release(0.3)
  .drive(0.3)
  .gain(0.7)

$: stack(
  s("bd [~ bd/2] bd bd"),
  s("~ sn ~ [sn cp]/2").gain(0.9).room(0.1),
  s("hh*8")
    .hpf(1200)
    .velocity(perlin.range(0.4, 1).slow(4))
    .every(8, (x) => x.s('oh').release(0.3).gain(1.1))
    .gain(0.6)
).compressor()