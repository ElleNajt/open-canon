setcps(125/60/4)

$: n("0 2 ~ 7 5 3 5 2").scale("g:minor").iter(1).slow(2)
  .s("supersaw")
  .fm(sine.range(0.2, 0.8).slow(5))
  .fmh(1.5)
  .release(0.1)
  .sustain(0)
  .lpf(1000)
  .lpq(8)
  .lpenv(2500)
  .lpdecay(0.2)
  .pan(perlin.range(0.2, 0.8).slow(6))
  .delay(0.4)
  .dfb(0.4)
  .dt(3/8)
  .room(0.25)
  .gain(0.6)

$: n("~ 7 ~ 5 ~ 3 [~ 2]").scale("g:minor").octave(3).slow(2)
  .s("square")
  .lpf(sine.range(400, 2000).slow(8))
  .lpq(5)
  .release(0.2)
  .sustain(0)
  .phaser(sine.range(0.1, 2).slow(12))
  .drive(0.3)
  .gain(0.6)

$: stack(
  s("bd ~ [bd bd]/2 bd"),
  s("~ sn ~ cp").gain(1.1).early(0.01),
  s("hh*16").euclid(9, 16)
    .hpf(2000)
    .velocity(rand.range(0.4, 1))
    .every(8, (x) => x.s('oh').release(0.3))
    .gain(0.6)
).compressor().postgain(1.1)