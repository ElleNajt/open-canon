setcps(108/60/4)

$: n("[0 3] 5 ~ <7 8> [5 3] ~").scale("g:minor")
  .s("supersaw")
  .detune(15)
  .slow(2)
  .release(0.2)
  .sustain(0)
  .lpf(sine.range(800, 4000).slow(6))
  .lpq(8)
  .penv(100)
  .pdecay(0.05)
  .pan(perlin.slow(16).range(0.2, 0.8))
  .delay(0.6)
  .dfb(0.5)
  .dt(3/8)
  .room(0.3)
  .gain(0.4)

$: n("0 ~ 0 3 [0 0] -4 ~").scale("g:minor").octave(2)
  .s("saw")
  .slow(2)
  .lpf(250)
  .lpq(2)
  .attack(0.01)
  .release(0.6)
  .drive(0.4)
  .gain(0.7)

$: stack(
  s("bd ~ [~ bd] [bd/2 bd/2]"),
  s("~ [sn cp] ~ [~ sn]"),
  s("[hh*3 oh]/2")
    .sustain(0)
    .release(0.08)
    .gain(perlin.range(0.5, 0.9).slow(4))
    .hpf(1000)
).compressor().gain(0.9)