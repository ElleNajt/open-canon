setcps(120/60/4)

$: n("0 7 2 5").scale("g:minor").palindrome().slow(4)
  .s("triangle")
  .attack(0.01)
  .release(0.1)
  .sustain(0)
  .lpf(sine.range(500, 2500).slow(8))
  .lpq(12)
  .pan(perlin.range(0.2, 0.8).slow(5))
  .delay(0.4).dfb(0.4).dt(1/6)
  .room(0.2)
  .gain(0.8)

$: n("0 3 5 <6 0>").scale("g:minor").chord("m7").octave(-1).slow(8)
  .s("supersaw")
  .attack(2)
  .release(2)
  .sustain(0.5)
  .lpf(perlin.range(300, 1000).slow(12))
  .lpq(4)
  .phaser(sine.range(0.1, 1).slow(18))
  .phaserdepth(0.6)
  .room(0.7)
  .size(0.95)
  .gain(0.5)

$: stack(
  s("bd ~ [~ bd]/2 ~").gain(1.1),
  s("~ sn ~ [~ rim]/2")
    .crush(4)
    .gain(1.3)
    .early(0.01),
  s("[hh hh] hh <hh oh>")
    .velocity(perlin.range(0.6, 1))
    .sustain(0)
    .release(0.05)
    .every(4, (x) => x.release(0.25))
    .gain(0.6)
).compressor().postgain(1.1)