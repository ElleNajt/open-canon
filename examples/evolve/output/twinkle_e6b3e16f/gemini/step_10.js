setcps(112/60/4)

$: note("g4 d5 a#4 d5 c5 g4 d#4 g4")
  .s("pulse")
  .slow(2)
  .release(0.3)
  .sustain(0)
  .lpf(sine.range(400, 3000).slow(4))
  .lpenv(1500)
  .lpdecay(0.15)
  .lpq(6)
  .gain(0.4)
  .pan(perlin.slow(8).range(0.3, 0.7))
  .delay(0.4)
  .dfb(0.5)
  .dt(3/8)
  .room(0.4)

$: n("g1 c2 d#1 f1")
  .s("sawtooth")
  .slow(4)
  .attack(0.01)
  .release(0.5)
  .sustain(0)
  .lpf(120)
  .lpenv(700)
  .lpdecay(0.3)
  .lpq(9)
  .drive(0.3)
  .gain(0.55)

