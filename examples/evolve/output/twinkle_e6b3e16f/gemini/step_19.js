setcps(125/60/4)

$: n("0 2 ~ 3 7 5 3 2").scale("g:minor").iter(1).slow(2)
  .s("sawtooth")
  .fm(sine.range(0.1, 1).slow(5))
  .fmh(1.5)
  .release(0.1)
  .sustain(0)
  .lpf(1200)
  .lpq(10)
  .lpenv(3000)
  .lpdecay(0.1)
  .pan(perlin.range(0.2, 0.8).slow(6))
  .delay(0.3)
  .dfb(0.5)
  .dt(3/8)
  .room(0.2)
  .gain(0.6)

$: n("0 ~ 0 0 3 ~ [2 2]/2").scale("g:minor").octave(2)
  .s("square")
  .slow(2)
  .lpf(sine.range(250, 700).slow(8))
  .lpq(6)
  .release(0.15)
  .sustain(0)
  .crush(5)
  .drive(0.4)
  .gain(0.7)

$: stack(
  s("bd ~ bd [~ bd/2]"),
  s("~ sn ~ cp").gain(1.1).early(0.01),
  s("hh*16").euclid(11, 16)
    .hpf(1500)
    .velocity(perlin.range(0.3, 1).fast(2))
    .every(4, (x) => x.s('oh').release(0.3))
    .gain(0.65)
).compressor().postgain(1.1)