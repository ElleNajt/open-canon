setcps(125/60/4)

$: n("0 5 7 2").scale("g:minor").iter(1).slow(2)
  .s("sawtooth")
  .release(0.1)
  .sustain(0)
  .lpf(sine.range(800, 2200).slow(6))
  .lpq(7)
  .pan(perlin.range(0.2, 0.8).slow(5))
  .delay(0.3)
  .dfb(0.5)
  .dt(3/8)
  .room(0.2)
  .gain(0.7)

$: n("0 6 3 5").scale("g:minor").chord("m").slow(8)
  .s("supersaw")
  .attack(1.5)
  .release(2)
  .sustain(0.4)
  .lpf(sine.range(600, 1400).slow(16))
  .lpq(2)
  .room(0.6)
  .size(0.9)
  .gain(0.5)

$: stack(
  s("bd ~ bd [~ bd]/2"),
  s("~ sn ~ cp")
    .gain(1.2)
    .crush(6)
    .early(0.01),
  s("[hh*3 oh]*4")
    .velocity(perlin.range(0.5, 1).slow(2))
    .sustain(0)
    .release(0.04)
    .every(4, (x) => x.release(0.2))
    .gain(0.7)
).compressor().postgain(1.1)