// BWV 1087 Canon 3 - Variation: The Cosmic Dissolution

let cosmicSynth = x => x
  .sound("supersaw")
  .gain(0.11)
  .attack(0.3)
  .decay(0.5)
  .sustain(0.4)
  .release(2.5)
  .lpf(sine.range(600, 2200).slow(12))
  .lpq(4)
  .room(0.7)
  .delay(0.35)
  .delaytime(0.333)
  .delayfeedback(0.4)

let voidPad = x => x
  .sound("sine")
  .gain(0.09)
  .attack(0.8)
  .decay(1.0)
  .sustain(0.3)
  .release(3.0)
  .fmi(1.5)
  .fmh(2)
  .room(0.8)

setcps(72/60/4)

// Track 1 - triumphant fanfare dissolves into floating fragments
$: note("e4 ~ ~ b4 ~ ~ ~ e5 ~ ~ ~ ~ b4 ~ ~ ~")
  .slow(6)
  .apply(cosmicSynth)
  .pan(sine.range(0.3, 0.7).slow(8))
  .sometimes(x => x.add(7).gain(0.08))

// Track 2 - power chords become suspended, questioning
$: note("<e3 b3 fs4> ~ ~ ~ <a3 e4 b4> ~ ~ ~ ~ ~ <b2 fs3 cs4> ~ ~ ~ ~ ~")
  .slow(6)
  .apply(voidPad)
  .pan(0.5)
  .jux(x => x.add(-12).lpf(400).gain(0.06))

// Track 3 - military snare dissolves into scattered raindrops
