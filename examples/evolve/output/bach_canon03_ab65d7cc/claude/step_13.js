// BWV 1087 Canon 3 - Variation: Fever Dream Waltz

let crystalBells = x => x
  .sound("sine")
  .gain(0.18)
  .attack(0.001)
  .decay(0.6)
  .sustain(0.05)
  .release(2.5)
  .fmi(12)
  .fmh(5)
  .fmdecay(0.08)
  .lpf(6000)
  .room(0.8)
  .delay(0.4)
  .delaytime(0.25)
  .delayfeedback(0.5)

let hauntedStrings = x => x
  .sound("sawtooth")
  .gain(0.09)
  .attack(2)
  .decay(1.5)
  .sustain(0.7)
  .release(4)
  .lpf(500)
  .lpq(4)
  .room(0.85)

setcps(72/60/4)

// Track 1 - melody transformed to lilting 3/4 waltz, lydian brightness piercing through
$: note("fs5 ~ gs5 a5 ~ ~ ds6 ~ ~ cs6 ~ b5 ~ a5 gs5 ~")
  .slow(3)
  .apply(crystalBells)
  .pan(0.35)
  .every(3, x => x.add(7))
  .sometimes(x => x.octave(6).gain(0.12))

// Track 2 - harmony ascends now, hopeful despite the fog
$: note("<fs3 cs4> <gs3 ds4> <a3 e4> <b3 fs4> <cs4 gs4>")
  .slow(6)
  .apply(hauntedStrings)
  .pan(0.65)
  .jux(x => x.add(12).lpf(400))

// Track 3 - DROPPED clock, ADDED: music box mechanism, skipping
$: note("cs6 fs6 ~ a6 ~ fs6 cs6 ~ ~ a5 ~ cs6 fs6 ~ ~ ~")
  .slow(1.5)
  .sound("triangle")
  .gain(0.07)
  .attack(0.001)
  .decay(0.08)
  .sustain(0.0)
  .release(0.3)
  .fmi(3)
  .fmh(7)
  .lpf(8000)
  .hpf(2000)
  .room(0.6)
  .pan(0.6)
  .degradeBy(0.2)

// Track 4 - bass becomes a slow waltz pulse, grounding the vertigo
$: note("fs2 ~ ~ ~ cs2 ~ ~ ~ gs2 ~ ~ ~ fs2 ~ ~ ~")
  .slow(3)
  .sound("sine")
  .gain(0.14)
  .attack(0.05)
  .decay(0.5)
  .sustain(0.5)
  .release(0.8)
  .lpf(250)
  .room(0.3)
  .pan(0.5)

// Track 5 - ghostly bells become shooting stars, rapid descents
$: note("a7 gs7 fs7 e7 ds7 cs7 b6 ~ ~ ~ ~ ~ ~ ~ ~ ~")
  .slow(4)
  .sound("sine")
  .gain(0.055)
  .attack(0.001)
  .decay(0.3)
  .sustain(0.0)
  .release(1.5)
  .fmi(1)
  .fmh(11)
  .room(0.95)
  .hpf(3000)
  .pan(sine.range(0.1, 0.9).fast(2))
  .every(4, x => x.rev())

// Track 6 - arpeggios become major, spiraling upward now
$: note("fs3 a3 cs4 fs4 a4 cs5 fs5 a5 cs5 fs4 a4 cs4 fs3 ~ ~ ~")
  .slow(2)
  .sound("sine")
  .gain(0.07)
  .attack(0.008)
  .decay(0.15)
  .sustain(0.15)
  .release(0.6)
  .fmi(3)
  .fmh(4)
  .lpf(4000)
  .room(0.5)
  .delay(0.55)
  .delaytime(0.125)
  .delayfeedback(0.5)
  .pan(cosine.range(0.25, 0.75).slow(4))

// Track 7 - DROPPED growl, ADDED: distant choir, wordless and yearning
$: note("<a3 cs4 e4> <fs3 a3 cs4>")
  .slow(12)
  .sound("sawtooth")
  .gain(0.06)
  .attack(3)
  .decay(2)
  .sustain(0.8)
  .release(5)
  .lpf(cosine.range(400, 900).slow(16))
  .lpq(2)
  .room(0.9)
  .pan(0.5)
  .jux(x => x.add(0.1))

// Track 8 - companion now dances in parallel sixths, joyful
$: note("~ a4 ~ cs5 ~ e5 ~ ds5 ~ cs5 ~ b4 ~ a4 ~ ~")
  .slow(3)
  .late(0.333)
  .sound("pulse")
  .gain(0.08)
  .attack(0.015)
  .decay(0.25)
  .sustain(0.2)
  .release(0.9)
  .lpf(2200)
  .room(0.55)
  .pan(0.55)
  .add(note("<0 3 7>").slow(9))

// Track 9 - DROPPED string pad, ADDED: pizzicato heartbeat, syncopated
$: note("~ fs3 ~ ~ fs3 fs3 ~ ~ ~ fs3 ~ fs3 ~ ~ fs3 ~")
  .slow(1.5)
  .sound("triangle")
  .gain(0.1)
  .attack(0.001)
  .decay(0.06)
  .sustain(0.0)
  .release(0.2)
  .lpf(1500)
  .room(0.25)
  .pan(0.4)

// Track 10 - carnival organ becomes celeste, innocent and bright
$: note("fs5 a5 cs6 ~ ~ b5 a5 fs5 ~ e5 fs5 ~ ~ ~ ~ ~")
  .slow(4)
  .sound("sine")
  .gain(0.065)
  .attack(0.002)
  .decay(0.4)
  .sustain(0.1)
  .release(1.2)
  .fmi(6)
  .fmh(6)
  .fmdecay(0.2)
  .lpf(3500)
  .room(0.7)
  .delay(0.45)
  .delaytime(0.375)
  .delayfeedback(0.35)
  .pan(0.5)

