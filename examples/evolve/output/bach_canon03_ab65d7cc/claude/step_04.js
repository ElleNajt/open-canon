// BWV 1087 Canon 3 - Variation: Cathedral of Shattered Glass

let crystalVoice = x => x
  .sound("triangle")
  .gain(0.32)
  .attack(0.001)
  .decay(0.4)
  .sustain(0.15)
  .release(0.8)
  .lpf(4500)
  .room(0.5)
  .delay(0.35)
  .delaytime(0.25)
  .delayfeedback(0.45)

let choirPad = x => x
  .sound("sawtooth")
  .gain(0.18)
  .attack(0.8)
  .decay(0.6)
  .sustain(0.7)
  .release(3)
  .lpf(900)
  .lpq(2)
  .room(0.85)

let shimmerVoice = x => x
  .sound("sine")
  .gain(0.12)
  .attack(0.15)
  .decay(0.3)
  .sustain(0.5)
  .release(1.5)
  .lpf(3200)

setcps(72/60/4)

// Track 1 - melody ascends now, reaching toward light, lydian brightness
$: note("a4 b4 cs5 ds5 ~ e5 fs5 ~ gs5 ~ ~ fs5 e5 ~ ds5 ~")
  .slow(4)
  .apply(crystalVoice)
  .pan(0.35)
  .sometimes(x => x.octave(5).gain(0.2))

// Track 2 - harmonic movement now breathes, suspension and release
$: note("<a3 b3> <cs4 ds4> <e4 fs4> <ds4 cs4>")
  .slow(6)
  .apply(choirPad)
  .pan(0.65)
  .jux(x => x.note("<e4 fs4> <gs4 a4> <b4 cs5> <a4 gs4>").octave(3))

// Track 3 - heartbeat transformed to dancing pizzicato
$: note("a3 ~ cs4 ~ e4 ~ cs4 ~ a3 ~ e3 ~ ~ a3 ~ ~")
  .slow(2)
  .sound("triangle")
  .gain(0.24)
  .attack(0.005)
  .decay(0.15)
  .sustain(0.05)
  .release(0.3)
  .lpf(2200)
  .room(0.4)
  .pan(sine.range(0.3, 0.7).slow(3))

// Track 4 - new voice: falling glass, descending arpeggios
$: n("11 9 7 4 2 0 -3 -5")
  .scale("A:lydian")
  .octave(6)
  .slow(3)
  .apply(shimmerVoice)
  .delay(0.5)
  .delaytime(0.333)
  .delayfeedback(0.5)
  .pan(cosine.range(0.2, 0.8).slow(5))
  .degradeBy(0.15)

// Track 5 - wind through broken windows, breathy texture
$: note("~ e6 ~ ~ gs6 ~ ~ ~ b6 ~ ~ ~ ~ a6 ~ ~")
  .slow(8)
  .sound("sawtooth")
  .gain(0.07)
  .attack(0.5)
  .decay(0.4)
  .sustain(0.3)
  .release(2)
  .lpf(1400)
  .hpf(800)
  .delay(0.8)
  .delaytime(0.75)
  .delayfeedback(0.55)
  .pan(0.15)
  .room(0.7)

// Track 6 - warmth rises from below, drone shifts major
$: note("a1 ~ ~ ~ ~ ~ ~ ~ e2 ~ ~ ~ cs2 ~ ~ ~")
  .slow(16)
  .sound("sine")
  .gain(0.28)
  .attack(3)
  .decay(1.5)
  .sustain(0.6)
  .release(4)
  .lpf(180)
  .room(0.85)
  .pan(0.5)
  .fmi(0.3)
  .fmh(2)