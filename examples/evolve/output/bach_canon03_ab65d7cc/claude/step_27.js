// BWV 1087 Canon 3 - Variation: The Storm Breaks

let stormSynth = x => x
  .sound("sawtooth")
  .gain(0.14)
  .attack(0.01)
  .decay(0.2)
  .sustain(0.7)
  .release(0.8)
  .lpf(sine.range(400, 2800).slow(4))
  .lpq(6)
  .room(0.4)
  .delay(0.15)
  .delaytime(0.125)
  .delayfeedback(0.4)

let thunderPad = x => x
  .sound("supersaw")
  .gain(0.1)
  .attack(0.02)
  .decay(0.5)
  .sustain(0.7)
  .release(1.5)
  .lpf(800)
  .distort(0.2)
  .room(0.5)

setcps(108/60/4)

// Track 1 - jagged lightning melody, angular and urgent
$: note("e4 ~ gs4 ~ ~ b4 e5 ~ ~ gs4 a4 ~ b4 ~ ~ e5")
  .fast(1.5)
  .apply(stormSynth)
  .pan(rand.range(0.2, 0.8))
  .sometimes(x => x.add(12).gain(0.08))

// Track 2 - dark diminished chords, tension unresolved
$: note("<e3 g3 bb3> ~ <a3 c4 eb4> ~ <d3 f3 ab3> ~ <gs3 b3 d4> ~ ~ ~ ~ ~")
  .slow(4)
  .apply(thunderPad)
  .pan(0.5)
  .jux(x => x.sub(12).lpf(400).gain(0.08))

// Track 3 - chaotic polyrhythmic percussion
$: s("bd bd ~ cp bd ~ bd cp ~ bd oh cp bd ~ cp bd")
  .fast(1.5)
  .gain(0.14)
  .room(0.3)
  .delay(0.1)
  .delaytime(0.0625)
  .delayfeedback(0.5)
  .pan(rand.range(0.1, 0.9))
