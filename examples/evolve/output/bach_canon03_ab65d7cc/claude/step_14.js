// BWV 1087 Canon 3 - Variation: Crystalline Ascension

let glassMarimba = x => x
  .sound("sine")
  .gain(0.16)
  .attack(0.001)
  .decay(0.35)
  .sustain(0.02)
  .release(1.8)
  .fmi(8)
  .fmh(4)
  .fmdecay(0.05)
  .lpf(5500)
  .room(0.65)
  .delay(0.35)
  .delaytime(0.166)
  .delayfeedback(0.45)

let warmStrings = x => x
  .sound("sawtooth")
  .gain(0.1)
  .attack(1.5)
  .decay(1)
  .sustain(0.75)
  .release(3)
  .lpf(700)
  .lpq(2)
  .room(0.75)

setcps(84/60/4)

// Track 1 - melody now in dorian, earthier and more grounded
$: note("d5 ~ e5 f5 ~ ~ a5 ~ ~ g5 ~ f5 ~ e5 d5 ~")
  .slow(3)
  .apply(glassMarimba)
  .pan(0.4)
  .every(4, x => x.add(5))
