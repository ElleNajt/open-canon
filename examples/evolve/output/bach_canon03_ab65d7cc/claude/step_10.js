// BWV 1087 Canon 3 - Variation: Awakening from Stone

let crystalChime = x => x
  .sound("sine")
  .gain(0.22)
  .attack(0.001)
  .decay(0.3)
  .sustain(0.15)
  .release(2.5)
  .fmi(6)
  .fmh(7)
  .fmdecay(0.2)
  .lpf(6000)
  .room(0.85)
  .delay(0.45)
  .delaytime(0.25)
  .delayfeedback(0.5)

let warmthRising = x => x
  .sound("triangle")
  .gain(0.12)
  .attack(2)
  .decay(3)
  .sustain(0.7)
  .release(4)
  .lpf(800)
  .lpq(2)
  .room(0.8)

setcps(66/60/4)

// Track 1 - melody shifts to dorian, reaching upward now
$: note("d5 e5 f5 ~ g5 a5 ~ ~ b5 a5 g5 ~ f5 e5 ~ d5")
  .slow(5)
  .apply(crystalChime)
  .pan(0.35)
  .every(4, x => x.add(5).fast(1.2))
  .sometimes(x => x.octave(6).gain(0.15))

// Track 2 - harmony opens into major suspensions, light breaking through
$: note("<d3 a3> <g3 d4> <c3 g3> <f3 c4> <g3 b3>")
  .slow(10)
  .apply(warmthRising)
  .pan(0.65)
  .jux(x => x.add(12).attack(4))

// Track 3 - REPLACED metallic chimes with dancing pulse, almost playful
$: note("d4 f4 a4 d5 ~ a4 f4 ~ g4 b4 d5 g5 ~ ~ d5 ~")
  .slow(3)
  .sound("pulse")
  .gain(0.1)
  .attack(0.002)
  .decay(0.12)
  .sustain(0.1)
  .release(0.6)
  .lpf(2800)
  .hpf(400)
  .room(0.6)
  .delay(0.4)
  .delaytime(0.167)
  .delayfeedback(0.45)
  .pan(sine.range(0.2, 0.8).slow(7))

// Track 4 - pizzicato becomes a walking heartbeat, steady and alive
$: note("d2 ~ a2 d3 ~ ~ f2 ~ c3 f3 ~ ~ g2 ~ d3 ~")
  .slow(2)
  .sound("triangle")
  .gain(0.16)
  .attack(0.003)
  .decay(0.15)
  .sustain(0.05)
  .release(0.4)
  .lpf(1800)
  .hpf(200)
  .room(0.35)
  .pan(0.5)

// Track 5 - great bell becomes a dawn horn, sustained and hopeful
$: note("d2 ~ ~ ~ a2 ~ ~ ~ d3 ~ ~ ~ ~ ~ g2 ~")
  .slow(12)
  .sound("sawtooth")
  .gain(0.14)
  .attack(0.8)
  .decay(2)
  .sustain(0.6)
  .release(3)
  .lpf(600)
  .lpq(3)
  .room(0.9)
  .pan(0.5)

// Track 6 - DROPPED heavy bass, ADDED: rippling arpeggios like water
$: note("d3 f3 a3 d4 f4 a4 d5 a4 f4 d4 a3 f3 d3 ~ ~ ~")
  .slow(4)
  .sound("sine")
  .gain(0.08)
  .attack(0.01)
  .decay(0.2)
  .sustain(0.3)
  .release(0.8)
  .fmi(2)
  .fmh(3)
  .lpf(3500)
  .room(0.7)
  .delay(0.55)
  .delaytime(0.125)
  .delayfeedback(0.55)
  .pan(tri.range(0.3, 0.7).slow(6))

// Track 7 - ice crystals become birdsong, high trills
$: note("a6 b6 a6 ~ d7 e7 d7 ~ ~ g6 a6 g6 ~ ~ ~ ~")
  .slow(3)
  .sound("sine")
  .gain(0.06)
  .attack(0.001)
  .decay(0.08)
  .sustain(0.1)
  .release(0.5)
  .fmi(4)
  .fmh(5)
  .lpf(9000)
  .hpf(5000)
  .room(0.75)
  .pan(rand.range(0.2, 0.8))
  .degradeBy(0.3)

// Track 8 - canonic shadow now rises in parallel thirds, companion voice
$: note("f4 g4 a4 ~ b4 c5 ~ ~ d5 c5 b4 ~ a4 g4 ~ f4")
  .slow(5)
  .late(0.5)
  .sound("triangle")
  .gain(0.1)
  .attack(0.05)
  .decay(0.35)
  .sustain(0.25)
  .release(1.2)
  .lpf(2200)
  .room(0.7)
  .pan(0.55)
  .add(note("<0 2 4 -3>").slow(14))