// BWV 1087 Canon 3 - Variation: The Dissolving Dream

let ghostPiano = x => x
  .sound("sine")
  .gain(0.11)
  .attack(0.08)
  .decay(0.6)
  .sustain(0.2)
  .release(1.8)
  .lpf(1200)
  .lpq(2)
  .room(0.7)
  .delay(0.45)
  .delaytime(0.25)
  .delayfeedback(0.5)

let fadeStrings = x => x
  .sound("sawtooth")
  .gain(0.08)
  .attack(0.5)
  .decay(0.6)
  .sustain(0.3)
  .release(2.0)
  .lpf(800)
  .lpq(1)
  .room(0.65)

setcps(72/60/4)

// Track 1 - melody descends like fading memory, intervals widening
$: note("e5 ~ ~ b4 ~ ~ fs4 ~ ~ ~ c4 ~ ~ ~ ~ ~")
  .slow(4)
  .apply(ghostPiano)
  .pan(0.4)
  .every(3, x => x.sub(12).gain(0.07))
  .degradeBy(0.15)

