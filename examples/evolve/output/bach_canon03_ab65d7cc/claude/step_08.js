// Track 6 - foundation: now a slow walking bass, modal
$: note("a1 ~ c2 ~ d2 ~ e2 ~ g2 ~ f2 ~ e2 ~ d2 ~")
  .slow(16)
  .sound("sawtooth")
  .gain(0.18)
  .attack(0.8)
