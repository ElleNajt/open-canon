// BWV 1087 Canon 3 - Variation: Cathedral of Glass

let crystalBell = x => x
  .sound("sine")
  .gain(0.22)
  .attack(0.001)
  .decay(0.3)
  .sustain(0.15)
  .release(2.5)
  .fmi(2.5)
  .fmh(7)
  .fmdecay(0.2)
  .lpf(5500)
  .room(0.85)
  .delay(0.6)
  .delaytime(0.222)
  .delayfeedback(0.6)

let organSwell = x => x
  .sound("sawtooth")
  .gain(0.12)
  .attack(2.5)
  .decay(1.2)
  .sustain(0.7)
  .release(4)
  .lpf(400)
  .lpq(2)
  .room(0.95)

setcps(72/60/4)

// Track 1 - melody transformed: now a descending prayer in dorian
$: note("a5 g5 ~ f5 e5 ~ d5 ~ c5 ~ d5 e5 ~ ~ a4 ~")
  .slow(5)
  .apply(crystalBell)
  .pan(0.35)
  .every(4, x => x.add(5).slow(1.5))
  .sometimes(x => x.octave(6).gain(0.18))

// Track 2 - harmony inverted: suspended chords, unresolved yearning
$: note("<a2 d3 e3> <g2 c3 d3> <f2 a2 c3> <e2 a2 b2>")
  .slow(10)
  .apply(organSwell)
  .pan(0.65)
  .jux(x => x.add(12).attack(4))

// Track 3 - REPLACED: harp-like arpeggios cascading down
$: note("a4 e4 c4 a3 ~ g4 d4 b3 ~ f4 c4 a3 ~ e4 b3 ~")
  .slow(3)
  .sound("triangle")
  .gain(0.16)
  .attack(0.002)
  .decay(0.2)
  .sustain(0.1)
  .release(0.8)
  .lpf(3200)
  .hpf(400)
  .room(0.6)
  .delay(0.4)
  .delaytime(0.125)
  .delayfeedback(0.45)
  .pan(saw.range(0.2, 0.8).slow(7))

// Track 4 - distant choir: hollow fifths singing through stone
$: note("<a3 e4> <g3 d4> <f3 c4> <e3 b3>")
  .slow(12)
  .sound("square")
  .gain(0.08)
  .attack(1.8)
  .decay(1)
  .sustain(0.5)
  .release(3.5)
  .lpf(800)
  .lpq(3)
  .fmi(0.3)
  .fmh(1)
  .room(0.9)
  .pan(0.5)

// Track 5 - DROPPED birdsong, ADDED: tolling bell pattern
$: note("a2 ~ ~ ~ ~ ~ e3 ~ ~ ~ ~ ~ a2 ~ ~ ~")
  .slow(8)
  .sound("sine")
  .gain(0.2)
  .attack(0.01)
  .decay(0.8)
