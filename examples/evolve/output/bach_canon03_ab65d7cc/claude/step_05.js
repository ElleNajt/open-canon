// BWV 1087 Canon 3 - Variation: The Thaw

let bellTone = x => x
  .sound("triangle")
  .gain(0.28)
  .attack(0.002)
  .decay(0.6)
  .sustain(0.08)
  .release(1.2)
  .lpf(3800)
  .room(0.6)
  .delay(0.4)
  .delaytime(0.166)
  .delayfeedback(0.35)

let organSwell = x => x
  .sound("sawtooth")
  .gain(0.16)
  .attack(1.2)
  .decay(0.8)
  .sustain(0.65)
  .release(3.5)
  .lpf(750)
  .lpq(1.5)
  .room(0.9)

setcps(84/60/4)

// Track 1 - melody fragments into call and response, mixolydian descent
$: note("e5 d5 ~ b4 a4 ~ g4 ~ e4 ~ d4 ~ ~ e4 g4 a4")
  .slow(4)
  .apply(bellTone)
  .pan(0.3)
  .every(3, x => x.rev().octave(4))

// Track 2 - harmony opens up, fifths stacking like ice cracking
$: note("<e3 b3> <d3 a3> <g3 d4> <a3 e4>")
  .slow(8)
  .apply(organSwell)
  .pan(0.7)
  .jux(x => x.add(7).slow(1.5))

// Track 3 - pizzicato becomes urgent pulse, syncopated life returning
$: note("e3 ~ g3 a3 ~ g3 e3 ~ d3 e3 ~ ~ g3 ~ a3 ~")
  .fast(1.5)
  .sound("sine")
  .gain(0.22)
  .attack(0.003)
  .decay(0.12)
  .sustain(0.02)
  .release(0.25)
  .fmi(1.5)
  .fmh(3)
  .fmdecay(0.08)
  .lpf(2800)
  .room(0.3)
  .pan(rand.range(0.25, 0.75))

// Track 4 - NEW: water droplets, random pentatonic sparkles
$: n("0 2 4 7 9 11 14 16")
  .scale("E:pentatonic")
  .octave(7)
  .struct("t(5,8)")
  .slow(2)
  .sound("sine")
  .gain(0.09)
  .attack(0.001)
  .decay(0.2)
  .sustain(0)
  .release(0.6)
  .lpf(6000)
  .delay(0.7)
  .delaytime(0.125)
  .delayfeedback(0.6)
  .pan(rand)
  .degradeBy(0.3)

// Track 5 - breath becomes birdsong, trills emerging
$: note("b6 a6 b6 ~ ~ g6 a6 g6 ~ ~ ~ e6 ~ ~ ~ ~")
  .slow(6)
  .sound("triangle")
  .gain(0.06)
  .attack(0.01)
  .decay(0.15)
  .sustain(0.1)
  .release(0.8)
  .lpf(4200)
  .hpf(1200)
  .delay(0.5)
  .delaytime(0.083)
  .delayfeedback(0.4)
  .pan(0.85)
  .room(0.5)
  .sometimes(x => x.speed(2))

// Track 6 - drone warms and rises, earth awakening
$: note("e2 ~ ~ ~ b2 ~ ~ ~ g2 ~ ~ ~ a2 ~ ~ ~")
  .slow(12)
  .sound("sawtooth")
  .gain(0.2)
  .attack(2.5)
  .decay(2)
  .sustain(0.5)
  .release(5)
  .lpf(220)
  .lpenv(3)
  .lpdecay(4)
  .room(0.9)
  .pan(0.5)

// Track 7 - NEW: distant bells tolling, marking time's passage
$: note("<e4 b4> ~ ~ ~ ~ ~ ~ <a4 e5>")
  .slow(16)
  .sound("triangle")
  .gain(0.14)
  .attack(0.01)
  .decay(2)
  .sustain(0.2)
  .release(4)
  .lpf(1800)
  .room(0.95)
  .delay(0.3)
  .delaytime(0.5)
  .delayfeedback(0.3)
  .pan(0.5)