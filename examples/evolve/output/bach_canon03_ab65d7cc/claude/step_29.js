// BWV 1087 Canon 3 - Variation: Cathedral of Dawn (Triumphant Return)

let bellTower = x => x
  .sound("triangle")
  .gain(0.14)
  .attack(0.001)
  .decay(0.6)
  .sustain(0.15)
  .release(2)
  .fmi(3)
  .fmh(5.5)
  .fmdecay(0.5)
  .room(0.65)
  .delay(0.2)
  .delaytime(0.125)
  .delayfeedback(0.4)

let organSwell = x => x
  .sound("supersaw")
  .gain(0.1)
  .attack(0.3)
  .decay(0.8)
  .sustain(0.7)
  .release(2.5)
  .lpf(1800)
  .room(0.6)

setcps(92/60/4)

// Track 1 - triumphant fanfare melody, leaping fourths and fifths
$: note("e5 a5 e5 b5 ~ e6 ~ b5 a5 ~ e5 ~ a5 b5 e6 ~")
  .slow(2)
  .apply(bellTower)
  .pan(0.45)
  .every(4, x => x.add(12).gain(0.1))

// Track 2 - full organ chords, majestic progression in E major
$: note("<e3 gs3 b3 e4> ~ <a3 cs4 e4 a4> ~ <b3 ds4 fs4 b4> ~ <e3 gs3 b3 e4> ~")
  .slow(4)
  .apply(organSwell)
  .pan(0.5)
  .jux(x => x.add(12).lpf(2500).gain(0.08))

// Track 3 - processional drums, stately and bold
$: s("bd ~ bd ~ sn ~ bd sn bd ~ bd ~ sn ~ bd ~")
  .slow(2)
  .gain(0.14)
  .room(0.35)
  .lpf(3000)
  .pan(0.5)

// Track 4 - pedal bass, sustained power
$: note("e2 ~ ~ ~ a2 ~ ~ ~ b2 ~ ~ ~ e2 ~ ~ ~")
  .slow(4)
  .sound("sawtooth")
  .gain(0.12)
  .attack(0.05)
  .decay(0.4)
  .sustain(0.8)
  .release(1)
  .lpf(300)
  .pan(0.5)

// Track 5 - DROPPED birdsong, ADDED: brass-like fanfare countermelody
$: note("~ b4 e5 ~ gs5 ~ fs5 e5 ~ b4 ~ e5 gs5 a5 b5 ~")
  .slow(2)
  .sound("pulse")
  .gain(0.11)
  .attack(0.02)
  .decay(0.2)
  .sustain(0.6)
  .release(0.5)
  .lpf(2200)
  .lpq(4)
  .room(0.4)
  .pan(0.6)

// Track 6 - cascading arpeggios now in triumphant sixths
$: note("e3 cs4 e4 cs5 e5 cs6 a3 fs4 a4 fs5 a5 fs6 b3 gs4 b4 gs5")
  .slow(2)
  .sound("triangle")
  .gain(0.09)
  .attack(0.01)
  .decay(0.15)
  .sustain(0.3)
  .release(0.4)
  .lpf(3500)
  .room(0.4)
  .pan(0.4)

// Track 7 - carillon bells, rhythmic pealing
$: note("e6 b5 e6 gs6 e6 b5 gs5 e5 e6 b5 e6 gs6 b6 gs6 e6 b5")
  .slow(4)
  .sound("sine")
  .gain(0.08)
  .attack(0.001)
  .decay(0.3)
  .sustain(0.1)
  .release(1)
  .fmi(4)
  .fmh(7)
  .fmdecay(0.3)
  .room(0.55)
  .pan(sine.range(0.3, 0.7).slow(4))

// Track 8 - TRANSFORMED: descending golden sequence
$: note("gs6 fs6 e6 ds6 cs6 b5 a5 gs5 fs5 e5 ds5 cs5 b4 a4 gs4 e4")
  .slow(8)
  .sound("sine")
  .gain(0.07)
  .attack(0.02)
  .decay(0.25)
  .sustain(0.3)
  .release(0.6)
  .lpf(4000)
  .room(0.5)
  .pan(cosine.range(0.2, 0.8).slow(8))

// Track 9 - deep foundation drone, open fifth
$: note("[e1 b1]")
  .slow(16)
  .sound("sawtooth")
  .gain(0.09)
  .attack(1)
  .decay(2)
  .sustain(0.9)
  .release(4)
  .lpf(200)
  .room(0.5)
  .pan(0.5)

// Track 10 - DROPPED fifth, ADDED: jubilant timpani rolls
$: s("bd*8 ~ bd*4 bd bd*8 ~ bd*6 bd bd")
  .slow(4)
  .gain(0.1)
  .lpf(400)
  .room(0.5)
  .pan(0.5)
  .speed(0.7)

// Track 11 - angelic descant, soaring above
$: note("~ ~ gs6 ~ a6 ~ b6 ~ ~ ~ e7 ~ ~ ds7 ~ e7")
  .slow(4)
  .sound("sine")
  .gain(0.07)
  .attack(0.05)
  .decay(0.4)
  .sustain(0.5)
  .release(1.2)
  .fmi(2)
  .fmh(3)
  .room(0.6)
  .delay(0.25)
  .delaytime(0.2)
  .delayfeedback(0.45)
  .pan(0.55)

// Track 12 - DROPPED water drops, ADDED: shimmering cymbal swells
$: s("~ ~ oh ~ ~ ~ oh ~ ~ ~ cr ~ ~ ~ ~ ~")
  .slow(4)
  .gain(0.08)
  .hpf(3000)
  .room(0.65)
  .pan(rand.range(0.4, 0.6))

