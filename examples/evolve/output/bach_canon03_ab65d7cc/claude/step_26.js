// BWV 1087 Canon 3 - Variation: The Awakening Dawn

let dawnSynth = x => x
  .sound("triangle")
  .gain(0.12)
  .attack(0.15)
  .decay(0.4)
  .sustain(0.5)
  .release(1.8)
  .lpf(sine.range(800, 3500).slow(10))
