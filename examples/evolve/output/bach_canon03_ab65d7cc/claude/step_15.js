// BWV 1087 Canon 3 - Variation: Midnight Carnival

let circusOrgan = x => x
  .sound("square")
  .gain(0.12)
  .attack(0.01)
  .decay(0.2)
  .sustain(0.6)
  .release(0.4)
  .lpf(1800)
  .lpq(4)
  .room(0.4)
  .delay(0.25)
  .delaytime(0.125)
  .delayfeedback(0.35)

let darkCello = x => x
  .sound("sawtooth")
  .gain(0.11)
  .attack(0.8)
  .decay(0.6)
  .sustain(0.7)
  .release(2)
  .lpf(900)
  .lpq(3)
  .room(0.6)

setcps(104/60/4)

// Track 1 - melody now phrygian, Spanish and mysterious
$: note("e5 f5 ~ g5 a5 ~ ~ f5 e5 ~ d5 ~ e5 ~ ~ ~")
  .slow(2.5)
  .apply(circusOrgan)
  .pan(0.35)
  .every(3, x => x.add(7))
  .sometimes(x => x.fmi(6).fmh(3))

