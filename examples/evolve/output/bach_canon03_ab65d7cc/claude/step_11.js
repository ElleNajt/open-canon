// BWV 1087 Canon 3 - Variation: The Dance Begins

let crystalChime = x => x
  .sound("sine")
  .gain(0.22)
  .attack(0.001)
  .decay(0.3)
  .sustain(0.15)
  .release(2.5)
  .fmi(6)
  .fmh(7)
  .fmdecay(0.2)
  .lpf(6000)
  .room(0.85)
  .delay(0.45)
  .delaytime(0.25)
  .delayfeedback(0.5)

let warmthRising = x => x
  .sound("triangle")
  .gain(0.12)
  .attack(2)
  .decay(3)
  .sustain(0.7)
  .release(4)
  .lpf(800)
  .lpq(2)
  .room(0.8)

setcps(76/60/4)

// Track 1 - melody now syncopated, dancing with confidence
$: note("d5 ~ e5 f5 ~ g5 ~ a5 ~ b5 ~ a5 g5 ~ ~ d5")
  .slow(4)
  .apply(crystalChime)
  .pan(0.35)
  .every(3, x => x.add(7).fast(1.5))
  .sometimes(x => x.octave(6).gain(0.15))

// Track 2 - harmony shifts to lydian brightness, ascending by fourths
$: note("<d3 a3> <g3 d4> <c4 gs4> <fs3 cs4> <b3 fs4>")
  .slow(8)
  .apply(warmthRising)
  .pan(0.65)
  .jux(x => x.add(12).attack(4))

// Track 3 - TRANSFORMED: now a driving rhythmic motor, infectious groove
$: note("d4 d4 ~ f4 d4 ~ a4 ~ d4 f4 ~ d4 a4 ~ ~ d4")
  .fast(1.5)
  .sound("pulse")
  .gain(0.12)
  .attack(0.001)
  .decay(0.08)
  .sustain(0.05)
  .release(0.3)
  .lpf(2200)
  .hpf(600)
  .room(0.4)
  .delay(0.3)
  .delaytime(0.083)
  .delayfeedback(0.35)
  .pan(0.4)

// Track 4 - bass becomes a confident stride, almost jazz-like
$: note("d2 ~ ~ a2 ~ f2 ~ ~ c3 ~ ~ g2 ~ ~ d2 ~")
  .slow(2)
  .sound("sawtooth")
  .gain(0.14)
  .attack(0.01)
  .decay(0.2)
  .sustain(0.3)
  .release(0.5)
  .lpf(400)
  .room(0.3)
  .pan(0.5)

// Track 5 - DROPPED the dawn horn, ADDED: percussive clicks like footsteps
$: s("~ hh ~ hh:1 ~ ~ hh ~ hh:2 ~ hh ~ ~ hh:1 ~ ~")
  .slow(2)
  .gain(0.08)
  .hpf(6000)
  .room(0.5)
  .pan(rand.range(0.3, 0.7))

// Track 6 - arpeggios now cascade in sixths, more harmonic richness
$: note("d3 b3 f4 d4 a4 fs4 d5 b4 fs4 d4 b3 fs3 d3 ~ ~ ~")
  .slow(3)
  .sound("sine")
  .gain(0.09)
  .attack(0.01)
  .decay(0.15)
  .sustain(0.25)
  .release(0.6)
  .fmi(3)
  .fmh(4)
  .lpf(4000)
  .room(0.6)
  .delay(0.5)
  .delaytime(0.1)
  .delayfeedback(0.5)
  .pan(tri.range(0.25, 0.75).slow(5))

// Track 7 - birdsong becomes a fluttering laugh, more playful
$: note("d7 ~ fs7 ~ a7 fs7 ~ d7 ~ ~ b6 ~ d7 ~ ~ ~")
  .slow(2)
  .sound("sine")
  .gain(0.07)
  .attack(0.001)
  .decay(0.06)
  .sustain(0.08)
  .release(0.4)
  .fmi(5)
  .fmh(6)
  .lpf(10000)
  .hpf(6000)
  .room(0.7)
  .pan(rand.range(0.15, 0.85))
  .degradeBy(0.25)

// Track 8 - companion voice now in counterpoint, call and response
$: note("~ ~ a4 b4 ~ ~ d5 ~ e5 d5 ~ ~ b4 a4 ~ ~")
  .slow(4)
  .late(0.25)
  .sound("triangle")
  .gain(0.11)
  .attack(0.03)
  .decay(0.25)
  .sustain(0.3)
  .release(1)
  .lpf(2500)
  .room(0.65)
  .pan(0.6)
  .add(note("<0 4 7 2>").slow(12))

// Track 9 - NEW: a sustained string pad emerges, grounding the dance
$: note("<d3 a3 d4> <g3 d4 g4>")
  .slow(16)
  .sound("sawtooth")
  .gain(0.06)
  .attack(3)
  .decay(4)
  .sustain(0.8)
  .release(5)
  .lpf(1200)
  .lpq(1)
  .room(0.9)
  .pan(0.5)