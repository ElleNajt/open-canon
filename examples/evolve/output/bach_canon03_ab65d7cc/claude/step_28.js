// BWV 1087 Canon 3 - Variation: After the Storm (Fragments of Light)

let echoGlass = x => x
  .sound("triangle")
  .gain(0.12)
  .attack(0.02)
  .decay(0.4)
  .sustain(0.3)
  .release(1.2)
  .lpf(cosine.range(1200, 4000).slow(6))
