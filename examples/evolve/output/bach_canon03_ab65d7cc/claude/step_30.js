// BWV 1087 Canon 3 - Variation: Tempest's Eye (Storm Approaching)

let stormBell = x => x
  .sound("triangle")
  .gain(0.13)
  .attack(0.001)
  .decay(0.4)
  .sustain(0.1)
  .release(1.5)
  .fmi(5)
