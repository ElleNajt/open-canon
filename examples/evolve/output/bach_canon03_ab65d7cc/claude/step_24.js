// BWV 1087 Canon 3 - Variation: The Triumphant Return

let triumphantBrass = x => x
  .sound("sawtooth")
  .gain(0.13)
  .attack(0.05)
  .decay(0.3)
  .sustain(0.6)
  .release(0.8)
  .lpf(1800)
  .lpq(2)
  .room(0.4)
  .delay(0.2)
  .delaytime(0.125)
  .delayfeedback(0.25)

let choirPad = x => x
  .sound("triangle")
  .gain(0.1)
  .attack(0.4)
  .decay(0.6)
  .sustain(0.55)
  .release(2.0)
  .lpf(1600)
  .room(0.6)

setcps(96/60/4)

// Track 1 - TRANSFORMED: triumphant fanfare leaps in fifths and octaves
$: note("e4 b4 e5 ~ b4 e5 b5 ~ e5 b5 e6 ~ ~ ~ ~ ~")
  .slow(4)
  .apply(triumphantBrass)
  .pan(0.5)
  .every(3, x => x.add(5).gain(0.15))

