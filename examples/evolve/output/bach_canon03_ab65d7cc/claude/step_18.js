// BWV 1087 Canon 3 - Variation: The Dance Begins

let ghostPiano = x => x
  .sound("triangle")
  .gain(0.14)
  .attack(0.001)
  .decay(0.25)
  .sustain(0.4)
  .release(0.6)
  .lpf(2800)
  .lpq(4)
