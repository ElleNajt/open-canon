// BWV 1087 Canon 3 - Variation: Midnight Carnival

let glassMarimba = x => x
  .sound("sine")
  .gain(0.2)
  .attack(0.002)
  .decay(0.4)
  .sustain(0.1)
  .release(1.8)
  .fmi(8)
  .fmh(3)
  .fmdecay(0.15)
  .lpf(5000)
  .room(0.7)
  .delay(0.35)
  .delaytime(0.166)
  .delayfeedback(0.45)

let darkVelvet = x => x
  .sound("sawtooth")
  .gain(0.1)
  .attack(1.5)
  .decay(2)
  .sustain(0.6)
  .release(3)
  .lpf(600)
  .lpq(3)
  .room(0.75)

setcps(92/60/4)

// Track 1 - melody now minor, restless, leaping sevenths
$: note("d5 ~ cs6 ~ a5 ~ ~ g5 f5 ~ e5 ~ ~ d5 ~ bf5")
  .slow(4)
  .apply(glassMarimba)
  .pan(0.3)
  .every(4, x => x.rev().sub(5))
  .sometimes(x => x.octave(5).fmi(12))

// Track 2 - harmony darkens to phrygian, descending by minor seconds
$: note("<d3 a3> <cs3 gs3> <c3 g3> <b2 fs3> <bf2 f3>")
  .slow(8)
  .apply(darkVelvet)
  .pan(0.7)
  .jux(x => x.sub(12).lpf(300))

// Track 3 - TRANSFORMED: nervous ticking clock, 7/8 feel against 4
$: note("d4 ~ d4 d4 ~ d4 d4 ~ ~ d4 d4 ~ d4 ~ ~")
  .fast(1.75)
  .sound("square")
  .gain(0.09)
  .attack(0.001)
  .decay(0.04)
  .sustain(0.02)
  .release(0.15)
  .lpf(1800)
  .hpf(800)
  .room(0.3)
  .delay(0.4)
  .delaytime(0.071)
  .delayfeedback(0.5)
  .pan(0.45)

// Track 4 - bass now prowls in tritones, unsettling
$: note("d2 ~ ~ gs2 ~ ~ d2 ~ a1 ~ ~ eb2 ~ ~ d2 ~")
  .slow(2)
  .sound("triangle")
  .gain(0.16)
  .attack(0.02)
  .decay(0.3)
  .sustain(0.4)
  .release(0.6)
  .lpf(350)
  .room(0.25)
  .pan(0.5)

// Track 5 - DROPPED clicks, ADDED: ghostly whispered bells
$: note("~ a6 ~ ~ d7 ~ ~ fs6 ~ ~ ~ cs7 ~ ~ a6 ~")
  .slow(4)
  .sound("sine")
  .gain(0.06)
  .attack(0.001)
  .decay(0.5)
  .sustain(0.0)
  .release(2)
  .fmi(2)
  .fmh(9)
  .room(0.95)
  .hpf(4000)
  .pan(rand.range(0.2, 0.8))
  .degradeBy(0.4)

// Track 6 - arpeggios now diminished, spiraling downward
$: note("d5 bf4 fs4 d4 bf3 fs3 d3 bf3 fs4 d4 bf4 fs4 d5 ~ ~ ~")
  .slow(2.5)
  .sound("sine")
  .gain(0.08)
  .attack(0.01)
  .decay(0.12)
  .sustain(0.2)
  .release(0.5)
  .fmi(4)
  .fmh(5)
  .lpf(3500)
  .room(0.55)
  .delay(0.6)
  .delaytime(0.083)
  .delayfeedback(0.55)
  .pan(sine.range(0.2, 0.8).slow(6))

// Track 7 - DROPPED birdsong, ADDED: low growling drone, menacing
$: note("d1")
  .slow(8)
  .sound("sawtooth")
  .gain(0.07)
  .attack(4)
  .decay(2)
  .sustain(0.9)
  .release(4)
  .lpf(sine.range(80, 200).slow(16))
  .distort(0.15)
  .room(0.4)
  .pan(0.5)

// Track 8 - companion now echoes in canon, 3 beats late, inverted
$: note("~ ~ a4 gs4 ~ ~ cs5 ~ d5 cs5 ~ ~ gs4 a4 ~ ~")
  .slow(4)
  .late(0.375)
  .sound("pulse")
  .gain(0.1)
  .attack(0.02)
  .decay(0.2)
  .sustain(0.25)
  .release(0.8)
  .lpf(2000)
  .room(0.6)
  .pan(0.4)
  .sub(note("<0 -3 -7 -2>").slow(12))

// Track 9 - string pad shifts to whole-tone, dreamlike confusion
$: note("<d3 e3 fs3> <gs3 as3 c4>")
  .slow(12)
  .sound("triangle")
  .gain(0.07)
  .attack(2.5)
  .decay(3)
  .sustain(0.75)
  .release(4)
  .lpf(900)
  .lpq(2)
  .room(0.85)
  .pan(0.5)

// Track 10 - NEW: distant carnival organ, warped and woozy
$: note("d4 fs4 a4 d5 ~ cs5 a4 fs4 ~ ~ e4 g4 bf4 ~ ~ ~")
  .slow(6)
  .sound("square")
  .gain(0.06)
  .attack(0.05)
  .decay(0.3)
  .sustain(0.4)
  .release(1)
  .lpf(cosine.range(800, 2000).slow(10))
  .fmi(1)
  .fmh(2)
  .room(0.8)
  .delay(0.5)
  .delaytime(0.333)
  .delayfeedback(0.4)
  .pan(tri.range(0.3, 0.7).slow(8))