// BWV 1087 Canon 3 - Variation: The Awakening Storm

let bellTone = x => x
  .sound("triangle")
  .gain(0.32)
  .attack(0.001)
  .decay(0.3)
  .sustain(0.15)
  .release(0.8)
  .lpf(5200)
  .room(0.5)
  .delay(0.35)
  .delaytime(0.125)
  .delayfeedback(0.45)

let organSwell = x => x
  .sound("sawtooth")
  .gain(0.18)
  .attack(0.8)
  .decay(0.6)
  .sustain(0.7)
  .release(2.5)
  .lpf(950)
  .lpq(2)
  .room(0.85)

setcps(96/60/4)

// Track 1 - melody transformed: phrygian urgency, climbing desperation
$: note("e5 f5 g5 ~ a5 b5 ~ c6 b5 a5 ~ g5 f5 e5 ~ ~")
  .slow(3)
  .apply(bellTone)
  .pan(0.35)
  .every(4, x => x.add(5).fast(1.5))
  .sometimes(x => x.octave(6).gain(0.2))

// Track 2 - harmony darkens: minor seconds grinding like thunder
$: note("<e3 f3> <a3 bb3> <d3 eb4> <g3 ab3>")
  .slow(6)
  .apply(organSwell)
  .pan(0.65)
  .jux(x => x.add(12).slow(2))

// Track 3 - pulse becomes driving rain, relentless sixteenths
$: note("e4 e4 g4 e4 a4 e4 b4 e4 c5 b4 a4 g4 e4 d4 e4 ~")
  .fast(2)
  .sound("pulse")
  .gain(0.18)
  .attack(0.002)
  .decay(0.08)
  .sustain(0.05)
  .release(0.15)
  .fmi(2.5)
  .fmh(4)
  .fmdecay(0.05)
  .lpf(sine.range(1200, 3500).slow(8))
  .room(0.25)
  .pan(saw.range(0.2, 0.8).slow(4))

// Track 4 - REPLACED: lightning strikes, harsh stabs piercing texture
$: note("~ ~ ~ e6 ~ ~ ~ ~ ~ ~ b6 ~ ~ ~ ~ ~")
  .slow(4)
  .sound("square")
  .gain(0.12)
  .attack(0.001)
  .decay(0.05)
  .sustain(0)
  .release(0.3)
  .lpf(8000)
  .hpf(2000)
  .distort(0.3)
  .delay(0.8)
  .delaytime(0.0625)
  .delayfeedback(0.7)
  .pan(rand)

// Track 5 - birdsong becomes warning cries, chromatic alarm
$: note("e7 eb7 e7 f7 ~ e7 eb7 d7 ~ ~ e7 f7 ~ ~ ~ ~")
  .slow(5)
  .sound("sine")
  .gain(0.08)
  .attack(0.005)
  .decay(0.1)
  .sustain(0.15)
  .release(0.5)
  .lpf(5500)
  .hpf(1800)
  .tremolo(0.8)
  .tremolosync(6)
  .delay(0.4)
  .delaytime(0.0833)
  .delayfeedback(0.5)
  .pan(0.15)
  .room(0.4)

// Track 6 - drone fractures: pedal point with dissonant overtones
$: note("e2 ~ f2 ~ e2 ~ eb2 ~ e2 ~ ~ ~ d2 ~ e2 ~")
  .slow(16)
  .sound("sawtooth")
  .gain(0.22)
  .attack(1.5)
  .decay(1.5)
  .sustain(0.6)
  .release(4)
  .lpf(280)
  .lpenv(4)
  .lpdecay(3)
  .fmi(0.5)
  .fmh(1)
  .room(0.9)
  .pan(0.5)

// Track 7 - NEW: wind howl, filtered noise sweeping through
$: sound("sine")
  .freq(rand.range(80, 160))
  .gain(0.07)
  .attack(0.5)
  .decay(1)
  .sustain(0.3)
  .release(2)
  .lpf(cosine.range(150, 600).slow(12))
  .lpq(8)
  .room(0.95)
  .pan(sine.range(0.1, 0.9).slow(7))
  .slow(8)

// Track 8 - NEW: heartbeat beneath chaos, primal pulse
$: sound("sine")
