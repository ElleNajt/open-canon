// Track 6 - bass becomes a phrygian descent, heavier steps
$: note("e1 ~ f1 ~ g1 ~ a1 ~ ~ b1 ~ a1 ~ g1 ~ f1")
  .slow(16)
  .sound("sawtooth")
  .gain(0.2)
