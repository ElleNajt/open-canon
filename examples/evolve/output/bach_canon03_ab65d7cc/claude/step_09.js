// BWV 1087 Canon 3 - Variation: Midnight Processional

let obsidianBell = x => x
  .sound("sine")
  .gain(0.24)
  .attack(0.002)
  .decay(0.5)
  .sustain(0.08)
  .release(3)
  .fmi(3.5)
  .fmh(5)
  .fmdecay(0.35)
  .lpf(4200)
  .room(0.9)
  .delay(0.5)
  .delaytime(0.333)
  .delayfeedback(0.55)

let monasticDrone = x => x
  .sound("sawtooth")
  .gain(0.1)
  .attack(3)
  .decay(2)
  .sustain(0.8)
  .release(5)
  .lpf(280)
  .lpq(4)
  .room(0.95)

setcps(54/60/4)

// Track 1 - melody now phrygian, more ancient and mournful
$: note("e5 f5 ~ d5 ~ c5 b4 ~ a4 ~ ~ g4 a4 ~ b4 ~")
  .slow(6)
  .apply(obsidianBell)
  .pan(0.4)
  .every(3, x => x.sub(7).slow(1.3))
  .sometimes(x => x.octave(5).gain(0.2))

// Track 2 - harmony: open fifths and tritones, darker tension
$: note("<e2 b2> <f2 c3> <d2 a2> <g2 cs3>")
  .slow(12)
  .apply(monasticDrone)
  .pan(0.6)
  .jux(x => x.add(7).attack(5))

// Track 3 - REPLACED arpeggios with tolling metallic chimes
$: note("e3 ~ b3 ~ e3 ~ ~ ~ f3 ~ c4 ~ ~ ~ d3 ~")
  .slow(4)
  .sound("square")
  .gain(0.12)
  .attack(0.001)
  .decay(0.15)
  .sustain(0.05)
  .release(1.2)
  .lpf(1800)
  .hpf(600)
  .fmi(1.5)
  .fmh(4.5)
  .room(0.75)
  .delay(0.55)
  .delaytime(0.25)
  .delayfeedback(0.5)
  .pan(tri.range(0.25, 0.75).slow(9))

// Track 4 - DROPPED choir, ADDED: restless pizzicato shadows
$: note("b2 e3 ~ g3 ~ b2 ~ d3 fs3 ~ a3 ~ e3 ~ ~ ~")
  .slow(2.5)
  .sound("triangle")
  .gain(0.14)
  .attack(0.001)
  .decay(0.1)
  .sustain(0)
  .release(0.3)
  .lpf(2400)
