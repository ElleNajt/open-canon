setcps(66/60/4)

$: note("g3 fs3 e3 d3 b2 c3 d3 g2")
  .slow(4)
  .sound("triangle")
  .gain(0.33)
  .lpf(sine.range(300, 1800).slow(16))
  .shape(0.25)
  .release(1.4)
  .every(4, x=>x.add(12).gain(0.13))

$: note("g4 fs4 e4 d4 b3 c4 d4 g3")
  .slow(4)
  .sound("sine")
  .gain(0.2)
  .fmi(sine.range(0.5, 4).slow(13))
  .fmh(5)
  .release(1.3)
  .sometimes(x=>x.add(7).gain(0.1))

$: note("<[g5,b5,d6] [d5,fs5,a5] [e5,g5,b5] [fs5,a5,cs6] [g5,d6,fs6] [e5,b5,d6] [fs5,c6,e6] [b4,g5,d6]>")
  .slow(4)
  .sound("sine")
  .gain(0.13)
  .attack(0.8)
  .release(3)
  .room(0.7)
  .pan(sine.range(0.15, 0.85).slow(11))

$: note("g2 ~ ~ e2 ~ b1 d2 ~")
  .slow(8)
  .sound("sawtooth")
  .gain(0.22)
  .lpf(sine.range(60, 250).slow(14))
  .shape(0.15)
  .every(3, x=>x.add(note("<0 5 -7>")))

$: note("[~ g4] [~ a4] [b4 c5] [a4 ~] [g4 fs4] [e4 ~] [~ fs4] [g4 ~]")
  .slow(4)
  .sound("triangle")
  .gain(sine.range(0.06, 0.2).slow(12))
  .delay(0.4)
  .delaytime(0.375)
  .delayfeedback(0.55)
  .jux(x=>x.add(note("<5 7 12>")).gain(0.09))

