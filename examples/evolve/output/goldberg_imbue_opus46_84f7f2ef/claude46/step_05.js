setcps(66/60/4)

$: note("g3 fs3 e3 d3 b2 c3 d3 g2")
  .slow(4)
  .sound("triangle")
  .gain(0.31)
  .lpf(sine.range(200, 2200).slow(14))
  .shape(0.3)
  .release(1.6)
  .every(4, x=>x.add(12).gain(0.11))

$: note("g4 fs4 e4 d4 b3 c4 d4 g3")
  .slow(4)
  .sound("sine")
  .gain(0.18)
  .fmi(sine.range(0.3, 6).slow(11))
  .fmh(7)
  .release(1.5)
  .sometimes(x=>x.add(note("<7 12 -5>")).gain(0.09))

