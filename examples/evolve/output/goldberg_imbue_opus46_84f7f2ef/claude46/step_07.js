setcps(66/60/4)

$: note("g3 fs3 e3 d3 b2 c3 d3 g2")
  .slow(4)
  .sound("triangle")
  .gain(0.27)
  .lpf(sine.range(220, 3200).slow(14))
  .shape(0.4)
  .release(2.2)
  .every(3, x=>x.rev().add(note("<0 7 -5>")))

$: note("g4 fs4 e4 d4 b3 c4 d4 g3")
  .slow(4)
  .sound("sine")
  .gain(0.15)
  .fmi(sine.range(0.3, 12).slow(11))
  .fmh(cosine.range(3, 11).slow(7))
  .release(2.4)
  .sometimes(x=>x.add(note("<7 19 -5 24>")).gain(0.06))

