samples('shabda/speech:darkness,future,forever,empty')
setcps(140/60/4)

$: note("[g3? gb3] [e3 ~] [b2 c3?] [d3 g2] a2~")
  .slow(2)
  .s("sawtooth")
  .gain(0.5)
  .shape(0.7)
  .lpf(perlin.range(200, 1000).slow(8))
  .lpq(4)
  .delay(0.2)
  .cut(1)

$: n(perlin.range(0,15).slow(8))
  .scale("g:minor")
  .s("sine")
  .gain(0.3)
  .fmenv(8)
  .fmdecay(0.1)
  .phaser(0.2)
  .delay(0.4)
  .pan(sine.range(0, 1).slow(6))

$: s("bd*2 [bd bd] bd")
  .every(4, fast(2))
  .gain(1)
  .drive(0.4)
  .shape(0.8)
  .penv(-12)
  .lpf(4000)

