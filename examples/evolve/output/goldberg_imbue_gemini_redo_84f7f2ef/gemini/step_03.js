// Goldberg Variations - Ground Bass (BWV 988)
// Evolved techno interpretation

samples('shabda/speech:goldberg,variation,bach')
setcps(120/60/4)

$: note("g3 gb3 e3 d3 b2 c3 d3 g2")
  .slow(2)
  .s("pulse")
  .gain(0.7)
  .shape(0.4)
  .lpf(sine.range(200,800).slow(8))
  .lpq(4)
  .cut(1)

$: note("[g4,b4] d5 <c5 e5>")
  .s("triangle")
  .gain(0.3)
  .room(0.5)
  .pan(sine.range(0.1, 0.9).slow(4))
  .lpf(800)
  .delay(0.4)

$: s("bd*3 [bd bd/2]")
  .gain(1)
  .shape(0.1)
  .drive(0.2)
  .lpf(5000)
  .cut(1)

$: s("hh [sn cp] [hh/2,hh/2] hh cp")
  .gain(0.7)
  .hpf(1500)
  .crush(5)
  .room(0.2)
  .pan(rand.range(0.4, 0.6))

$: n(perlin.range(0, 12))
  .slow(8)
  .scale("g:minor")
  .s("supersaw")
  .gain(0.15)
  .release(2)
  .lpf(perlin.range(400, 2000).slow(13))
  .room(0.6)
  .delay(0.2)

$: s("goldberg <variation ~> bach")
  .slow(16)
  .gain(0.8)
  .begin(perlin.range(0, 0.2))
  .speed(perlin.range(0.5, 1.5))
  .bpf(cosine.range(600, 2500).slow(6))
  .crush(7)