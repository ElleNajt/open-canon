samples('shabda/speech:goldberg,variation,bach,endless')
setcps(130/60/4)

$: note("g3 gb3 e3 d3 b2 c3 d3 g2")
  .slow(2)
  .s("pulse")
  .gain(0.6)
  .shape(0.4)
  .lpf(saw.range(300, 1500).slow(4))
  .room(0.2)
  .cut(1)

$: note("<g4 b4 d5> <c5 a4 c5>")
  .euclid(7, 12)
  .s("sine")
  .gain(0.4)
  .fm(2)
  .delay(0.5)
  .dfb(0.5)
  .pan(sine.range(0.2, 0.8).slow(3))

$: s("bd*2 [bd,bd/2]")
  .gain(0.9)
  .shape(0.1)
  .crush(8)
  .hpf(40)
  .room(0.05)
  .cut(1)

$: s("[hh*2, <sn cp>]")
  .ply(perlin.range(1,3).round().slow(2))
  .gain(0.5)
  .hpf(4000)
  .crush(5)
  .delay(0.4)
  .dt(0.125)

$: n(perlin.range(-2, 10))
  .scale("G:minor")
  .slow(16)
  .s("supersaw")
  .gain(0.2)
  .octave(3)
  .vowel("a o u".slow(4))
  .distort(0.2)
  .room(0.6)

$: s("goldberg endless variation bach")
  .slow(8)
  .chop(8)
  .speed(perlin.range(-1.5, 1.5).slow(5))
  .gain(0.7)
  .ringf(sine.range(20, 200).slow(13))
  .pan(perlin.range(0, 1).slow(3))