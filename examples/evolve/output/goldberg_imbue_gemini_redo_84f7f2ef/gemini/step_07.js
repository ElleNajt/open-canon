samples('shabda/speech:goldberg,variation,bach,endless')
setcps(132/60/4)

$: note("g3 gb3 [e3 d3] [b2 c3] d3 [g2 a2]")
  .slow(2)
  .s("square")
  .gain(0.5)
  .distort(0.4)
  .lpf(saw.range(300, 1500).slow(4))
  .lpq(5)
  .cut(1)

$: note("<g4 bb4> d5 [c5 a4] [eb5 g5]")
  .euclid(7,12)
  .s("pulse")
  .gain(0.4)
  .fmi(tri.range(0.1, 8).slow(6))
  .delay(0.3)
  .dfb(0.7)
  .phaser(saw.range(0.1, 4).slow(8))

$: s("bd*2 [~ bd] [bd/2, bd]")
  .gain(0.9)
  .drive(0.3)
  .crush(8)
  .penv(-24)
  .pdecay(0.05)
  .lpf(4000)

$: s("[hh*4, <oh sn?>*2]")
  .every(3, fast(2))
  .gain(0.5)
  .shape(0.5)
  .ringf(perlin.range(100, 500).slow(5))
  .hpf(5000)
  .hpq(6)

$: n(perlin.range(0, 12))
  .scale("G:lydian")
  .slow(12)
  .s("supersaw")
  .gain(0.2)
  .octave(4)
  .lpenv(4000)
  .lpdecay(4)
  .trem(sine.range(0.1, 0.4).slow(12))
  .room(0.8)

