samples('shabda/speech:darkness,future,forever,empty')
setcps(135/60/4)

$: note("[g3 gb3?] [~ e3] b2 [c3? d3] [g2 a2]~")
  .slow(2)
  .s("square")
  .gain(0.6)
  .shape(0.6)
  .lpf(perlin.range(100, 800).slow(8))
  .lpq(6)
  .delay(0.3)

$: n(perlin.range(0,10).slow(12))
  .scale("g:minor")
  .s("triangle")
  .gain(0.25)
  .distort(0.4)
  .phaser(perlin.range(0,0.5).slow(9))
  .fmenv(10)
  .delay(0.4)

$: s("bd*2, [~ bd]")
  .every(4, fast(2))
  .gain(1.1)
  .drive(0.8)
  .crush(8)
  .lpf(1800)

$: s("<[hh cp] [~ sn]>*2")
  .gain(0.7)
  .crush(8)
  .djf(perlin.range(0,1).slow(4))
  .room(0.3)
  .hpf(100)

$: n(perlin.range(0, 7))
  .scale("G:minor")
  .slow(8)
  .s("sawtooth")
  .gain(0.4)
  .octave(4)
  .vowel("a e o u".slow(16))
  .lpq(8)
  .room(0.7)

$: s("darkness [future*2] [forever empty]")
  .slow(8)
