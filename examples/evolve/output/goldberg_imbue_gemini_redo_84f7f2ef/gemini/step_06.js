samples('shabda/speech:goldberg,variation,bach,endless')
setcps(130/60/4)

$: note("g3 ~ gb3 e3 [d3 b2] c3 d3 g2")
  .slow(2)
  .s("sawtooth")
  .gain(0.6)
  .distort(0.2)
  .lpf(perlin.range(200, 1200).slow(8))
  .lpq(4)
  .cut(1)

$: note("[g4,b4] d5 <c5 a4 fs4>")
  .euclid(5, 8)
  .s("pulse")
  .gain(0.5)
  .vowel("e i o".slow(2))
  .delay(0.4)
  .dfb(0.6)

$: s("[bd, bd/2]*2")
  .gain(1)
  .drive(0.5)
  .crush(10)
  .lpf(3000)
  .cut(1)

$: s("[hh*2, <sn? cp?>]")
  .ply(perlin.range(1,2).round().slow(4))
  .gain(0.6)
  .bandf(sine.range(3000, 8000).slow(6))
  .bandq(8)
  .dt("0.125 0.25".fast(2))

$: n(perlin.range(0, 14))
  .scale("G:minor")
  .slow(8)
  .s("supersaw")
  .gain(0.25)
  .octave(4)
  .jux(rev)
  .lpf(800)
  .room(0.7)

$: s("goldberg endless variation bach")
  .slow(12)
  .striate(perlin.range(8, 64).slow(7))
  .speed("1 -1".every(4, rev))
  .gain(0.8)
  .delay(0.3)
  .pan(perlin.range(0, 1).slow(3))