samples('shabda/speech:abyss,silence,fading,endless,time,alone'), samples('shabda/speech/it-IT:eterno'), samples('shabda/speech/de-DE:stille')
setcps(110/60/4)

$: note("<g2 c3> [eb2,f2] ~").slow(4)
  .s("pulse")
  .gain(0.3)
  .lpf(perlin.range(100, 1200).slow(8))
  .lpq(5)
  .shape(0.6)
  .crush(8)
  .room(0.2)

$: n(perlin.range(-5, 5).slow(10))
  .scale("g:phrygian")
  .s("triangle")
  .gain(0.25)
  .bpf(perlin.range(600, 2500).slow(9))
  .delay(0.3)
  .fmi(cosine.range(0, 6).slow(6))
  .fmh(1.5)
  .penv(1000)

$: s("bd")
  .euclid(7, 16).fast(2)
  .cut(1)
  .gain(0.9)
  .compressor("-18:6:2:0.01:0.2")
  .drive(0.5)
  .lpf(perlin.range(700, 2500).slow(13))
  .coarse(perlin.range(5,9).slow(11))
  .room(0.1)

$: s("[hh*2 [~ hh]?, [oh hh] oh]")
  .fast(2)
  .gain(0.3)
  .crush(8)
  .hpf(5000)
  .delay(0.4)
  .pan(tri.range(0.2, 0.8).slow(3))
  .djf(tri.slow(5))

$: note("<g4 cs5 eb5>/2 <f4 ab4 c5>/2")
  .palindrome()
