// Goldberg Variations - Ground Bass (BWV 988)
// Evolved techno interpretation

samples('shabda/speech:goldberg,variation,bach')
setcps(120/60/4)

$: note("g3 gb3 e3 d3 b2 c3 d3 g2")
  .slow(2)
  .s("sawtooth")
  .gain(0.6)
  .drive(0.4)
  .lpf(square.range(200, 1000).slow(6))
  .lpq(8)
  .cut(1)

$: note("[g4,b4] <d5 ~> [c5 e5]")
  .s("sine")
  .gain(0.4)
  .room(0.3)
  .delay(0.6)
  .dt("[0.25 0.125 0.5]/2")

$: s("[bd, bd/2] bd*2")
  .gain(0.9)
  .distort(0.3)
  .crush(6)
  .lpf(2500)
  .cut(1)

$: s("hh*2 [~ sn] [hh cp]/2")
  .gain(0.6)
  .crush(4)
  .hpf(perlin.range(2000, 5000).slow(16))
  .pan(perlin.range(0.2, 0.8).slow(7))
  .delay(0.3)

$: n(perlin.range(0, 12))
  .slow(8)
  .scale("g:minor")
  .s("supersaw")
  .gain(0.2)
  .release(3)
  .phaser(sine.range(0.1, 1).slow(13))
  .lpf(1500)

$: s("goldberg variation bach").every(3, rev).palindrome()
  .slow(8)
  .gain(0.8)
  .speed(perlin.range(-1, 1).slow(5))
  .striate(cosine.range(16, 64).slow(11))
  .delay(0.4)
  .dfb(0.6)