samples('shabda/speech:abyss,silence,fading,endless,time,alone'), samples('shabda/speech/it-IT:eterno'), samples('shabda/speech/de-DE:stille'), samples('shabda/speech/ja-JP:yami')
setcps(96/60/4)

$: note("[c2, eb2, gb2, a2].euclid(5,8)").slow(4)
  .s("sawtooth")
  .gain(0.2)
  .distort(0.4)
  .lpf(perlin.range(300, 800).slow(16))
  .delay(0.5)
  .room(0.2)
  .hpf(100)

$: n("<0 5 11 3> <7 12 10 5>").iter(2).slow(16)
  .scale("c:minor")
  .octave(4)
  .s("sine")
  .fmi(cosine.range(0.5, 4).slow(8))
  .gain(0.1)
  .slide(0.05)
  .delay(0.5)
  .room(0.4)
  .pan(sine.range(0.1, 0.9).slow(12))

$: s("bd").euclid(5,13).slow(2)
  .cut(1)
  .gain(0.9)
  .shape(0.5)
  .distort(0.2)
  .bpf(90)
  .bpq(3)
  .compressor("-20:4:2:0.02:0.2")

$: s("[sn, {hh oh}?]*8").fast(4).degradeBy(0.1)
  .gain(0.1)
  .pan(perlin.range(0, 1).slow(9))
  .hpf(2000)
  .phaser(sine.range(0.1, 8).slow(6))
  .room(0.2)
  .off(0.125, s => s.speed(0.5))

$: note("g3 c4 a3 d4").chord("m9sus4").slow(16)
  .s("supersaw")
  .gain(0.15)
  .lpf(800)
  .leslie(sine.range(1, 8).slow(16))
  .distort(0.1)
  .delay(0.4)
  .room(0.6)

