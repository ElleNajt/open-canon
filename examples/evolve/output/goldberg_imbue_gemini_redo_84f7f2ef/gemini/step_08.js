samples('shabda/speech:goldberg,variation,bach,endless')
setcps(132/60/4)

$: note("g3? gb3 [e3 ~] [b2 c3?] d3 [g2 a2]~")
  .slow(2)
  .s("sawtooth")
  .gain(0.5)
  .shape(0.6)
  .lpf(perlin.range(200, 1200).slow(6))
  .lpq(7)
  .cut(1)

$: n(perlin.range(0,12).slow(4))
  .scale("g:minor")
  .s("sine")
  .gain(0.4)
  .fmenv(8)
  .fmdecay(0.1)
  .vowel("a e i o u".slow(4))
  .delay(0.4)
  .dfb(0.6)

$: s("bd*4")
  .every(4, fast(2))
  .gain(1)
  .drive(0.5)
  .coarse(8)
  .penv(-12)
  .pdecay(0.08)
  .lpf(3000)

$: s("[cp*2 mt, <cb? rim>*2]")
  .every(5, rev)
  .gain(0.6)
  .crush(12)
  .bpf(perlin.range(1000, 8000).slow(8))
  .bpq(8)

