samples('shabda/speech:alone,silence,abyss,fading,endless,time')
setcps(120/60/4)

$: note("g2 ~ c3 eb2 ~").slow(4)
  .s("pulse")
  .gain(0.35)
  .lpf(perlin.range(100, 800).slow(8))
  .lpq(6)
  .crush(6)
  .room(0.4)

$: n(perlin.range(-7, 7).slow(8))
  .scale("g:minor")
  .s("triangle")
  .gain(0.3)
  .penv(12)
  .djf(tri.range(0.1, 0.9).slow(6))
  .delay(0.2)
  .pan(perlin.range(0.1, 0.9).slow(10))

$: s("bd")
  .euclid(7,16)
  .cut(1)
  .gain(0.9)
  .crush(5)
  .shape(0.2)
  .lpf(2000)
  .room(0.2)

$: s("hh*4 [~ hh [hh/2 hh/4]]")
  .fast(2)
  .gain(0.4)
  .crush(8)
  .hpf(3000)
  .delay(0.5)
  .pan(perlin.range(0.3, 0.7).slow(12))

$: note("<g4 c5 d5> <c4 f4 g4>")
  .palindrome()
  .slow(8)
  .s("sawtooth")
  .gain(0.2)
  .lpf(sine.range(400, 2000).slow(10))
  .detune(12)
  .tremolo(0.4)
  .room(0.5)

$: s("[abyss silence] [fading endless] ~ [time alone]")
  .slow(16)
  .striate(perlin.range(8, 32).slow(8))
  .gain(0.6)
  .vowel("<e o a u>")
  .room(0.8)
  .pan(sine.slow(6))