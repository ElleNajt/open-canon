setcps(128/60/4)
samples('shabda/speech/en-GB/m:process,data,system,compute,control')

$: note("g2 [c3 eb3] g2 [f2 bb2]".slow(2))
  .sound("pulse")
  .gain(0.35)
  .lpf(perlin.slow(6).range(200, 2500))
  .lpq(6)
  .drive(0.4)
  .slide(0.02)

$: note("[c4 g3 eb4] [d4 <c4 g3> d4]?".palindrome())
  .fast(8)
  .sound("triangle")
  .gain(0.2)
  .penv(4)
  .pdecay(0.2)
  .delay(0.4)
  .lpf(1500)
  .distort(0.1)

$: s("bd [~ bd] bd [~ bd bd?]?".slow(2))
  .gain(0.9)
  .compressor("-24:6:2:0.01:0.3")
  .crush(6)
  .cutoff(3000)
  .hpf(40)

$: s("<hh*3 oh cr oh*3 hh>".fast(8))
  .gain(0.35)
  .bpf(perlin.slow(16).range(6000, 14000))
  .bpq(5)
  .delay(0.3)
  .pan(saw.range(0.2, 0.8).fast(2))

$: note("<g2 c4 eb4 g4> <f2 bb3 d4 f4> <d2 g3 a3 d4> <c2 f3 a3 c4>".slow(8))
  .sound("supersaw")
  .gain(0.25)
  .attack(1)
  .release(3)
  .room(0.8)
  .vowel(sine.slow(16).range(0,4))

