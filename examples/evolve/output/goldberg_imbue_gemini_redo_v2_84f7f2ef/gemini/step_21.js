setcps(128/60/4)
samples('shabda/speech/en-GB/m:process,data,system,compute,control')

$: note("[g2, g2 g2?] c3 [eb3, d3] [f2, f2 bb2, d3]".slow(4))
  .sound("sawtooth")
  .shape(0.3)
  .vowel("a o u".slow(2))
  .gain(0.35)
  .delay(0.25)

$: note("[c5, eb5 g5] [d5, f5 a5]".palindrome().fast(2))
  .sound("sine")
  .gain(0.15)
  .fmi(perlin.slow(4).range(1, 10))
  .penv(12)
  .pan(perlin.slow(8).range(0.1,0.9))

$: s("bd").euclid(7, 16)
  .gain(0.9)
  .coarse(12)
  .shape(0.5)
  .distort(0.2)
  .hpf(80)

$: s("[hh*2, mt] [~, cr?]".euclid(11, 16).fast(2))
  .gain(0.5)
  .chop(cosine.range(16, 64).slow(4))
  .delay(0.2)
  .hpf(7000)
  .pan(perlin.slow(8).range(0.2, 0.8))

$: note("<c3 g4 eb5> <g3 d4 bb4> <ab3 c4 eb5> <f3 ab4 c5>".slow(4).iter(1))
  .sound("supersaw")
  .gain(0.25)
  .release(2.5)
  .room(0.5)
  .lpf(sine.slow(8).range(1000, 4000))

$: s("system? <control data> [compute process]".sometimes(rev).slow(2))
  .gain(0.7)
  .speed(perlin.slow(4).range(0.8, 1.2))
  .delay(0.4)
  .bpf(cosine.range(500, 4000).slow(8))
