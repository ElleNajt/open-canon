setcps(124/60/4)
samples('shabda/speech:evolve,structure,glitch,sound')

$: note("<g2 b2 d3 eb3>.euclid(5,8)")
  .slow(4)
  .sound("pulse")
  .gain(0.4)
  .shape(0.5)
  .lpf(sine.slow(12).range(300,1500))
  .lpq(7)

$: note("[g4,b4] [d5,f5]?".palindrome())
  .fast(2)
  .sound("triangle")
  .gain(rand.range(0.1, 0.25))
  .penv(10)
  .pdecay(0.05)
  .delay(0.4)
  .dt(1/6)

$: s("[bd, bd [~ bd]]*2")
  .gain(0.9)
  .distort(0.3)
  .shape(0.6)
  .crush(perlin.slow(4).range(5,8))
  .compressor("threshold:-18:ratio:6:knee:5:attack:0.01:release:0.3")

$: s("<hh*3 oh>").fast(4)
  .gain(0.35)
  .hpf(7000)
  .crush(8)
  .delay(0.2)
  .dfb(0.5)

$: note("g2 c3 d3 <f2 bb2>")
  .slow(4)
  .sound("supersaw")
  .gain(0.3)
  .bpf(saw.range(400, 2500).slow(8))
  .bpq(9)
  .room(0.6)

$: s("<evolve structure glitch sound>").slow(4)
  .sometimesBy(0.2, p => p.speed(-1))
  .chop(perlin.range(8, 32).slow(4))
  .gain(0.5)
  .vowel("a e i o u".slow(2))
  .delay(0.5)
  .dfb(0.7)