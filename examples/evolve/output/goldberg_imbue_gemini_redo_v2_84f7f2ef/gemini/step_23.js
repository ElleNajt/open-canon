setcps(130/60/4)
samples('shabda/speech/en-GB/m:process,data,system,compute,control,algorithm,network,binary,signal')

$: note("[g2, g2 g2?] c3 [eb3, d3] [f2, f2 bb2, d3]".slow(4).every(4, rev))
  .sound("sawtooth")
  .shape(perlin.range(0.1, 0.4))
  .gain(0.4)
  .lpf(perlin.slow(8).range(400, 2000))
  .lpq(4)
  .delay(0.25)

$: note("[c5, g5 bb5] [d5, a5 c6]".palindrome().fast(2))
  .sound("supersaw")
  .gain(0.15)
  .phaser(sine.range(0.1, 8).slow(6))
  .pan(perlin.slow(10).range(0.1,0.9))
  .room(0.4)
  .hpf(perlin.slow(16).range(200, 500))

$: s("bd*4").every(8, fast(2))
  .gain(1)
  .drive(0.5)
  .hpf(60)
  .shape(0.3)
  .cutoff(4000)

$: s("[hh*3, oh] hh [hh, oh] hh")
  .gain(0.5)
  .crush(sine.slow(6).range(7, 12))
  .hpf(7000)
  .delay(0.1)
  .pan(perlin.slow(4).range(0.3, 0.7))

$: note("<c3 g4 eb5> <g3 d4 bb4> <ab3 c4 eb5> <f3 ab4 c5>".slow(4).iter(1))
  .sound("supersaw")
  .gain(0.2)
  .detune(perlin.slow(12).range(0, 15))
  .room(0.6)
  .lpf(sine.slow(6).range(800, 3000))
  .lpq(7)

$: s("[system, algorithm] ~ [network, data?] ~".slow(4).every(3, rev))
  .gain(0.6)
  .speed(perlin.slow(5).range(0.7, 1.3))
  .vowel("a e i o u".slow(3))
  .distort(0.2)
  .cut(1)