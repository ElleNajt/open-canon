setcps(112/60/4)

// Baroque style voices
let upperVoice = x => x
  .sound("triangle")
  .gain(0.42)
  .attack(0.03)
  .decay(0.18)
  .sustain(0.15)
  .release(0.12)
  .lpf(2200)
  .room(0.3)
  .size(0.55)

let lowerVoice = x => x
  .sound("square")
  .gain(0.35)
  .attack(0.01)
  .decay(0.15)
  .sustain(0.18)
  .release(0.1)
  .lpf(1200)
  .room(0.22)
  .size(0.5)

let bassVoice = x => x
  .sound("sine")
  .gain(0.52)
  .attack(0.06)
  .decay(0.25)
  .sustain(0.35)
  .release(0.2)
  .lpf(700)
  .room(0.15)

let innerVoice = x => x
  .sound("sawtooth")
  .gain(0.22)
  .attack(0.08)
  .decay(0.3)
  .sustain(0.2)
  .release(0.18)
  .lpf(900)
  .lpq(4)
  .room(0.35)
  .size(0.6)

// Track 1 - upper voice, slower FM breathing, richer detune
$: note("~!40 d5 ~!7 e5 ~!7 gb5 ~!7 g5 ~!7 b5 ~!7 a5 ~!7 g5 ~!7 d6 ~!7 d5 ~!7 e5 ~!7 gb5 ~!7 g5 ~!7 b5 ~!7 a5 ~!7 g5 ~!7 d6 ~!7 d5 ~!7 e5 ~!7 gb5 ~!7 g5 ~!15")
  .slow(208/8/4)
  .apply(upperVoice)
  .pan(0.22)
  .detune(sine.range(-7, 7).slow(53))
  .fmi(sine.range(0.02, 0.9).slow(67))
  .fmh(5)
  .room(sine.range(0.25, 0.6).slow(43))
  .juxBy(0.3, x => x.late(0.375).gain(0.14).room(0.7).size(0.8).lpf(1400))

// Track 2 - middle voice, phaser sweeps more dramatically, vowel drifts on longer cycle
$: note("~!8 g5 ~!7 gb5 ~!7 e5 ~!7 d5 ~!7 b4 ~!7 c5 ~!7 d5 ~!7 g4 ~!7 g5 ~!7 gb5 ~!7 e5 ~!7 d5 ~!7 b4 ~!7 c5 ~!7 d5 ~!7 g4 ~!7 g5 ~!7 gb5 ~!7 e5 ~!7 d5 ~!7 b4 ~!7 c5 ~!7 d5 ~!7 g4 ~!15")
  .slow(208/8/4)
  .apply(lowerVoice)
  .pan(0.78)
  .vowel(sine.range(0, 1).slow(47))
  .phaser(sine.range(0.08, 0.35).slow(59))
  .phaserdepth(0.85)
  .phasersweep(1200)
  .phasercenter(700)
  .lpf(sine.range(700, 1600).slow(31))

// Track 3 - inner voice, panning widens, filter opens up more
$: note("<b3 c4 d4 b3 a3 g3 e3 fs3>")
  .slow(13)
  .apply(innerVoice)
  .pan(sine.range(0.15, 0.85).slow(41))
  .lpf(sine.range(400, 1800).slow(23))
  .lpq(sine.range(2, 9).slow(37))
  .echo(2, 0.375, 0.32)
  .gain(0.22)

// Track 4 - bass, pitch envelope adds weight, off-voice strengthened
$: note("<g2 g2 d3 a2 c3 d3 e2 b2>")
  .slow(9)
  .apply(bassVoice)
  .pan(0.5)
  .lpf(sine.range(200, 1100).slow(29))
  .lpq(sine.range(1, 8).slow(53))
  .penv(sine.range(-0.5, 1.5).slow(19))
  .pdecay(0.4)
  .off(0.5, x => x.note("<d2 g2 a2 e2 c2 g2 b2 fs2>").gain(0.32).lpf(500).room(0.3).size(0.6).pan(0.45))