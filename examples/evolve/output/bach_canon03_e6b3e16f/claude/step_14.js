// Track 1 - upper voice, slower fmi drift, longer echo tail for cathedral bloom
$: note("~!40 d5 ~!7 e5 ~!7 gb5 ~!7 g5 ~!7 b5 ~!7 a5 ~!7 g5 ~!7 d6 ~!7 d5 ~!7 e5 ~!7 gb5 ~!7 g5 ~!7 b5 ~!7 a5 ~!7 g5 ~!7 d6 ~!7 d5 ~!7 e5 ~!7 gb5 ~!7 g5 ~!15")
  .slow(208/8/4)
  .apply(upperVoice)
  .pan(0.22)
  .detune(sine.range(-8, 8).slow(211))
  .fmi(sine.range(0.0, 1.6).slow(89))
  .fmh(sine.range(1.5, 6).slow(233))
  .fmenv(sine.range(0.0, 0.5).slow(103))
  .fmdecay(0.22)
  .room(sine.range(0.45, 0.92).slow(71))
  .size(sine.range(0.5, 0.9).slow(53))
  .echo(3, 0.75, 0.22)
  .juxBy(0.28, x => x.late(0.375).gain(0.05).room(0.99).size(0.98).lpf(420).pan(0.88))

// Track 2 - lower voice, vowel more languid, leslie gentler, hpf breathes slowly
