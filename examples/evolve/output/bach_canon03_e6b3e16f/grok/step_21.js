// BWV 1087 Canon 3 Refined Evolution

// Refined Baroque voices
let upperVoice = x => x
  .sound("supersaw")
  .gain(0.19)
  .attack(0.03)
  .decay(0.22)
  .sustain(0.5)
  .release(0.55)
  .lpf(sine.range(800,3000).slow(40))
  .lpq(sine.range(3,8).slow(42))
  .hpf(160)
  .room(0.25)
  .delay(0.11)
  .tremolo(0.12)
  .tremolosync(7)
  .tremoloshape("sine")
  .penv(0.025)
  .slide(0.01)
  .fmenv(0.08)
  .fmi(0.1)
  .vowel("e a")
  .compressor()

let lowerVoice = x => x
  .sound("triangle")
  .gain(0.2)
  .decay(0.22)
  .sustain(0.5)
  .detune(-1.2)
  .lpf(saw.range(450,2800).slow(30))
  .hpf(135)
  .room(0.28)
  .delay(0.13)
  .fmi(0.25)
  .fmenv(0.12)
  .vowel("u o")
  .shape(0.06)
  .compressor()

let bassVoice = x => x
  .sound("sine")
  .gain(0.3)
  .lpf(perlin.range(80,650).slow(30))
  .lpq(3.5)
  .hpf(40)
  .attack(0.06)
  .decay(0.26)
  .sustain(0.5)
  .release(0.75)
  .room(0.35)
  .delay(0.16)
  .delaytime(0.3)
  .delayfeedback(0.14)
  .detune(-1.5)
  .tremolo(0.1)
  .tremolosync(6)
  .distort(0.01)
  .penv(0.035)
  .coarse(0.98)
  .shape(0.02)
  .compressor()

setcps(0.6)

// Track 1: Upper
$: note("~*16 d5 ~*3 e5 ~*4 fs5 ~*2 g5 ~*4 b5 ~*2 a5 ~*2 g5 ~*3 d6 ~*2 d5 ~*2 e5 ~*4 fs5 ~*2 g5 ~*4 b5 ~*2 a5 ~*4 g5 ~*2 [d6 c6 b5]")
  .slow(200/8/4)
  .apply(upperVoice)
  .pan(perlin.range(0.25,0.75).slow(42))
  .detune(rand.range(-12,16).slow(30))
  .degradeBy(0.02)
  .every(32, x => x.rev())
  .swing(0.035)

// Track 2: Lower (canon offset)
$: note("~*3 [g5 b5] ~*3 fs5 ~*2 e5 ~*4 d5 ~*2 b4 ~*3 c5 ~*2 d5 ~*4 g4 ~*3 [g5 b5] ~*3 fs5 ~*2 e5 ~*4 d5 ~*2 b4 ~*3 c5 ~*2 d5 ~*4 [g4 fs4 d4]")
  .slow(200/8/4)
  .apply(lowerVoice)
  .off(0.25, x => x)
  .pan(sine.range(0.2,0.6).slow(46))
  .detune(perlin.range(-14,10).slow(34))
  .every(28, x => x.rev())
  .swing(0.035)

// Track 3: Bass
$: note("d2 ~ fs2 g2 ~ a2 ~ b2 g2 fs2 d3 ~ g2 fs2 d2 ~ e2 ~ d2 c2 b1 ~ a1 g1 fs1 ~ d2 fs2 a2 g2 bb2")
  .slow(200/16/4)
  .apply(bassVoice)
  .pan(tri.range(0.15,0.65).slow(46))
  .every(16, x => x.rev())
  .swing(0.035)