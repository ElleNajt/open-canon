// BWV 1087 Canon 3 Evolved

// Baroque style voices
let upperVoice = x => x
  .sound("triangle")
  .gain(0.22)
  .attack(0.035)
  .decay(0.24)
  .sustain(0.44)
  .release(0.65)
  .lpf(tri.range(650,3500).slow(40))
  .lpq(sine.range(3,8).slow(45))
  .hpf(160)
  .room(0.24)
  .delay(0.11)
  .tremolo(0.12)
  .tremolosync(7)
  .tremoloshape("tri")
  .penv(0.035)
  .slide(0.01)
  .ring(0.06)
  .fmenv(0.08)
  .fmi(0.1)
  .vowel("a e")
  .phaser(sine.range(0.2,0.6).slow(12))
  .compressor()

let lowerVoice = x => x
  .sound("square")
  .gain(0.24)
  .decay(0.23)
  .sustain(0.47)
  .detune(1.2)
  .lpf(saw.range(350,2800).slow(32))
  .hpf(135)
  .room(0.26)
  .delay(0.13)
  .fmi(0.35)
  .fmenv(0.16)
  .vowel("o u")
  .shape(0.09)
  .compressor()

let bassVoice = x => x
  .sound("saw")
  .gain(0.34)
  .lpf(perlin.range(100,750).slow(24))
  .lpq(3.5)
  .hpf(40)
  .attack(0.045)
  .decay(0.27)
  .sustain(0.51)
  .release(0.65)
  .room(0.27)
  .delay(0.13)
  .delaytime(0.27)
  .delayfeedback(0.17)
  .detune(-1.9)
  .tremolo(0.12)
  .tremolosync(4)
  .distort(0.02)
  .penv(0.035)
  .coarse(0.96)
  .leslie(sine.range(0.2,0.5).slow(20))
  .compressor()

setcps(0.62)

// Track 1: Upper
$: note("~*16 d5 ~*3 e5 ~*4 fs5 ~*2 g5 ~*4 b5 ~*2 a5 ~*2 g5 ~*3 d6 ~*2 d5 ~*2 e5 ~*4 fs5 ~*2 g5 ~*4 b5 ~*2 a5 ~*4 g5 ~*2 [d6 c6 b5]")
  .slow(200/8/4)
  .apply(upperVoice)
  .pan(perlin.range(0.35,0.85).slow(44))
  .detune(rand.range(-12,16).slow(32))
  .degradeBy(0.03)
  .every(32, x => x.rev())
  .swing(0.05)

// Track 2: Lower (longer canon offset)
$: note("~*3 [g5 b5] ~*3 fs5 ~*2 e5 ~*4 d5 ~*2 b4 ~*3 c5 ~*2 d5 ~*4 g4 ~*3 [g5 b5] ~*3 fs5 ~*2 e5 ~*4 d5 ~*2 b4 ~*3 c5 ~*2 d5 ~*4 [g4 fs4 d4]")
  .slow(200/8/4)
  .apply(lowerVoice)
  .off(1/4, x => x)
  .pan(rand.range(0.2,0.8).slow(48))
  .detune(perlin.range(-14,14).slow(36))
  .every(28, x => x.transpose(7))
  .swing(0.05)

// Track 3: Bass
$: note("d2 ~ fs2 g2 ~ a2 ~ b2 g2 fs2 d3 ~ g2 fs2 d2 ~ e2 ~ d2 c2 b1 ~ a1 g1 fs1 ~ d2 fs2 a2 g2 bb2")
  .slow(110/8/4)
  .apply(bassVoice)
  .pan(cosine.range(0.25,0.75).slow(48))
  .every(14, x => x.transpose(7))
  .every(36, x => x.rev())
  .swing(0.05)