// BWV 1087 Canon 3 Evolved

// Baroque style voices
let upperVoice = x => x
  .sound("supersaw")
  .gain(0.26)
  .attack(0.01)
  .decay(0.18)
  .sustain(0.45)
  .release(0.52)
  .lpf(sine.range(700,4000).slow(28))
  .lpq(cosine.range(1.8,9).slow(36))
  .hpf(180)
  .room(0.24)
  .delay(0.12)
  .tremolo(0.11)
  .tremolosync(4)
  .tremoloshape("tri")
  .penv(0.035)
  .slide(0.008)
  .ring(0.07)
  .compressor()

let lowerVoice = x => x
  .sound("triangle")
  .gain(0.28)
  .decay(0.18)
  .sustain(0.5)
  .detune(3)
  .lpf(saw.range(450,2800).slow(24))
  .hpf(140)
  .room(0.28)
  .delay(0.12)
  .leslie(0.24)
  .lrate(0.3)
  .fm(0.2)
  .fmenv(0.11)
  .compressor()

let bassVoice = x => x
  .sound("sine")
  .gain(0.38)
  .lpf(sine.range(240,980).slow(20))
  .hpf(35)
  .attack(0.04)
  .decay(0.3)
  .sustain(0.6)
  .release(0.68)
  .room(0.32)
  .delay(0.15)
  .delaytime(0.25)
  .delayfeedback(0.18)
  .detune(-3)
  .tremolo(0.1)
  .tremolosync(3)
  .distort(0.03)
  .compressor()

setcps(0.55)

// Track 1: Upper
$: note("~*32 d5 ~*5 e5 ~*5 fs5 ~*5 g5 ~*5 b5 ~*5 a5 ~*5 g5 ~*5 d6 ~*5 d5 ~*5 e5 ~*5 fs5 ~*5 g5 ~*5 b5 ~*5 a5 ~*5 g5 ~*5 [d6 c6 b5 a5]")
  .slow(208/8/4)
  .apply(upperVoice)
  .pan(perlin.range(0.3,0.6).slow(36))
  .detune(perlin.range(-14,16).slow(20))
  .every(16, x => x.transpose(12).detune(rand.range(-14,14)))
  .sometimes(x => x.rev())
  .echo(3, 1/16, 0.22)
  .swing(0.05)

// Track 2: Lower (offset evolution)
$: note("~*3 [g5 b5] ~*5 fs5 ~*5 e5 ~*5 d5 ~*5 b4 ~*5 c5 ~*5 d5 ~*5 g4 ~*3 [g5 b5] ~*5 fs5 ~*5 e5 ~*5 d5 ~*5 b4 ~*5 c5 ~*5 d5 ~*5 [g4 fs4]")
  .slow(208/8/4)
  .apply(lowerVoice)
  .pan(perlin.range(0.5,0.8).slow(36))
  .off(0.11, x => x.rev().pan(perlin.range(0.4,0.7).slow(36)))
  .every(16, x => x.transpose(7))
  .swing(0.05)

// Track 3: Bass (enhanced)
$: note("d2~ [fs2 g2]~ [a2 b2]~ [g2 fs2 d3]~ [g2 fs2]~ d2~ [e2 d2 c2]~ [b1 a1 g1] ~ [d2 fs2 a2] ~ [g2 b2 d3]")
  .slow(104/8/4)
  .apply(bassVoice)
  .pan(sine.range(0.36,0.64).slow(36))
  .every(5, x => x.transpose(7))
  .degradeBy(0.06)
  .swing(0.05)