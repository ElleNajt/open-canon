// BWV 1087 Canon 3 Evolved

// Baroque style voices
let upperVoice = x => x
  .sound("sawtooth")
  .gain(0.21)
  .attack(0.018)
  .decay(0.25)
  .sustain(0.4)
  .release(0.55)
  .lpf(sine.range(900,3800).slow(42))
  .lpq(cosine.range(2,8).slow(46))
  .hpf(160)
  .room(0.22)
  .delay(0.1)
  .tremolo(0.12)
  .tremolosync(3.5)
  .tremoloshape("sine")
  .penv(0.045)
  .slide(0.01)
  .ring(0.08)
  .phaser(sine.range(0.3,0.8).slow(16))
  .fmenv(0.06)
  .fmi(0.08)
  .compressor()

let lowerVoice = x => x
  .sound("supersaw")
  .gain(0.23)
  .decay(0.2)
  .sustain(0.48)
  .detune(1.2)
  .lpf(tri.range(450,2800).slow(30))
  .hpf(130)
  .room(0.25)
  .delay(0.11)
  .leslie(0.22)
  .lrate(0.28)
  .fm(0.32)
  .fmenv(0.14)
  .vowel("a e")
  .ring(0.05)
  .compressor()

let bassVoice = x => x
  .sound("sine")
  .gain(0.34)
  .lpf(cosine.range(160,900).slow(26))
  .lpq(2.8)
  .hpf(40)
  .attack(0.045)
  .decay(0.28)
  .sustain(0.5)
  .release(0.68)
  .room(0.3)
  .delay(0.13)
  .delaytime(0.28)
  .delayfeedback(0.15)
  .detune(-2.5)
  .tremolo(0.1)
  .tremolosync(2.8)
  .distort(0.015)
  .penv(0.025)
  .coarse(0.97)
  .compressor()

setcps(0.56)

// Track 1: Upper
$: note("~*24 d5 ~*3 e5 ~*3 fs5 ~*3 g5 ~*3 b5 ~*3 a5 ~*3 g5 ~*3 d6 ~*3 d5 ~*3 e5 ~*3 fs5 ~*3 g5 ~*3 b5 ~*3 a5 ~*3 g5 ~*3 [d6 c6 b5]")
  .slow(210/8/4)
  .apply(upperVoice)
  .pan(perlin.range(0.25,0.75).slow(46))
  .detune(perlin.range(-16,18).slow(30))
  .every(16, x => x.transpose(12).detune(rand.range(-12,12)))
  .palindrome()
  .echo(2, 1/8, 0.18)
  .swing(0.045)

// Track 2: Lower (offset for canon feel)
$: note("~*2 [g5 b5] ~*3 fs5 ~*3 e5 ~*3 d5 ~*3 b4 ~*3 c5 ~*3 d5 ~*3 g4 ~*2 [g5 b5] ~*3 fs5 ~*3 e5 ~*3 d5 ~*3 b4 ~*3 c5 ~*3 d5 ~*3 [g4 fs4 e4]")
  .slow(210/8/4)
  .apply(lowerVoice)
  .off(1/8, x => x)
  .pan(perlin.range(0.35,0.75).slow(46))
  .detune(perlin.range(-14,14).slow(34))
  .every(16, x => x.transpose(7))
  .swing(0.045)

// Track 3: Bass (refined rhythm)
$: note("d2~ [fs2 g2 a2]~ [b2 g2 fs2 d3]~ [g2 fs2 d2]~ e2~ [d2 c2 b1]~ [a1 g1 fs1]~ [d2 fs2 a2 g2 b2]")
  .slow(106/8/4)
  .apply(bassVoice)
  .pan(sine.range(0.3,0.7).slow(46))
  .every(8, x => x.transpose(7))
  .degradeBy(0.05)
  .swing(0.045)