// BWV 1087 Canon 3 Evolved

// Refined Baroque voices
let upperVoice = x => x
  .sound("supersaw")
  .gain(0.2)
  .attack(0.04)
  .decay(0.25)
  .sustain(0.45)
  .release(0.6)
  .lpf(sine.range(700,3200).slow(36))
  .lpq(sine.range(2.5,7).slow(40))
  .hpf(150)
  .room(0.28)
  .delay(0.12)
  .tremolo(0.1)
  .tremolosync(6)
  .tremoloshape("tri")
  .penv(0.03)
  .slide(0.008)
  .ring(0.05)
  .fmenv(0.07)
  .fmi(0.12)
  .vowel("a i")
  .phaser(sine.range(0.25,0.55).slow(14))
  .compressor()

let lowerVoice = x => x
  .sound("triangle")
  .gain(0.22)
  .decay(0.24)
  .sustain(0.48)
  .detune(1.1)
  .lpf(tri.range(400,2600).slow(28))
  .hpf(140)
  .room(0.3)
  .delay(0.14)
  .fmi(0.3)
  .fmenv(0.14)
  .vowel("o a")
  .shape(0.08)
  .compressor()

let bassVoice = x => x
  .sound("sine")
  .gain(0.32)
  .lpf(perlin.range(90,700).slow(28))
  .lpq(3.2)
  .hpf(45)
  .attack(0.05)
  .decay(0.28)
  .sustain(0.52)
  .release(0.7)
  .room(0.32)
  .delay(0.15)
  .delaytime(0.28)
  .delayfeedback(0.16)
  .detune(-1.8)
  .tremolo(0.11)
  .tremolosync(5)
  .distort(0.015)
  .penv(0.04)
  .coarse(0.97)
  .leslie(sine.range(0.25,0.45).slow(24))
  .compressor()

setcps(0.65)

// Track 1: Upper
$: note("~*16 d5 ~*3 e5 ~*4 fs5 ~*2 g5 ~*4 b5 ~*2 a5 ~*2 g5 ~*3 d6 ~*2 d5 ~*2 e5 ~*4 fs5 ~*2 g5 ~*4 b5 ~*2 a5 ~*4 g5 ~*2 [d6 c6 b5]")
  .slow(200/8/4)
  .apply(upperVoice)
  .pan(perlin.range(0.3,0.8).slow(40))
  .detune(rand.range(-10,14).slow(28))
  .degradeBy(0.025)
  .every(28, x => x.rev())
  .swing(0.04)

// Track 2: Lower (canon offset)
$: note("~*3 [g5 b5] ~*3 fs5 ~*2 e5 ~*4 d5 ~*2 b4 ~*3 c5 ~*2 d5 ~*4 g4 ~*3 [g5 b5] ~*3 fs5 ~*2 e5 ~*4 d5 ~*2 b4 ~*3 c5 ~*2 d5 ~*4 [g4 fs4 d4]")
  .slow(200/8/4)
  .apply(lowerVoice)
  .off(1/4, x => x)
  .pan(rand.range(0.15,0.75).slow(44))
  .detune(perlin.range(-12,12).slow(32))
  .every(24, x => x.transpose(7))
  .swing(0.04)

// Track 3: Bass
$: note("d2 ~ fs2 g2 ~ a2 ~ b2 g2 fs2 d3 ~ g2 fs2 d2 ~ e2 ~ d2 c2 b1 ~ a1 g1 fs1 ~ d2 fs2 a2 g2 bb2")
  .slow(200/16/4)
  .apply(bassVoice)
  .pan(cosine.range(0.2,0.7).slow(44))
  .every(12, x => x.transpose(7))
  .every(32, x => x.rev())
  .swing(0.04)