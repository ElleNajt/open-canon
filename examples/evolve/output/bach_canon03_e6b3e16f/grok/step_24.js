// BWV 1087 Canon 3 Evolved

// Refined Baroque voices
let upperVoice = x => x
  .sound("saw")
  .gain(0.16)
  .attack(0.035)
  .decay(0.25)
  .sustain(0.48)
  .release(0.6)
  .lpf(cosine.range(800,2800).slow(40))
  .lpq(perlin.range(2.8,8).slow(48))
  .hpf(150)
  .room(0.24)
  .delay(0.1)
  .tremolo(0.11)
  .tremolosync(7)
  .tremoloshape("tri")
  .penv(0.03)
  .slide(0.008)
  .fmenv(0.09)
  .fmi(0.12)
  .vowel("a e")
  .phaser(0.12)
  .compressor()

let lowerVoice = x => x
  .sound("pulse")
  .gain(0.17)
  .decay(0.25)
  .sustain(0.48)
  .detune(-1.1)
  .lpf(sine.range(450,2600).slow(32))
  .hpf(140)
  .room(0.26)
  .delay(0.12)
  .fmi(0.28)
  .fmenv(0.11)
  .vowel("o u")
  .shape(0.05)
  .leslie(0.2)
  .compressor()

let bassVoice = x => x
  .sound("sine")
  .gain(0.24)
  .lpf(saw.range(55,520).slow(32))
  .lpq(3.8)
  .hpf(38)
  .attack(0.07)
  .decay(0.28)
  .sustain(0.48)
  .release(0.8)
  .room(0.32)
  .delay(0.15)
  .delaytime(0.26)
  .delayfeedback(0.09)
  .detune(-1.4)
  .tremolo(0.09)
  .tremolosync(5.5)
  .distort(0.012)
  .penv(0.04)
  .fmenv(0.11)
  .fmi(0.16)
  .coarse(0.97)
  .shape(0.018)
  .ring(0.035)
  .compressor()

setcps(0.61)

// Track 1: Upper
$: note("~*16 [d5 e5] ~*3 fs5 ~*3 g5 ~*4 b5 ~*2 a5 ~*2 g5 ~*3 [d6 e6] ~*2 d5 ~*2 e5 ~*4 fs5 ~*2 g5 ~*4 b5 ~*2 a5 ~*3 [g5 fs5]")
  .slow(200/8/4)
  .apply(upperVoice)
  .pan(perlin.range(0.3,0.7).slow(45))
  .detune(rand.range(-7,11).slow(32))
  .every(28, x => x.rev())
  .every(56, x => x.transpose(12))
  .swing(0.038)

// Track 2: Lower (canon offset)
$: note("~*2 [g5 b5] ~*4 fs5 ~*2 e5 ~*4 d5 ~*2 b4 ~*3 c5 ~*2 d5 ~*4 g4 ~*3 [g5 b5] ~*3 fs5 ~*2 e5 ~*4 d5 ~*2 b4 ~*3 [c5 d5] ~*3 [g4 fs4 d4]")
  .slow(200/8/4)
  .apply(lowerVoice)
  .off(0.25, x => x)
  .pan(sine.range(0.25,0.55).slow(50))
  .detune(perlin.range(-12,12).slow(36))
  .every(32, x => x.rev())
  .swing(0.038)

// Track 3: Bass
$: note("d2 ~ fs2 g2 ~ a2 ~ b2 g2 fs2 d3 ~ g2 fs2 d2 ~ e2 ~ d2 c2 b1 ~ a1 g1 fs1 ~ [d2 fs2] a2 g2 bb2")
  .slow(200/16/4)
  .apply(bassVoice)
  .pan(tri.range(0.2,0.6).slow(50))
  .every(14, x => x.rev())
  .swing(0.038)

// Track 4: Evolved Perc
$: stack(
  s("~ bd ~ bd").euclid(3,16),
  s("hh*8 ~ hh*8").degradeBy(0.25),
  s("rim").euclid(3,32).late(0.025).gain(0.08)
)
.slow(200/16/4)
.gain(0.1)
.hpf(2900)
.room(0.14)
.delay(0.05)
.pan(sine.range(0.35,0.65).slow(8))
.swing(0.042)
.cut(1)
.every(16, x => x.rev())