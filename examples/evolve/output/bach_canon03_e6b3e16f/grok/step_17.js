// BWV 1087 Canon 3 Evolved

// Baroque style voices
let upperVoice = x => x
  .sound("triangle")
  .gain(0.22)
  .attack(0.025)
  .decay(0.25)
  .sustain(0.42)
  .release(0.55)
  .lpf(sine.range(800,3600).slow(36))
  .lpq(cosine.range(2,8).slow(40))
  .hpf(160)
  .room(0.22)
  .delay(0.1)
  .tremolo(0.12)
  .tremolosync(4)
  .tremoloshape("sine")
  .penv(0.045)
  .slide(0.01)
  .ring(0.08)
  .fmenv(0.06)
  .fmi(0.08)
  .phaser(0.15)
  .compressor()

let lowerVoice = x => x
  .sound("supersaw")
  .gain(0.23)
  .decay(0.2)
  .sustain(0.48)
  .detune(1.2)
  .lpf(tri.range(400,2800).slow(28))
  .hpf(130)
  .room(0.24)
  .delay(0.11)
  .fm(0.32)
  .fmenv(0.14)
  .vowel("e a i")
  .ring(0.05)
  .compressor()

let bassVoice = x => x
  .sound("sine")
  .gain(0.34)
  .lpf(cosine.range(140,900).slow(24))
  .lpq(3)
  .hpf(40)
  .attack(0.045)
  .decay(0.28)
  .sustain(0.5)
  .release(0.65)
  .room(0.3)
  .delay(0.13)
  .delaytime(0.28)
  .delayfeedback(0.15)
  .detune(-2)
  .tremolo(0.1)
  .tremolosync(3)
  .distort(0.015)
  .penv(0.025)
  .coarse(0.98)
  .compressor()

setcps(0.58)

// Track 1: Upper
$: note("~*18 d5 ~*3 e5 ~*4 fs5 ~*2 g5 ~*4 b5 ~*2 a5 ~*2 g5 ~*3 d6 ~*2 d5 ~*2 e5 ~*4 fs5 ~*2 g5 ~*4 b5 ~*2 a5 ~*4 g5 ~*2 [d6 c6 bb5]")
  .slow(200/8/4)
  .apply(upperVoice)
  .pan(perlin.range(0.35,0.7).slow(40))
  .detune(perlin.range(-12,14).slow(28))
  .every(32, x => x.rev())
  .ply(2)
  .swing(0.035)

// Track 2: Lower (offset for canon feel)
$: note("~*3 [g5 b5] ~*3 fs5 ~*2 e5 ~*4 d5 ~*2 b4 ~*3 c5 ~*2 d5 ~*4 g4 ~*3 [g5 b5] ~*3 fs5 ~*2 e5 ~*4 d5 ~*2 b4 ~*3 c5 ~*2 d5 ~*4 [g4 fs4 eb4]")
  .slow(200/8/4)
  .apply(lowerVoice)
  .off(1/8, x => x)
  .pan(perlin.range(0.2,0.65).slow(44))
  .detune(perlin.range(-14,14).slow(32))
  .every(16, x => x.transpose(7))
  .swing(0.035)

// Track 3: Bass (steadier rhythm)
$: note("d2 ~ fs2 g2 ~ a2 ~ b2 g2 fs2 d3 ~ g2 fs2 d2 ~ e2 ~ d2 c2 b1 ~ a1 g1 fs1 ~ d2 fs2 a2 g2 b2")
  .slow(100/8/4)
  .apply(bassVoice)
  .pan(sine.range(0.2,0.8).slow(44))
  .every(8, x => x.transpose(7))
  .swing(0.035)