// BWV 1087 Canon 3 Evolved

// Baroque style voices
let upperVoice = x => x
  .sound("sawtooth")
  .gain(0.21)
  .attack(0.03)
  .decay(0.22)
  .sustain(0.45)
  .release(0.6)
  .lpf(sine.range(700,3400).slow(38))
  .lpq(cosine.range(2.5,7.5).slow(42))
  .hpf(150)
  .room(0.23)
  .delay(0.12)
  .tremolo(0.14)
  .tremolosync(6)
  .tremoloshape("sine")
  .penv(0.04)
  .slide(0.012)
  .ring(0.07)
  .fmenv(0.07)
  .fmi(0.09)
  .vowel("a o")
  .compressor()

let lowerVoice = x => x
  .sound("pulse")
  .gain(0.25)
  .decay(0.22)
  .sustain(0.46)
  .detune(1.1)
  .lpf(saw.range(380,2900).slow(30))
  .hpf(140)
  .room(0.25)
  .delay(0.12)
  .fm(0.34)
  .fmenv(0.15)
  .vowel("e i")
  .shape(0.08)
  .compressor()

let bassVoice = x => x
  .sound("saw")
  .gain(0.33)
  .lpf(perlin.range(130,880).slow(26))
  .lpq(3.2)
  .hpf(45)
  .attack(0.04)
  .decay(0.26)
  .sustain(0.52)
  .release(0.62)
  .room(0.28)
  .delay(0.14)
  .delaytime(0.26)
  .delayfeedback(0.16)
  .detune(-1.8)
  .tremolo(0.11)
  .tremolosync(3.5)
  .distort(0.018)
  .penv(0.03)
  .coarse(0.97)
  .compressor()

setcps(0.6)

// Track 1: Upper
$: note("~*16 d5 ~*3 e5 ~*4 fs5 ~*2 g5 ~*4 b5 ~*2 a5 ~*2 g5 ~*3 d6 ~*2 d5 ~*2 e5 ~*4 fs5 ~*2 g5 ~*4 b5 ~*2 a5 ~*4 g5 ~*2 [d6 c6 b5]")
  .slow(200/8/4)
  .apply(upperVoice)
  .pan(perlin.range(0.4,0.8).slow(42))
  .detune(perlin.range(-11,15).slow(30))
  .every(48, x => x.rev())
  .swing(0.045)

// Track 2: Lower (longer canon offset)
$: note("~*3 [g5 b5] ~*3 fs5 ~*2 e5 ~*4 d5 ~*2 b4 ~*3 c5 ~*2 d5 ~*4 g4 ~*3 [g5 b5] ~*3 fs5 ~*2 e5 ~*4 d5 ~*2 b4 ~*3 c5 ~*2 d5 ~*4 [g4 fs4 d4]")
  .slow(200/8/4)
  .apply(lowerVoice)
  .off(1/4, x => x)
  .pan(perlin.range(0.25,0.75).slow(46))
  .detune(perlin.range(-13,13).slow(34))
  .every(24, x => x.transpose(7))
  .swing(0.045)

// Track 3: Bass
$: note("d2 ~ fs2 g2 ~ a2 ~ b2 g2 fs2 d3 ~ g2 fs2 d2 ~ e2 ~ d2 c2 b1 ~ a1 g1 fs1 ~ d2 fs2 a2 g2 bb2")
  .slow(100/8/4)
  .apply(bassVoice)
  .pan(sine.range(0.3,0.7).slow(46))
  .every(12, x => x.transpose(7))
  .every(32, x => x.rev())
  .swing(0.045)