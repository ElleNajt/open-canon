// BWV 1087 Canon 3 Further Evolved

// Refined Baroque voices
let upperVoice = x => x
  .sound("triangle")
  .gain(0.17)
  .attack(0.045)
  .decay(0.24)
  .sustain(0.48)
  .release(0.6)
  .lpf(sine.range(600,3200).slow(48))
  .lpq(perlin.range(2,10).slow(50))
  .hpf(150)
  .room(0.28)
  .delay(0.1)
  .tremolo(0.15)
  .tremolosync(7)
  .tremoloshape("sine")
  .penv(0.04)
  .slide(0.015)
  .fmenv(0.12)
  .fmi(0.16)
  .vowel("a e i")
  .phaser(0.16)
  .compressor()

let lowerVoice = x => x
  .sound("sawtooth")
  .gain(0.18)
  .attack(0.05)
  .decay(0.25)
  .sustain(0.45)
  .detune(-1)
  .lpf(cosine.range(350,2800).slow(38))
  .hpf(140)
  .room(0.3)
  .delay(0.12)
  .fmi(0.35)
  .fmenv(0.14)
  .vowel("o u")
  .shape(0.08)
  .distort(0.02)
  .compressor()

let bassVoice = x => x
  .sound("supersaw")
  .gain(0.25)
  .lpf(tri.range(45,550).slow(38))
  .lpq(3.5)
  .hpf(35)
  .attack(0.1)
  .decay(0.28)
  .sustain(0.45)
  .release(0.8)
  .room(0.35)
  .delay(0.15)
  .delaytime(0.28)
  .delayfeedback(0.12)
  .detune(-1.8)
  .tremolo(0.12)
  .tremolosync(5.5)
  .distort(0.02)
  .penv(0.05)
  .fmenv(0.15)
  .fmi(0.2)
  .coarse(0.95)
  .shape(0.03)
  .ring(0.05)
  .orbit(2)
  .compressor()

setcps(0.60)

// Track 1: Upper
$: note("~*16 [d5 e5] ~*3 fs5 ~*3 g5 ~*4 b5 ~*2 a5 ~*2 g5 ~*3 [d6 e6] ~*2 d5 ~*2 e5 ~*4 fs5 ~*2 g5 ~*4 b5 ~*2 a5 ~*3 [g5 fs5]")
  .slow(210/8/4)
  .apply(upperVoice)
  .pan(cosine.range(0.25,0.75).slow(48))
  .detune(rand.range(-10,15).slow(38))
  .every(32, x => x.rev())
  .every(70, x => x.transpose(12))
  .swing(0.045)

// Track 2: Lower (canon offset)
$: note("~*2 [g5 b5] ~*4 fs5 ~*2 e5 ~*4 d5 ~*2 b4 ~*3 c5 ~*2 d5 ~*4 g4 ~*3 [g5 b5] ~*3 fs5 ~*2 e5 ~*4 d5 ~*2 b4 ~*3 [c5 d5] ~*3 [g4 fs4 d4]")
  .slow(210/8/4)
  .apply(lowerVoice)
  .off(0.27, x => x)
  .pan(perlin.range(0.2,0.5).slow(58))
  .detune(sine.range(-16,16).slow(42))
  .every(36, x => x.rev())
  .swing(0.045)

// Track 3: Bass
$: note("d2 ~ fs2 g2 ~ a2 ~ b2 g2 fs2 d3 ~ g2 fs2 d2 ~ e2 ~ d2 c2 b1 ~ a1 g1 fs1 ~ [d2 fs2] a2 g2 bb2")
  .slow(210/16/4)
  .apply(bassVoice)
  .pan(saw.range(0.15,0.55).slow(58))
  .every(18, x => x.rev())
  .swing(0.045)

// Track 4: Evolved Perc
$: stack(
  s("bd ~ bd ~").euclid(3,16),
  s("hh*8 ~ hh*8").degradeBy(0.2),
  s("~ sn ~ sn").sometimes(x=>x.gain(0.15).late(0.02)),
  s("cp*2 rim ~ cp").euclid(3,24).late(0.025).gain(0.08)
)
.slow(210/16/4)
.gain(0.1)
.hpf(2800)
.room(0.18)
.delay(0.07)
.pan(cosine.range(0.3,0.7).slow(12))
.swing(0.05)
.cut(1)
.every(24, x => x.speed(rand.range(0.9,1.1)))
.sometimes(x => x.rev())