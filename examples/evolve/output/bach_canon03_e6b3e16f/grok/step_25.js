// BWV 1087 Canon 3 Evolved

// Refined Baroque voices
let upperVoice = x => x
  .sound("supersaw")
  .gain(0.15)
  .attack(0.04)
  .decay(0.22)
  .sustain(0.5)
  .release(0.55)
  .lpf(cosine.range(700,3000).slow(45))
  .lpq(perlin.range(3,9).slow(52))
  .hpf(160)
  .room(0.25)
  .delay(0.09)
  .tremolo(0.12)
  .tremolosync(6.5)
  .tremoloshape("sine")
  .penv(0.035)
  .slide(0.01)
  .fmenv(0.1)
  .fmi(0.14)
  .vowel("e a")
  .phaser(0.14)
  .compressor()

let lowerVoice = x => x
  .sound("square")
  .gain(0.16)
  .decay(0.22)
  .sustain(0.5)
  .detune(-1.2)
  .lpf(sine.range(400,2500).slow(35))
  .hpf(145)
  .room(0.27)
  .delay(0.11)
  .fmi(0.3)
  .fmenv(0.12)
  .vowel("u o")
  .shape(0.06)
  .leslie(0.22)
  .compressor()

let bassVoice = x => x
  .sound("sine")
  .gain(0.22)
  .lpf(saw.range(50,500).slow(35))
  .lpq(4)
  .hpf(40)
  .attack(0.08)
  .decay(0.25)
  .sustain(0.5)
  .release(0.75)
  .room(0.33)
  .delay(0.14)
  .delaytime(0.25)
  .delayfeedback(0.1)
  .detune(-1.5)
  .tremolo(0.1)
  .tremolosync(6)
  .distort(0.015)
  .penv(0.045)
  .fmenv(0.12)
  .fmi(0.18)
  .coarse(0.96)
  .shape(0.02)
  .ring(0.04)
  .orbit(2)
  .compressor()

setcps(0.59)

// Track 1: Upper
$: note("~*16 [d5 e5] ~*3 fs5 ~*3 g5 ~*4 b5 ~*2 a5 ~*2 g5 ~*3 [d6 e6] ~*2 d5 ~*2 e5 ~*4 fs5 ~*2 g5 ~*4 b5 ~*2 a5 ~*3 [g5 fs5]")
  .slow(200/8/4)
  .apply(upperVoice)
  .pan(perlin.range(0.3,0.7).slow(50))
  .detune(rand.range(-8,12).slow(35))
  .every(30, x => x.rev())
  .every(60, x => x.transpose(12))
  .swing(0.04)

// Track 2: Lower (canon offset)
$: note("~*2 [g5 b5] ~*4 fs5 ~*2 e5 ~*4 d5 ~*2 b4 ~*3 c5 ~*2 d5 ~*4 g4 ~*3 [g5 b5] ~*3 fs5 ~*2 e5 ~*4 d5 ~*2 b4 ~*3 [c5 d5] ~*3 [g4 fs4 d4]")
  .slow(200/8/4)
  .apply(lowerVoice)
  .off(0.25, x => x)
  .pan(sine.range(0.25,0.55).slow(55))
  .detune(perlin.range(-14,14).slow(40))
  .every(34, x => x.rev())
  .swing(0.04)

// Track 3: Bass
$: note("d2 ~ fs2 g2 ~ a2 ~ b2 g2 fs2 d3 ~ g2 fs2 d2 ~ e2 ~ d2 c2 b1 ~ a1 g1 fs1 ~ [d2 fs2] a2 g2 bb2")
  .slow(200/16/4)
  .apply(bassVoice)
  .pan(tri.range(0.2,0.6).slow(55))
  .every(16, x => x.rev())
  .swing(0.04)

// Track 4: Evolved Perc
$: stack(
  s("~ bd*2 ~ bd").euclid(4,16),
  s("hh*16").degradeBy(0.15),
  s("~ sn*2").sometimes(x=>x.gain(0.12)),
  s("rim cp").euclid(2,32).late(0.03).gain(0.075)
)
.slow(200/16/4)
.gain(0.095)
.hpf(3000)
.room(0.15)
.delay(0.06)
.pan(sine.range(0.35,0.65).slow(10))
.swing(0.045)
.cut(1)
.every(20, x => x.rev())