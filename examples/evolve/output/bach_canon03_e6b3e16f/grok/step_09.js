// BWV 1087 Canon 3 Evolved

// Baroque style voices
let upperVoice = x => x
  .sound("supersaw")
  .gain(0.26)
  .attack(0.01)
  .decay(0.14)
  .sustain(0.4)
  .release(0.5)
  .lpf(sine.range(900,4500).slow(20))
  .lpq(cosine.range(1.8,12).slow(28))
  .hpf(220)
  .room(0.26)
  .delay(0.12)
  .tremolo(0.14)
  .tremolosync(3.5)
  .penv(0.05)
  .slide(0.012)
  .vowel("e i o a".slow(4))
  .leslie(0.32)
  .fmenv(0.08)
  .compressor()

let lowerVoice = x => x
  .sound("square")
  .gain(0.28)
  .decay(0.14)
  .sustain(0.5)
  .detune(5)
  .lpf(tri.range(650,3200).slow(18))
  .hpf(160)
  .room(0.28)
  .delay(0.12)
  .phaser(0.28)
  .phaserdepth(0.45)
  .phasersweep(0.3)
  .fm(0.25)
  .fmenv(0.14)
  .ring(0.12)
  .compressor()

let bassVoice = x => x
  .sound("sine")
  .gain(0.38)
  .lpf(sine.range(280,1100).slow(14))
  .hpf(45)
  .attack(0.04)
  .decay(0.25)
  .sustain(0.55)
  .release(0.65)
  .room(0.32)
  .delay(0.18)
  .delaytime(0.28)
  .delayfeedback(0.22)
  .detune(-5)
  .tremolo(0.1)
  .tremolosync(3.5)
  .compressor()

let pianoVoice = x => x
  .sound("piano")
  .gain(0.17)
  .attack(0.025)
  .decay(0.22)
  .sustain(0.55)
  .release(0.8)
  .lpf(2800)
  .hpf(90)
  .room(0.32)
  .pan(0.5)
  .compressor()

setcps(0.57)

// Track 1: Upper
$: note("~!32 d5 ~!6 e5 ~!6 fs5 ~!6 g5 ~!6 b5 ~!6 a5 ~!6 g5 ~!6 d6 ~!6 d5 ~!6 e5 ~!6 fs5 ~!6 g5 ~!6 b5 ~!6 a5 ~!6 g5 ~!6 [d6 c6 bb5 a5]")
  .slow(208/8/4)
  .apply(upperVoice)
  .pan(perlin.range(0.3,0.6).slow(28))
  .detune(perlin.range(-14,16).slow(16))
  .every(16, x => x.transpose(12).detune(rand.range(-14,14)))
  .sometimes(x => x.rev())
  .swing(0.025)

// Track 2: Lower (offset evolution)
$: note("~!4 [g5 b5] ~!6 fs5 ~!6 e5 ~!6 d5 ~!6 b4 ~!6 c5 ~!6 d5 ~!6 g4 ~!4 [g5 b5] ~!6 fs5 ~!6 e5 ~!6 d5 ~!6 b4 ~!6 c5 ~!6 d5 ~!6 [g4 fs4]")
  .slow(208/8/4)
  .apply(lowerVoice)
  .pan(perlin.range(0.5,0.8).slow(28))
  .off(0.125, x => x.rev().pan(perlin.range(0.4,0.7).slow(28)))
  .every(16, x => x.transpose(7))
  .swing(0.025)

// Track 3: Bass
$: note("d2~ [fs2 g2]~ [a2 b2]~ [g2 fs2 d3]~ [g2 fs2]~ d2~ [e2 d2 c2]~ [b1 a1 g1]")
  .slow(104/8/4)
  .apply(bassVoice)
  .pan(sine.range(0.35,0.65).slow(28))
  .every(5, x => x.transpose(7))
  .degradeBy(0.1)
  .swing(0.025)

// Track 4: Continuo chords
$: note("d3 [fs3 a3] g3 [b3 d4] a3 [cs4 e4] [g3 fs3 d4] [g3 fs3] d3 [e3 d3 c3] [b2 a2 g2]")
  .slow(104/8/4)
  .apply(pianoVoice)
  .pan(sine.range(0.42,0.58).slow(20))
  .every(6, x => x.transpose(7))
  .sometimes(x => x.rev())
  .swing(0.025)