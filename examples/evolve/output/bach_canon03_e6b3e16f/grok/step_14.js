// BWV 1087 Canon 3 Evolved

// Baroque style voices
let upperVoice = x => x
  .sound("supersaw")
  .gain(0.22)
  .attack(0.015)
  .decay(0.22)
  .sustain(0.42)
  .release(0.52)
  .lpf(sine.range(850,3600).slow(40))
  .lpq(cosine.range(1.8,7.5).slow(44))
  .hpf(150)
  .room(0.2)
  .delay(0.09)
  .tremolo(0.1)
  .tremolosync(4)
  .tremoloshape("tri")
  .penv(0.04)
  .slide(0.008)
  .ring(0.07)
  .phaser(sine.range(0.25,0.75).slow(14))
  .fmenv(0.05)
  .compressor()

let lowerVoice = x => x
  .sound("pulse")
  .gain(0.24)
  .decay(0.18)
  .sustain(0.5)
  .detune(1.5)
  .lpf(saw.range(500,2600).slow(28))
  .hpf(120)
  .room(0.24)
  .delay(0.1)
  .leslie(0.2)
  .lrate(0.25)
  .fm(0.3)
  .fmenv(0.12)
  .vowel("a o")
  .compressor()

let bassVoice = x => x
  .sound("sine")
  .gain(0.35)
  .lpf(sine.range(180,800).slow(24))
  .lpq(2.5)
  .hpf(35)
  .attack(0.04)
  .decay(0.25)
  .sustain(0.52)
  .release(0.65)
  .room(0.28)
  .delay(0.12)
  .delaytime(0.26)
  .delayfeedback(0.14)
  .detune(-3)
  .tremolo(0.09)
  .tremolosync(3)
  .distort(0.01)
  .penv(0.02)
  .compressor()

setcps(0.57)

// Track 1: Upper
$: note("~*24 d5 ~*3 e5 ~*3 fs5 ~*3 g5 ~*3 b5 ~*3 a5 ~*3 g5 ~*3 d6 ~*3 d5 ~*3 e5 ~*3 fs5 ~*3 g5 ~*3 b5 ~*3 a5 ~*3 g5 ~*3 [d6 c6 b5]")
  .slow(208/8/4)
  .apply(upperVoice)
  .pan(perlin.range(0.3,0.7).slow(44))
  .detune(perlin.range(-14,16).slow(28))
  .every(16, x => x.transpose(12).detune(rand.range(-10,10)))
  .sometimes(x => x.rev())
  .echo(2, 1/8, 0.16)
  .swing(0.04)

// Track 2: Lower (offset for canon feel)
$: note("~*2 [g5 b5] ~*3 fs5 ~*3 e5 ~*3 d5 ~*3 b4 ~*3 c5 ~*3 d5 ~*3 g4 ~*2 [g5 b5] ~*3 fs5 ~*3 e5 ~*3 d5 ~*3 b4 ~*3 c5 ~*3 d5 ~*3 [g4 fs4 e4]")
  .slow(208/8/4)
  .apply(lowerVoice)
  .off(1/8, x => x)
  .pan(perlin.range(0.4,0.8).slow(44))
  .detune(perlin.range(-12,12).slow(32))
  .every(16, x => x.transpose(7))
  .swing(0.04)

// Track 3: Bass (refined rhythm)
$: note("d2~ [fs2 g2 a2]~ [b2 g2 fs2 d3]~ [g2 fs2 d2]~ e2~ [d2 c2 b1]~ [a1 g1 fs1] ~ [d2 fs2 a2 g2] ~ [b2 d3]")
  .slow(104/8/4)
  .apply(bassVoice)
  .pan(sine.range(0.35,0.65).slow(44))
  .every(8, x => x.transpose(7))
  .degradeBy(0.04)
  .swing(0.04)