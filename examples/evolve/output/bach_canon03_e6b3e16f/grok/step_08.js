// BWV 1087 Canon 3 Evolved

// Baroque style voices
let upperVoice = x => x
  .sound("supersaw")
  .gain(0.25)
  .attack(0.01)
  .decay(0.12)
  .sustain(0.42)
  .release(0.48)
  .lpf(sine.range(800,4200).slow(16))
  .lpq(cosine.range(2,14).slow(24))
  .hpf(200)
  .room(0.24)
  .delay(0.14)
  .tremolo(0.12)
  .tremolosync(4)
  .penv(0.06)
  .slide(0.015)
  .vowel("e i a o".slow(3))
  .leslie(0.35)
  .compressor()

let lowerVoice = x => x
  .sound("pulse")
  .gain(0.3)
  .decay(0.12)
  .sustain(0.48)
  .detune(4)
  .lpf(tri.range(700,3000).slow(16))
  .room(0.3)
  .delay(0.1)
  .phaser(0.3)
  .phaserdepth(0.5)
  .phasersweep(0.25)
  .fm(0.28)
  .fmenv(0.16)
  .ring(0.15)
  .compressor()

let bassVoice = x => x
  .sound("sine")
  .gain(0.4)
  .lpf(sine.range(300,1200).slow(12))
  .hpf(40)
  .attack(0.035)
  .decay(0.28)
  .sustain(0.52)
  .release(0.7)
  .room(0.34)
  .detune(-4)
  .tremolo(0.12)
  .tremolosync(4)
  .compressor()

setcps(0.56)

// Track 1: Upper
$: note("~!32 d5 ~!6 e5 ~!6 fs5 ~!6 g5 ~!6 b5 ~!6 a5 ~!6 g5 ~!6 d6 ~!6 d5 ~!6 e5 ~!6 fs5 ~!6 g5 ~!6 b5 ~!6 a5 ~!6 g5 ~!6 [d6 c6 b5 a5]")
  .slow(208/8/4)
  .apply(upperVoice)
  .pan(perlin.range(0.28,0.58).slow(24))
  .detune(perlin.range(-16,18).slow(14))
  .every(16, x => x.transpose(12).detune(rand.range(-12,12)))
  .sometimes(x => x.rev())
  .swing(0.02)

// Track 2: Lower (offset evolution)
$: note("~!4 [g5 b5] ~!6 fs5 ~!6 e5 ~!6 d5 ~!6 b4 ~!6 c5 ~!6 d5 ~!6 g4 ~!4 [g5 b5] ~!6 fs5 ~!6 e5 ~!6 d5 ~!6 b4 ~!6 c5 ~!6 d5 ~!6 [g4 fs4]")
  .slow(208/8/4)
  .apply(lowerVoice)
  .pan(perlin.range(0.52,0.82).slow(24))
  .off(1/8, x => x.rev().pan(perlin.range(0.42,0.72).slow(24)))
  .every(16, x => x.transpose(7))
  .swing(0.02)

// Track 3: Bass
$: note("d2~ [fs2 g2]~ [a2 b2]~ [g2 fs2 d3]~ [g2 fs2]~ d2~ [e2 d2 c2]~ [b1 a1 g1]")
  .slow(104/8/4)
  .apply(bassVoice)
  .pan(sine.range(0.32,0.68).slow(24))
  .every(5, x => x.transpose(7))
  .degradeBy(0.08)
  .swing(0.02)

// Track 4: Subtle continuo rhythm
$: s("bd ~ [sn cp] ~ [hh*2 oh]").euclid(7,16).slow(1.5)
  .gain(0.14)
  .room(0.12)
  .lpf(900)
  .hpf(240)
  .pan(sine.range(0.38,0.62).slow(16))
  .sometimes(x => x.speed(0.9))
  .sometimes(x => x.speed(1.1))
  .distort(0.08)
  .swing(0.03)