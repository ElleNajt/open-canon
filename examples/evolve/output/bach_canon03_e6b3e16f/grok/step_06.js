// BWV 1087 Canon 3 Evolved

// Baroque style voices
let upperVoice = x => x
  .sound("triangle")
  .gain(0.26)
  .attack(0.01)
  .decay(0.1)
  .sustain(0.45)
  .release(0.45)
  .lpf(sine.range(900,4200).slow(16))
  .lpq(cosine.range(4,14).slow(24))
  .hpf(180)
  .room(0.22)
  .delay(0.12)
  .tremolo(0.1)
  .tremolosync(5)
  .penv(0.05)
  .slide(0.02)
  .vowel("a e o i".slow(3))

let lowerVoice = x => x
  .sound("pulse")
  .gain(0.34)
  .decay(0.1)
  .sustain(0.45)
  .detune(5)
  .lpf(tri.range(800,3000).slow(16))
  .room(0.28)
  .delay(0.12)
  .phaser(0.3)
  .phaserdepth(0.4)
  .phasersweep(0.2)
  .fm(0.22)
  .fmenv(0.14)

let bassVoice = x => x
  .sound("sine")
  .gain(0.45)
  .lpf(sine.range(350,1100).slow(12))
  .hpf(35)
  .attack(0.03)
  .decay(0.25)
  .sustain(0.55)
  .release(0.65)
  .room(0.32)
  .detune(-5)
  .tremolo(0.1)
  .tremolosync(3.5)

setcps(0.52)

// Track 1: Upper
$: note("~!32 d5 ~!6 e5 ~!6 fs5 ~!6 g5 ~!6 b5 ~!6 a5 ~!6 g5 ~!6 d6 ~!6 d5 ~!6 e5 ~!6 fs5 ~!6 g5 ~!6 b5 ~!6 a5 ~!6 g5 ~!6 [d6 eb6 d6]")
  .slow(208/8/4)
  .apply(upperVoice)
  .pan(perlin.range(0.25,0.55).slow(20))
  .detune(perlin.range(-18,20).slow(12))
  .every(24, x => x.transpose(12).detune(rand.range(-10,10)))
  .sometimes(x => x.rev())

// Track 2: Lower (offset evolution)
$: note("~!4 [g5 b5] ~!6 fs5 ~!6 e5 ~!6 d5 ~!6 b4 ~!6 c5 ~!6 d5 ~!6 g4 ~!4 [g5 b5] ~!6 fs5 ~!6 e5 ~!6 d5 ~!6 b4 ~!6 c5 ~!6 d5 ~!6 g4")
  .slow(208/8/4)
  .apply(lowerVoice)
  .pan(perlin.range(0.55,0.85).slow(20))
  .off(1/8, x => x.rev().pan(perlin.range(0.45,0.75).slow(20)))
  .every(16, x => x.transpose(7))

// Track 3: Bass
$: note("d2~ [fs2 g2]~ [a2 b2]~ [g2 fs2 d3]~ [g2 fs2]~ d2~ [e2 d2 c2]~ [b1 a1]")
  .slow(65/8/4)
  .apply(bassVoice)
  .pan(sine.range(0.3,0.7).slow(20))
  .every(4, x => x.transpose(7))
  .degradeBy(0.1)

// Track 4: Subtle continuo rhythm
$: s("bd ~ [cp rim] ~ [hh*3 oh]").euclid(7,16).slow(1.8)
  .gain(0.16)
  .room(0.15)
  .hpf(220)
  .pan(sine.range(0.35,0.65).slow(12))
  .sometimes(x => x.speed(0.92))
  .sometimes(x => x.speed(1.08))