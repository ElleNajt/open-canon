// BWV 1087 Canon 3 Restrained Evolution

// Refined Baroque voices
let upperVoice = x => x
  .sound("sine")
  .gain(0.17)
  .attack(0.06)
  .decay(0.28)
  .sustain(0.45)
  .release(0.7)
  .lpf(sine.range(600,3600).slow(16))
  .lpq(saw.range(2,12).slow(8))
  .hpf(150)
  .room(0.35)
  .delay(0.12)
  .tremolo(0.2)
  .tremolosync(6)
  .tremoloshape("tri")
  .penv(0.05)
  .accelerate(0.0005)
  .fmenv(0.14)
  .fmi(0.2)
  .vowel("e a o i")
  .leslie(0.25)
  .compressor()

let lowerVoice = x => x
  .sound("pulse")
  .gain(0.18)
  .attack(0.06)
  .decay(0.28)
  .sustain(0.42)
  .detune(-1)
  .lpf(perlin.range(400,3000).slow(36))
  .hpf(140)
  .room(0.36)
  .delay(0.14)
  .fmi(0.42)
  .fmenv(0.16)
  .vowel("o a u")
  .shape(0.1)
  .distort(0.03)
  .phaser(0.2)
  .compressor()

let bassVoice = x => x
  .sound("supersaw")
  .gain(0.24)
  .lpf(tri.range(50,600).slow(36))
  .lpq(4)
  .hpf(35)
  .attack(0.12)
  .decay(0.32)
  .sustain(0.42)
  .release(0.9)
  .room(0.4)
  .delay(0.17)
  .delaytime(0.28)
  .delayfeedback(0.15)
  .detune(-1.8)
  .tremolo(0.15)
  .tremolosync(5.5)
  .distort(0.03)
  .penv(0.06)
  .fmenv(0.17)
  .fmi(0.24)
  .coarse(0.9)
  .shape(0.05)
  .ring(0.07)
  .orbit(2)
  .compressor()

setcps(0.6)

// Track 1: Upper
$: note("~*12 [d5 e5 fs5] ~*2 g5 ~*2 fs5 ~*3 g5 ~*3 b5 ~*2 a5 ~*2 g5 ~*2 [d6 e6] ~*2 d5 ~*2 e5 ~*3 fs5 ~*2 g5 ~*3 b5 ~*2 a5 ~*2 [g5 fs5]")
  .slow(212/8/4)
  .apply(upperVoice)
  .pan(sine.range(0.25,0.75).slow(24))
  .detune(rand.range(-14,20).slow(36))
  .every(24, x => x.rev())
  .every(64, x => x.transpose(12))
  .swing(0.06)

// Track 2: Lower (canon offset)
$: note("~*2 [g5 b5] ~*3 fs5 ~*2 e5 ~*3 d5 ~*2 b4 ~*2 c5 ~*2 d5 ~*3 g4 ~*2 [g5 b5] ~*2 fs5 ~*2 e5 ~*3 d5 ~*2 b4 ~*2 [c5 d5] ~*2 [g4 fs4 d4]")
  .slow(212/8/4)
  .apply(lowerVoice)
  .off(0.25, x => x)
  .pan(perlin.range(0.2,0.5).slow(48))
  .detune(cosine.range(-20,20).slow(42))
  .every(28, x => x.rev())
  .swing(0.06)

// Track 3: Bass
$: note("d2 ~ fs2 g2 ~ a2 ~ b2 g2 fs2 d3 ~ g2 fs2 d2 ~ e2 ~ d2 c2 b1 ~ a1 g1 fs1 ~ [d2 fs2] a2 g2 bb2")
  .slow(212/16/4)
  .apply(bassVoice)
  .pan(tri.range(0.15,0.55).slow(48))
  .every(18, x => x.rev())
  .swing(0.06)

// Track 4: Restrained Perc
$: stack(
  s("bd ~ bd").euclid(3,12),
  s("hh*8").degradeBy(0.3),
  s("~ [rim cp]").sometimes(x=>x.gain(0.14).late(0.02))
)
.slow(212/16/4)
.gain(0.12)
.hpf(2800)
.room(0.25)
.delay(0.09)
.pan(sine.range(0.3,0.7).slow(12))
.swing(0.06)
.cut(1)
.every(24, x => x.speed(rand.range(0.9,1.1)))
.sometimes(x => x.rev())