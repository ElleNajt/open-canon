// BWV 1087 Canon 3 Restrained Evolution

// Refined Baroque voices
let upperVoice = x => x
  .sound("sine")
  .gain(0.16)
  .attack(0.06)
  .decay(0.28)
  .sustain(0.5)
  .release(0.8)
  .lpf(cosine.range(650,3600).slow(24))
  .lpq(tri.range(1.8,9).slow(12))
  .hpf(150)
  .room(0.4)
  .delay(0.12)
  .tremolo(0.2)
  .tremolosync(6)
  .tremoloshape("tri")
  .penv(0.045)
  .accelerate(0.0005)
  .fmenv(0.14)
  .fmi(0.2)
  .vowel("e i a")
  .leslie(0.25)
  .compressor()

let lowerVoice = x => x
  .sound("sawtooth")
  .gain(0.16)
  .attack(0.06)
  .decay(0.28)
  .sustain(0.46)
  .detune(-0.9)
  .lpf(saw.range(420,3000).slow(45))
  .hpf(140)
  .room(0.4)
  .delay(0.14)
  .fmi(0.4)
  .fmenv(0.15)
  .vowel("o u e")
  .shape(0.09)
  .distort(0.03)
  .ring(0.08)
  .compressor()

let bassVoice = x => x
  .sound("triangle")
  .gain(0.21)
  .lpf(perlin.range(55,600).slow(45))
  .lpq(4)
  .hpf(40)
  .attack(0.12)
  .decay(0.32)
  .sustain(0.46)
  .release(1)
  .room(0.45)
  .delay(0.17)
  .delaytime(0.28)
  .delayfeedback(0.2)
  .detune(-1.6)
  .tremolo(0.14)
  .tremolosync(5.5)
  .distort(0.03)
  .penv(0.055)
  .fmenv(0.16)
  .fmi(0.24)
  .coarse(0.9)
  .shape(0.05)
  .compressor()

setcps(0.56)

// Track 1: Upper
$: note("~*12 [d5 e5 fs5] ~*2 g5 ~*2 fs5 ~*3 g5 ~*3 b5 ~*2 a5 ~*2 g5 ~*2 [d6 e6] ~*2 d5 ~*2 e5 ~*3 fs5 ~*2 g5 ~*3 b5 ~*2 a5 ~*2 [g5 fs5]")
  .slow(210/8/4)
  .apply(upperVoice)
  .pan(sine.range(0.35,0.65).slow(32))
  .detune(rand.range(-14,16).slow(48))
  .every(28, x => x.rev())
  .every(72, x => x.transpose(12))
  .swing(0.07)

// Track 2: Lower (canon offset)
$: note("~*2 [g5 b5] ~*3 fs5 ~*2 e5 ~*3 d5 ~*2 b4 ~*2 c5 ~*2 d5 ~*3 g4 ~*2 [g5 b5] ~*2 fs5 ~*2 e5 ~*3 d5 ~*2 b4 ~*2 [c5 d5] ~*2 [g4 fs4 d4]")
  .slow(210/8/4)
  .apply(lowerVoice)
  .off(0.26, x => x)
  .pan(perlin.range(0.3,0.6).slow(56))
  .detune(cosine.range(-20,20).slow(50))
  .every(32, x => x.rev())
  .swing(0.07)

// Track 3: Bass
$: note("d2 ~ fs2 g2 ~ a2 ~ b2 g2 fs2 d3 ~ g2 fs2 d2 ~ e2 ~ d2 c2 b1 ~ a1 g1 fs1 ~ [d2 fs2] a2 g2 bb2")
  .slow(210/16/4)
  .apply(bassVoice)
  .pan(tri.range(0.25,0.55).slow(56))
  .detune(rand.range(-12,12).slow(32))
  .every(20, x => x.rev())
  .swing(0.07)