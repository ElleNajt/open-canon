// BWV 1087 Canon 3 Evolved

// Baroque style voices
let upperVoice = x => x
  .sound("sawtooth")
  .gain(0.25)
  .attack(0.01)
  .decay(0.16)
  .sustain(0.42)
  .release(0.55)
  .lpf(sine.range(800,4200).slow(24))
  .lpq(cosine.range(2,10).slow(32))
  .hpf(200)
  .room(0.25)
  .delay(0.11)
  .tremolo(0.12)
  .tremolosync(4)
  .penv(0.04)
  .slide(0.01)
  .vowel("a e i o u".slow(6))
  .leslie(0.3)
  .fmenv(0.07)
  .compressor()

let lowerVoice = x => x
  .sound("triangle")
  .gain(0.27)
  .decay(0.16)
  .sustain(0.52)
  .detune(4)
  .lpf(saw.range(500,3000).slow(20))
  .hpf(150)
  .room(0.27)
  .delay(0.11)
  .phaser(0.26)
  .phaserdepth(0.42)
  .phasersweep(0.28)
  .fm(0.22)
  .fmenv(0.12)
  .ring(0.1)
  .compressor()

let bassVoice = x => x
  .sound("sine")
  .gain(0.36)
  .lpf(sine.range(260,1050).slow(16))
  .hpf(40)
  .attack(0.045)
  .decay(0.28)
  .sustain(0.58)
  .release(0.7)
  .room(0.3)
  .delay(0.16)
  .delaytime(0.26)
  .delayfeedback(0.2)
  .detune(-4)
  .tremolo(0.09)
  .tremolosync(4)
  .compressor()

let pianoVoice = x => x
  .sound("pulse")
  .gain(0.15)
  .attack(0.03)
  .decay(0.25)
  .sustain(0.58)
  .release(0.85)
  .lpf(2600)
  .hpf(85)
  .room(0.3)
  .compressor()

setcps(0.56)

// Track 1: Upper
$: note("~*32 d5 ~*5 e5 ~*5 fs5 ~*5 g5 ~*5 b5 ~*5 a5 ~*5 g5 ~*5 d6 ~*5 d5 ~*5 e5 ~*5 fs5 ~*5 g5 ~*5 b5 ~*5 a5 ~*5 g5 ~*5 [d6 c6 bb5 a5]")
  .slow(208/8/4)
  .apply(upperVoice)
  .pan(perlin.range(0.32,0.58).slow(32))
  .detune(perlin.range(-12,14).slow(18))
  .every(16, x => x.transpose(12).detune(rand.range(-12,12)))
  .sometimes(x => x.rev())
  .echo(3, 1/16, 0.25)
  .swing(0.03)

// Track 2: Lower (offset evolution)
$: note("~*3 [g5 b5] ~*5 fs5 ~*5 e5 ~*5 d5 ~*5 b4 ~*5 c5 ~*5 d5 ~*5 g4 ~*3 [g5 b5] ~*5 fs5 ~*5 e5 ~*5 d5 ~*5 b4 ~*5 c5 ~*5 d5 ~*5 [g4 fs4]")
  .slow(208/8/4)
  .apply(lowerVoice)
  .pan(perlin.range(0.52,0.78).slow(32))
  .off(0.12, x => x.rev().pan(perlin.range(0.42,0.68).slow(32)))
  .every(16, x => x.transpose(7))
  .swing(0.03)

// Track 3: Bass
$: note("d2~ [fs2 g2]~ [a2 b2]~ [g2 fs2 d3]~ [g2 fs2]~ d2~ [e2 d2 c2]~ [b1 a1 g1]")
  .slow(104/8/4)
  .apply(bassVoice)
  .pan(sine.range(0.38,0.62).slow(32))
  .every(5, x => x.transpose(7))
  .degradeBy(0.08)
  .swing(0.03)

// Track 4: Continuo chords (sparser)
$: note("d3 [fs3 a3]~ g3 [b3 d4]~ a3 [cs4 e4]~ [g3 fs3 d4]~ [g3 fs3]~ d3 [e3 d3 c3]~ [b2 a2 g2]~")
  .slow(104/8/4)
  .apply(pianoVoice)
  .pan(sine.range(0.45,0.55).slow(24))
  .every(7, x => x.transpose(7))
  .sometimes(x => x.rev())
  .swing(0.03)