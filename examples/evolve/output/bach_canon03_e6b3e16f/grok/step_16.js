// BWV 1087 Canon 3 Evolved

// Baroque style voices
let upperVoice = x => x
  .sound("triangle")
  .gain(0.2)
  .attack(0.02)
  .decay(0.22)
  .sustain(0.45)
  .release(0.52)
  .lpf(sine.range(850,3700).slow(40))
  .lpq(cosine.range(1.8,7.5).slow(44))
  .hpf(155)
  .room(0.21)
  .delay(0.095)
  .tremolo(0.11)
  .tremolosync(3.8)
  .tremoloshape("sine")
  .penv(0.042)
  .slide(0.009)
  .ring(0.075)
  .fmenv(0.055)
  .fmi(0.075)
  .compressor()

let lowerVoice = x => x
  .sound("supersaw")
  .gain(0.225)
  .decay(0.19)
  .sustain(0.49)
  .detune(1.1)
  .lpf(tri.range(425,2900).slow(32))
  .hpf(125)
  .room(0.235)
  .delay(0.105)
  .fm(0.3)
  .fmenv(0.13)
  .vowel("a e i")
  .ring(0.045)
  .compressor()

let bassVoice = x => x
  .sound("sine")
  .gain(0.33)
  .lpf(cosine.range(150,920).slow(28))
  .lpq(2.9)
  .hpf(38)
  .attack(0.042)
  .decay(0.26)
  .sustain(0.51)
  .release(0.66)
  .room(0.29)
  .delay(0.125)
  .delaytime(0.27)
  .delayfeedback(0.145)
  .detune(-2.2)
  .tremolo(0.095)
  .tremolosync(2.9)
  .distort(0.013)
  .penv(0.022)
  .coarse(0.975)
  .compressor()

setcps(0.55)

// Track 1: Upper
$: note("~*20 d5 ~*2 e5 ~*3 fs5 ~*3 g5 ~*3 b5 ~*2 a5 ~*3 g5 ~*2 d6 ~*3 d5 ~*2 e5 ~*3 fs5 ~*3 g5 ~*3 b5 ~*3 a5 ~*3 g5 ~*3 [d6 c6 bb5]")
  .slow(200/8/4)
  .apply(upperVoice)
  .pan(perlin.range(0.3,0.75).slow(44))
  .detune(perlin.range(-14,16).slow(32))
  .every(16, x => x.transpose(12).detune(rand.range(-10,10)))
  .ply(2)
  .swing(0.04)

// Track 2: Lower (offset for canon feel)
$: note("~*2 [g5 b5] ~*2 fs5 ~*3 e5 ~*3 d5 ~*3 b4 ~*2 c5 ~*3 d5 ~*3 g4 ~*2 [g5 b5] ~*2 fs5 ~*3 e5 ~*3 d5 ~*3 b4 ~*2 c5 ~*3 d5 ~*3 [g4 fs4 eb4]")
  .slow(200/8/4)
  .apply(lowerVoice)
  .off(1/8, x => x)
  .pan(perlin.range(0.25,0.7).slow(48))
  .detune(perlin.range(-12,16).slow(36))
  .every(16, x => x.transpose(7))
  .swing(0.04)

// Track 3: Bass (refined rhythm)
$: note("d2~ [fs2 g2 a2]~ [b2 g2 fs2 d3]~ [g2 fs2 d2]~ e2~ [d2 c2 b1]~ [a1 g1 fs1]~ [d2 fs2 a2 g2 b2]")
  .slow(100/8/4)
  .apply(bassVoice)
  .pan(sine.range(0.25,0.75).slow(48))
  .every(8, x => x.transpose(7))
  .degradeBy(0.04)
  .swing(0.04)