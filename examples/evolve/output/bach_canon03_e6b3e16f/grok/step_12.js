// BWV 1087 Canon 3 Evolved

// Baroque style voices
let upperVoice = x => x
  .sound("supersaw")
  .gain(0.25)
  .attack(0.01)
  .decay(0.2)
  .sustain(0.4)
  .release(0.55)
  .lpf(sine.range(800,4200).slow(32))
  .lpq(cosine.range(2,8).slow(40))
  .hpf(160)
  .room(0.22)
  .delay(0.1)
  .tremolo(0.12)
  .tremolosync(3.5)
  .tremoloshape("sine")
  .penv(0.04)
  .slide(0.01)
  .ring(0.08)
  .phaser(sine.range(0.3,0.8).slow(12))
  .compressor()

let lowerVoice = x => x
  .sound("pulse")
  .gain(0.27)
  .decay(0.2)
  .sustain(0.48)
  .detune(2)
  .lpf(saw.range(500,3000).slow(28))
  .hpf(130)
  .room(0.26)
  .delay(0.11)
  .leslie(0.22)
  .lrate(0.28)
  .fm(0.22)
  .fmenv(0.12)
  .compressor()

let bassVoice = x => x
  .sound("sine")
  .gain(0.36)
  .lpf(sine.range(220,900).slow(24))
  .hpf(40)
  .attack(0.045)
  .decay(0.28)
  .sustain(0.55)
  .release(0.7)
  .room(0.3)
  .delay(0.14)
  .delaytime(0.28)
  .delayfeedback(0.16)
  .detune(-4)
  .tremolo(0.11)
  .tremolosync(2.8)
  .distort(0.035)
  .compressor()

setcps(0.53)

// Track 1: Upper
$: note("~*28 d5 ~*4 e5 ~*4 fs5 ~*4 g5 ~*4 b5 ~*4 a5 ~*4 g5 ~*4 d6 ~*4 d5 ~*4 e5 ~*4 fs5 ~*4 g5 ~*4 b5 ~*4 a5 ~*4 g5 ~*4 [d6 c6 b5 a5]")
  .slow(208/8/4)
  .apply(upperVoice)
  .pan(perlin.range(0.35,0.65).slow(40))
  .detune(perlin.range(-12,18).slow(24))
  .every(16, x => x.transpose(12).detune(rand.range(-12,12)))
  .sometimes(x => x.rev())
  .echo(2, 1/8, 0.18)
  .swing(0.04)

// Track 2: Lower (simplified evolution)
$: note("~*2 [g5 b5] ~*4 fs5 ~*4 e5 ~*4 d5 ~*4 b4 ~*4 c5 ~*4 d5 ~*4 g4 ~*2 [g5 b5] ~*4 fs5 ~*4 e5 ~*4 d5 ~*4 b4 ~*4 c5 ~*4 d5 ~*4 [g4 fs4]")
  .slow(208/8/4)
  .apply(lowerVoice)
  .pan(perlin.range(0.45,0.75).slow(40))
  .every(16, x => x.transpose(7))
  .swing(0.04)

// Track 3: Bass (refined)
$: note("d2~ [fs2 g2]~ [a2 b2]~ [g2 fs2 d3]~ [g2 fs2]~ d2~ [e2 d2 c2]~ [b1 a1 g1] ~ [d2 fs2 a2] ~ [g2 b2 d3]")
  .slow(104/8/4)
  .apply(bassVoice)
  .pan(sine.range(0.4,0.6).slow(40))
  .every(6, x => x.transpose(7))
  .degradeBy(0.05)
  .swing(0.04)