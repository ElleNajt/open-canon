// BWV 1087 Canon 3

// Baroque style voices
let upperVoice = x => x
  .sound("triangle")
  .gain(0.33)
  .attack(0.037)
  .decay(0.11)
  .sustain(0.17)
  .lpf(1200)
  .room(0.26)

let lowerVoice = x => x
  .sound("square")
  .gain(0.29)
  .attack(0.046)
  .decay(0.10)
  .sustain(0.17)
  .lpf(730)
  .room(0.15)

setcps(116/60/4)

// Track 1 — upper voice: focus on filtering and movement
$: note("~!40 d5 ~!7 e5 ~!7 gb5 ~!7 g5 ~!7 b5 ~!7 a5 ~!7 g5 ~!7 d6 ~!7 d5 ~!7 e5 ~!7 gb5 ~!7 g5 ~!7 b5 ~!7 a5 ~!7 g5 ~!7 d6 ~!7 d5 ~!7 e5 ~!7 gb5 ~!7 g5 ~!15")
  .slow(208/8/4)
  .apply(upperVoice)
  .pan(0.23)
  .room(0.20)
  .degradeBy(0.010)
  .every(16, x => x.lpf(sine.range(1100, 1400).slow(18)).gain(0.22))
  .sometimesBy(0.22, x => x.vowel("e i"))
  .sometimes(x => x.hpf(1350).gain(0.13).room(0.08))
  .sometimes(x => x.phaser(0.12).gain(0.17))
  .every(22, x => x.rev())
  .every(24, x => x.attack(0.018).decay(0.14).sustain(0.15))
  .often(x => x.room(0.21))

// Track 2 — lower voice: soften, make vowel swells more active, remove delay
$: note("~!8 g5 ~!7 gb5 ~!7 e5 ~!7 d5 ~!7 b4 ~!7 c5 ~!7 d5 ~!7 g4 ~!7 g5 ~!7 gb5 ~!7 e5 ~!7 d5 ~!7 b4 ~!7 c5 ~!7 d5 ~!7 g4 ~!7 g5 ~!7 gb5 ~!7 e5 ~!7 d5 ~!7 b4 ~!7 c5 ~!7 d5 ~!7 g4 ~!15")
  .slow(208/8/4)
  .apply(lowerVoice)
  .pan(0.76)
  .room(0.10)
  .every(10, x => x.decay(0.11).room(0.12).lpf(600))
  .every(8, x => x.sustain(0.11).vowel("o u"))
  .rarely(x => x.sustain(0.18).lpf(720).vowel("u"))
  .every(18, x => x.room(0.11))
  .sometimesBy(0.14, x => x.lpf(570).vowel("a o"))

// Track 3 — bass: reduce octave jumps, more dynamic filtering, remove compressor for clarity
$: n("[d2 ~ a2] [d2 ~ fs2] [g2 ~ b1] [d2 ~ a1] [fs2 g2] [b1 a1]")
  .sound("piano")
  .gain(0.09)
  .sustain(sine.range(0.12, 0.19).slow(10))
  .attack(0.016)
  .release(0.16)
  .lpf(sine.range(410, 870).slow(10))
  .lpq(8)
  .room(0.10)
  .pan(sine.range(0.41,0.46).slow(14))
  .every(20, x => x.lpf(380).release(0.11).gain(0.075))
  .sometimesBy(0.03, x => x.octave(1))

// Track 4 — subtle upper harmonic “halo” (removed an effect from other voices to add this)
$: n("~!48 g5 ~!24 d6 ~!16 a5 ~!8 b5 ~!8 e6 ~!8 d6 ~!8")
  .sound("supersaw")
  .gain(0.045)
  .attack(0.008)
  .decay(0.18)
  .sustain(0.05)
  .release(0.11)
  .lpf(2400)
  .room(0.38)
  .pan(0.11)
  .every(12, x => x.hpf(840))
  .degradeBy(0.21)