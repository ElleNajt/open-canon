setcps(94/60/4)
samples('shabda/speech:strudel,groove,evolving')

$: note("g3 bb2 c3 d3 e3 fs3 g3 ~ d3 f1 eb2 g2")
  .slow(3)
  .every(4,rev)
  .sound("sawtooth")
  .lpf(perlin.range(250,1500))
  .gain(0.42)

$: s("bd*4 [sn cp ~ cp] bd*2 [~ sn oh] [hh*8? oh*4 ~ oh*4]")
  .swing(0.22)
  .gain(0.4)
  .room(0.3)
  .hpf(110)
  .pan(rand.range(0.4,0.6))

$: note("g2 bb2 d3 fs3 g3 bb3 d4")
  .slow(2)
  .sound("supersaw")
  .fm(sine.range(1.5,4.5).slow(2))
  .lpf(cosine.range(120,1900))
  .gain(0.34)

$: note("[b3 d4 g4 b4] [a3 c4 fs4 a4] [g3 b3 e4 g4] [f3 a3 d4 f4]")
  .slow(1.8)
  .every(4,rev)
  .sound("piano")
  .gain(0.36)
  .room(0.25)

$: n("0 3 7 10 ~ 2, 5 9 12 0 ~ 7").scale("G:mixolydian")
  .fast(3.5)
  .sound("pulse")
  .lpf(tri.range(350,3400).slow(3))
  .gain(0.4)

$: s("[strudel*2 ~ groove?] groove*3 [evolving*2 ~], ~ [strudel groove*2 evolving?]")
  .slow(4)
  .every(8,x=>x.rev())
  .gain(0.3)
  .room(0.7)
  .chop(sine.range(8,16))
  .speed(perlin.range(0.8,1.25))