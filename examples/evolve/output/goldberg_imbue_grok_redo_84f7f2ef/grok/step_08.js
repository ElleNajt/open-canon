setcps(94/60/4)
samples('shabda/speech:strudel,groove,evolving')

$: note("g3 bb2 c3 d3 e3 fs3 g3 d3 f1 eb2 g2")
  .slow(4)
  .every(4,rev)
  .sound("sawtooth")
  .lpf(perlin.range(300,1600))
  .slide(0.08)
  .gain(0.45)

$: s("bd*4 [sn cp ~ cp] bd*2 [~ sn cp] hh*16? [oh*4 ~ oh*8 oh*4]")
  .swing(0.2)
  .degradeBy(0.2)
  .gain(0.38)
  .room(0.3)
  .hpf(120)

$: note("g2 b2 d3 e3 fs3 g3")
  .slow(2.5)
  .every(8,x=>x.rev())
  .sound("supersaw")
  .fm(sine.range(2,4))
  .lpf(sine.range(100,2000).slow(4))
  .tremolo(0.4)
  .gain(0.35)

$: note("b3 d4 g4 b4 a4, a3 c4 fs4 a4 c5, g3 b3 e4 g4 bb4, f3 a3 d4 f4 ab4")
  .slow(2)
  .degradeBy(0.25)
  .every(8,rev)
  .sound("piano")
  .gain(0.38)
  .delay(0.3)
  .pan(sine.range(0.2,0.8).slow(6))

$: n("0 3 7 10 ~ 2, 5 9 12 0 ~ 7").scale("G:mixolydian")
  .fast(4)
  .sound("pulse")
  .lpf(saw.range(400,3500).slow(2.5))
  .accelerate(0.08)
  .gain(0.42)

$: s("[strudel*2 groove?] groove*4 [evolving*2 ~], ~ [strudel groove evolving?]")
  .slow(4.5)
  .every(8,x=>x.rev().fast(1.1))
  .gain(0.32)
  .room(0.65)
  .chop(sine.range(8,18))
  .speed(perlin.range(0.8,1.3))