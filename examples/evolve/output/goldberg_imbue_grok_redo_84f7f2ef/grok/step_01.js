setcps(72/60/4)

$: note("g3 gb3 e3 d3 b2 c3 d3 g2")
  .slow(2)
  .every(4,rev)
  .sound("triangle")
  .detune(rand.range(-15,15))
  .lpf(600)
  .gain(0.45)

$: s("bd*4, sn*2, hh*8")
  .gain(0.25)
  .room(0.15)
  .crush(9)
  .hpf(120)
  .pan(sine.range(0.25,0.75))

$: note("g2 b2 d3")
  .sound("supersaw")
  .slow(4)
  .lpf(cosine.range(400,1400).slow(6))
  .phaser(0.4)
  .room(0.5)

$: note("b3 d4 g4 b4, a3 c4 fs4 a4, g3 b3 e4 g4, f3 a3 d4 f4")
  .slow(2)
  .sound("piano")
  .gain(0.4)
  .delay(0.12)
  .tremolo(0.3)