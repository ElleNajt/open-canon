setcps(94/60/4)
samples('shabda/speech:strudel,groove,evolving')

$: note("g3 fs3 e3 d3 bb2 c3 d3 g2 eb2 f1")
  .slow(4)
  .every(4,rev)
  .sound("sawtooth")
  .lpf(perlin.range(400,1400))
  .detune(perlin.range(-25,25))
  .gain(0.42)

$: s("bd*4 [~sn cp] bd*2,~ [sn cp], hh*8? [oh*4 ~ oh*4 oh*4]")
  .swing(0.16)
  .degradeBy(0.15)
  .gain(0.36)
  .room(0.3)
  .hpf(100)

$: note("g2 b2 d3 e3")
  .slow(3)
  .every(12,x=>x.rev())
  .sound("supersaw")
  .fm(sine.range(2.5,3.5))
  .lpf(sine.range(150,1800).slow(5))
  .room(0.5)

$: note("b3 d4 g4 b4 a4, a3 c4 fs4 a4 c5, g3 b3 e4 g4 bb4, f3 a3 d4 f4 ab4")
  .slow(2)
  .degradeBy(0.2)
  .every(8,rev)
  .sound("piano")
  .gain(0.36)
  .delay(0.25)

$: n("0 3 7 10 ~, 2 5 9 12 0").scale("G:mixolydian")
  .fast(3.5)
  .sound("pulse")
  .lpf(saw.range(600,3000).slow(3))
  .accelerate(0.05)
  .gain(0.4)

$: s("strudel*2, groove*4 evolving*2, ~ strudel groove?")
  .slow(5)
  .every(8,x=>x.rev())
  .gain(0.3)
  .room(0.7)
  .chop(perlin.range(8,16))
  .speed(perlin.range(0.75,1.25))