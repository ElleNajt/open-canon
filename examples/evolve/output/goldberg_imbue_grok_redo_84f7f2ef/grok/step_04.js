setcps(88/60/4)
samples('shabda/speech:strudel,groove,evolving')

$: note("g3 fs3 e3 d3 bb2 c3 d3 g2 eb2 f1")
  .slow(4)
  .every(4,rev)
  .swing(0.1)
  .sound("sawtooth")
  .detune(sine.range(-25,25))
  .penv(0.4)
  .lpf(perlin.range(350,1100))
  .gain(0.45)

$: s("bd*4 [~ sn cp] bd*2 [sn cp], hh*16 [oh*4 ~ oh*4 oh*8]?")
  .swing(0.15)
  .gain(0.35)
  .room(0.2)
  .crush(rand.range(6,14))
  .hpf(110)

$: note("g2 b2 d3 e3")
  .slow(3)
  .sound("supersaw")
  .fm(2.8)
  .lpf(sine.range(250,1800).slow(5))
  .fmenv(0.8)
  .room(0.5)

$: note("b3 d4 g4 b4 a4, a3 c4 fs4 a4 c5, g3 b3 e4 g4 bb4, f3 a3 d4 f4 ab4")
  .slow(2)
  .degradeBy(0.2)
  .every(8,rev)
  .sound("piano")
  .gain(0.35)
  .delay(0.25)
  .tremolo(0.5)
  .vowel("a e")

$: n("0 3 7 10 ~, 2 5 9 12 0").scale("G:mixolydian")
  .fast(3.5)
  .sound("pulse")
  .lpf(tri.range(800,3000).slow(3))
  .detune(rand.range(-20,20))
  .accelerate(0.05)
  .gain(0.4)

$: s("strudel*2 groove*4, ~ evolving*2 strudel?")
  .slow(6)
  .gain(0.3)
  .room(0.7)
  .chop(16)
  .speed(perlin.range(0.8,1.2))
  .pan(sine.range(0.1,0.9))