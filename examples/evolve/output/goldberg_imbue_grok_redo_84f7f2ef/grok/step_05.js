setcps(92/60/4)
samples('shabda/speech:strudel,groove,evolving')

$: note("g3 fs3 e3 d3 bb2 c3 d3 g2 eb2 f1")
  .slow(4)
  .every(4,rev)
  .swing(0.12)
  .sound("sawtooth")
  .detune(perlin.range(-30,30))
  .lpf(perlin.range(300,1200))
  .phaser(sine.range(0.1,0.4).slow(3))
  .gain(0.45)

$: s("bd*4 [~ sn cp] bd*2 [sn cp], hh*16 [oh*4 ~ oh*4 oh*8]?")
  .swing(0.18)
  .degradeBy(0.12)
  .gain(0.38)
  .room(0.25)
  .crush(rand.range(5,13))
  .hpf(120)

$: note("g2 b2 d3 e3")
  .slow(3)
  .sound("supersaw")
  .fm(3.2)
  .leslie(0.6)
  .lpf(sine.range(200,2000).slow(6))
  .room(0.55)
  .fmenv(0.85)

$: note("b3 d4 g4 b4 a4, a3 c4 fs4 a4 c5, g3 b3 e4 g4 bb4, f3 a3 d4 f4 ab4")
  .slow(2)
  .degradeBy(0.25)
  .every(8,rev)
  .sound("piano")
  .gain(0.38)
  .delay(0.3)
  .ring(0.4)

$: n("0 3 7 10 ~, 2 5 9 12 0").scale("G:mixolydian")
  .fast(3.5)
  .sound("pulse")
  .lpf(tri.range(700,3200).slow(2.5))
  .detune(rand.range(-25,25))
  .accelerate(0.06)
  .gain(0.42)

$: s("strudel*2 groove*4, ~ evolving*2 strudel?")
  .slow(6)
  .every(8,x=>x.rev())
  .gain(0.32)
  .room(0.75)
  .striate(12)
  .speed(perlin.range(0.7,1.3))
  .pan(sine.range(0,1))