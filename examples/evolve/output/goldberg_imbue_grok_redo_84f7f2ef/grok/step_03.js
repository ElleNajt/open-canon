samples('shabda/speech:strudel,groove,evolving')

$: note("g3 gb3 e3 d3 b2 c3 d3 g2 f1")
  .slow(4)
  .every(4,rev)
  .swing(0.06)
  .sound("triangle")
  .detune(sine.range(-20,20))
  .coarse(2)
  .lpf(perlin.range(400,1000))
  .gain(0.4)

