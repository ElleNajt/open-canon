// Goldberg Evolutions
setcps(70/60/4)

$: note("gb3 eb3/2 [d3 b2] c3 ab2/2 g2 [d3 fs3]/2")
  .slow(4)
  .sound("pulse")
  .gain(0.15)
  .lpf(perlin.range(600, 2200).slow(8)).lpq(4)
  .drive(0.2)
  .vowel("a e".slow(4))
  .room(0.4)

$: note("[d5 c5?]/2 b4 <g4 bb4 d5> [d5 g5 d5 fs5]").euclid(7,11)
  .slow(2)
  .sound("square")
  .gain(0.08)
  .bpf(sine.range(1000, 4000).slow(6)).bpq(5)
  .delay(0.5).dfb(0.65)
  .fmi(cosine.range(1, 10).slow(8))
  .trem(sine.range(0, 0.7).slow(6))
  .pan(perlin.range(0.1, 0.9).slow(12))

$: s("<bd sn:1> <bd [sn:2 cp?]> [ht mt] <[sn:2 cp] sn:3>").chop(perlin.range(2,8).slow(8))
  .slow(4)
  .gain(0.4)
  .compressor("-22:4:5:0.01:0.25")
  .djf(saw.range(0,1).slow(8))
  .crush(perlin.range(4,8).slow(12))
  .ply(perlin.range(1,2).slow(0.5))
  .room(0.2)

$: chord("g2minor f2major eb2major d2minor")
  .slow(8)
  .sound("supersaw")
  .gain(0.12)
  .detune(cosine.range(-12, 12).slow(12))
  .lpf(perlin.range(150, 900).slow(16)).lpattack(4)
  .hpf(80)
  .pan(sine.range(0.05, 0.95).slow(8))
  .room(0.7).size(0.95)

$: n(perlin.range(0, 10).slow(2)).scale("g:minor")
  .fast(4)
  .sound("triangle")
  .gain(0.09)
  .release(0.15)
  .delay(0.6).dt("3/8").dfb(0.7)
  .pan(saw.range(0.1, 0.9).slow(6))
  .bpf(perlin.range(800, 5000).slow(8)).bpq(6)
  .room(0.4)
  .crush(6)

$: s("<[hh oh] [cr? cp? ~]>/2").euclid(11, 16)
  .fast(2)
  .gain(0.16)
  .chop(perlin.range(4, 32).slow(8))
  .hpf(perlin.range(4000, 8000).slow(12)).hpq(6)
  .pan(perlin.range(0.2, 0.8).slow(8))
  .delay(0.2).dfb(0.4).dt("1/16")
  .ringf(perlin.range(50, 200).slow(10))