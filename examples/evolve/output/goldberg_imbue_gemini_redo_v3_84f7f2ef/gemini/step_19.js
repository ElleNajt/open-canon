// Goldberg Evolutions v3
setcps(72/60/4)

$: note("[gb3/2 d3] [bb2 c3]~/2 g2")
  .degradeBy(0.15)
  .slow(4)
  .sound("pulse")
  .gain(0.16)
  .lpf(perlin.range(300, 2800).slow(6)).lpq(6)
  .shape(0.3)
  .slide(perlin.range(-0.05, 0.05).slow(7))
  .vowel("o u a".slow(5))
  .room(0.5)

$: note("<d5 c5> g4 <g4 bb4> [g5 g5 fs5]?7")
  .euclid(5,8)
  .slow(2)
  .sound("square")
  .gain(0.08)
  .bpf(sine.range(900, 4000).slow(4)).bpq(7)
  .delay(0.6).dfb(0.7).dt("3/16")
  .ring(perlin.range(0.1, 0.6).slow(8))
  .room(0.4)
  .pan(perlin.range(0.1, 0.9).slow(10))

$: s("<bd*2 [sn cp]?> <ht [~ sn?]>")
  .ply(perlin.range(1,3).slow(4))
  .slow(4)
  .gain(0.4)
  .compressor("-20:8:2:0.01:0.2")
  .crush(perlin.range(5, 9).slow(7))
  .hpf(80)
  .delay(0.3).dfb(0.5).dt("1/16")
  .pan(perlin.range(0.3, 0.7).slow(9))

$: chord("g2minor7 c2minor eb2major7 d2sus4")
  .slow(8)
  .sound("supersaw")
  .gain(0.14)
  .lpf(perlin.range(200, 1200).slow(10)).lpattack(2.5)
  .fm(sine.range(0.1, 0.5).slow(8))
  .phaser(sine.range(0.1, 4).slow(9))
  .room(0.8).size(0.9)
  .trem(sine.range(0.1, 0.5).slow(7))

$: n("0 3 5 7 8 10 12").iter(2).scale("g:minor")
  .fast(2)
  .sound("sawtooth")
  .gain(0.08)
  .jux(x => x.add(5))
  .delay(0.5).dt("3/16").dfb(0.6)
  .lpf(sine.range(1800, 5500).slow(6)).lpq(8)
  .crush(perlin.range(6,9).slow(5))
  .pan(saw.range(0.1, 0.9).slow(8))
  .penv(perlin.range(1, 5).slow(6))

$: s("[hh oh*2] [cr cp? ~] hh*2 [cp oh]").palindrome()
  .fast(4)
  .every(4, rev)
  .gain(0.15)
  .hpf(perlin.range(5000, 9000).slow(7)).hpq(5)
  .delay(0.4).dfb(0.6).dt("1/8.")
  .crush(8)
  .shape(0.6)
  .pan(perlin.range(0.2, 0.8).slow(12))