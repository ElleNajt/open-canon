// Goldberg Variations - Ground Bass (BWV 988)
// The 8-note descending bass that underlies all 30 variations

setcps(72/60/4)

$: note("g3 gb3 e3 d3 b2 c3 d3 g2")
  .slow(2)
  .sound("pulse")
  .gain(0.3)
  .shape(0.3)
  .lpf(sine.range(500, 1500).slow(4))
  .resonance(4)
  .pan(0.4)

$: note("d5 b4 c5 a4 g4 a4 b4 d5")
  .slow(2)
  .sound("sine")
  .gain(0.25)
  .pan(0.8)
  .delay(0.4)
  .delayfeedback(0.5)
  .room(0.2)

$: s("bd sn [hh hh] bd [sn hh]")
  .slow(2)
  .swing(0.25)
  .gain(0.5)
  .crush(5)
  .hpf(100)
  .room(0.1)

$: note("g2")
  .slow(16)
  .sound("supersaw")
  .gain(0.15)
  .lpf(sine.range(300, 1000).slow(8))
  .lpq(8)
  .leslie(0.2)
  .distort(0.1)

$: n(perlin.range(0, 7)).scale("g:major")
  .octave(5)
  .fast(8)
  .sound("triangle")
  .gain(0.15)
  .pan(rand)
  .delay(0.3)
  .room(0.4)