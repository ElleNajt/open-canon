// Goldberg Evolutions v4
setcps(72/60/4)

$: note("[gb3 d3 bb2 c3] g2")
  .euclid(5,8)
  .slow(4)
  .sound("pulse")
  .gain(0.15)
  .lpf(perlin.range(300, 2800).slow(6)).lpq(5)
  .coarse(perlin.range(4,10).slow(5))
  .vowel("a e".slow(3))
  .room(0.4)
  .phaser(sine.range(0.1, 2).slow(8))

$: note("<d5 c5> g4 <g4 bb4> [g5 g5 fs5]??")
  .euclid(7,8)
  .slow(2)
  .sound("square")
  .gain(0.09)
  .bpf(sine.range(1000, 4200).slow(4)).bpq(8)
  .delay(0.5).dfb(0.7).dt("3/8")
  .fm(perlin.range(0.5, 3).slow(5))
  .room(0.5)
  .pan(perlin.range(0.1, 0.9).slow(10))

$: s("<bd bd> [sn cp]? <ht [~ sn]??>")
  .chop(perlin.range(2,8).slow(3))
  .slow(4)
  .gain(0.4)
  .compressor("-18:6:2:0.01:0.3")
  .hpf(100)
  .delay(0.2).dfb(0.4).dt("1/16")
  .shape(0.7)
  .room(0.2)

$: chord("g2minor7 c3minor7 f2major7 d2sus4")
  .slow(8)
  .sound("supersaw")
  .gain(0.12)
  .lpf(perlin.range(250, 1500).slow(12)).lpattack(1.5).lpdecay(2)
  .distort(0.4)
  .phaser(perlin.range(0.1, 8).slow(12))
  .room(0.9).size(0.9)

$: n("0 3 5 7 8 10 12").iterBack(1).scale("g:minor")
  .fast(2)
  .sound("sawtooth")
  .gain(0.07)
  .jux(x => x.add(7))
  .striate(perlin.range(8, 32).slow(3))
  .lpf(sine.range(2000, 6000).slow(5)).lpq(7)
  .delay(0.6).dt("3/16").dfb(0.7)
  .room(0.6)

$: s("[hh,oh] [~,cp,cr]? [hh,hh,oh]").palindrome()
  .fast(8)
  .every(4, rev)
  .gain(0.13)
  .hpf(perlin.range(6000, 9500).slow(8)).hpq(4)
  .vowel("i e o".slow(6))
  .distort(0.3)
  .delay(0.3).dfb(0.5).dt("1/8.")