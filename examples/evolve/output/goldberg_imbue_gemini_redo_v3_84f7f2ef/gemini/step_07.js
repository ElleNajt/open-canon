// Goldberg Evolutions
setcps(74/60/4)

$: note("g3 gb3 e3 [d3 b2] c3 d3 g2")
  .slow(4)
  .sound("sawtooth")
  .gain(0.18)
  .lpf(perlin.range(300, 1200).slow(4))
  .lpq(6)
  .room(0.3)
  .drive(0.2)

$: note("<d5 c5> b4 <g4 a4> g4 b4 [d5 g5]")
  .slow(2)
  .sound("square")
  .gain(0.1)
  .vowel("i e a o")
  .jux(rev)
  .delay(0.5)
  .dfb(0.7)

$: s("[bd sn] [bd bd/2] [bd sn? cp/2] [bd bd/2]")
  .slow(4)
  .gain(0.4)
  .distort(0.2)
  .crush(6)
  .djf(saw.range(0.2, 0.8).slow(8))
  .room(0.1)

$: chord("g2minor d3major c3major b2major")
  .slow(16)
  .sound("supersaw")
  .gain(0.15)
  .detune(cosine.range(-10, 10).slow(13))
  .tremolo(sine.range(0.1, 0.5).slow(9))
  .room(0.7)
  .lpf(400)

$: n(perlin.range(0,12)).scale("g:minor")
  .euclid(5,8)
  .fast(12)
  .sound("triangle")
  .gain(0.1)
  .release(0.1)
  .delay(0.6)
  .dt("3/8")
  .dfb(0.6)
  .room(0.5)

$: s("<hh*2 [~ oh]> <[~ cp]>*2")
  .fast(8)
  .degradeBy(0.15)
  .gain(0.18)
  .speed(perlin.range(0.9, 1.1).slow(6))
  .hpf(6000)
  .phaser(sine.range(0.1, 5).slow(12))
  .pan(perlin.slow(5))