// Goldberg Evolutions v2
setcps(70/60/4)

$: note("gb3/2 [d3 bb2] c3~/2 g2")
  .euclid(7,8)
  .slow(4)
  .sound("pulse")
  .gain(0.18)
  .lpf(perlin.range(400, 2500).slow(6)).lpq(5)
  .distort(0.2)
  .vowel("o u a".slow(3))
  .room(0.5)

$: note("<d5 c5> g4 <g4 bb4> [g5 fs5]")
  .euclid(7,9)
  .slow(2)
  .sound("square")
  .gain(0.09)
  .bpf(sine.range(800, 3500).slow(4)).bpq(6)
  .delay(0.6).dfb(0.7).dt("3/16")
  .phaser(perlin.range(1, 12).slow(6))
  .room(0.4)
  .pan(perlin.range(0.1, 0.9).slow(10))

$: s("<bd [sn cp?]>*2 <[ht mt] [~ sn]>")
  .ply(perlin.range(1,2).slow(2))
  .slow(4)
  .gain(0.45)
  .compressor("-18:6:3:0.01:0.3")
  .distort(0.25)
  .crush(perlin.range(6, 10).slow(8))
  .hpf(60)
  .room(0.3)

$: chord("g2minor c2minor eb2major d2minor")
  .slow(8)
  .sound("supersaw")
  .gain(0.15)
  .trem(sine.range(0.2, 0.6).slow(6))
  .lpf(perlin.range(200, 1200).slow(10)).lpattack(2)
  .hpf(100)
  .fm(sine.range(0.1, 0.5).slow(8))
  .room(0.8).size(0.9)

$: n("0 3 5 7 8 10 12").iter(1).scale("g:minor")
  .fast(2)
  .sound("triangle")
  .gain(0.10)
  .release(0.2)
  .jux(x => x.add(4))
  .delay(0.5).dt("3/16").dfb(0.6)
  .lpf(sine.range(1500, 5000).slow(6)).lpq(7)
  .crush(perlin.range(6,9).slow(4))
  .pan(saw.range(0.1, 0.9).slow(8))

$: s("[hh oh*2] [cr cp? ~] hh*2 [cp oh]").palindrome()
  .fast(2)
  .every(3, rev)
  .gain(0.18)
  .hpf(perlin.range(4000, 8000).slow(8)).hpq(5)
  .delay(0.4).dfb(0.6).dt("3/32")
  .crush(8)
  .pan(perlin.range(0.2, 0.8).slow(12))