// Goldberg Evolutions
setcps(74/60/4)

$: note("g3 gb3 e3 d3 b2 c3 d3 g2")
  .slow(4)
  .sound("sawtooth")
  .gain(0.2)
  .lpf(perlin.range(200, 1000).slow(8))
  .lpq(8)
  .room(0.2)

$: note("<d5 c5> b4 <g4 a4> a4 b4 d5")
  .slow(2)
  .sound("square")
  .gain(0.12)
  .vowel("i e a")
  .delay(0.5)
  .dfb(0.7)

$: s("[bd sn] [bd bd/2] [~ cp/2]")
  .slow(4)
  .gain(0.5)
  .distort(0.3)
  .crush(5)
  .hpf(100)
  .room(0.1)

$: note("g2 d3 c3 b2")
  .slow(16)
  .sound("supersaw")
  .gain(0.15)
  .detune(cosine.range(-10, 10).slow(13))
  .room(0.6)
  .lpf(600)

$: n(perlin.range(0,12)).scale("c:minor")
  .euclid(5,8)
  .fast(8)
  .sound("triangle")
  .gain(0.15)
  .release(0.05)
  .delay(0.4)
  .pan(rand)

$: s("<hh*2 [~ oh]> <[~ cp]>*2")
  .fast(8)
  .gain(0.2)
  .speed(perlin.range(0.9, 1.1).slow(6))
  .hpf(5000)
  .room(0.4)
  .pan(perlin.slow(5))