samples('shabda/speech:future,past,now')
setcps(80/60/4)

$: note("[gb3 db4 bb3 a3]/2")
  .slow(4)
  .sound("triangle")
  .gain(0.2)
  .jux(x => x.gain(0.5).pan(sine.range(0,1).slow(7)))
  .vowel(perlin.range(0, 1).slow(8))
  .lpf(perlin.range(500, 4000).slow(12)).lpq(6)
  .delay(0.3).dt("3/16").dfb(0.7)
  .room(0.4)

$: note("<g4 [bb4 d5]> [~ c5]")
  .slow(4)
  .sound("sawtooth")
  .gain(0.1)
  .phaser(tri.range(0.1, 8).slow(16))
  .tremolo(sine.range(0, 0.5).slow(6)).tremolosync(4)
  .lpf(1500).lpq(8)
  .delay(0.5).dfb(0.5).dt("1/8")
  .room(0.6)

$: stack(s("bd [~ bd] bd ~").fast(2), s("[~ hh sn oh] [cp hh] [~ sn?] [~ hh mt hh]").slow(2))
  .gain(0.45)
  .compressor("threshold:-20:ratio:8:knee:5:attack:0.01:release:0.3")
  .distort(0.2)
  .hpf(80)
  .pan(saw.range(0.2, 0.8).slow(16))
  .room(0.2)

$: chord("eb2major9 g2minor7b5 db2major7 gb2major9")
  .slow(8)
  .sound("supersaw")
  .gain(0.15)
  .detune(5)
  .lpf(perlin.range(300, 2500).slow(12)).lpattack(3).lpsustain(0.5)
  .phaser(sine.range(0.1, 2).slow(16))
  .pan(cosine.range(0.1, 0.9).slow(14))
  .room(0.7).size(0.95)

$: s("future past now").slow(16)
