// Goldberg Evolutions
setcps(68/60/4)

$: note("gb3 eb3/2 [d3 b2] c3 ab2/2 g2 [d3 fs3]/2")
  .slow(4)
  .sound("pulse")
  .gain(0.15)
  .lpf(perlin.range(400, 2000).slow(8)).lpenv(800).lpq(2)
  .drive(0.3)
  .room(0.4)
  .shape(0.2)

$: note("[d5 c5?]/2 b4 <g4 bb4 g4> [d5 g5 d5 fs5]").euclid(5,8)
  .slow(2)
  .sound("square")
  .gain(0.09)
  .lpf(sine.range(900, 4000).slow(6))
  .delay(0.5).dfb(0.65)
  .fmi(cosine.range(1, 10).slow(8))
  .trem(sine.range(0, 0.7).slow(6))

$: s("<bd sn:1> <bd [sn:2 cp?]> [ht] <~ sn:3>").chop(4)
  .slow(4)
  .gain(0.4)
  .compressor("-22:4:5:0.01:0.25")
  .lpf(perlin.range(400, 3000).slow(8)).lpq(8)
  .room(0.2)
  .delay(0.1).dfb(0.5).dt("1/8")
  .shape(0.4)

$: chord("g2minor c2minor eb2major bb2major")
  .slow(8)
  .sound("supersaw")
  .gain(0.13)
  .detune(cosine.range(-12, 12).slow(12))
  .lpf(120).lpattack(6)
  .pan(sine.range(0.05, 0.95).slow(8))
  .room(0.7).size(0.95)

$: n(perlin.range(0, 8)).scale("g:minor")
  .euclid(7,12)
  .iter(2)
  .fast(4)
  .sound("triangle")
  .gain(0.1)
  .release(0.15)
  .delay(0.6).dt("3/8").dfb(0.7)
  .pan(saw.range(0.1, 0.9).slow(6))
  .lpf(2800).lpenv(2000).lpdecay(0.05)
  .room(0.4)
  .fmi(perlin.range(0,4).slow(12))

$: s("<[hh oh] cr>/2").euclid(13, 16)
  .fast(2)
  .gain(0.18)
  .chop(perlin.range(4, 32).slow(8))
  .hpf(perlin.range(4000, 8000).slow(12)).hpq(4)
  .pan(perlin.range(0.2, 0.8).slow(8))
  .vowel("a o u e".slow(2))
  .delay(0.2).dfb(0.4).dt("1/16")