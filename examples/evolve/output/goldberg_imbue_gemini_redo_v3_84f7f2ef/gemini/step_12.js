// Goldberg Evolutions
setcps(74/60/4)

$: note("gb3 eb3/2 [d3 b2] c3 ab2/2 g2 [d3 g3?]/2")
  .slow(4)
  .sound("sawtooth")
  .gain(0.14)
  .bpf(perlin.range(400, 4000).slow(5))
  .bpq(6)
  .room(0.3)
  .shape(0.5)
  .slide(0.03)

$: note("[d5 c5?]/2 b4 <g4 a4 g4> [d5 g5 d5 fs5]").euclid(5,8)
  .slow(2)
  .sound("square")
  .gain(0.07)
  .lpf(sine.range(600, 3000).slow(6))
  .lpenv(2500)
  .delay(0.5).dfb(0.7)
  .fmi(cosine.range(1, 15).slow(8))
  .fmh(saw.range(0.5, 2).slow(12))

$: s("[bd sn] [bd [~ sn]]/2 [cp ht?] [sn bd [~ rim]] [bd,sn/2]")
  .slow(4)
  .gain(0.35)
  .compressor("-20:4:5:0.01:0.25")
  .djf(saw.range(0.1, 0.9).slow(5))
  .room(0.1)
  .delay(0.2).dfb(0.4).dt("3/16")
  .coarse(4)

$: chord("g2minor f2minor eb3major d3sus4")
  .slow(8)
  .sound("supersaw")
  .gain(0.12)
  .detune(cosine.range(-15, 15).slow(13))
  .lpf(150).lpattack(4)
  .shape(cosine.range(0, 0.7).slow(9))
  .room(0.5).size(0.9)
  .hpf(100)

$: n(perlin.range(0,15)).scale("g:minor")
  .euclid(7,12)
  .iter(4)
  .fast(8)
  .sound("pulse")
  .gain(0.08)
  .release(0.1)
  .delay(0.7).dt("3/8").dfb(0.75)
  .pan(saw.range(0.1, 0.9).slow(6))
  .lpf(2000).lpenv(4000).lpdecay(0.05)
  .distort(perlin.range(0, 0.5).slow(7))
  .crush(cosine.range(8, 4).slow(10))

$: s("[hh*3 [~ oh]] <[cr,hh] [oh ht?]>/2 [hh*2, cr/2]")
  .fast(4)
  .sometimes(() => rev())
  .gain(0.15)
  .speed(perlin.range(0.9, 1.3).slow(8))
  .hpf(perlin.range(4000, 8000).slow(12)).hpq(6)
  .crush(perlin.range(12, 6).slow(9))
  .pan(perlin.range(0.2, 0.8).slow(7))
  .delay(0.1).dfb(0.2).dt("1/16")