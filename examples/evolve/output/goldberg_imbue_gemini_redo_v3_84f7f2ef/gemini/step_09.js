// Goldberg Evolutions
setcps(74/60/4)

$: note("gb3 e3 [d3 b2]/2 c3 d3 [g2 d3] g3")
  .slow(4)
  .sound("sawtooth")
  .gain(0.15)
  .lpf(perlin.range(400, 2000).slow(8))
  .lpq(6)
  .room(0.4)
  .phaser(0.1)
  .slide(0.05)

$: note("<d5 c5> b4 <g4 fs4> g4 b4 [d5 g5]")
  .slow(2)
  .sound("square")
  .gain(0.07)
  .lpf(400)
  .lpenv(3000)
  .lpdecay(0.15)
  .delay(0.5)
  .dfb(0.7)
  .fm(2.5)
  .detune(3)

$: s("[bd sn] bd [sn [~ cp]] [bd bd/2 sn]")
  .slow(4)
  .gain(0.35)
  .compressor("-20:4:5:0.01:0.25")
  .djf(saw.range(0.1, 0.9).slow(8))
  .room(0.2)
  .crush(6)

$: chord("g2minor d3major eb3major f3major")
  .slow(16)
  .sound("supersaw")
  .gain(0.12)
  .detune(cosine.range(-15, 15).slow(13))
  .lpf(120)
  .lpenv(2500)
  .lpattack(7)
  .lprelease(7)
  .tremolo(0.5)
  .tremolosync(8)

$: n(perlin.range(0,15)).scale("g:minor")
  .euclid(5,8)
  .iter(4)
  .fast(12)
  .sound("triangle")
  .gain(0.09)
  .release(0.1)
  .delay(0.7)
  .dt("3/8")
  .dfb(0.6)
  .bpf(perlin.range(1000, 4000).slow(9))
  .bpq(8)
  .pan(perlin.slow(11))

$: s("<hh*3 [~ oh]> [~ cr hh oh]/2")
  .fast(8)
  .degradeBy(0.15)
  .gain(0.15)
  .speed(perlin.range(0.9, 1.3).slow(9))
  .hpf(6000)
  .delay(0.3)
  .dt("3/16")
  .pan(rand)