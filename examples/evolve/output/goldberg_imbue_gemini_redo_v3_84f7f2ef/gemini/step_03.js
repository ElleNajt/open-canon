// Goldberg Variations - Ground Bass (BWV 988)
// The 8-note descending bass that underlies all 30 variations

setcps(80/60/4)

$: note("g3 gb3 e3 d3 b2 c3 d3 g2")
  .slow(2)
  .sound("sawtooth")
  .gain(0.25)
  .drive(0.4)
  .lpf(sine.range(400, 2000).slow(4))
  .resonance(5)
  .pan(0.4)
  .room(0.1)

$: note("d5 b4 c5 a4 g4 a4 b4 d5")
  .slow(2)
  .sound("sine")
  .gain(0.2)
  .pan(0.8)
  .delay(0.4)
  .delayfeedback(0.6)
  .tremolo(0.3)
  .room(0.3)
  .hpf(500)

$: s("[bd*2, <~ sn>] hh*3/2")
  .slow(2)
  .swing(0.1)
  .gain(0.6)
  .crush(6)
  .shape(0.3)
  .postgain(1.5)

$: note("g2")
  .slow(16)
  .sound("supersaw")
  .gain(0.15)
  .vowel("a e o u".slow(8))
  .lpq(9)
  .leslie(0.1)
  .distort(0.05)
  .room(0.6)

$: n(perlin.range(0, 7)).scale("g:major")
  .octave(5)
  .fast(8)
  .sound("triangle")
  .gain(0.15)
  .decay(0.05)
  .sustain(0)
  .delay(0.5)
  .djf(perlin.slow(16))
  .pan(rand)

$: s("cr")
  .fast(16)
  .gain(0.1)
  .crush(perlin.range(2, 7).slow(5))
  .pan(perlin.slow(7))
  .room(0.8)