// Goldberg Variations - Ground Bass (BWV 988)
// The 8-note descending bass that underlies all 30 variations

setcps(80/60/4)

$: note("g3 gb3 e3 d3 b2 c3 d3 g2")
  .slow(2)
  .sound("pulse")
  .gain(0.25)
  .shape(0.2)
  .lpf(perlin.range(300, 1500).slow(6))
  .resonance(5)
  .pan(0.4)
  .room(0.1)

$: note("d5 b4 c5 a4 g4 a4 b4 d5")
  .slow(2)
  .sound("piano")
  .gain(0.2)
  .pan(0.8)
  .delay(0.4)
  .delayfeedback(0.6)
  .tremolosync(2)
  .hpf(500)

$: s("[bd, sn] <hh oh>*2")
  .slow(2)
  .swing(0.1)
  .gain(0.7)
  .lpf(800)
  .crush(5)
  .shape(0.4)
  .room(0.1)

$: note("g2 e2 c2 g2")
  .slow(16)
  .sound("supersaw")
  .gain(0.15)
  .vowel("a e o u".slow(8))
  .lpq(9)
  .leslie(0.1)
  .distort(0.05)
  .room(0.6)

$: n(perlin.range(0, 7)).scale("g:minor")
  .octave(5)
  .fast(8)
  .sound("triangle")
  .gain(0.15)
  .decay(0.05)
  .sustain(0)
  .delay(0.5)
  .djf(perlin.slow(16))
  .pan(rand)

$: s("<cr oh>")
  .fast(16)
  .gain(0.1)
  .bpf(perlin.range(2000, 8000).slow(9))
  .crush(perlin.range(2, 7).slow(5))
  .pan(perlin.slow(7))
  .delay(0.1)
  .room(0.5)