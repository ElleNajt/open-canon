// Goldberg Evolutions
setcps(70/60/4)

$: note("gb3/2 [d3 b2] c3~/2 g2")
  .euclid(5,8)
  .slow(4)
  .sound("pulse")
  .gain(0.18)
  .lpf(perlin.range(400, 2500).slow(6)).lpq(5)
  .shape(0.3)
  .vowel("o u".slow(2))
  .room(0.5)

$: note("<d5 c5> b4? <g4 bb4> [g5 fs5]").euclid(5,9)
  .slow(2)
  .sound("square")
  .gain(0.09)
  .bpf(sine.range(800, 3500).slow(4)).bpq(6)
  .delay(0.6).dfb(0.7).dt("3/16")
  .phaser(perlin.range(0.1, 10).slow(8))
  .shape(0.4)
  .pan(perlin.range(0.1, 0.9).slow(10))

$: s("<bd sn:1> <bd*2 [sn:2 cp?]> [ht [~ mt]] <[sn:2 cp]!2 sn:3>").chop(perlin.range(4,16).slow(6))
  .slow(4)
  .gain(0.45)
  .compressor("-18:6:3:0.01:0.3")
  .ringf(perlin.range(20, 300).slow(10))
  .crush(perlin.range(5, 9).slow(10))
  .ply(sine.range(1, 3).slow(2))
  .room(0.3)

$: chord("g2minor f2major eb2major d2minor")
  .slow(8)
  .sound("supersaw")
  .gain(0.15)
  .trem(sine.range(0.1, 0.5).slow(4))
  .lpf(perlin.range(200, 1200).slow(10)).lpattack(2)
  .hpf(100)
  .shape(0.1)
  .room(0.8).size(0.9)

$: n("0 3 5 7 8 10 12").iter(8).scale("g:minor")
  .fast(4)
  .sound("triangle")
  .gain(0.10)
  .release(0.2)
  .jux(x => x.add(4))
  .delay(0.5).dt("3/16").dfb(0.6)
  .bpf(perlin.range(1000, 6000).slow(6)).bpq(8)
  .crush(7)
  .pan(saw.range(0.1, 0.9).slow(8))

$: s("[hh oh*2] [cr cp? ~] hh*2 [cp oh]").palindrome()
  .fast(2)
  .gain(0.18)
  .chop(perlin.range(8, 24).slow(10))
  .hpf(perlin.range(5000, 9000).slow(10)).hpq(5)
  .delay(0.3).dfb(0.5).dt("1/8")
  .vowel("i o".slow(2))
  .pan(perlin.range(0.2, 0.8).slow(12))