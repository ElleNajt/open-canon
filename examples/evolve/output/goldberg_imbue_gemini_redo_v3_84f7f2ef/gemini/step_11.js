// Goldberg Evolutions
setcps(74/60/4)

$: note("gb3 eb3/2 [d3 b2] c3 ab2/2 [g2 d3]/2 g3?")
  .slow(4)
  .sound("sawtooth")
  .gain(0.14)
  .lpf(perlin.range(400, 4000).slow(5))
  .lpq(8)
  .room(0.3)
  .drive(0.6)
  .slide(0.03)

$: note("[d5 c5?]/2 b4 <g4 fs4 g4> [d5 g5 d5 fs5]").euclid(5,8)
  .slow(2)
  .sound("square")
  .gain(0.07)
  .lpf(saw.range(400, 2500).slow(8))
  .lpenv(2500)
  .delay(0.5)
  .dfb(0.7)
  .fmi(cosine.range(0.5, 8).slow(10))
  .phaser(tri.range(0.1, 2).slow(10))

$: s("[[bd sn]*2] [bd [cp ht?]] [sn bd [~ rim]] [bd/2,sn]")
  .slow(4)
  .gain(0.35)
  .compressor("-20:4:5:0.01:0.25")
  .djf(saw.range(0.1, 0.9).slow(5))
  .room(0.1)
  .crush(6)
  .shape(0.3)

$: chord("g2minor f2major eb3major d2minor7")
  .slow(16)
  .sound("supersaw")
  .gain(0.12)
  .detune(cosine.range(-15, 15).slow(13))
  .lpf(150)
  .lpattack(8)
  .phaser(tri.range(0.2, 1.2).slow(12))
  .tremolosync(8).tremolodepth(0.5)

$: n(perlin.range(0,15)).scale("g:minor")
  .euclid(5,8)
  .iter(4)
  .fast(12)
  .sound("pulse")
  .gain(0.08)
  .release(0.1)
  .delay(0.7).dt("3/8").dfb(0.75)
  .vowel("a e o u".slow(3))
  .pan(saw.range(0.1, 0.9).slow(6))
  .ring(cosine.range(0.1, 0.8).slow(9))

$: s("[hh*3 [~ oh]] <[cr,hh] [oh ht]>/2 hh*2")
  .fast(4)
  .sometimes(() => rev())
  .gain(0.15)
  .speed(perlin.range(0.8, 1.4).slow(10))
  .hpf(perlin.range(5000,9000).slow(12))
  .hpq(6)
