// Goldberg Evolutions
setcps(74/60/4)

$: note("gb3 eb3/2 [d3 b2] c3 ab2/2 g2 [d3 g3?]/2")
  .slow(4)
  .sound("pulse")
  .gain(0.14)
  .djf(saw.range(0.9, 0.1).slow(8))
  .drive(0.4)
  .room(0.3)
  .shape(0.3)

$: note("[d5 c5?]/2 b4 <g4 a4 g4> [d5 g5 d5 fs5]").euclid(5,8)
  .slow(2)
  .sound("square")
  .gain(0.08)
  .lpf(sine.range(800, 3500).slow(6))
  .lpenv(2000)
  .delay(0.5).dfb(0.7)
  .fmi(cosine.range(1, 15).slow(8))
  .phaser(perlin.range(0.1, 3).slow(7))

$: s("[bd sn] [bd sn?]/2 <cp [~ ht]> [sn bd <~ rim>]").ply(2)
  .slow(4)
  .gain(0.35)
  .compressor("-20:4:5:0.01:0.25")
  .bpf(perlin.range(200, 2000).slow(8)).bpq(5)
  .room(0.1)
  .delay(0.2).dfb(0.5).dt("1/8")
  .coarse(perlin.range(3, 8).slow(6))

$: chord("g2minor c2minor eb2major d2major")
  .slow(8)
  .sound("supersaw")
  .gain(0.12)
  .detune(cosine.range(-15, 15).slow(13))
  .lpf(150).lpattack(4)
  .trem(cosine.range(0, 0.5).slow(7))
  .room(0.6).size(0.9)
  .hpf(100)

$: n(perlin.range(0,15)).scale("g:minor")
  .euclid(7,12)
  .iter(4)
  .fast(8)
  .sound("triangle")
  .gain(0.09)
  .release(0.1)
  .delay(0.7).dt("3/8").dfb(0.75)
  .pan(saw.range(0.1, 0.9).slow(6))
  .lpf(2500).lpenv(4000).lpdecay(0.05)
  .ring(perlin.range(0.1, 0.5).slow(9))
  .crush(cosine.range(8, 4).slow(10))

