// Goldberg Evolutions
setcps(80/60/4)

$: note("g3 gb3 e3 d3 b2 c3 d3 g2")
  .slow(4)
  .sound("sawtooth")
  .gain(0.2)
  .lpf(perlin.range(200, 1000).slow(8))
  .lpq(6)

$: note("<d5 c5> b4 <a4 g4> a4 b4 d5")
  .slow(2)
  .sound("square")
  .gain(0.15)
  .delay(0.5)
  .dfb(0.7)

$: s("bd sn bd [sn cp/2]")
  .slow(4)
  .gain(0.6)
  .crush(6)
  .distort(0.2)
  .lpf(2000)

$: note("g2 e2 c2 g2")
  .slow(16)
  .sound("supersaw")
  .gain(0.2)
  .vowel("a u")
  .lpf(400)

$: n(perlin.range(0, 14)).scale("g:minor")
  .euclid(7,11)
  .fast(4)
  .sound("sine")
  .gain(0.2)
  .release(0.1)

$: s("<rim mt>?")
  .fast(16)
  .gain(0.15)
  .bpf(perlin.range(1000, 6000).slow(7))
  .crush(4)
  .pan(perlin.slow(5))