samples('shabda/speech:thought,memory,dream')
setcps(70/60/4)

$: note("[gb3 d4? bb3 ~ a3] <c4,eb4>")
  .slow(4)
  .sound("square")
  .gain(0.15)
  .distort(0.4)
  .lpf(perlin.range(500, 2500).slow(12)).lpq(6)
  .tremolo(saw.range(0.1, 0.5).slow(6))
  .delay(0.4).dt("3/16").dfb(0.5)
  .room(0.5)

$: note("[g4 bb4? d5 <c5 eb5>]")
  .slow(4)
  .sound("sawtooth")
  .gain(0.1)
  .phaser(sine.range(0.1, 4).slow(10))
  .penv(-36).pdecay(0.05).prelease(0.3)
  .lpf(400).lpenv(7000).lpdecay(0.8)
  .delay(0.5).dfb(0.6).dt("1/8")
  .room(0.6)

$: stack(s("bd").euclid(3,8), s("[~ sn cp ~ sn? <cb mt>]").slow(2))
  .gain(0.5)
  .pan(saw.range(0.2, 0.8).slow(12))
  .compressor("threshold:-24:ratio:6:knee:10:attack:0.01:release:0.25")
  .shape(0.25)
  .delay(0.2).dfb(0.4).dt("3/32")
  .room(0.3)

$: chord("eb2major9 db2major7:1 f2minor7:1 gb2major7")
  .slow(12)
  .sound("supersaw")
  .gain(0.12)
  .jux(x => x.octave(1).gain(0.7))
  .detune(6)
  .lpf(perlin.range(200, 2200).slow(14)).lpattack(3).lpdecay(5)
  .delay(0.5).dt("1/4").dfb(0.6)
  .room(0.7).size(0.9)

$: s("thought memory dream").slow(10)
  .euclid(3, 11).every(2, rev)
  .gain(0.25)
  .chop(16)
  .speed(perlin.range(0.8, 1.2).slow(7))
  .lpf(perlin.range(800, 5000).slow(8)).lpq(4)
  .delay(0.5).dt("3/16").dfb(0.7)
  .room(0.6)

$: s("[hh*4 oh? hh]/2").fast(8).ply(2)
  .gain(0.08)
