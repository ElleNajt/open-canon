// Goldberg Evolutions
setcps(74/60/4)

$: note("gb3 e3 [d3 b2] c3 d3 g2 g3")
  .slow(4)
  .sound("sawtooth")
  .gain(0.15)
  .lpf(perlin.range(400, 1800).slow(6))
  .lpq(7)
  .room(0.4)
  .phaser(0.2)

$: note("<d5 c5> b4 <g4 a4> g4 b4 [d5 g5]")
  .slow(2)
  .sound("square")
  .gain(0.08)
  .vowel("i e a o u")
  .jux(rev)
  .delay(0.5)
  .dfb(0.7)
  .fm(2)
  .pan(sine.slow(5))

$: s("[bd sn] bd [~ sn cp/2] [bd bd/2]")
  .slow(4)
  .gain(0.4)
  .striate(perlin.range(8, 24).slow(16))
  .djf(saw.range(0.2, 0.8).slow(8))
  .room(0.1)
  .crush(8)

$: chord("g2minor d3major c3major b2dim")
  .slow(16)
  .sound("supersaw")
  .gain(0.12)
  .detune(cosine.range(-15, 15).slow(13))
  .lpf(100)
  .lpenv(2000)
  .lpattack(6)
  .lprelease(6)
  .room(0.8)

$: n(perlin.range(0,15)).scale("g:minor")
  .euclid(7,11)
  .iter(2)
  .fast(16)
  .sound("triangle")
  .gain(0.09)
  .release(0.1)
  .delay(0.6)
  .dt("3/8")
  .dfb(0.7)
  .shape(0.3)
  .pan(perlin.slow(11))

$: s("<hh*2 [~ oh]> <[~ cr]>*2")
  .fast(10)
  .degradeBy(0.1)
  .gain(0.16)
  .speed(perlin.range(0.8, 1.2).slow(7))
  .hpf(7000)
  .crush(10)
  .delay(0.4)
  .dt("3/16")
