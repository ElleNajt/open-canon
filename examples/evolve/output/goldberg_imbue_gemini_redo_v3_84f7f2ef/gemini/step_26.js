samples('shabda/speech:thought,memory,dream')
setcps(68/60/4)

$: note("[gb3 d4 bb3 ~ a3] <c4,eb4>")
  .slow(4)
  .sound("square")
  .gain(0.15)
  .shape(0.7)
  .lpf(perlin.range(400, 3500).slow(8)).lpq(5)
  .tremolo(sine.range(0.1, 0.6).slow(8))
  .delay(0.4).dt("1/8").dfb(0.6)
  .room(0.4)

$: note("[g4 bb4 d5 <c5 eb5>]")
  .slow(4)
  .sound("sawtooth")
  .gain(0.1)
  .crush(perlin.range(4, 9).slow(5))
  .penv(-24).pdecay(0.1).prelease(0.2)
  .lpf(500).lpenv(6000).lpdecay(0.6)
  .delay(0.5).dfb(0.7).dt("3/8")
  .room(0.5)

$: stack(s("bd").euclid(5,16), s("[~ sn, ~ <cp rim>]").every(3, rev))
  .gain(0.45)
  .pan(saw.range(0.25, 0.75).slow(16))
  .crush(perlin.range(6, 12).slow(12))
  .shape(0.3)
  .delay(0.3).dfb(0.5).dt("3/16")
  .room(0.2)

$: chord("eb2major9 db2major7:1 f2minor7")
  .slow(8)
  .sound("supersaw")
  .gain(0.12)
  .jux(x => x.detune(8))
  .lpf(perlin.range(300, 1800).slow(16)).lpattack(2).lpdecay(4)
  .fmi(perlin.range(0, 7).slow(12)).fmh(0.5)
  .delay(0.6).dt("1/2").dfb(0.7)
  .room(0.8).size(0.95)

$: s("thought memory dream").slow(8)
