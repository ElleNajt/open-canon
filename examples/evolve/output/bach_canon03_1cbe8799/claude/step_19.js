setcps(120/60/4)

let upperVoice = x => x
  .sound("triangle")
  .gain(0.44)
  .attack(0.08)
  .decay(0.32)
  .sustain(0.15)
  .lpf(sine.range(900, 2800).slow(10))
  .room(0.7)
  .size(0.88)

let lowerVoice = x => x
  .sound("supersaw")
  .gain(0.18)
  .decay(0.4)
  .sustain(0.1)
  .lpf(sine.range(300, 900).slow(6))
  .room(0.55)
  .shape(0.25)

$: note("<d5 fs5 a5 g5 b5 e5 d6 a5>")
  .slow(12)
  .apply(upperVoice)
  .pan(sine.range(0.2, 0.45).slow(8))
  .off(0.25, x => x.note(x => x + 7).gain(0.09).pan(0.75).lpf(1200))
  .off(0.5, x => x.note(x => x + 12).gain(0.04).pan(0.5).lpf(1800).room(0.95))
  .vowel("<a i o e u o>".slow(9))
  .phaser(sine.range(0.06, 0.35).slow(13))
  .phaserdepth(sine.range(0.15, 0.45).slow(8))
  .delay(0.22)
  .delaytime(0.375)
  .delayfeedback(0.42)

$: note("<g2 d3 b2 e2 a2 c2 d2 g2>")
  .slow(14)
  .sound("sine")
  .gain(perlin.range(0.22, 0.38).slow(9))
  .attack(1.5)
  .release(6.0)
  .lpf(sine.range(40, 220).slow(11))
  .lpq(perlin.range(4, 12).slow(8))
  .room(0.75)
  .size(0.96)
  .pan(sine.range(0.3, 0.7).slow(10))
  .fmi(perlin.range(0.2, 3.2).slow(9))
  .fmh(perlin.range(0.5, 2.5).slow(5))
  .fmdecay(2.5)
  .fmrelease(5.0)

$: note("<g4 a4 fs4 b4 e4 d4 a4 g4>")
  .slow(15)
  .apply(lowerVoice)
  .pan(sine.range(0.55, 0.78).slow(11))
  .fmi(perlin.range(0.3, 2.6).slow(7))
  .fmh(perlin.range(1.0, 3.5).slow(5))
  .off(0.125, x => x.note(x => x + 5).gain(0.07).lpf(500).room(0.6).pan(0.28))
  .leslie(sine.range(0.15, 0.9).slow(9))
  .lrate(sine.range(0.15, 0.7).slow(6))
  .tremolo(perlin.range(0.05, 0.3).slow(8))
  .tremolosync(perlin.range(2, 6).slow(12))
  .detune(sine.range(-8, 8).slow(13))
  .delay(0.15)
  .delaytime(0.25)
  .delayfeedback(0.32)