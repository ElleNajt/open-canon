setcps(120/60/4)

let upperVoice = x => x
  .sound("triangle")
  .gain(0.28)
  .attack(0.6)
  .decay(1.2)
  .sustain(0.03)
  .lpf(sine.range(280, 1100).slow(7))
  .room(0.94)
  .size(0.98)

let lowerVoice = x => x
  .sound("supersaw")
  .gain(0.10)
  .decay(1.8)
  .sustain(0.03)
  .lpf(sine.range(140, 420).slow(8))
  .room(0.82)
  .shape(0.22)

$: note("<d5 fs5 a5 g5 b5 e5 d6 a5>")
  .slow(11)
  .apply(upperVoice)
  .pan(sine.range(0.1, 0.5).slow(13))
  .off(0.25, x => x.note(x => x + 7).gain(0.04).pan(0.78).lpf(580))
  .off(0.5, x => x.note(x => x + 12).gain(0.01).pan(0.5).lpf(900).room(0.99))
  .vowel("<a o i e u a>".slow(9))
  .phaser(sine.range(0.03, 0.22).slow(5))
  .phaserdepth(sine.range(0.15, 0.6).slow(6))
  .delay(0.32)
  .delaytime(0.375)
  .delayfeedback(0.42)

$: note("<g2 d3 b2 e2 c3 a2 f2>")
  .slow(16)
  .sound("sine")
  .gain(perlin.range(0.04, 0.13).slow(10))
  .attack(14.0)
  .release(22.0)
  .lpf(sine.range(40, 130).slow(12))
  .lpq(perlin.range(8, 22).slow(7))
  .room(0.99)
  .size(0.99)
  .pan(sine.range(0.25, 0.75).slow(15))
  .fmi(perlin.range(0.01, 1.4).slow(11))
  .fmh(perlin.range(0.5, 2.0).slow(8))
  .fmdecay(16.0)
  .fmrelease(22.0)

$: note("<g4 b4 fs4 a4 e4 c4>")
  .slow(13)
  .apply(lowerVoice)
  .pan(sine.range(0.55, 0.9).slow(9))
  .fmi(perlin.range(0.1, 2.0).slow(7))
  .fmh(perlin.range(1.5, 3.5).slow(4))
  .off(0.125, x => x.note(x => x + 5).gain(0.03).lpf(260).room(0.9).pan(0.1))
  .leslie(sine.range(0.0, 0.5).slow(11))
  .lrate(sine.range(0.06, 0.35).slow(7))
  .tremolo(perlin.range(0.01, 0.06).slow(10))
  .tremolosync(perlin.range(3, 7).slow(8))
  .detune(sine.range(-8, 8).slow(12))
  .delay(0.14)
  .delaytime(0.5)
  .delayfeedback(0.3)