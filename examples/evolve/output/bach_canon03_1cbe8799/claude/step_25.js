setcps(120/60/4)

let upperVoice = x => x
  .sound("triangle")
  .gain(0.35)
  .attack(0.3)
  .decay(0.7)
  .sustain(0.06)
  .lpf(sine.range(400, 1600).slow(11))
  .room(0.88)
  .size(0.95)

let lowerVoice = x => x
  .sound("supersaw")
  .gain(0.14)
  .decay(1.2)
  .sustain(0.05)
  .lpf(sine.range(180, 520).slow(7))
  .room(0.75)
  .shape(0.25)

$: note("<d5 fs5 a5 g5 b5 e5 d6 a5>")
  .slow(14)
  .apply(upperVoice)
  .pan(sine.range(0.1, 0.5).slow(10))
  .off(0.25, x => x.note(x => x + 7).gain(0.05).pan(0.72).lpf(700))
  .off(0.5, x => x.note(x => x + 12).gain(0.015).pan(0.5).lpf(1100).room(0.97))
  .vowel("<a o e i>".slow(9))
  .phaser(sine.range(0.03, 0.22).slow(8))
  .phaserdepth(sine.range(0.15, 0.5).slow(5))
  .delay(0.32)
  .delaytime(0.375)
  .delayfeedback(0.42)

$: note("<g2 d3 b2 a2 e2 c3>")
  .slow(16)
  .sound("sine")
  .gain(perlin.range(0.06, 0.18).slow(9))
  .attack(8.0)
  .release(16.0)
  .lpf(sine.range(55, 180).slow(12))
  .lpq(perlin.range(4, 14).slow(6))
  .room(0.97)
  .size(0.99)
  .pan(sine.range(0.25, 0.75).slow(15))
  .fmi(perlin.range(0.01, 2.2).slow(10))
  .fmh(perlin.range(0.5, 2.0).slow(7))
  .fmdecay(10.0)
  .fmrelease(16.0)

$: note("<g4 b4 fs4 a4 e4 d4>")
  .slow(11)
  .apply(lowerVoice)
  .pan(sine.range(0.55, 0.9).slow(9))
  .fmi(perlin.range(0.1, 2.0).slow(6))
  .fmh(perlin.range(1.5, 3.0).slow(4))
  .off(0.125, x => x.note(x => x + 5).gain(0.04).lpf(300).room(0.85).pan(0.15))
  .leslie(sine.range(0.05, 0.5).slow(10))
  .lrate(sine.range(0.1, 0.35).slow(6))
  .tremolo(perlin.range(0.02, 0.1).slow(9))
  .tremolosync(perlin.range(3, 7).slow(7))
  .detune(sine.range(-8, 8).slow(12))
  .delay(0.22)
  .delaytime(0.333)
  .delayfeedback(0.4)