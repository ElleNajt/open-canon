setcps(120/60/4)

let upperVoice = x => x
  .sound("triangle")
  .gain(0.32)
  .attack(0.4)
  .decay(0.9)
  .sustain(0.04)
  .lpf(sine.range(350, 1400).slow(9))
  .room(0.92)
  .size(0.97)

let lowerVoice = x => x
  .sound("supersaw")
  .gain(0.12)
  .decay(1.4)
  .sustain(0.04)
  .lpf(sine.range(160, 480).slow(6))
  .room(0.78)
  .shape(0.3)

$: note("<d5 fs5 a5 g5 b5 e5 d6 a5>")
  .slow(13)
  .apply(upperVoice)
  .pan(sine.range(0.12, 0.48).slow(11))
  .off(0.25, x => x.note(x => x + 7).gain(0.045).pan(0.75).lpf(650))
  .off(0.5, x => x.note(x => x + 12).gain(0.012).pan(0.5).lpf(1000).room(0.98))
  .vowel("<a e o i u>".slow(11))
  .phaser(sine.range(0.02, 0.18).slow(7))
  .phaserdepth(sine.range(0.2, 0.55).slow(4))
  .delay(0.28)
  .delaytime(0.375)
  .delayfeedback(0.38)

$: note("<g2 d3 b2 e2 c3 a2>")
  .slow(14)
  .sound("sine")
  .gain(perlin.range(0.05, 0.15).slow(8))
  .attack(10.0)
  .release(18.0)
  .lpf(sine.range(45, 160).slow(10))
  .lpq(perlin.range(6, 18).slow(5))
  .room(0.98)
  .size(0.99)
  .pan(sine.range(0.2, 0.8).slow(13))
  .fmi(perlin.range(0.01, 1.8).slow(9))
  .fmh(perlin.range(0.5, 1.5).slow(6))
  .fmdecay(12.0)
  .fmrelease(18.0)

$: note("<g4 b4 fs4 a4 e4>")
  .slow(10)
  .apply(lowerVoice)
  .pan(sine.range(0.52, 0.88).slow(8))
  .fmi(perlin.range(0.2, 2.5).slow(5))
  .fmh(perlin.range(2.0, 4.0).slow(3))
  .off(0.125, x => x.note(x => x + 5).gain(0.035).lpf(280).room(0.88).pan(0.12))
  .leslie(sine.range(0.0, 0.6).slow(9))
  .lrate(sine.range(0.08, 0.4).slow(5))
  .tremolo(perlin.range(0.01, 0.08).slow(8))
  .tremolosync(perlin.range(4, 8).slow(6))
  .detune(sine.range(-12, 12).slow(10))
  .delay(0.18)
  .delaytime(0.333)
  .delayfeedback(0.35)