setcps(120/60/4)

let upperVoice = x => x
  .sound("triangle")
  .gain(0.42)
  .attack(0.03)
  .decay(0.18)
  .sustain(0.18)
  .lpf(sine.range(1600, 2800).slow(10))
  .room(0.4)
  .size(0.7)

let lowerVoice = x => x
  .sound("square")
  .gain(0.35)
  .decay(0.2)
  .sustain(0.12)
  .lpf(sine.range(700, 1400).slow(13))
  .room(0.25)
  .shape(0.15)

// Track 1 - upper canon voice
$: note("~!40 d5 ~!7 e5 ~!7 gb5 ~!7 g5 ~!7 b5 ~!7 a5 ~!7 g5 ~!7 d6 ~!7 d5 ~!7 e5 ~!7 gb5 ~!7 g5 ~!7 b5 ~!7 a5 ~!7 g5 ~!7 d6 ~!7 d5 ~!7 e5 ~!7 gb5 ~!7 g5 ~!15")
  .slow(208/8/4)
  .apply(upperVoice)
  .pan(0.28)
  .off(0.25, x => x.note(x => x + 7).gain(0.13).pan(0.6).lpf(2000))
  .off(0.5, x => x.note(x => x + 12).gain(0.07).pan(0.4).lpf(1600).room(0.55))
  .phaser(sine.range(0.15, 0.7).slow(16))
  .phaserdepth(sine.range(0.2, 0.55).slow(11))

// Track 2 - lower canon voice, now with FM warmth creeping in
$: note("~!8 g5 ~!7 gb5 ~!7 e5 ~!7 d5 ~!7 b4 ~!7 c5 ~!7 d5 ~!7 g4 ~!7 g5 ~!7 gb5 ~!7 e5 ~!7 d5 ~!7 b4 ~!7 c5 ~!7 d5 ~!7 g4 ~!7 g5 ~!7 gb5 ~!7 e5 ~!7 d5 ~!7 b4 ~!7 c5 ~!7 d5 ~!7 g4 ~!15")
  .slow(208/8/4)
  .apply(lowerVoice)
  .pan(0.72)
  .fmi(perlin.range(0.0, 1.2).slow(16))
  .fmh(1.5)
  .juxBy(0.3, x => x.detune(18).lpf(700).room(0.4).shape(0.08))
  .leslie(sine.range(0.2, 0.8).slow(14))
  .lrate(0.6)

// Track 3 - bass, now subtly pulsing with tremolo
$: note("<g2 g2 d3 b2>")
  .sound("sine")
  .gain(perlin.range(0.20, 0.32).slow(7))
  .attack(0.2)
  .release(1.2)
  .lpf(sine.range(180, 480).slow(11))
  .room(0.45)
  .size(0.8)
  .pan(0.5)
  .fmi(perlin.range(0.3, 2.2).slow(9))
  .fmh(perlin.range(1.5, 3.0).slow(15))
  .fmdecay(0.5)
  .fmrelease(0.8)
  .tremolo(perlin.range(0.0, 0.5).slow(12))
  .tremolosync(2)

// Track 4 - sparse shimmer, delay now breathing with perlin time
$: note("<d6 ~ g5 ~ b5 ~ ~ e6>")
  .sound("triangle")
  .gain(perlin.range(0.08, 0.16).slow(6))
  .attack(0.3)
  .decay(0.8)
  .sustain(0.04)
  .release(2.2)
  .lpf(sine.range(2400, 4000).slow(8))
  .room(0.85)
  .size(0.95)
  .pan(sine.range(0.15, 0.85).slow(13))
  .degradeBy(0.45)
  .delay(0.5)
  .delaytime(perlin.range(0.38, 0.62).slow(8))
  .delayfeedback(0.38)
  .phaser(0.3)
  .phaserdepth(sine.range(0.2, 0.6).slow(9))