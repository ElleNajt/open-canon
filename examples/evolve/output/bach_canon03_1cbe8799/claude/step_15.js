setcps(120/60/4)

let upperVoice = x => x
  .sound("triangle")
  .gain(0.42)
  .attack(0.03)
  .decay(0.18)
  .sustain(0.18)
  .lpf(sine.range(1400, 2600).slow(12))
  .room(0.5)
  .size(0.75)

let lowerVoice = x => x
  .sound("square")
  .gain(0.32)
  .decay(0.22)
  .sustain(0.12)
  .lpf(sine.range(600, 1300).slow(11))
  .room(0.3)
  .shape(0.18)

$: note("<d5 e5 fs5 g5 b5 a5 g5 d6>")
  .slow(24)
  .apply(upperVoice)
  .pan(0.28)
  .off(0.25, x => x.note(x => x + 7).gain(0.12).pan(0.65).lpf(1800))
  .off(0.5, x => x.note(x => x + 12).gain(0.06).pan(0.5).lpf(2400).room(0.85))
  .vowel("<a e i o>".slow(6))
  .phaser(sine.range(0.1, 0.5).slow(14))
  .phaserdepth(sine.range(0.15, 0.45).slow(9))

$: note("<g5 fs5 e5 d5 b4 c5 d5 g4>")
  .slow(24)
  .apply(lowerVoice)
  .pan(0.72)
  .fmi(perlin.range(0.5, 2.5).slow(10))
  .fmh(perlin.range(1.0, 3.0).slow(7))
  .juxBy(0.3, x => x.detune(24).lpf(800).room(0.55).shape(0.25))
  .leslie(sine.range(0.2, 0.8).slow(13))
  .lrate(sine.range(0.3, 0.7).slow(8))

$: note("<g2 g2 d3 b2 a2 g2 e2 d2>")
  .slow(16)
  .sound("sine")
  .gain(perlin.range(0.28, 0.42).slow(9))
  .attack(0.5)
  .release(3.0)
  .lpf(sine.range(80, 380).slow(11))
  .lpq(perlin.range(2, 7).slow(8))
  .room(0.5)
  .size(0.85)
  .pan(sine.range(0.38, 0.62).slow(14))
  .fmi(perlin.range(0.5, 3.5).slow(9))
  .fmh(perlin.range(1.0, 2.5).slow(6))
  .fmdecay(1.0)
  .fmrelease(2.0)
  .tremolo(perlin.range(0.1, 0.5).slow(8))
  .tremolosync(2)