setcps(120/60/4)

let upperVoice = x => x
  .sound("triangle")
  .gain(0.42)
  .attack(0.03)
  .decay(0.18)
  .sustain(0.18)
  .lpf(sine.range(1400, 2600).slow(12))
  .room(0.5)
  .size(0.75)

let lowerVoice = x => x
  .sound("square")
  .gain(0.32)
  .decay(0.22)
  .sustain(0.12)
  .lpf(sine.range(600, 1300).slow(11))
  .room(0.3)
  .shape(0.18)

$: note("<d5 e5 fs5 g5 b5 a5 g5 d6>")
  .slow(32)
  .apply(upperVoice)
  .pan(0.28)
  .off(0.25, x => x.note(x => x + 7).gain(0.12).pan(0.65).lpf(1800))
  .vowel("<a e i o>".slow(8))
  .phaser(sine.range(0.1, 0.5).slow(14))
  .phaserdepth(sine.range(0.15, 0.45).slow(9))

$: note("<g5 fs5 e5 d5 b4 c5 d5 g4>")
  .slow(32)
  .apply(lowerVoice)
  .pan(0.72)
  .fmi(perlin.range(0.2, 1.8).slow(13))
  .fmh(perlin.range(1.0, 2.0).slow(9))
  .juxBy(0.2, x => x.detune(18).lpf(700).room(0.45))
  .leslie(sine.range(0.1, 0.6).slow(16))
  .lrate(0.4)

