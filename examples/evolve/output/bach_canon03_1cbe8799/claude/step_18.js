setcps(120/60/4)

let upperVoice = x => x
  .sound("triangle")
  .gain(0.42)
  .attack(0.06)
  .decay(0.28)
  .sustain(0.18)
  .lpf(sine.range(1000, 2600).slow(12))
  .room(0.65)
  .size(0.85)

let lowerVoice = x => x
  .sound("supersaw")
  .gain(0.16)
  .decay(0.35)
  .sustain(0.08)
  .lpf(sine.range(350, 850).slow(7))
  .room(0.5)
  .shape(0.2)

$: note("<d5 e5 fs5 b5 a5 g5 d6 fs5>")
  .slow(14)
  .apply(upperVoice)
  .pan(sine.range(0.22, 0.42).slow(9))
  .off(0.25, x => x.note(x => x + 7).gain(0.11).pan(0.72).lpf(1400))
  .off(0.5, x => x.note(x => x + 12).gain(0.05).pan(0.5).lpf(2000).room(0.92))
  .vowel("<a e i o u i>".slow(8))
  .phaser(sine.range(0.08, 0.4).slow(11))
  .phaserdepth(sine.range(0.1, 0.4).slow(7))
  .delay(0.18)
  .delaytime(0.375)
  .delayfeedback(0.38)

$: note("<g2 d3 b2 a2 e2 d2 c2 g2>")
  .slow(16)
  .sound("sine")
  .gain(perlin.range(0.25, 0.4).slow(8))
  .attack(1.2)
  .release(5.0)
  .lpf(sine.range(45, 260).slow(13))
  .lpq(perlin.range(3, 9).slow(7))
  .room(0.7)
  .size(0.95)
  .pan(sine.range(0.35, 0.65).slow(12))
  .fmi(perlin.range(0.1, 2.8).slow(11))
  .fmh(perlin.range(0.5, 2.0).slow(6))
  .fmdecay(2.0)
  .fmrelease(4.0)

$: note("<g4 fs4 a4 e4 d4 b4 a4 g4>")
  .slow(18)
  .apply(lowerVoice)
  .pan(0.68)
  .fmi(perlin.range(0.4, 2.2).slow(8))
  .fmh(perlin.range(1.2, 3.2).slow(6))
  .off(0.125, x => x.note(x => x + 5).gain(0.08).lpf(550).room(0.55).pan(0.3))
  .leslie(sine.range(0.1, 0.8).slow(10))
  .lrate(sine.range(0.2, 0.6).slow(7))
  .tremolo(perlin.range(0.04, 0.28).slow(9))
  .tremolosync(perlin.range(3, 7).slow(14))
  .detune(sine.range(-12, 12).slow(16))
  .delay(0.12)
  .delaytime(0.25)
  .delayfeedback(0.28)