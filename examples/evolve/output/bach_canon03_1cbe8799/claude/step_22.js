setcps(120/60/4)

let upperVoice = x => x
  .sound("triangle")
  .gain(0.38)
  .attack(0.15)
  .decay(0.5)
  .sustain(0.1)
  .lpf(sine.range(600, 2200).slow(11))
  .room(0.8)
  .size(0.92)

let lowerVoice = x => x
  .sound("supersaw")
  .gain(0.16)
  .decay(0.7)
  .sustain(0.08)
  .lpf(sine.range(180, 580).slow(7))
  .room(0.7)
  .shape(0.3)

$: note("<d5 fs5 a5 g5 b5 e5 d6 a5>")
  .slow(16)
  .apply(upperVoice)
  .pan(sine.range(0.12, 0.52).slow(11))
  .off(0.25, x => x.note(x => x + 7).gain(0.06).pan(0.8).lpf(800))
  .off(0.5, x => x.note(x => x + 12).gain(0.02).pan(0.5).lpf(1200).room(0.97))
  .vowel("<a o i u e>".slow(11))
  .phaser(sine.range(0.02, 0.18).slow(9))
  .phaserdepth(sine.range(0.1, 0.4).slow(6))
  .delay(0.28)
  .delaytime(0.375)
  .delayfeedback(0.38)

$: note("<g2 d3 b2 e2 a2 c3>")
  .slow(14)
  .sound("sine")
  .gain(perlin.range(0.12, 0.24).slow(8))
  .attack(4.0)
  .release(10.0)
  .lpf(sine.range(40, 160).slow(9))
  .lpq(perlin.range(6, 16).slow(5))
  .room(0.92)
  .size(0.99)
  .pan(sine.range(0.28, 0.72).slow(13))
  .fmi(perlin.range(0.02, 1.8).slow(11))
  .fmh(perlin.range(0.5, 1.5).slow(6))
  .fmdecay(5.0)
  .fmrelease(10.0)

$: note("<g4 a4 fs4 b4 e4 d4 c4 e4>")
  .slow(13)
  .apply(lowerVoice)
  .pan(sine.range(0.5, 0.88).slow(9))
  .fmi(perlin.range(0.05, 1.8).slow(8))
  .fmh(perlin.range(1.2, 2.8).slow(4))
  .off(0.125, x => x.note(x => x + 5).gain(0.04).lpf(320).room(0.75).pan(0.15))
  .leslie(sine.range(0.05, 0.6).slow(11))
  .lrate(sine.range(0.08, 0.4).slow(7))
  .tremolo(perlin.range(0.02, 0.14).slow(10))
  .tremolosync(perlin.range(2, 6).slow(8))
  .detune(sine.range(-12, 12).slow(14))
  .delay(0.18)
  .delaytime(0.333)
  .delayfeedback(0.34)