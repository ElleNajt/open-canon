setcps(120/60/4)

let upperVoice = x => x
  .sound("triangle")
  .gain(0.42)
  .attack(0.03)
  .decay(0.18)
  .sustain(0.18)
  .lpf(sine.range(1600, 2800).slow(10))
  .room(0.4)
  .size(0.7)

let lowerVoice = x => x
  .sound("square")
  .gain(0.35)
  .decay(0.2)
  .sustain(0.12)
  .lpf(sine.range(700, 1400).slow(13))
  .room(0.25)
  .shape(0.15)

// Track 1 - upper canon voice
$: note("~!40 d5 ~!7 e5 ~!7 gb5 ~!7 g5 ~!7 b5 ~!7 a5 ~!7 g5 ~!7 d6 ~!7 d5 ~!7 e5 ~!7 gb5 ~!7 g5 ~!7 b5 ~!7 a5 ~!7 g5 ~!7 d6 ~!7 d5 ~!7 e5 ~!7 gb5 ~!7 g5 ~!15")
  .slow(208/8/4)
  .apply(upperVoice)
  .pan(0.28)
  .off(0.25, x => x.note(x => x + 7).gain(0.13).pan(0.6).lpf(2000))
  .off(0.5, x => x.note(x => x + 12).gain(0.07).pan(0.4).lpf(1600).room(0.55))
  .phaser(sine.range(0.15, 0.7).slow(16))
  .phaserdepth(0.3)

// Track 2 - lower canon voice
$: note("~!8 g5 ~!7 gb5 ~!7 e5 ~!7 d5 ~!7 b4 ~!7 c5 ~!7 d5 ~!7 g4 ~!7 g5 ~!7 gb5 ~!7 e5 ~!7 d5 ~!7 b4 ~!7 c5 ~!7 d5 ~!7 g4 ~!7 g5 ~!7 gb5 ~!7 e5 ~!7 d5 ~!7 b4 ~!7 c5 ~!7 d5 ~!7 g4 ~!15")
  .slow(208/8/4)
  .apply(lowerVoice)
  .pan(0.72)
  .juxBy(0.3, x => x.detune(18).lpf(700).room(0.4).shape(0.08))

// Track 3 - bass, slowly morphing
$: note("<g2 g2 d3 b2>")
  .sound("sine")
  .gain(perlin.range(0.18, 0.30).slow(7))
  .attack(0.15)
  .release(1.0)
  .lpf(sine.range(200, 420).slow(11))
  .room(0.4)
  .size(0.75)
  .pan(0.5)
  .fmi(perlin.range(0.2, 1.5).slow(9))
  .fmh(2)
  .fmdecay(0.4)

// Track 4 - sparse shimmer with vowel drift
$: note("<d6 ~ g5 ~ b5 ~ ~ e6>")
  .sound("triangle")
  .gain(perlin.range(0.10, 0.20).slow(6))
  .attack(0.18)
  .decay(0.6)
  .sustain(0.06)
  .release(1.6)
  .lpf(3200)
  .vowel(saw.range(0, 1).slow(12))
  .room(0.7)
  .size(0.92)
  .pan(sine.range(0.2, 0.8).slow(9))
  .degradeBy(0.4)
  .delay(0.35)
  .delaytime(0.375)
  .delayfeedback(0.28)