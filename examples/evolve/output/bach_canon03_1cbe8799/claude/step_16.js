setcps(120/60/4)

let upperVoice = x => x
  .sound("triangle")
  .gain(0.44)
  .attack(0.04)
  .decay(0.22)
  .sustain(0.2)
  .lpf(sine.range(1200, 2800).slow(10))
  .room(0.6)
  .size(0.8)

let lowerVoice = x => x
  .sound("square")
  .gain(0.3)
  .decay(0.25)
  .sustain(0.14)
  .lpf(sine.range(500, 1100).slow(9))
  .room(0.35)
  .shape(0.22)

$: note("<d5 e5 fs5 g5 b5 a5 g5 d6>")
  .slow(20)
  .apply(upperVoice)
  .pan(0.28)
  .off(0.25, x => x.note(x => x + 7).gain(0.14).pan(0.68).lpf(1600))
  .off(0.5, x => x.note(x => x + 12).gain(0.07).pan(0.5).lpf(2200).room(0.9))
  .vowel("<a e i o u>".slow(8))
  .phaser(sine.range(0.15, 0.6).slow(11))
  .phaserdepth(sine.range(0.2, 0.5).slow(7))

$: note("<g2 d3 b2 a2 g2 e2 d2 c2>")
  .slow(14)
  .sound("sine")
  .gain(perlin.range(0.3, 0.45).slow(8))
  .attack(0.6)
  .release(3.5)
  .lpf(sine.range(60, 340).slow(13))
  .lpq(perlin.range(3, 9).slow(7))
  .room(0.55)
  .size(0.9)
  .pan(sine.range(0.4, 0.6).slow(12))
  .fmi(perlin.range(0.3, 2.8).slow(11))
  .fmh(perlin.range(1.0, 2.0).slow(5))
  .fmdecay(1.2)
  .fmrelease(2.5)

$: note("<g4 fs4 a4 e4 d4 g4 b4 a4>")
  .slow(28)
  .apply(lowerVoice)
  .pan(0.72)
  .fmi(perlin.range(0.4, 2.0).slow(8))
  .fmh(perlin.range(1.5, 3.5).slow(6))
  .off(0.125, x => x.note(x => x + 5).gain(0.1).lpf(700).room(0.4).pan(0.35))
  .leslie(sine.range(0.1, 0.6).slow(10))
  .lrate(sine.range(0.2, 0.6).slow(6))
  .tremolo(perlin.range(0.1, 0.4).slow(9))
  .tremolosync(4)