setcps(120/60/4)

let upperVoice = x => x
  .sound("triangle")
  .gain(0.32)
  .attack(0.8)
  .decay(1.4)
  .sustain(0.04)
  .lpf(sine.range(320, 1400).slow(9))
  .room(0.92)
  .size(0.97)

let lowerVoice = x => x
  .sound("supersaw")
  .gain(0.12)
  .decay(2.2)
  .sustain(0.04)
  .lpf(sine.range(160, 520).slow(6))
  .room(0.85)
  .shape(0.18)

$: note("<d5 fs5 a5 g5 b5 e5 d6 a5>")
  .slow(13)
  .apply(upperVoice)
  .pan(sine.range(0.15, 0.55).slow(11))
  .off(0.25, x => x.note(x => x + 7).gain(0.05).pan(0.82).lpf(640))
  .off(0.5, x => x.note(x => x + 12).gain(0.015).pan(0.5).lpf(1100).room(0.99))
  .vowel("<a o i e u>".slow(7))
  .phaser(sine.range(0.04, 0.28).slow(6))
  .phaserdepth(sine.range(0.2, 0.7).slow(8))
  .delay(0.28)
  .delaytime(0.375)
  .delayfeedback(0.38)

$: note("<g2 d3 b2 e2 c3 a2>")
  .slow(14)
  .sound("sine")
  .gain(perlin.range(0.05, 0.15).slow(12))
  .attack(16.0)
  .release(20.0)
  .lpf(sine.range(45, 160).slow(10))
  .lpq(perlin.range(6, 18).slow(9))
  .room(0.99)
  .size(0.99)
  .pan(sine.range(0.2, 0.8).slow(13))
  .fmi(perlin.range(0.02, 1.8).slow(9))
  .fmh(perlin.range(0.5, 2.5).slow(11))
  .fmdecay(18.0)
  .fmrelease(20.0)

$: note("<g4 b4 fs4 a4 e4 c4 d4>")
  .slow(11)
  .apply(lowerVoice)
  .pan(sine.range(0.5, 0.88).slow(7))
  .fmi(perlin.range(0.05, 2.4).slow(9))
  .fmh(perlin.range(1.2, 4.0).slow(5))
  .off(0.125, x => x.note(x => x + 5).gain(0.035).lpf(300).room(0.88).pan(0.12))
  .leslie(sine.range(0.0, 0.6).slow(13))
  .lrate(sine.range(0.04, 0.4).slow(9))
  .tremolo(perlin.range(0.01, 0.08).slow(12))
  .tremolosync(perlin.range(2, 6).slow(7))
  .detune(sine.range(-12, 12).slow(14))
  .delay(0.18)
  .delaytime(0.75)
  .delayfeedback(0.35)