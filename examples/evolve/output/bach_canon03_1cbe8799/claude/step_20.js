setcps(120/60/4)

let upperVoice = x => x
  .sound("triangle")
  .gain(0.44)
  .attack(0.08)
  .decay(0.32)
  .sustain(0.15)
  .lpf(sine.range(900, 2800).slow(10))
  .room(0.7)
  .size(0.88)

let lowerVoice = x => x
  .sound("supersaw")
  .gain(0.16)
  .decay(0.5)
  .sustain(0.08)
  .lpf(sine.range(250, 800).slow(8))
  .room(0.6)
  .shape(0.3)

$: note("<d5 fs5 a5 g5 b5 e5 d6 a5>")
  .slow(12)
  .apply(upperVoice)
  .pan(sine.range(0.2, 0.45).slow(8))
  .off(0.25, x => x.note(x => x + 7).gain(0.08).pan(0.75).lpf(1000))
  .off(0.5, x => x.note(x => x + 12).gain(0.03).pan(0.5).lpf(1600).room(0.95))
  .vowel("<a i o e u o>".slow(11))
  .phaser(sine.range(0.04, 0.28).slow(15))
  .phaserdepth(sine.range(0.1, 0.4).slow(9))
  .delay(0.28)
  .delaytime(0.375)
  .delayfeedback(0.38)

$: note("<g2 d3 b2 e2 a2 c2 d2 g2>")
  .slow(16)
  .sound("sine")
  .gain(perlin.range(0.18, 0.32).slow(11))
  .attack(2.0)
  .release(7.0)
  .lpf(sine.range(40, 180).slow(13))
  .lpq(perlin.range(6, 16).slow(7))
  .room(0.82)
  .size(0.97)
  .pan(sine.range(0.28, 0.72).slow(12))
  .fmi(perlin.range(0.1, 4.0).slow(11))
  .fmh(perlin.range(0.5, 3.0).slow(6))
  .fmdecay(3.0)
  .fmrelease(6.5)

$: note("<g4 a4 fs4 b4 e4 d4 a4 g4>")
  .slow(13)
  .apply(lowerVoice)
  .pan(sine.range(0.52, 0.82).slow(9))
  .fmi(perlin.range(0.2, 3.2).slow(8))
  .fmh(perlin.range(1.0, 4.0).slow(4))
  .off(0.125, x => x.note(x => x + 5).gain(0.06).lpf(450).room(0.65).pan(0.22))
  .off(0.33, x => x.note(x => x - 5).gain(0.05).lpf(350).room(0.5).pan(0.78))
  .leslie(sine.range(0.1, 0.85).slow(11))
  .lrate(sine.range(0.12, 0.6).slow(7))
  .tremolo(perlin.range(0.04, 0.25).slow(10))
  .tremolosync(perlin.range(2, 5).slow(14))
  .detune(sine.range(-12, 12).slow(15))
  .delay(0.18)
  .delaytime(0.333)
  .delayfeedback(0.36)