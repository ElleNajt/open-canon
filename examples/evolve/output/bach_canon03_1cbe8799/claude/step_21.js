setcps(120/60/4)

let upperVoice = x => x
  .sound("triangle")
  .gain(0.42)
  .attack(0.1)
  .decay(0.4)
  .sustain(0.12)
  .lpf(sine.range(700, 2400).slow(13))
  .room(0.75)
  .size(0.9)

let lowerVoice = x => x
  .sound("supersaw")
  .gain(0.14)
  .decay(0.6)
  .sustain(0.07)
  .lpf(sine.range(200, 650).slow(9))
  .room(0.65)
  .shape(0.25)

$: note("<d5 fs5 a5 g5 b5 e5 d6 a5>")
  .slow(14)
  .apply(upperVoice)
  .pan(sine.range(0.15, 0.5).slow(9))
  .off(0.25, x => x.note(x => x + 7).gain(0.07).pan(0.78).lpf(900))
  .off(0.5, x => x.note(x => x + 12).gain(0.025).pan(0.5).lpf(1400).room(0.95))
  .vowel("<a o i u e i>".slow(13))
  .phaser(sine.range(0.03, 0.22).slow(11))
  .phaserdepth(sine.range(0.15, 0.45).slow(7))
  .delay(0.32)
  .delaytime(0.375)
  .delayfeedback(0.42)

$: note("<g2 d3 b2 e2 a2 c2>")
  .slow(16)
  .sound("sine")
  .gain(perlin.range(0.14, 0.28).slow(9))
  .attack(3.0)
  .release(9.0)
  .lpf(sine.range(35, 140).slow(11))
  .lpq(perlin.range(8, 18).slow(6))
  .room(0.88)
  .size(0.98)
  .pan(sine.range(0.3, 0.7).slow(14))
  .fmi(perlin.range(0.05, 2.5).slow(13))
  .fmh(perlin.range(0.5, 2.0).slow(7))
  .fmdecay(4.0)
  .fmrelease(8.0)

$: note("<g4 a4 fs4 b4 e4 d4>")
  .slow(11)
  .apply(lowerVoice)
  .pan(sine.range(0.55, 0.85).slow(8))
  .fmi(perlin.range(0.1, 2.4).slow(10))
  .fmh(perlin.range(1.0, 3.0).slow(5))
  .off(0.125, x => x.note(x => x + 5).gain(0.05).lpf(380).room(0.7).pan(0.18))
  .leslie(sine.range(0.08, 0.7).slow(13))
  .lrate(sine.range(0.1, 0.5).slow(8))
  .tremolo(perlin.range(0.03, 0.18).slow(12))
  .tremolosync(perlin.range(2, 4).slow(10))
  .detune(sine.range(-8, 8).slow(12))
  .delay(0.22)
  .delaytime(0.333)
  .delayfeedback(0.38)