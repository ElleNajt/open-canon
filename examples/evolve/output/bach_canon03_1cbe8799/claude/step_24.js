setcps(120/60/4)

let upperVoice = x => x
  .sound("triangle")
  .gain(0.35)
  .attack(0.3)
  .decay(0.7)
  .sustain(0.06)
  .lpf(sine.range(400, 1600).slow(11))
  .room(0.88)
  .size(0.95)

let lowerVoice = x => x
  .sound("supersaw")
  .gain(0.12)
  .decay(1.0)
  .sustain(0.05)
  .lpf(sine.range(140, 480).slow(7))
  .room(0.75)
  .shape(0.3)

$: note("<d5 fs5 a5 g5 b5 e5 d6 a5>")
  .slow(16)
  .apply(upperVoice)
  .pan(sine.range(0.1, 0.5).slow(10))
  .off(0.25, x => x.note(x => x + 7).gain(0.04).pan(0.75).lpf(600))
  .off(0.5, x => x.note(x => x + 12).gain(0.012).pan(0.5).lpf(900).room(0.97))
  .vowel("<a o i u>".slow(12))
  .phaser(sine.range(0.02, 0.18).slow(10))
  .phaserdepth(sine.range(0.1, 0.4).slow(6))
  .delay(0.28)
  .delaytime(0.375)
  .delayfeedback(0.45)

$: note("<g2 d3 b2 e2 a2 c3>")
  .slow(14)
  .sound("sine")
  .gain(perlin.range(0.08, 0.2).slow(9))
  .attack(6.0)
  .release(14.0)
  .lpf(sine.range(45, 160).slow(10))
  .lpq(perlin.range(6, 16).slow(5))
  .room(0.96)
  .size(0.99)
  .pan(sine.range(0.2, 0.8).slow(13))
  .fmi(perlin.range(0.01, 1.8).slow(12))
  .fmh(perlin.range(0.5, 1.5).slow(6))
  .fmdecay(8.0)
  .fmrelease(14.0)

$: note("<g4 b4 fs4 a4 e4 d4 c4 e4>")
  .slow(13)
  .apply(lowerVoice)
  .pan(sine.range(0.55, 0.92).slow(9))
  .fmi(perlin.range(0.05, 1.6).slow(8))
  .fmh(perlin.range(1.2, 2.8).slow(4))
  .off(0.125, x => x.note(x => x + 5).gain(0.03).lpf(260).room(0.82).pan(0.1))
  .leslie(sine.range(0.03, 0.45).slow(12))
  .lrate(sine.range(0.08, 0.3).slow(7))
  .tremolo(perlin.range(0.01, 0.08).slow(11))
  .tremolosync(perlin.range(2, 6).slow(8))
  .detune(sine.range(-12, 12).slow(14))
  .delay(0.18)
  .delaytime(0.333)
  .delayfeedback(0.38)