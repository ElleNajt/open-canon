setcps(120/60/4)

let upperVoice = x => x
  .sound("triangle")
  .gain(0.26)
  .attack(0.8)
  .decay(2.2)
  .sustain(0.02)
  .lpf(sine.range(220, 1400).slow(9))
  .room(0.96)
  .size(0.99)

let lowerVoice = x => x
  .sound("supersaw")
  .gain(0.09)
  .decay(3.2)
  .sustain(0.02)
  .lpf(sine.range(120, 520).slow(6))
  .room(0.90)
  .shape(0.18)

$: note("<d5 fs5 a5 g5 b5 e5 d6 a5>")
  .slow(14)
  .apply(upperVoice)
  .pan(sine.range(0.15, 0.65).slow(11))
  .off(0.25, x => x.note(x => x + 7).gain(0.035).pan(0.82).lpf(520))
  .off(0.5, x => x.note(x => x + 12).gain(0.008).pan(0.5).lpf(860).room(0.99))
  .vowel("<a o i e u>".slow(6))
  .phaser(sine.range(0.01, 0.18).slow(10))
  .phaserdepth(sine.range(0.2, 0.7).slow(13))
  .delay(0.18)
  .delaytime(0.375)
  .delayfeedback(0.38)

$: note("<g2 d3 b2 e2 c3 a2>")
  .slow(14)
  .sound("sine")
  .gain(perlin.range(0.03, 0.11).slow(12))
  .attack(14.0)
  .release(18.0)
  .lpf(sine.range(35, 120).slow(14))
  .lpq(perlin.range(6, 18).slow(9))
  .room(0.99)
  .size(0.99)
  .pan(sine.range(0.2, 0.8).slow(13))
  .fmi(perlin.range(0.01, 1.2).slow(10))
  .fmh(perlin.range(0.4, 1.8).slow(15))
  .fmdecay(16.0)
  .fmrelease(18.0)

$: note("<g4 b4 fs4 a4 e4 d4 c4>")
  .slow(11)
  .apply(lowerVoice)
  .pan(sine.range(0.4, 0.88).slow(7))
  .fmi(perlin.range(0.02, 1.4).slow(9))
  .fmh(perlin.range(1.2, 3.0).slow(5))
  .off(0.125, x => x.note(x => x + 5).gain(0.02).lpf(220).room(0.94).pan(0.12))
  .leslie(sine.range(0.0, 0.6).slow(13))
  .lrate(sine.range(0.04, 0.4).slow(9))
  .tremolo(perlin.range(0.01, 0.08).slow(11))
  .tremolosync(perlin.range(2, 6).slow(7))
  .detune(sine.range(-12, 12).slow(14))
  .delay(0.12)
  .delaytime(0.75)
  .delayfeedback(0.28)