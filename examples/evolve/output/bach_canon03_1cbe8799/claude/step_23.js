setcps(120/60/4)

let upperVoice = x => x
  .sound("triangle")
  .gain(0.35)
  .attack(0.2)
  .decay(0.6)
  .sustain(0.08)
  .lpf(sine.range(500, 1800).slow(9))
  .room(0.85)
  .size(0.94)

let lowerVoice = x => x
  .sound("supersaw")
  .gain(0.14)
  .decay(0.8)
  .sustain(0.06)
  .lpf(sine.range(160, 520).slow(6))
  .room(0.72)
  .shape(0.25)

$: note("<d5 fs5 a5 g5 b5 e5 d6 a5>")
  .slow(14)
  .apply(upperVoice)
  .pan(sine.range(0.1, 0.5).slow(10))
  .off(0.25, x => x.note(x => x + 7).gain(0.05).pan(0.78).lpf(700))
  .off(0.5, x => x.note(x => x + 12).gain(0.015).pan(0.5).lpf(1100).room(0.97))
  .vowel("<a o i u>".slow(9))
  .phaser(sine.range(0.03, 0.2).slow(8))
  .phaserdepth(sine.range(0.15, 0.45).slow(5))
  .delay(0.32)
  .delaytime(0.375)
  .delayfeedback(0.42)

$: note("<g2 d3 b2 e2 a2 c3>")
  .slow(16)
  .sound("sine")
  .gain(perlin.range(0.1, 0.22).slow(7))
  .attack(5.0)
  .release(12.0)
  .lpf(sine.range(50, 180).slow(8))
  .lpq(perlin.range(8, 18).slow(4))
  .room(0.94)
  .size(0.99)
  .pan(sine.range(0.25, 0.75).slow(11))
  .fmi(perlin.range(0.01, 1.4).slow(10))
  .fmh(perlin.range(0.5, 1.2).slow(5))
  .fmdecay(6.0)
  .fmrelease(12.0)

$: note("<g4 b4 fs4 a4 e4 d4>")
  .slow(11)
  .apply(lowerVoice)
  .pan(sine.range(0.52, 0.9).slow(8))
  .fmi(perlin.range(0.05, 1.4).slow(7))
  .fmh(perlin.range(1.5, 3.0).slow(3))
  .off(0.125, x => x.note(x => x + 5).gain(0.035).lpf(280).room(0.78).pan(0.12))
  .leslie(sine.range(0.04, 0.5).slow(10))
  .lrate(sine.range(0.1, 0.35).slow(6))
  .tremolo(perlin.range(0.01, 0.1).slow(9))
  .tremolosync(perlin.range(3, 7).slow(7))
  .detune(sine.range(-8, 8).slow(12))
  .delay(0.22)
  .delaytime(0.333)
  .delayfeedback(0.36)