setcps(120/60/4)

let upperVoice = x => x
  .sound("triangle")
  .gain(0.44)
  .attack(0.04)
  .decay(0.22)
  .sustain(0.2)
  .lpf(sine.range(1200, 2800).slow(10))
  .room(0.6)
  .size(0.8)

let lowerVoice = x => x
  .sound("supersaw")
  .gain(0.18)
  .decay(0.3)
  .sustain(0.1)
  .lpf(sine.range(400, 900).slow(9))
  .room(0.45)
  .shape(0.15)

$: note("<d5 e5 fs5 g5 b5 a5 g5 d6>")
  .slow(16)
  .apply(upperVoice)
  .pan(0.28)
  .off(0.25, x => x.note(x => x + 7).gain(0.13).pan(0.68).lpf(1600))
  .off(0.5, x => x.note(x => x + 12).gain(0.06).pan(0.5).lpf(2200).room(0.9))
  .vowel("<a e i o u a i>".slow(6))
  .phaser(sine.range(0.1, 0.5).slow(8))
  .phaserdepth(sine.range(0.15, 0.45).slow(5))

$: note("<g2 d3 b2 a2 g2 e2 d2 c2>")
  .slow(12)
  .sound("sine")
  .gain(perlin.range(0.28, 0.42).slow(7))
  .attack(0.8)
  .release(4.0)
  .lpf(sine.range(55, 280).slow(11))
  .lpq(perlin.range(4, 11).slow(6))
  .room(0.65)
  .size(0.92)
  .pan(sine.range(0.38, 0.62).slow(10))
  .fmi(perlin.range(0.2, 3.2).slow(9))
  .fmh(perlin.range(0.5, 2.5).slow(4))
  .fmdecay(1.6)
  .fmrelease(3.2)

$: note("<g4 fs4 a4 e4 d4 g4 b4 a4>")
  .slow(22)
  .apply(lowerVoice)
  .pan(0.7)
  .fmi(perlin.range(0.6, 2.4).slow(7))
  .fmh(perlin.range(1.0, 3.0).slow(5))
  .off(0.125, x => x.note(x => x + 5).gain(0.09).lpf(600).room(0.5).pan(0.32))
  .leslie(sine.range(0.05, 0.7).slow(8))
  .lrate(sine.range(0.15, 0.55).slow(5))
  .tremolo(perlin.range(0.05, 0.35).slow(7))
  .tremolosync(perlin.range(2, 6).slow(12))
  .detune(sine.range(-8, 8).slow(14))