setcps(135/60/4)

samples('shabda/speech:this_is_not_human_music')

$: s("this_is_not_human_music*8")
  .chop(64)
  .rev()
  .room(0.6)
  .size(0.9)
  .delay(0.8)
  .dt(0.333)
  .dfb(0.7)
  .bpf(sine.range(200, 6000).slow(8))
  .bpq(20)
  .jux(x => x.rev().hurry(2))

$: s("bd(<5 3 7 4>,8) [~ sn:2] bd [~ <sn:3 cp mt>]")
  .compressor("0.2:4:0.1:0.01:0.1")
  .room(0.3)
  .gain(1.4)
  .shape(0.6)
  .every(4, x => x.hurry(2))
  .every(3, x => x.rev())

$: s("hh*16")
  .gain(sine.range(0.3, 0.8).fast(4))
  .pan(sine.range(0.1, 0.9).fast(3))
  .crush(3)
  .delay(0.4)
  .dt(0.25)
  .room(0.8)
  .every(4, x => x.ply(2).fast(2))

$: note("<c2 c2 eb2 d2> <f2 c2 a2 g2>")
  .s("supersaw")
  .slow(2)
  .lpf(saw.range(200, 4000).fast(4))
  .lpq(40)
  .distort(0.8)
  .room(0.5)
  .gain(0.8)
  .struct("x(5,8,2)")
  .jux(x => x.octave(1).delay(0.5).dt(0.375).pan(0.8))