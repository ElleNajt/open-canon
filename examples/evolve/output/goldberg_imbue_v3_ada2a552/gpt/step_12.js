// Goldberg Variations - Ground Bass (BWV 988)
// The 8-note descending bass that underlies all 30 variations

setcps(83/60/4)

$: stack(
  note("g3 gb3 e3 d3 b2 c3 d3 g2")
    .slow(4)
    .sound("triangle")
    .gain(0.41)
    .lpf(perlin.range(410,2000).slow(7))
    .lpq(7.5)
    .every(3, x=>x.rev()),
  note("g4 gb4 e4 d4 b3 c4 d4 <g3 cs4>")
    .slow(5)
    .sound("piano")
    .gain(0.19)
    .hpf(1100)
    .palindrome()
    .every(4, x=>x.slide(0.5))
)

$: s("hh [hh cr] <oh hh> hh*5 [cp ~]")
  .gain(0.1)
  .delay(0.13)
  .pan(perlin.range(0.15,0.79).slow(10))
  .degradeBy(0.13)
  .echo(2, 0.16, 0.19)

$: s("supersaw")
  .n("[7 <5 9>] ~ <2 4> [0 11] 4")
  .scale("C:minor")
  .gain(0.18)
  .room(0.25)
  .every(3, x=>x.jux(y=>y.hpf(1637)))
  .palindrome()
  .degradeBy(0.09)

$: s("[bd bd ~ bd] [bd*2 ~] ~ bd")
  .gain(0.15)
  .lpf(420)
  .room(0.34)
  .swing(0.14)
  .every(5, x=>x.degradeBy(0.18))

$: s("[triangle supersaw]*2 [pulse square] [triangle ~] <triangle square>*2")
  .n("0 7 4 <9 3> 1 2 5")
  .scale("E:minor")
  .gain(0.14)
  .room(0.37)
  .hpf(sine.range(800,1240).slow(11))
  .every(2, x => x.rev())