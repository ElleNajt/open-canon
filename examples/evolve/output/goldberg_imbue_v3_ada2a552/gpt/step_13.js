// Goldberg Variations - Ground Bass (BWV 988)
// The 8-note descending bass that underlies all 30 variations

setcps(83/60/4)

$: stack(
  note("g3 gb3 e3 d3 b2 c3 d3 g2")
    .slow(4)
    .sound("triangle")
    .gain(0.41)
    .lpf(perlin.range(410,1800).slow(6))
    .lpq(7.2)
    .every(3, x=>x.rev()),
  note("g4 gb4 e4 d4 b3 c4 d4 <g3 cs4>")
    .slow(5)
    .sound("piano")
    .gain(0.19)
    .hpf(1330)
    .palindrome()
    .every(4, x=>x.slide(0.5))
)

$: s("hh <cr hh> [oh hh] hh*3 cp")
  .gain(0.13)
  .delay(0.15)
  .pan(perlin.range(0.17,0.8).slow(8))
  .degradeBy(0.11)

$: s("supersaw")
  .n("[7 <5 9>] ~ <2 4> [0 11] 4")
  .scale("C:minor")
  .gain(0.18)
  .room(0.22)
  .jux(x=>x.hpf(1615))
  .palindrome()
  .degradeBy(0.09)

$: s("[bd bd ~ bd] [bd*2 ~] ~ bd")
  .gain(0.16)
  .lpf(470)
  .room(0.31)
  .swing(0.13)

$: s("[triangle supersaw]*2 [pulse square] [triangle ~] <triangle square>*2")
  .n("0 7 4 <9 3> 1 2 5")
  .scale("E:minor")
  .gain(0.15)
  .room(0.36)
  .hpf(sine.range(710,1220).slow(9))
  .rev()