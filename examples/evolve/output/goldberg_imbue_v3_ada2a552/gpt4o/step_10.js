$: note("g3 gb3 e3 d3 b2 c3 d3 g2")
  .sound("triangle")
  .gain(0.6)
  .delay(0.25)
  .room(0.5)
  .pan(0.2)

$: note("g4 b3 d4 f4")
  .slow(4)
  .sound("piano")
  .gain(0.6)
  .pan(0.5)
  .room(0.6)

$: note("e4 g4 b4 d5 f5")
  .sound("supersaw")
  .lpf(sine.range(300, 900).slow(4))
  .lpq(5)
  .room(0.8)
  .echo(4, 0.3, 0.5)

$: s("bd*8")
  .gain(0.35)
  .hpf(250)
  .room(0.4)
  .delay(0.15)
  .tremolo(0.1)

$: note("g3 e4 d4 g4")
  .sound("sine")
  .gain(0.5)
  .pan(0.75)
  .delay(0.5)
  .compressor()

$: note("f3 a3 c4 g4 d4")
  .sound("pulse")
  .gain(0.4)
  .hpf(200)
  .room(0.3)
  .pan(0.3)
  .distort(0.2)