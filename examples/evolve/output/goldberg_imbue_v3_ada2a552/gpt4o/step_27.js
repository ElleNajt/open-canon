$: note("g3 eb3 e3 d3 b2 c3 eb3 g2")
  .sound("triangle")
  .gain(0.85)
  .hpf(180)
  .delay(0.15)
  .compressor()

$: note("a4 b3 d4 f4")
  .sound("piano")
  .slow(4)
  .gain(0.5)
  .room(0.6)
  .vowel("a i")

$: note("e4 g4 b4 cs5 f5")
  .sound("supersaw")
  .lpf(cosine.range(120, 800).slow(6))
  .compressor()
  .tremolo(0.6)
  .gain(0.7)

$: s("bd*8")
  .gain(0.6)
  .hpf(250)
  .distort(0.3)
  .delay(0.2)

$: note("f3 a3 c4 g4")
  .sound("pulse")
  .bpf(450)
  .bpq(6)
  .tremolo(0.3)
  .release(0.5)

