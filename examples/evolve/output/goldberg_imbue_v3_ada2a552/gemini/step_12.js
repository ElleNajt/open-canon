$: note("g2 ab2 d3 eb3 g3 eb3 d3 ab2")
  .iter(1)
  .slow(4)
  .sound("pulse")
  .lpf(perlin.range(200, 2500).slow(5)).lpq(6)
  .shape(0.3)
  .fm(saw.range(0.1, 1.5).slow(8))
  .delay(0.4).dfb(0.6).dt(0.75)
  .gain(0.35)

$: n("<g5 eb6 d5 bb5> <c5 g5 d5 ab5>")
  .iterBack(2)
  .fast(4)
  .sound("sine")
  .pan(0.2).juxBy(0.7, (x) => x.pan(0.8).add(4))
  .hpf(1500).hpq(6)
  .phaser(cosine.range(0.1, 5).slow(12))
  .delay(0.3).dfb(0.5).dt(0.125)
  .gain(0.25)
  
$: chord("g2:m7 eb2:maj7 f2:maj7 d2:m7")
  .euclid("<3 5>", 8)
  .slow(4)
  .sound("supersaw")
  .vowel(saw.slow(8))
  .shape(0.2)
  .room(0.6)
  .gain(0.25)
  
$: stack(
    s("[bd, bd] [~, cp]").slow(2),
    s("~ sn").ply(2).euclid(5,13).late(0.5)
  )
  .coarse(6)
  .compressor()
  .bpf(2000).bpq(2)
  .gain(0.6)

