$: note("g2 ab2 d3 eb3 g3 eb3 d3 ab2")
  .iter(2)
  .slow(4)
  .sound("pulse")
  .lpf(perlin.range(200, 2000).slow(6)).lpq(6)
  .shape(0.2).distort(0.4)
  .delay(0.4).dfb(0.6).dt(0.5)
  .gain(0.35)

$: n("<g5 eb6> <d5 bb5 c5> <g5 d5 ab5>")
  .iterBack(1)
  .fast(4)
  .sound("sine")
  .pan(0.2).juxBy(0.7, (x) => x.pan(0.8).add(7))
  .hpf(1500).hpq(6)
  .ring(perlin.range(0.1, 0.4).slow(13))
  .delay(0.3).dfb(0.5).dt(0.375)
  .gain(0.25)
  
$: chord("g2:m7 eb2:maj7 f2:maj7 d2:m7")
  .euclid(3, 7)
  .slow(4)
  .sound("supersaw")
  .lpf(2000)
  .vowel(saw.slow(10))
  .tremolo(sine.range(0, 0.5).slow(7))
  .room(0.6)
  .gain(0.25)
  
$: stack(
    s("bd*2 [~ cp] bd [~ rim]").slow(2),
    s("~ sn").ply(2).euclid(5,13).sometimes(x => x.s("~ mt"))
  )
  .coarse(6)
  .drive(0.4)
  .bpf(2200).bpq(2)
  .gain(0.6)

$: s("[hh, hh*3, hh*2, hh] oh").fast(4)
  .swing(0.6)
  .sometimesBy(0.2, (x) => x.s("cr").striate(4))
  .crush(6)
  .pan(perlin.slow(3))
  .delay(0.2).dt(0.125).dfb(0.4)
  .gain(0.2)
  
