setcps(150/60/4)
samples('shabda/speech:groove,pulse,evolve,grok,mutate,change,strudel,livecode')

$: note("[eb1 [ab1 bb1] cs2]*2 [c2 [eb2 g2] bb2 [c3 eb3]] [ab2 [d3 f3] ab3 [c4 eb4] g4]").scale("Eb:minor").transpose(perlin.range(-5,12).slow(10))
  .slow(perlin.range(1.5,4.5))
  .sound("pulse")
  .lpf(sine.range(100,14000).slow(4))
  .fmi(perlin.range(2,12).slow(5))
  .gain(perlin.range(0.6,1.2))
  .delay(0.25)
  .pan(sine.range(0,1).slow(3))

$: note("eb2 [ab2 c3] [eb3 g3] [bb3 [c4 eb4] g4 bb4]").transpose(sine.range(-7,12).slow(8))
  .sometimesBy(0.25, x=>x.rev())
  .slow(perlin.range(1,3.5))
  .sound("square")
  .lpf(perlin.range(250,10000).slow(2.5))
  .detune(sine.range(-30,50).slow(6))
  .ring(perlin.range(0.4,0.7).slow(4))
  .gain(perlin.range(0.4,1))

$: note("g2 [c3 eb3] [g3 bb3] [c4 [eb4 g4] bb4 [d5 f5]]").slow(perlin.range(1.5,4.5))
  .sound("supersaw")
  .lpf(saw.range(200,18000).slow(3.5))
  .detune(sine.range(-60,60).slow(5))
  .leslie(perlin.range(0.4,0.9).slow(6))
  .gain(perlin.range(0.5,1.1)).room(0.4)

$: stack(
  s("bd*4 [~ bd bd]").euclid(7,16).slow(perlin.range(1.2,2.8)).gain(1.1).pan(0.1),
  s("[sn ~ cp]").euclid(9,16).slow(perlin.range(1.4,3.5)).gain(0.85).pan(sine.range(0.2,0.8)),
  s("hh*16? [oh ~ hh*8 lt]").fast(perlin.range(3,12)).gain(0.75).hpf(4500).pan(cosine.range(0.2,0.8).slow(5)).crush(perlin.range(5,11).slow(8))
).room(0.5)
.delay(0.4)
.dt(perlin.range(0.2,0.4).slow(4))
.swing(perlin.range(0.25,0.55).slow(12))
.juxBy(sine.range(-0.3,0.2).slow(3), rev)
.compressor("-20:5:0.4:0.03:0.25")

$: note("ab1 c2 [eb2 g2 bb2] [d3 f3 ab3 c4 eb4 g4]").every(10, x=>x.transpose(rand.range(-5,10)))
  .slow(perlin.range(1.5,4.8))
  .sound("triangle")
  .fmi(saw.range(1.5,10).slow(3))
  .lpf(perlin.range(150,11000).slow(5))
  .detune(sine.range(-25,40).slow(8))
  .tremolo(perlin.range(0.3,0.6).slow(4))
  .legato(0.7)

$: s("[grok*2 strudel] [groove*2 livecode grok?] [pulse evolve*2] [mutate change grok pulse] [strudel*3 ~ evolve]").sometimesBy(0.25, rev).degradeBy(0.12)
  .gain(perlin.range(0.7,1.3))
  .speed(perlin.range(0.6,1.7).slow(6))
  .chop(perlin.range(10,24).slow(5))
  .stretch(perlin.range(0.8,1.4).slow(7))
  .pan(sine.range(0.1,0.9).slow(2))
  .vowel("a e i o u".slow(3))