setcps(93/60/4)

$: stack(
  note("g3 gb3 e3 <d3 b2> c3 d3 g2").slow(3)
    .sound("triangle")
    .gain(0.39)
    .lpf(sine.range(990, 3400).slow(11))
    .lpq(6.2)
    .every(5, x => x.rev())
    .every(4, x => x.pan(sine.range(0.13,0.59).slow(11))),
  s("bd*3 <bd bd~>")
    .gain(0.19)
    .room(0.3)
    .cutoff(1030)
    .every(6, x => x.echo(0.19,0.1,0.17))
)

