// Goldberg Variations - Variation V: Fractured Consolation
// The hope from IV collapses into questioning fragments — melody inverts and stutters,
// bass becomes sparse and hollow, a new pizzicato voice emerges like distant memories,
// speech sample dissolves into whispered ghosts

setcps(54/60/4)

samples('shabda/speech:goldberg_variations')

// Bass: hollow, questioning — sparse hits with long decay, pitch uncertainty
$: note("[g2 ~ ~ ~] [~ eb2 ~ ~] [~ ~ d2 ~] [~ ~ ~ g1]")
  .slow(4)
  .sound("sine")
  .gain(0.35)
  .lpf(400)
  .attack(0.01)
  .decay(0.8)
  .sustain(0.1)
  .release(1.5)
  .room(0.7)
  .size(0.8)
  .detune(sine.range(-15, 15).slow(8))

// Melody: inverted, fragmented — falling where it once rose, stuttering
$: note("[d4 ~ e4 ~] [~ c4 ~ b3] [~ ~ a3 g3] [~ d4 ~ ~]")
  .slow(4)
  .ply(2)
  .degradeBy(0.3)
  .sound("triangle")
  .gain(0.3)
  .lpf(cosine.range(800, 2500).slow(4))
  .fmi(1.5)
  .fmh(2)
  .fmdecay(0.5)
  .attack(0.08)
  .decay(0.3)
  .release(1.2)
  .room(0.6)
  .delay(0.45)
  .delaytime(0.333)
  .delayfeedback(0.5)
  .pan(sine.range(0.2, 0.8).slow(6))

// NEW: Pizzicato memories — major thirds hinting at what was
$: note("<[b4 d5] ~ [g4 b4] ~> <~ [e4 g4] ~ [c5 e5]>")
  .slow(2)
  .sound("pluck")
  .gain(0.22)
  .lpf(3500)
  .attack(0.001)
  .decay(0.15)
  .sustain(0)
  .release(0.4)
  .room(0.5)
  .pan(rand.range(0.3, 0.7))
  .velocity(rand.range(0.6, 1))

// High voice: transformed to breathy pads, sustained grief
$: note("<[eb5 bb5] [d5 g5] [c5 ab5] [bb4 f5]>")
  .slow(8)
  .sound("sawtooth")
  .gain(0.12)
  .lpf(1800)
  .lpq(2)
  .attack(0.8)
  .decay(0.5)
  .sustain(0.6)
  .release(2)
  .room(0.8)
  .size(0.7)
  .pan(0.6)
  .phaser(0.3)
  .phaserdepth(0.5)

// Intrusion: speech now whispered, stretched to breaking
$: s("goldberg_variations")
  .slow(16)
  .speed(0.5)
  .chop(48)
  .gain(0.08)
  .lpf(800)
  .hpf(300)
  .room(0.9)
  .size(0.9)
  .delay(0.6)
  .delaytime(0.75)
  .delayfeedback(0.7)
  .pan(perlin.range(0.1, 0.9))
  .degradeBy(0.4)