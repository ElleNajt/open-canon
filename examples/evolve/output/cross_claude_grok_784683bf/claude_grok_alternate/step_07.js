// Goldberg Variations - Variation VII: Triumphant Stride
// Resolution crystallizes — bass marches in confident fifths,
// melody transforms to fanfare, pizzicato becomes percussive bells,
// a new brass-like voice announces arrival, rhythm drives forward

setcps(62/60/4)

samples('shabda/speech:goldberg_variations')

// Bass: confident march in open fifths, striding upward
$: note("[d2 a2] [e2 b2] [fs2 cs3] [g2 d3]")
  .slow(2)
  .sound("sawtooth")
  .gain(0.32)
  .lpf(380)
  .lpq(2)
  .attack(0.02)
  .decay(0.3)
  .sustain(0.5)
  .release(0.8)
  .room(0.6)
  .size(0.7)
  .shape(0.15)
  .pan(0.35)

// Fanfare melody: bold, declarative, major triumph
$: note("[d5 ~ fs5 ~] [a5 ~ d6 ~] [cs6 ~ b5 ~] [a5 fs5 d5 ~]")
  .slow(4)
  .sound("square")
  .gain(0.24)
  .lpf(1800)
  .lpenv(4)
  .lpdecay(0.3)
  .fmi(0.8)
  .fmh(2)
  .attack(0.01)
  .decay(0.15)
  .sustain(0.6)
  .release(0.5)
  .room(0.5)
  .delay(0.25)
  .delaytime(0.166)
  .delayfeedback(0.3)
  .pan(0.6)

// Bells: transformed pizzicato into celebratory chimes
$: note("<d6 a6 fs6 d7> <a5 e6 cs6 a6>")
  .fast(2)
  .sound("sine")
  .gain(0.18)
  .fmi(5)
  .fmh(3.5)
  .fmdecay(0.8)
  .attack(0.001)
  .decay(0.6)
  .sustain(0)
  .release(1.5)
  .room(0.8)
  .size(0.85)
  .pan(rand.range(0.2, 0.8))
  .velocity(rand.range(0.6, 1))

// NEW: brass chorale — stately harmonic pillars
$: note("<[d4 fs4 a4] [e4 gs4 b4] [fs4 a4 cs5] [d4 a4 d5]>")
  .slow(4)
  .sound("supersaw")
  .gain(0.2)
  .lpf(1400)
  .lpq(1.5)
  .attack(0.15)
  .decay(0.2)
  .sustain(0.8)
  .release(1.2)
  .drive(0.2)
  .room(0.7)
  .pan(0.5)
  .tremolo(0.08)
  .tremolosync(2)

// Driving rhythm: snare and kick propel forward motion
$: s("[bd ~ ~ bd] [~ sn ~ ~] [bd ~ bd ~] [~ sn bd ~]")
  .slow(2)
  .gain(0.22)
  .lpf(4000)
  .shape(0.1)
  .room(0.4)
  .pan(0.5)

// Shimmering high strings: golden sustain
$: note("[fs6 a6]")
