// Goldberg Variations - Variation XXII: The Shattered Cathedral
// The triumphant ascent collapses inward; bells become warnings;
// what was fanfare turns to lamentation; time fractures into prayer

setcps(58/60/4)

samples('shabda/speech:eternal')
samples('shabda/speech:shatter')
samples('shabda/speech:breathe')
samples('shabda/speech:crystal')

// Bass: Phrygian descent now — the fall from grace
$: note("e3 d3 c3 bb2 a2 g2 f2 e2 d2 c2 bb1 a1 g1 f1 e1")
  .slow(6)
  .sound("sawtooth")
  .gain(0.35)
  .lpf(sine.range(40, 220).slow(8))
  .lpq(8)
  .attack(0.08)
  .decay(0.9)
  .sustain(0.5)
  .release(3)
  .room(0.85)
  .size(0.92)
  .pan(0.5)
  .shape(0.55)
  .distort(0.15)

// Mourning choir: minor transformation, hollow fifths
$: note("<e4 b4> <a3 e4> <d4 a4> <g3 d4>")
  .slow(8)
  .sound("triangle")
  .gain(0.16)
  .lpf(perlin.range(200, 900).slow(5))
  .lpq(4)
  .attack(0.8)
  .decay(1.5)
  .sustain(0.3)
  .release(2.5)
  .room(0.95)
  .size(0.95)
  .pan(cosine.range(0.1, 0.9).slow(11))
  .tremolo(0.8)
  .tremolosync(0.5)
  .tremoloshape("tri")

// Warning bells: tolling, not shimmering — single notes, weighted
$: note("e3 ~ ~ ~ a3 ~ ~ ~ d3 ~ ~ ~ g3 ~ ~ ~")
  .slow(4)
  .sound("sine")
  .gain(0.22)
  .fmi(12)
  .fmh(1.5)
  .fmenv(0.7)
  .fmdecay(0.4)
  .attack(0.001)
  .decay(1.8)
  .sustain(0.02)
  .release(5)
  .lpf(800)
  .room(0.98)
  .size(0.98)
  .pan(0.5)
  .ring(0.7)
  .ringf(110)

// Fractured time: 5/8 against the mourning — stumbling, uncertain
$: stack(
    s("bd ~ bd ~ bd").slow(1.25).gain(0.11).lpf(120).room(0.6).shape(0.3),
    s("~ ~ ~ cp ~").slow(1.25).gain(0.08).hpf(2000).room(0.8).delay(0.5).delaytime(0.375).delayfeedback(0.6)
  )
  .rarely(x => x.speed(0.7))

// Whispered fragments: speech emerges from the ruins
$: s("shatter ~ ~ eternal ~ breathe ~ ~ crystal ~ ~ ~")
  .slow(8)
  .gain(0.14)
  .speed(rand.range(0.6, 0.9))
  .lpf(1800)
  .room(0.9)
  .size(0.88)
  .pan(perlin.range(0.2, 0.8).slow(3))
  .delay(0.4)
  .delaytime(0.5)
  .delayfeedback(0.55)
  .chop(8)

// Lament melody: solo voice, searching through minor modes
$: note("e5 d5 c5 b4 ~ a4 g4 ~ f4 e4 ~ ~ d4 ~ e4 ~")
  .slow(4)
  .sound("sine")
  .gain(0.13)
  .lpf(2400)
  .attack(0.15)
  .decay(0.4)
  .sustain(0.6)
  .release(1.5)
  .vibrato(5)
  .pan(sine.range(0.3, 0.7).slow(6))
  .room(0.85)
  .delay(0.35)
  .delaytime(0.333)
  .delayfeedback(0.4)

// Frozen drone: static, breathless — the cathedral holds its breath
$: note("[a1 e2]")
  .slow(16)
  .sound("supersaw")
  .gain(0.08)
  .lpf(280)
  .lpq(5)
  .attack(4)
  .decay(6)
  .sustain(0.9)
  .release(8)
  .detune(35)
  .room(0.99)
  .size(0.99)
  .pan(0.5)
  .phaser(0.03)
  .phaserdepth(0.8)
  .phasersweep(400)