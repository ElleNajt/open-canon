// Goldberg Variations - Variation XII: Apotheosis Transfigured
// The ascent fractures into prismatic shards;
// voices become instruments, instruments become breath;
// glory dissolves into intimate wonder

setcps(52/60/4)

samples('shabda/speech:infinite')
samples('shabda/speech:dissolve')

// Bass: the foundation becomes unstable, questioning
$: note("[fs2 ~ cs3 ~] [b2 ~ fs3 ~] [e3 ~ b3 ~] [a2 ~ e3 ~]")
  .slow(6)
  .sound("sine")
  .gain(0.28)
  .lpf(cosine.range(200, 500).slow(12))
  .lpq(5)
  .attack(0.5)
  .decay(1.2)
  .sustain(0.6)
  .release(4)
  .room(0.95)
  .size(0.98)
  .pan(0.5)
  .slide(0.3)

// Glass harmonics: bells transform to fragile resonance
$: note("<[fs5 a5 cs6] [e5 gs5 b5] [d5 fs5 a5] [cs5 e5 gs5]>")
  .slow(3)
  .sound("sine")
  .gain(0.12)
  .fmi(2)
  .fmh(12)
  .fmdecay(0.3)
  .attack(0.1)
  .decay(3)
  .sustain(0.05)
  .release(5)
  .room(0.99)
  .size(0.95)
  .pan(tri.range(0.1, 0.9).slow(6))
  .phaser(0.15)
  .phaserdepth(2)
  .every(3, x => x.transpose(7))

// Pulse: new element - anxious heartbeat emerges
$: note("cs4 ~ ~ cs4 ~ cs4 ~ ~")
  .sound("triangle")
  .gain(0.14)
  .lpf(800)
  .lpq(6)
  .attack(0.01)
  .decay(0.15)
  .sustain(0.1)
  .release(0.3)
  .pan(0.35)
  .room(0.7)
  .delay(0.4)
  .delaytime(0.375)
  .delayfeedback(0.55)
  .sometimes(x => x.transpose(12))

// Whispered fragments: speech becomes texture
$: stack(
    s("infinite").speed(0.6).gain(0.08).pan(0.2),
    s("dissolve").speed(1.2).gain(0.07).pan(0.75).late(1.5)
  )
  .slow(8)
  .chop(32)
  .speed(perlin.range(0.7, 1.4))
  .lpf(1800)
  .hpf(500)
  .room(0.99)
  .size(0.98)
  .delay(0.6)
  .delaytime(0.666)
  .delayfeedback(0.6)
  .degradeBy(0.3)

// Harp ghosts: piano replaced by spectral plucks
$: note("a4 cs5 e5 a5 e5 cs5").euclid(7, 12)
  .slow(5)
  .sound("sawtooth")
  .gain(0.11)
  .lpf(2200)
  .lpq(8)
  .attack(0.01)
  .decay(0.8)
  .sustain(0.1)
  .release(1.5)
  .room(0.9)
  .pan(sine.range(0.25, 0.75).slow(3))
  .jux(x => x.transpose(12).gain(0.06))

// Drone cloud: organ disperses into held breath
$: note("a2, e3, a3, cs4")
  .slow(16)
  .sound("supersaw")
  .gain(0.09)
  .lpf(900)
  .lpq(3)
  .detune(24)
  .attack(6)
  .decay(2)
  .sustain(0.95)
  .release(8)
  .room(0.99)
  .size(0.99)
  .pan(0.5)
  .tremolo(0.15)
  .tremolosync(0.1)