// Goldberg Variations - Variation IX: Fractured Cathedral
// The triumph collapses into introspection; brass pillars shatter into crystalline shards;
// driving rhythm dissolves into scattered heartbeats; speech becomes ghostly whispers;
// a new plainchant melody emerges from the ruins, searching for resolution

setcps(52/60/4)

samples('shabda/speech:cathedral')
samples('shabda/speech:remember')

// Bass: now a slow, mournful pedal tone with octave drops - grief beneath
$: note("[d2 ~ ~ d1] [a1 ~ ~ a2] [g1 ~ ~ g2] [f1 ~ ~ f2]")
  .slow(4)
  .sound("triangle")
  .gain(0.28)
  .lpf(280)
  .lpq(3)
  .attack(0.3)
  .decay(0.5)
  .sustain(0.7)
  .release(2)
  .room(0.85)
  .size(0.9)
  .pan(0.5)

// Plainchant: new modal melody, unaccompanied voice searching through darkness
$: note("d4 f4 e4 d4 ~ a3 c4 d4 ~ e4 f4 g4 f4 e4 d4 ~")
  .slow(8)
  .sound("sine")
  .gain(0.22)
  .lpf(sine.range(800, 1600).slow(16))
  .fmi(0.3)
  .fmh(3)
  .attack(0.2)
  .decay(0.3)
  .sustain(0.6)
  .release(1.5)
  .room(0.9)
  .size(0.85)
  .delay(0.4)
  .delaytime(0.375)
  .delayfeedback(0.5)
  .pan(0.45)

// Crystalline shards: the brass pillars broken into high bell-like fragments
$: note("<[d6 ~ a5 ~] [f6 ~ c6 ~] [e6 ~ g5 ~] [a5 ~ d6 ~]>")
  .slow(2)
  .sound("sine")
  .gain(0.14)
  .lpf(6000)
  .fmi(2.5)
  .fmh(5)
  .fmdecay(0.4)
  .attack(0.001)
  .decay(0.8)
  .sustain(0.1)
  .release(1.5)
  .room(0.8)
  .pan(rand.range(0.2, 0.8))
  .degradeBy(0.3)

// Scattered heartbeats: rhythm reduced to sparse, uncertain pulses
$: s("bd ~ ~ ~ bd:3 ~ ? ~, ~ ~ sn:2 ~ ~ ? ~ ~")
  .slow(2)
  .gain(0.18)
  .lpf(1200)
  .room(0.7)
  .shape(0.05)
  .pan(0.5)

// Ghostly whispers: speech stretched and fragmented, barely there
$: s("cathedral remember")
  .slow(8)
  .chop(24)
  .speed(0.5)
  .gain(0.11)
  .lpf(1800)
  .hpf(400)
  .room(0.95)
  .size(0.9)
  .delay(0.6)
  .delaytime(0.5)
  .delayfeedback(0.65)
  .pan(sine.range(0.2, 0.8).slow(7))
  .degradeBy(0.4)

// New texture: distant organ drone, the cathedral breathing
$: note("<d3 a2 f3 g3>")
  .slow(16)
  .sound("sawtooth")
  .gain(0.1)
  .lpf(400)
  .lpq(1)
  .attack(2)
  .decay(1)
  .sustain(0.9)
  .release(4)
  .room(0.95)
  .tremolo(0.15)
  .tremolosync(0.5)
  .pan(0.5)