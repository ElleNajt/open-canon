// Goldberg Variations - Evolved: The Eye of the Storm
// Sudden calm - sparse textures, hollow spaces, eerie stillness before the next wave

setcps(72/60/4)

// Bass drops to ghostly sustained tones - wide intervals, exposed
$: note("[b1 ~ ~ ~] [~ ~ fs2 ~] [~ g1 ~ ~] [~ ~ ~ e2]")
  .slow(4)
  .sound("sine")
  .lpf(400)
  .gain(0.35)
  .attack(0.5)
  .decay(0.3)
  .sustain(0.6)
  .release(2)
  .room(0.6)

// Melody becomes a distant memory - single notes, much space
$: note("[~ ~ g5 ~] [~ ~ ~ ~] [~ fs5 ~ ~] [~ ~ ~ e5]")
  .slow(4)
  .sound("triangle")
  .lpf(1800)
  .attack(0.1)
  .decay(0.4)
  .sustain(0.2)
  .release(1.5)
  .gain(0.2)
  .pan(0.7)
  .room(0.5)
  .delay(0.4)
  .delaytime(0.75)
  .delayfeedback(0.6)

// Arpeggios replaced with hollow fifths - frozen, bell-like
$: note("<[b3,fs4] [e3,b3] [g3,d4] [fs3,cs4]>")
  .slow(2)
  .sound("sine")
  .fmi(0.5)
  .fmh(2)
  .attack(0.01)
  .decay(1.2)
  .sustain(0)
  .gain(0.25)
  .pan(0.3)
  .room(0.45)
  .hpf(200)

// New: Breath-like texture - filtered noise swells
$: s("~ hh ~ hh")
  .slow(2)
  .gain(0.12)
  .lpf(sine.range(400, 2000).slow(8))
  .hpf(300)
  .attack(0.3)
  .release(0.5)
  .pan(sine.range(0.3, 0.7).slow(6))
  .room(0.3)

// New: Deep resonant pulse - like a distant heartbeat
$: note("e1")
  .slow(4)
  .euclid(3, 8)
  .sound("sine")
  .lpf(120)
  .gain(0.3)
  .attack(0.05)
  .decay(0.8)
  .sustain(0)
  .room(0.5)

// Drone shifts to pure fifth - open, suspended
$: note("[b1,fs2]")
  .slow(8)
  .sound("sawtooth")
  .lpf(sine.range(200, 500).slow(16))
  .lpq(4)
  .gain(0.15)
  .attack(2)
  .release(3)
  .room(0.55)