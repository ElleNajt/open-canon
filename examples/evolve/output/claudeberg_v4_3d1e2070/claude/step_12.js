// Goldberg Variations - Evolved: The Tempest
// Storm clouds gather - urgent counterpoint, restless energy

setcps(120/60/4)

// Bass becomes agitated ostinato - relentless eighth notes
$: note("[c2 g2 eb2 g2] [bb1 f2 d2 f2] [ab1 eb2 c2 eb2] [g1 d2 b1 d2]")
  .slow(2)
  .sound("sawtooth")
  .lpf(500)
  .lpq(3)
  .gain(0.4)
  .attack(0.005)
  .decay(0.1)
  .sustain(0.6)
  .release(0.2)
  .room(0.3)

// Melody transformed to jagged, angular leaps - Bartok-esque
$: note("[eb5 ~ b4 ~] [g5 db5 ~ ab5] [~ f5 c5 ~] [bb5 ~ eb5 gb5]")
  .slow(2)
  .sound("square")
  .lpf(2800)
  .lpq(4)
  .attack(0.01)
  .decay(0.15)
  .sustain(0.4)
  .release(0.5)
  .gain(0.24)
  .pan(sine.range(0.2, 0.8).slow(6))
  .room(0.4)
  .delay(0.3)
  .delaytime(0.333)
  .delayfeedback(0.4)

// Harmony now cluster chords - dissonant, tense
$: note("<[c3,db3,f3,ab3] [bb2,eb3,gb3,a3] [ab2,b2,eb3,g3] [g2,c3,e3,bb3]>")
  .slow(4)
  .sound("sine")
  .fmi(1.2)
  .fmh(1.5)
  .attack(0.5)
  .decay(0.8)
  .sustain(0.5)
  .release(1.5)
  .gain(0.15)
  .lpf(1200)
  .room(0.55)

// Drums shift to double-time urgency
$: s("[bd bd ~ bd] [sn ~ bd sn] [bd ~ sn ~] [bd sn bd ~]")
  .fast(1)
  .gain(0.32)
  .lpf(350)
  .shape(0.3)
  .room(0.25)

// Hats become frantic 16th note bursts
$: s("[hh*4] [hh hh oh hh] [~ hh*3] [oh hh hh ~]")
  .gain(0.11)
  .lpf(8000)
  .hpf(5000)
  .pan(rand.range(0.3, 0.7))
  .room(0.2)

// NEW: Stabbing brass hits - punctuation marks
$: note("[~ ~ c4 ~] [~ eb4 ~ ~] [g4 ~ ~ ~] [~ ~ ~ bb3]")
  .slow(2)
  .sound("sawtooth")
  .lpf(sine.range(800, 2500).slow(4))
  .lpq(5)
  .attack(0.02)
  .decay(0.25)
  .sustain(0.3)
  .release(0.4)
  .gain(0.26)
  .pan(0.6)
  .room(0.35)
  .distort(0.15)

// NEW: Tremolo strings - nervous energy underneath
$: note("[ab3,c4,eb4] [g3,bb3,d4] [gb3,bb3,db4] [f3,ab3,c4]")
  .slow(8)
  .sound("triangle")
  .tremolo(0.7)
  .tremolosync(8)
  .lpf(2000)
  .attack(0.4)
  .decay(0.3)
  .sustain(0.7)
  .release(1)
  .gain(0.14)
  .room(0.5)

// Sub becomes syncopated heartbeat - anxious pulse
$: note("[c1 ~ c1 ~] [~ c1 ~ c1] [g0 ~ ~ g0] [~ ~ c1 ~]")
