// Goldberg Variations - Evolved: The Descent
// After the peak, the harmony darkens - shifting to minor, textures fragment and reform

setcps(88/60/4)

// Bass descends chromatically - darker, more ominous
$: note("[e2 ds2 d2 cs2] [c2 b1 as1 a1] [gs1 g1 fs1 f1] [e1 ~ ~ ~]")
  .slow(8)
  .sound("sawtooth")
  .lpf(600)
  .lpq(3)
  .gain(0.45)
  .attack(0.02)
  .decay(0.3)
  .sustain(0.7)
  .release(0.6)
  .room(0.4)
  .distort(0.2)

// Melody transformed to minor - lamenting, falling phrases
$: note("[e5 ds5 ~ b4] [~ c5 b4 a4] [gs4 ~ a4 ~] [b4 ~ ~ ~]")
  .slow(2)
  .sound("triangle")
  .fmi(1.5)
  .fmh(3)
  .fmdecay(0.8)
  .lpf(2400)
  .attack(0.05)
  .decay(0.4)
  .sustain(0.3)
  .release(1)
  .gain(0.22)
  .pan(sine.range(0.3, 0.7).slow(6))
  .room(0.5)
  .delay(0.35)
  .delaytime(0.5)
  .delayfeedback(0.45)

// Harmony shifts to minor - suspended tensions, unresolved
$: note("<[e3,g3,b3] [a2,e3,c4] [gs2,d3,b3] [a2,e3,a3]>")
  .sound("sine")
  .fmi(0.5)
  .fmh(2)
  .attack(0.15)
  .decay(0.6)
  .sustain(0.4)
  .release(1.5)
  .gain(0.23)
  .pan(0.5)
  .room(0.55)
  .lpf(1800)

// Drums become sparse - half-time feel, space opens
$: s("bd ~ ~ ~ ~ ~ bd ~ ~ bd ~ ~ ~ ~ ~ ~")
  .slow(2)
  .gain(0.4)
  .lpf(150)
  .room(0.3)
  .shape(0.15)

// Hats dissolve into scattered whispers
$: s("~ hh ~ ~ oh ~ ~ hh ~ ~ ~ hh ~ oh ~ ~")
  .slow(2)
  .gain(0.12)
  .lpf(5000)
  .hpf(4000)
  .pan(rand.range(0.1, 0.9))
  .room(0.4)
  .delay(0.4)
  .delaytime(0.375)
  .delayfeedback(0.55)

// NEW: Ghostly chorale - voices emerge from reverb
$: note("[b3,e4,gs4] ~ ~ [a3,c4,e4] ~ ~ [gs3,b3,e4] ~ [a3,d4,fs4] ~ ~ ~")
  .slow(4)
  .sound("supersaw")
  .detune(12)
  .lpf(1400)
  .lpenv(3)
  .lpdecay(1.5)
  .attack(0.3)
  .decay(0.8)
  .sustain(0.2)
  .release(2)
  .gain(0.15)
  .pan(0.4)
  .room(0.7)

// NEW: Pizzicato countermelody - unexpected brightness
$: note("~ [e5 ~] [gs5 ~] ~ [b4 ~] ~ [a5 ~] ~ ~ [fs5 ~] ~ [e5 ~] ~ ~ ~")
