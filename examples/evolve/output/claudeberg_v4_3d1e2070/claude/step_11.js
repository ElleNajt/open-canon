// Goldberg Variations - Evolved: The Awakening
// Dawn breaks through stained glass - new motifs emerge from silence

setcps(108/60/4)

// Bass transforms to walking counterpoint - Bach-like independent line
$: note("[c2 e2 g2 c3] [b1 d2 g2 b2] [a1 c2 e2 a2] [g1 b1 d2 g2]")
  .slow(4)
  .sound("sawtooth")
  .lpf(400)
  .lpq(2)
  .gain(0.38)
  .attack(0.01)
  .decay(0.2)
  .sustain(0.7)
  .release(0.4)
  .room(0.4)

// Melody becomes a dance - dotted rhythms, playful leaps
$: note("[g5 ~ e5 d5] [c5 d5 e5 g5] [a5 g5 ~ e5] [d5 ~ c5 ~]")
  .slow(2)
  .sound("triangle")
  .fmi(0.8)
  .fmh(2)
  .fmdecay(0.5)
  .lpf(3500)
  .attack(0.02)
  .decay(0.3)
  .sustain(0.5)
  .release(0.8)
  .gain(0.28)
  .pan(sine.range(0.3, 0.7).slow(8))
  .room(0.5)
  .delay(0.25)
  .delaytime(0.375)
  .delayfeedback(0.35)

// Harmony shifts to minor mode - darker, more mysterious
$: note("<[c3,eb3,g3,bb3] [f2,ab3,c4,eb4] [g2,bb2,d3,f3] [ab2,c3,eb3,g3]>")
  .slow(2)
  .sound("sine")
  .fmi(0.5)
  .fmh(1)
  .attack(0.3)
  .decay(0.5)
  .sustain(0.6)
  .release(1.2)
  .gain(0.17)
  .lpf(1400)
  .room(0.5)

// Drums return with momentum - syncopated groove
$: s("[bd ~ bd ~] [~ sn ~ sn] [bd ~ ~ bd] [~ sn ~ ~]")
  .slow(1)
  .gain(0.35)
  .lpf(300)
  .room(0.35)

// Hats become ticking clock - insistent, driving
$: s("[hh hh hh hh] [hh hh oh hh]")
  .gain(0.12)
  .lpf(7000)
  .hpf(4000)
  .pan(rand.range(0.4, 0.6))
  .room(0.3)

// NEW: Pizzicato strings - plucked countermelody weaving through
$: note("[~ c4 ~ e4] [g4 ~ e4 ~] [~ d4 ~ f4] [e4 ~ c4 ~]")
  .slow(2)
  .sound("triangle")
  .lpf(2200)
  .lpq(3)
  .attack(0.001)
  .decay(0.15)
  .sustain(0)
  .release(0.3)
  .gain(0.22)
  .pan(0.7)
  .room(0.4)
  .delay(0.2)
  .delaytime(0.25)
  .delayfeedback(0.3)

// NEW: Marimba-like percussive melody - woody, bright
