setcps(66/60/4)

$: note("g3 fs3 e3 d3 b2 c3 d3 g2")
  .slow(4)
  .sound("triangle")
  .gain(0.35)
  .lpf(sine.range(300, 1800).slow(13))
  .release(0.9)
  .shape(0.15)

$: note("g4 fs4 e4 d4 b3 c4 d4 g3")
  .slow(4)
  .sound("sine")
  .gain(0.18)
  .delay(0.5).delaytime(0.333).delayfeedback(0.52)
  .every(3, x => x.add(12))

$: note("<g5 b5 d5 fs5 g5 e5 fs5 b4>")
  .slow(4)
  .sound("sine")
  .gain(0.14)
  .fmi(sine.range(0.3, 4).slow(11))
  .attack(0.4).release(1.5)

$: note("[g3 b3 d4] [fs3 a3 <d4 cs4>] [e3 g3 b3] [d3 fs3 a3] [b2 d3 <g3 fs3>] [c3 e3 g3] [d3 fs3 a3] [g2 b2 d3]")
  .slow(8)
  .sound("piano")
  .gain(0.22)
  .room(0.4)
  .velocity(perlin.range(0.25, 0.85))

$: note("<d5 [~ b4] [~ c5] [a4 ~] g4 [~ e5] [fs5 ~] [~ d5]>")
  .slow(8)
  .sound("sawtooth")
  .gain(0.1)
  .lpf(perlin.range(600, 2400).slow(9))
  .pan(sine.range(0.2, 0.8).slow(7))

$: s("<[~ ~ ~ bd ~ ~ sn:3 ~] [~ bd ~ ~ sn:3 ~ ~ bd] [~ ~ bd ~ ~ sn:3 ~ ~]>")
  .slow(4)
  .gain(0.15)
  .shape(0.35)
  .room(0.25)
  .sometimes(x => x.speed(0.8))