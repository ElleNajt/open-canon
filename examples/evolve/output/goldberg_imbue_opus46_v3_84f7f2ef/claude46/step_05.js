setcps(66/60/4)

$: note("g3 fs3 e3 d3 b2 c3 d3 g2")
  .slow(4)
  .sound("triangle")
  .gain(0.26)
  .lpf(sine.range(400, 2200).slow(13))
  .shape(0.3)
  .off(0.125, x => x.add(12).gain(0.09).lpf(900))

$: note("g4 fs4 e4 d4 b3 c4 d4 g3")
  .slow(4)
  .sound("sine")
  .gain(0.14)
  .delay(0.45).delaytime(0.375).delayfeedback(0.58)
  .every(3, x => x.add(5))
  .every(7, x => x.rev())

$: note("<[g5 b5 d6] [d5 fs5 a5] [g5 a5 c6] [e5 fs5 b5] [d5 b4 g5] [c5 e5 a5] [fs5 a5 d6] [g5 d5 b5]>")
  .slow(8)
  .sound("sine")
  .fmi(sine.range(0.5, 11).slow(14))
  .attack(1.2).release(4)
  .gain(0.1)
  .juxBy(0.6, x => x.add(0.1).slow(2))

$: note("[g3 b3 d4] [fs3 a3 <d4 cs4>] [e3 g3 b3] [d3 fs3 a3] [b2 d3 <g3 fs3>] [c3 e3 g3] [d3 fs3 a3] [g2 b2 d3]")
  .slow(8)
  .sound("piano")
  .gain(0.18)
  .room(0.7).size(0.85)
  .velocity(perlin.range(0.3, 0.9))

$: note("<d5 [~ b4] [~ c5] [a4 ~] g4 [~ e5] [fs5 ~] [~ d5]>")
  .slow(8)
  .sound("sawtooth")
  .gain(0.07)
  .lpf(perlin.range(350, 1800).slow(9))
  .pan(sine.range(0.15, 0.85).slow(11))
  .sometimes(x => x.add(12).gain(0.06))

$: s("[~ ~ ~ bd ~ ~ sn:3 ~] [~ bd ~ ~ sn:3 ~ ~ bd] [~ ~ bd ~ ~ sn:3 ~ ~]")
  .slow(4)
  .gain(0.11)
  .shape(0.4)
  .room(0.3)
  .often(x => x.speed(perlin.range(0.6, 1.3)))