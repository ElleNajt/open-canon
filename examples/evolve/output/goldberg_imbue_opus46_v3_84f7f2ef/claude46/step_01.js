setcps(66/60/4)

$: note("g3 fs3 e3 d3 b2 c3 d3 g2")
  .slow(4)
  .sound("triangle")
  .gain(0.45)
  .lpf(sine.range(400, 2200).slow(16))
  .room(0.3)
  .release(0.8)

$: note("g4 fs4 e4 d4 b3 c4 d4 g3")
  .slow(4)
  .sound("sine")
  .gain(0.2)
  .delay(0.4).delaytime(0.333).delayfeedback(0.45)
  .late(0.125)

$: note("<g5 b5 d5 fs5 g5 e5 fs5 b4>")
  .slow(4)
  .sound("sine")
  .gain(0.15)
  .fmi(sine.range(0.1, 2.5).slow(11))
  .attack(0.3).release(1.2)

$: note("[g3 b3 d4] [fs3 a3 d4] [e3 g3 b3] [d3 fs3 a3] [b2 d3 g3] [c3 e3 g3] [d3 fs3 a3] [g2 b2 d3]")
  .slow(8)
