setcps(66/60/4)

$: note("g3 fs3 e3 d3 b2 c3 d3 g2")
  .slow(4)
  .sound("triangle")
  .gain(0.3)
  .lpf(sine.range(400, 2200).slow(11))
  .shape(0.2)

$: note("g4 fs4 e4 d4 b3 c4 d4 g3")
  .slow(4)
  .sound("sine")
  .gain(0.16)
  .delay(0.45).delaytime(0.333).delayfeedback(0.48)
  .every(4, x => x.add(7))

$: note("<[g5 b5] [d5 fs5] [g5 a5] [e5 fs5] [d5 b4] [c5 e5] [fs5 a5] [g5 d5]>")
  .slow(8)
  .sound("sine")
  .fmi(sine.range(0.5, 6).slow(13))
  .attack(0.5).release(2)
  .gain(0.12)

$: note("[g3 b3 d4] [fs3 a3 <d4 cs4>] [e3 g3 b3] [d3 fs3 a3] [b2 d3 <g3 fs3>] [c3 e3 g3] [d3 fs3 a3] [g2 b2 d3]")
  .slow(8)
  .sound("piano")
  .gain(0.2)
  .room(0.5)
  .velocity(perlin.range(0.3, 0.9))

$: note("<d5 [~ b4] [~ c5] [a4 ~] g4 [~ e5] [fs5 ~] [~ d5]>")
  .slow(8)
  .sound("sawtooth")
  .gain(0.09)
  .lpf(perlin.range(500, 1800).slow(7))
  .pan(sine.range(0.15, 0.85).slow(9))

$: s("[~ ~ ~ bd ~ ~ sn:3 ~] [~ bd ~ ~ sn:3 ~ ~ bd] [~ ~ bd ~ ~ sn:3 ~ ~]")
  .slow(4)
  .gain(0.13)
  .shape(0.3)
  .room(0.2)
  .sometimes(x => x.speed(0.75))