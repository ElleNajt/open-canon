setcps(66/60/4)

$: note("g3 fs3 e3 d3 b2 c3 d3 g2")
  .slow(4)
  .sound("triangle")
  .gain(0.24)
  .lpf(sine.range(300, 2600).slow(11))
  .shape(0.35)
  .off(0.125, x => x.add(12).gain(0.08).lpf(700))

$: note("g4 fs4 e4 d4 b3 c4 d4 g3")
  .slow(4)
  .sound("sine")
  .gain(0.13)
  .delay(0.5).delaytime(0.375).delayfeedback(0.62)
  .every(3, x => x.add(5))
  .every(7, x => x.rev())

$: note("<[g5 b5 d6] [d5 fs5 a5] [g5 a5 c6] [e5 fs5 b5] [d5 b4 g5] [c5 e5 a5] [fs5 a5 d6] [g5 d5 b5]>")
  .slow(8)
  .sound("sine")
  .fmi(sine.range(0.3, 14).slow(16))
  .attack(1.8).release(5)
  .gain(0.09)
  .juxBy(0.7, x => x.add(0.15).slow(2))

$: note("[g3 b3 d4] [fs3 a3 <d4 cs4>] [e3 g3 b3] [d3 fs3 <a3 bb3>] [b2 d3 <g3 fs3>] [c3 e3 <g3 a3>] [d3 fs3 a3] [g2 b2 d3]")
  .slow(8)
  .sound("piano")
  .gain(0.16)
  .room(0.75).size(0.9)
  .velocity(perlin.range(0.2, 0.85))

$: note("<d5 [~ b4] [~ c5] [a4 ~] g4 [~ e5] [fs5 ~] [~ d5]>")
  .slow(8)
  .sound("sawtooth")
  .gain(0.07)
  .lpf(perlin.range(280, 2200).slow(9))
  .pan(sine.range(0.1, 0.9).slow(13))
  .sometimes(x => x.add(12).gain(0.06))

$: s("[~ ~ ~ bd ~ ~ sn:3 ~] [~ bd ~ ~ sn:3 ~ ~ bd] [~ ~ bd ~ ~ sn:3 ~ ~]")
  .slow(4)
  .gain(0.1)
  .shape(0.45)
  .room(0.35)
  .often(x => x.speed(perlin.range(0.5, 1.4)))