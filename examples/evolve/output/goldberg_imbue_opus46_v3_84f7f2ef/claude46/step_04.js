setcps(66/60/4)

$: note("g3 fs3 e3 d3 b2 c3 d3 g2")
  .slow(4)
  .sound("triangle")
  .gain(0.28)
  .lpf(sine.range(300, 1900).slow(11))
  .shape(0.25)

$: note("g4 fs4 e4 d4 b3 c4 d4 g3")
  .slow(4)
  .sound("sine")
  .gain(0.15)
  .delay(0.5).delaytime(0.333).delayfeedback(0.52)
  .every(4, x => x.add(7))

$: note("<[g5 b5] [d5 fs5] [g5 a5] [e5 fs5] [d5 b4] [c5 e5] [fs5 a5] [g5 d5]>")
  .slow(8)
  .sound("sine")
  .fmi(sine.range(0.3, 8).slow(16))
  .attack(0.8).release(3)
  .gain(0.11)

$: note("[g3 b3 d4] [fs3 a3 <d4 cs4>] [e3 g3 b3] [d3 fs3 a3] [b2 d3 <g3 fs3>] [c3 e3 g3] [d3 fs3 a3] [g2 b2 d3]")
  .slow(8)
  .sound("piano")
  .gain(0.19)
  .room(0.6).size(0.8)
  .velocity(perlin.range(0.25, 0.85))

$: note("<d5 [~ b4] [~ c5] [a4 ~] g4 [~ e5] [fs5 ~] [~ d5]>")
  .slow(8)
  .sound("sawtooth")
  .gain(0.08)
  .lpf(perlin.range(400, 1600).slow(7))
  .pan(sine.range(0.1, 0.9).slow(9))

$: s("[~ ~ ~ bd ~ ~ sn:3 ~] [~ bd ~ ~ sn:3 ~ ~ bd] [~ ~ bd ~ ~ sn:3 ~ ~]")
  .slow(4)
  .gain(0.12)
  .shape(0.35)
  .room(0.25)
  .sometimes(x => x.speed(0.7))