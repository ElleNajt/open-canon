setcps(120/60/4)

// Arp
$: chord("[cm g] [ab eb] [fm g] [abmaj7 g]")
  .arp("updown")
  .slow(2)
  .octave(5)
  .s("supersaw")
  .attack(0.01)
  .release(0.15)
  .lpenv(2500)
  .lpdecay(0.1)
  .crush(10)
  .gain(0.3)
  .pan(0.4)
  .jux(p => p.s("sine").add(12).pan(0.6).gain(0.5))
  .delay(0.3)
  .delaytime("3/16")
  .dfb(0.6)
  .room(0.3)
  .roomlp(4000)

// Lead
$: n("g5 ~ eb5 d5 ~ c5 ~ g4")
  .slow(4)
  .s("square")
  .release(0.4)
  .cutoff(3000)
  .resonance(2)
  .gain(0.35)
  .delay(0.6)
  .delaytime("3/8")
  .dfb(0.7)
  .room(0.5)

// Pads
$: chord("[cm g] [ab eb] [fm g] [abmaj7 g]")
  .slow(8)
  .sound("piano")
  .voicing()
  .octave(3)
  .attack(3)
  .release(7)
  .cutoff(sine.range(600, 2200).slow(12))
  .resonance(5)
  .ftype(1)
  .gain(0.6)
  .room(0.7)
  .roomsize(0.9)

// Bass
$: n("c ab f <ab g>").slow(4)
  .euclid(3, 8).fast(2)
  .octave(1)
  .sound("pulse")
  .cut(1)
  .attack(0.01)
  .release(0.3)
  .cutoff(400)
  .penv(3)
  .pdecay(0.05)
  .drive(0.5)
  .gain(0.7)

// Drums
$: stack(
  s("bd ~ bd [~ bd]").gain(1.1),
  s("~ sn ~ [sn cp]").crush(12).hpf(120).room(0.1).gain(0.8),
  s("[hh hh] hh [ht hh] [~ hh]")
    .swing(0.5)
    .velocity(perlin.range(0.5, 1).slow(4))
    .hpf(7000)
    .gain(0.5)
    .degradeBy(0.05),
  s("~ ~ oh ~ ~ ~ oh ~")
    .gain(0.4)
    .release(0.2)
    .hpf(6000)
).gain(1.1)