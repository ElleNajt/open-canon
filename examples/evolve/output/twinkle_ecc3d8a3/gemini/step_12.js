setcps(120/60/4)

// Dreamy Arp
$: chord("[cm g] [ab eb] [fm g] [abmaj7 g]")
  .arp("updown")
  .slow(2)
  .octave(5)
  .s("sawtooth")
  .attack(0.01)
  .release(0.3)
  .gain(0.35)
  .lpenv(2000)
  .lpdecay(0.1)
  .jux(p => p.s("pulse").octave(4).gain(0.4).pan(perlin.range(0.2, 0.8).slow(7)))
  .delay(0.5)
  .delaytime("3/16")
  .dfb(0.6)
  .room(0.4)
  .lpf(perlin.range(1000, 6000).slow(10))
  .lpq(3)

// Pads
$: chord("[cm g] [ab eb] [fm g] [abmaj7 g]")
  .slow(8)
  .s("supersaw")
  .voicing()
  .octave(3)
  .attack(5)
  .release(9)
  .cutoff(perlin.range(600, 3500).slow(16))
  .resonance(8)
  .ftype(1)
  .phaser(0.05)
  .phaserdepth(0.7)
  .gain(0.55)
  .pan(perlin.range(0.2, 0.8).slow(20))
  .room(0.7)
  .roomsize(0.9)

// Bassline
$: n("c1 ab0 f0 g0").slow(4).euclid(7, 8).rev()
  .s("sawtooth")
  .cut(1)
  .attack(0.01)
  .release(0.4)
  .gain(0.7)
  .lpf(500)
  .lpq(4)
  .drive(0.3)

// Drums
$: stack(
  s("bd ~ bd [~ bd]").gain(1.2),
  s("~ <sn cp>").gain(0.9),
  s("hh*8")
    .velocity(perlin.range(0.6, 1).slow(3))
    .hpf(8000)
    .degradeBy(0.15)
    .gain(0.5)
    .swing(0.05),
  s("<~ ~ mt ~> <~ mt ~ mt>")
    .gain(0.7)
    .pan(perlin.range(0.6, 0.9).slow(13))
    .room(0.3)
).gain(0.9).compressor()