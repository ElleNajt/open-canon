// Evolving Pads
$: chord("[cm9] [gm11] [abmaj7] [ebmaj7]")
  .slow(8)
  .s("triangle")
  .voicing()
  .octave(3)
  .attack(4)
  .release(9)
  .cutoff(perlin.range(900, 4500).slow(16))
  .resonance(6)
  .ftype(1)
