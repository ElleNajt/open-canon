setcps(92/60/4)

// Evolved Arp
$: n("[0 2 4] [7 4 2] [5 7 9] [12 9 7]")
  .scale("c:minor")
  .fast(2)
  .octave(5)
  .sound("pulse")
  .attack(0.02)
  .release(0.6)
  .lpenv(2000)
  .lpdecay(0.4)
  .gain(0.4)
  .pan(0.65)
  .off(1/8, p => p.add(7).pan(0.35).gain(0.7))
  .delay(0.5)
  .delaytime(3/8)
  .dfb(0.6)
  .room(0.4)

// Evolved Pads
$: chord("[cm g] [ab eb] [fm g] [cm eb7]")
  .slow(8)
  .sound("supersaw")
  .voicing()
  .octave(3)
  .attack(3)
  .release(5)
  .cutoff(sine.range(500, 2500).slow(16))
  .resonance(4)
  .vowel(saw.range("a", "u").slow(32))
  .gain(0.3)
  .leslie(0.1)
  .room(0.8)
  .roomsize(0.9)

// Evolved Bass
