setcps(120/60/4)

// Arp
$: chord("[cm g] [ab eb] [fm g] [abmaj7 g]")
  .arp("updown")
  .slow(2)
  .octave(5)
  .sound("triangle")
  .attack(0.01)
  .release(0.2)
  .lpenv(3000)
  .lpdecay(0.1)
  .crush(8)
  .gain(0.4)
  .pan(0.4)
  .jux(p => p.add(12).pan(0.6).gain(0.6))
  .delay(0.3)
  .delaytime("3/16")
  .dfb(0.6)
  .room(0.3)
  .roomlp(5000)

// Pads
$: chord("[cm g] [ab eb] [fm g] [abmaj7 gm]")
  .slow(8)
  .sound("piano")
  .voicing()
  .octave(3)
  .attack(2)
  .release(6)
  .cutoff(perlin.range(600, 2500).slow(16))
  .resonance(4)
  .ftype(1)
  .delay(0.6)
  .delaytime("3/8")
  .dfb(0.7)
  .gain(0.5)
  .room(0.8)
  .roomsize(0.95)

// Bass
$: n("c ab f <ab g>").slow(4)
  .euclid(5, 8)
  .octave(1)
  .sound("pulse")
  .cut(1)
  .attack(0.01)
  .release(0.4)
  .cutoff(220)
  .lpenv(800)
  .lpdecay(0.1)
  .drive(0.4)
  .gain(0.8)

