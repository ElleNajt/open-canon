setcps(124/60/4)

// Dreamy Arp
$: chord("[cm9] [gm11] [abmaj7] [ebmaj7]")
  .arp("updown")
  .slow(4)
  .octave(5)
  .s("sawtooth")
  .attack(0.01)
  .release(0.5)
  .lpenv(2000)
  .lpdecay(0.2)
  .gain(0.25)
  .jux(p => p.s("pulse").octave(4).gain(0.2).pan(perlin.range(0.2, 0.8).slow(9)).fast(2))
  .delay(0.5)
  .delaytime("3/16")
  .dfb(0.65)
  .room(0.5)
  .roomlp(4000)
  .lpf(sine.range(1000, 4500).slow(8))
  .lpq(5)

// Pads
$: chord("[cm9] [gm11] [abmaj7] [ebmaj7]")
  .slow(8)
  .s("supersaw")
  .voicing()
  .octave(3)
  .attack(4)
  .release(8)
  .cutoff(perlin.range(600, 3500).slow(18))
  .resonance(6)
  .ftype(1)
  .phaser(perlin.range(0.02, 0.1).slow(19))
  .gain(0.4)
  .pan(perlin.range(0.1, 0.9).slow(22))
  .jux(p => p.s("sine").octave(2).gain(0.4).add(0.01))
  .room(0.7)
  .roomsize(0.9)

// Bassline
$: n("[c1 ~ c1 ~] [g0 ~ g0 g0] [ab0 ~ ab0 ~] [eb1 eb1 ~ ~]")
