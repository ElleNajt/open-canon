setcps(90/60/4)

$: n("0 0 7 7 9 9 7 ~ 5 5 4 4 2 2 0 ~ 7 7 5 5 4 4 2 ~ 7 7 5 5 4 4 2 ~ 0 0 7 7 9 9 7 ~ 5 5 4 4 2 2 0 ~")
  .scale("c:major")
  .octave(4)
  .sound("triangle")
  .attack(0.01)
  .release(0.4)
  .gain(0.5)
  .pan(0.7)
  .jux(p => p.pan(0.3).detune(-4))
  .delay(0.4)
  .delaytime(0.75)
  .dfb(0.4)
  .room(0.3)

$: chord("[cmaj fmaj] [cmaj gmaj] [cmaj fmaj] [cmaj cmaj]")
  .slow(8)
  .arp("updown")
  .sound("sine")
  .octave(5)
  .gain(0.15)
  .release(0.25)
  .pan(perlin.range(0.2, 0.8).slow(6))
  .room(0.5)

$: n("c2 f1 c2 g1")
  .slow(8)
  .sound("pulse")
  .cutoff(300)
  .gain(0.45)
  .resonance(1)

