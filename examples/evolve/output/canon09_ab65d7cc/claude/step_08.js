// BWV 1087 Canon 9 - Variation: The Cathedral Remembers Its Fire

// Ash and light intermingle - what burned now glows
let emberOrgan = x => x
  .sound("sawtooth")
  .gain(0.28)
  .attack(0.15)
  .decay(0.6)
  .sustain(0.7)
  .release(1.2)
  .lpf(perlin.range(400, 1800).slow(9))
  .lpq(6)
  .shape(0.2)
  .room(0.75)
  .delay(0.4)
  .delaytime(0.333)
  .delayfeedback(0.5)

// The ghost learns to sing again - but in a different key
let phoenixVoice = x => x
  .sound("triangle")
  .gain(0.25)
  .attack(0.5)
  .decay(1.2)
  .sustain(0.5)
  .release(2)
  .fmi(2)
  .fmh(5)
  .fmdecay(1.5)
  .room(0.85)

setcps(66/60/4)

// Track 1 - Melody inverts and descends like falling sparks
$: note("b5 ~ a5 fs5 ~ e5 cs5 ~ b4 a4 ~ ~")
  .slow(8)
  .apply(emberOrgan)
  .pan(0.4)
  .every(3, x => x.transpose(-5).fast(1.5))
  .juxBy(0.5, x => x.late(0.75).transpose(12).gain(0.18))

// Track 2 - Harmony shifts to minor 7ths - grief with light behind it
$: note("<[fs3,a3,e4] [e3,g3,d4] [d3,f3,c4] [c3,eb3,bb3] [b2,d3,a3]>")
  .slow(12)
  .apply(phoenixVoice)
  .pan(0.6)
  .lpf(sine.range(600, 2400).slow(15))
  .phaser(0.2)
  .phaserdepth(0.8)
  .every(5, x => x.transpose(2))

// Track 3 - Bass becomes a heartbeat returning - fifths now, alive
$: note("[e1 b1] ~ ~ [d1 a1] ~ ~ [c1 g1] ~ ~ [b0 fs1] ~ ~")
  .slow(6)
  .sound("sine")
  .gain(0.35)
  .attack(0.4)
  .decay(0.8)
  .sustain(0.85)
  .release(1.5)
  .lpf(200)
  .fmi(0.5)
  .fmh(3)
  .fmdecay(2)

// Track 4 - Percussion awakens - ritual drums through cathedral stone
$: s("bd:3 ~ [rim rim] ~ bd:3 ~ rim ~")
  .slow(2)
  .gain(0.2)
  .room(0.6)
  .lpf(1200)
  .speed(0.8)
  .shape(0.1)

// NEW: Choir of the rebuilt - stacked voices rise from rubble
$: note("[e4,gs4,b4] ~ [fs4,a4,cs5] ~ [gs4,b4,ds5] ~ [a4,cs5,e5] ~")
  .slow(8)
  .sound("supersaw")
  .gain(0.14)
  .attack(1.5)
  .decay(2)
  .sustain(0.6)
  .release(2.5)
  .lpf(cosine.range(800, 2200).slow(14))
  .detune(12)
  .room(0.9)
  .pan(sine.range(0.3, 0.7).slow(11))

// The bells ring backwards - time folding
$: note("[b6 e6] [a5 d6] [gs5 cs6] [fs5 b5]")
  .slow(5)
  .sound("sine")
  .gain(0.12)
  .attack(0.002)
  .decay(2)
  .sustain(0.05)
  .release(2.5)
  .fmi(12)
  .fmh(13)
  .fmdecay(0.2)
  .hpf(2000)
  .room(0.95)
  .pan(perlin.range(0.15, 0.85).slow(6))
  .delay(0.55)
  .delaytime(0.5)
  .delayfeedback(0.65)
  .rev()

// NEW: A pulse emerges - not machine, but breath
$: s("~ ~ hh:1 ~ ~ hh:2 ~ hh:1")
  .fast(1.5)
  .gain(0.15)
  .hpf(4000)
  .room(0.5)
  .pan(rand)
  .speed(rand.range(1.1, 1.6))
  .degradeBy(0.3)

// NEW: Low drone remembers what was lost - pedal tone witness
$: note("e2")
  .slow(16)
  .sound("sawtooth")
  .gain(0.18)
  .attack(4)
  .decay(2)
  .sustain(0.8)
  .release(4)
  .lpf(300)
  .lpq(2)
  .shape(0.08)
  .room(0.7)