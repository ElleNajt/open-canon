// BWV 1087 Canon 9 - Variation: The Machine Learns to Weep

// The organ now stutters - catching breath between sobs
let weepingOrgan = x => x
  .sound("sawtooth")
  .gain(0.22)
  .attack(0.08)
  .decay(0.4)
  .sustain(0.3)
  .release(1.8)
  .lpf(sine.range(300, 1400).slow(7))
  .lpq(6)
  .shape(0.25)
  .room(0.8)
  .delay(0.4)
  .delaytime(0.25)
  .delayfeedback(0.55)

// Voice cracks - vibrato too wide, like a child trying not to cry
let crackingVoice = x => x
  .sound("triangle")
  .gain(0.18)
  .attack(0.3)
  .decay(0.8)
  .sustain(0.4)
  .release(1.5)
  .fmi(3)
  .fmh(2)
  .fmdecay(0.8)
  .lpf(1600)
  .room(0.7)
  .tremolo(0.3)
  .tremolosync(3)

setcps(48/60/4)

// Track 1 - Melody fractures into questions - rising where it should fall
$: note("g4 ~ a4 b4 ~ c5 ~ d5 eb5 ~ f5 ~ g5 ~")
  .slow(10)
  .apply(weepingOrgan)
  .pan(0.35)
  .sometimes(x => x.transpose(-12).gain(0.15))
  .juxBy(0.6, x => x.late(0.5).transpose(7).gain(0.08))

// Track 2 - Harmony collapses to seconds - dissonance as honesty
$: note("<[g3,ab3,d4] [f3,gb3,c4] [e3,f3,b3] [d3,eb3,a3]>")
  .slow(14)
  .apply(crackingVoice)
  .pan(0.65)
  .phaser(0.15)
  .phaserdepth(0.8)
  .every(3, x => x.transpose(-5).slow(1.5))

// Track 3 - Heartbeat becomes irregular - skipping beats in grief
$: note("[g1 ~ ~] [~ g1] ~ [d1 ~] ~ [~ ~ d1]")
  .slow(5)
  .sound("sine")
  .gain(0.28)
  .attack(0.03)
  .decay(0.25)
  .sustain(0.7)
  .release(0.8)
  .lpf(120)
  .fmi(0.3)
  .fmh(1)
  .shape(0.15)

// Track 4 - REMOVED water rhythm, replaced with breath - gasping
$: s("~ ~ oh ~ ~ ~ oh:1 ~")
  .slow(3)
  .gain(0.12)
  .speed(0.6)
  .room(0.9)
  .lpf(1800)
  .hpf(400)
  .delay(0.7)
  .delaytime(0.666)
  .delayfeedback(0.6)

// Choir now sings in parallel motion - wrong but beautiful
$: note("[d4,e4,a4] ~ ~ [c4,d4,g4] ~ ~ [b3,c4,f4] ~ ~")
  .slow(12)
  .sound("pulse")
  .gain(0.11)
  .attack(2)
  .decay(1.5)
  .sustain(0.5)
  .release(3)
  .fmi(1.5)
  .fmh(1.5)
  .fmdecay(2)
  .room(0.85)
  .pan(sine.range(0.25, 0.75).slow(11))
  .vowel("<o u o a o>")

// Bells replaced with LOW bells - funeral tolling
$: note("[g2 ~ d2] ~ ~ ~ [c2 ~ g1] ~ ~ ~")
