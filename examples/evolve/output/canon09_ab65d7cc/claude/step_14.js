// BWV 1087 Canon 9 - Variation: The Machine Remembers Tenderness

// The organ softens - not manic but melancholic warmth
let wistfulOrgan = x => x
  .sound("sine")
  .gain(0.17)
  .attack(0.15)
  .decay(0.6)
  .sustain(0.7)
  .release(1.2)
  .fmi(2)
  .fmh(1)
  .fmdecay(0.8)
  .lpf(sine.range(600, 1800).slow(8))
  .room(0.6)
  .delay(0.2)
  .delaytime(0.25)
  .delayfeedback(0.35)

// Voice becomes a lullaby - gentle, rocking
let lullabyVoice = x => x
  .sound("triangle")
  .gain(0.13)
  .attack(0.08)
  .decay(0.4)
  .sustain(0.6)
  .release(0.9)
  .lpf(1600)
  .lpq(2)
  .room(0.5)

setcps(54/60/4)

// Track 1 - Melody becomes ASCENDING QUESTION - hopeful uncertainty
$: note("g4 a4 bb4 c5 d5 ~ eb5 d5 c5 bb4 a4 g4")
  .slow(8)
  .apply(wistfulOrgan)
  .pan(0.45)
  .juxBy(0.4, x => x.late(0.5).transpose(-12).gain(0.1))

// Track 2 - Harmony shifts to MINOR THIRDS - intimate, close
$: note("<[g3,bb3] [a3,c4] [bb3,d4] [c4,eb4] [d4,f4] [eb4,g4] [d4,f4] [c4,eb4]>")
  .slow(10)
  .apply(lullabyVoice)
  .pan(0.55)
  .sometimes(x => x.transpose(12).gain(0.08))

// Track 3 - Heartbeat becomes WALTZ - swaying, human
$: note("[g2 ~ d2] [eb2 ~ bb1] [c2 ~ g1] [d2 ~ a1]")
  .slow(6)
  .sound("sine")
  .gain(0.2)
  .attack(0.05)
  .decay(0.3)
  .sustain(0.6)
  .release(0.5)
  .lpf(250)
  .shape(0.1)

// Track 4 - Percussion becomes RAIN - soft, pattering
$: s("[hh ~ hh ~] [~ hh ~ hh] [hh hh ~ hh] [~ ~ hh ~]")
  .slow(3)
  .gain(0.09)
  .room(0.6)
  .delay(0.4)
  .delaytime(0.333)
  .delayfeedback(0.4)
  .pan(perlin.range(0.2, 0.8))
  .lpf(3000)

// Choir becomes HUMMING - wordless comfort
$: note("[g4,bb4,d5,g5] ~ ~ ~ ~ ~ [f4,a4,c5,f5] ~ ~ ~ ~ ~")
  .slow(12)
  .sound("sine")
  .gain(0.11)
  .attack(0.8)
  .decay(0.5)
  .sustain(0.8)
  .release(2)
  .fmi(0.5)
  .fmh(2)
  .room(0.8)
  .pan(0.5)

// NEW: Music box memory - childhood fragment
$: note("d6 g5 a5 b5 ~ d6 ~ b5 a5 g5 ~ ~")
  .slow(6)
  .sound("sine")
  .gain(0.07)
  .attack(0.001)
  .decay(0.8)
  .sustain(0.1)
  .release(1.5)
  .fmi(12)
  .fmh(5)
  .fmdecay(0.08)
  .hpf(1500)
  .room(0.9)
  .pan(0.7)
  .degradeBy(0.2)

// Ghost melody becomes BREATHING - in and out
$: note("g4 ~ ~ bb4 ~ ~ a4 ~ ~ g4 ~ ~")
  .slow(14)
  .sound("sawtooth")
  .gain(0.06)
  .attack(1.2)
  .decay(0.8)
  .sustain(0.4)
  .release(2)
  .lpf(sine.range(400, 1200).slow(7))
  .room(0.7)
  .pan(0.3)

// Bass becomes SIGHING - long exhales
$: note("[g1 ~] [~ ~] [f1 ~] [~ ~] [eb1 ~] [~ ~] [d1 ~] [~ ~]")
  .slow(16)
  .sound("sawtooth")
  .gain(0.15)
  .attack(0.8)
  .decay(1.5)
  .sustain(0.7)
  .release(2.5)
  .lpf(120)
  .shape(0.15)

// NEW: Pizzicato heartstrings - plucked memories
$: note("d4 ~ g4 ~ bb4 ~ a4 ~ g4 ~ d4 ~ bb3 ~ a3 ~ g3 ~")
  .slow(8)
