// BWV 1087 Canon 9 - Variation: The Cathedral Speaks in Tongues

// What was sacred becomes strange - organ pipes bent by heat
let warpedOrgan = x => x
  .sound("sawtooth")
  .gain(0.26)
  .attack(0.08)
  .decay(0.4)
  .sustain(0.6)
  .release(0.8)
  .lpf(perlin.range(600, 2400).slow(7))
  .lpq(8)
  .shape(0.35)
  .room(0.6)
  .delay(0.5)
  .delaytime(0.25)
  .delayfeedback(0.6)

// The phoenix now speaks in clusters - dissonance as renewal
let clusterVoice = x => x
  .sound("square")
  .gain(0.18)
  .attack(0.3)
  .decay(0.8)
  .sustain(0.4)
  .release(1.5)
  .fmi(4)
  .fmh(7)
  .fmdecay(0.6)
  .lpf(1600)
  .room(0.7)

setcps(72/60/4)

// Track 1 - Melody fractures into tritones and minor seconds
$: note("[b5 f5] ~ [a5 eb5] ~ [gs5 d5] ~ [g5 cs5] ~ [fs5 c5] ~")
  .slow(6)
  .apply(warpedOrgan)
  .pan(0.35)
  .every(4, x => x.transpose(7).fast(2))
  .juxBy(0.6, x => x.late(0.5).transpose(-12).gain(0.15))

// Track 2 - Harmony becomes quartal - neither major nor minor
$: note("<[e3,a3,d4,g4] [d3,g3,c4,f4] [c3,f3,bb3,eb4] [bb2,eb3,ab3,db4]>")
  .slow(10)
  .apply(clusterVoice)
  .pan(0.65)
  .phaser(0.4)
  .phaserdepth(0.9)
  .every(3, x => x.transpose(-3).slow(1.5))

// Track 3 - Bass becomes polyrhythmic - 5 against the world
$: note("e1 ~ a1 ~ d1 ~ g1 ~ c1 ~")
  .euclid(5, 8)
  .slow(4)
  .sound("triangle")
  .gain(0.32)
  .attack(0.2)
  .decay(0.5)
  .sustain(0.9)
  .release(1)
  .lpf(280)
  .fmi(1)
  .fmh(2)
  .shape(0.15)

// Track 4 - Ritual becomes industrial - stone grinding on stone
$: s("[bd:3 bd:3] ~ cp ~ [rim*3] ~ [bd:1 cp] ~")
  .slow(2)
  .gain(0.22)
  .room(0.4)
  .lpf(900)
  .hpf(100)
  .speed(0.7)
  .shape(0.25)
  .crush(10)

// NEW: Spectral choir - semitone clusters that shimmer
$: note("[e4,f4,fs4] ~ ~ [a4,bb4,b4] ~ ~ [d5,eb5,e5] ~ ~")
  .slow(12)
  .sound("sine")
  .gain(0.12)
  .attack(2)
  .decay(1.5)
  .sustain(0.7)
  .release(3)
  .fmi(6)
  .fmh(11)
  .fmdecay(2)
  .room(0.95)
  .pan(sine.range(0.2, 0.8).slow(9))
  .tremolo(0.3)
  .tremolosync(5)

// The bells now toll in wrong octaves - time unstuck
$: note("[c7 gb6] [f6 b5] [bb5 e5] [eb5 a4]")
  .slow(7)
  .sound("sine")
  .gain(0.1)
  .attack(0.001)
  .decay(1.5)
  .sustain(0.03)
  .release(2)
  .fmi(15)
  .fmh(11)
  .fmdecay(0.15)
  .hpf(2500)
  .room(0.9)
  .delay(0.7)
  .delaytime(0.666)
  .delayfeedback(0.7)
  .palindrome()

// NEW: A voice emerges from static - speaking without words
$: s("hh:0 ~ oh:1 ~ hh:2 oh:0 ~ hh:1")
  .fast(2)
  .gain(0.14)
  .hpf(3000)
  .lpf(8000)
  .room(0.6)
  .pan(perlin.range(0.1, 0.9).slow(3))
  .speed(rand.range(0.6, 2))
  .vowel("<a e i o u>")
  .degradeBy(0.25)

// NEW: Subsonic presence - felt not heard
$: note("[b0 ~ ~ e1] ~ ~ ~")
  .slow(8)
  .sound("sine")
  .gain(0.25)
  .attack(2)
  .decay(3)
  .sustain(0.95)
  .release(3)
  .lpf(80)
  .fmi(0.3)
  .fmh(1.5)

