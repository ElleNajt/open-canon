// BWV 1087 Canon 9 - Variation: The Storm Before Resolution

// Urgency takes hold - restless energy replaces certainty
let anxiousVoice = x => x
  .sound("pulse")
  .gain(0.09)
  .attack(0.01)
  .decay(0.2)
  .sustain(0.6)
  .release(0.4)
  .lpf(3500)
  .room(0.25)

// Dissonance creeps in - the shadow of doubt
let tensionChord = x => x
  .sound("sawtooth")
  .gain(0.08)
  .attack(0.08)
  .decay(0.6)
  .sustain(0.4)
  .release(1.2)
  .lpf(2000)
  .room(0.35)

setcps(108/60/4)

// Track 1 - Melody becomes FRAGMENTED - gasping, searching
$: note("d5 ~ fs5 ~ a4 e5 ~ cs5 d5 ~ ~ a4 fs5 e5 d5 ~")
  .slow(4)
  .apply(anxiousVoice)
  .pan(sine.range(0.3, 0.7).slow(2))
  .delay(0.4)
  .delaytime(0.125)
  .delayfeedback(0.5)

// Track 2 - Harmony DARKENS - minor intrusions, suspended chords
$: note("<[d3,a3,e4] [b2,fs3,d4] [g3,d4,a4] [a2,e3,g3]>")
  .slow(2)
  .apply(tensionChord)
  .pan(0.4)

// Track 3 - Bass becomes SYNCOPATED - ground shifting underfoot
$: note("d2 ~ a1 ~ e2 d2 ~ a1 fs2 ~ d2 a1 ~ e2 ~ a1")
  .slow(2)
  .sound("sawtooth")
  .gain(0.12)
  .attack(0.01)
  .decay(0.15)
  .sustain(0.5)
  .release(0.3)
  .lpf(350)
  .distort(0.2)

// Drums become CHAOTIC - the march fractures
$: s("bd bd ~ sn ~ bd sn [bd bd]")
  .slow(2)
  .gain(0.11)
  .lpf(1800)
  .room(0.2)
  .pan(0.5)
  .sometimes(x => x.speed(0.8))

// Hihat becomes ERRATIC - nervous energy
$: s("[hh hh hh] ~ hh [hh hh] ~ hh hh [hh hh hh hh]")
  .slow(2)
  .gain(0.08)
  .hpf(5500)
  .pan(rand.range(0.2, 0.8))

// Bells become WARNING SIGNALS - dissonant clusters
$: note("d6 eb6 a6 cs7")
  .slow(4)
  .euclid(7, 12)
  .sound("sine")
  .gain(0.07)
  .attack(0.005)
  .decay(0.3)
  .sustain(0.15)
  .release(1)
  .fmi(5)
  .fmh(7)
  .room(0.4)
  .pan(rand.range(0.1, 0.9))

// Chords become UNSTABLE - whole tone ambiguity
$: note("[d4,e4,fs4] ~ [e4,fs4,gs4] ~ [fs4,gs4,as4] ~ [gs4,as4,c5] ~")
  .slow(4)
  .sound("square")
  .gain(0.065)
  .attack(0.03)
  .decay(0.5)
  .sustain(0.3)
  .release(0.6)
  .lpf(2200)
  .pan(0.55)
  .room(0.3)

// NEW: Trembling strings - anxiety made audible
$: note("a4 a4 a4 a4 gs4 gs4 a4 a4")
  .fast(2)
  .sound("sawtooth")
  .gain(0.06)
  .attack(0.01)
  .decay(0.05)
  .sustain(0.7)
  .release(0.1)
  .lpf(1600)
  .tremolo(0.8)
  .pan(0.35)

// Drone becomes WAVERING - unstable foundation
$: note("d2 cs2 d2 eb2")
  .slow(8)
  .sound("triangle")
  .gain(0.09)
  .attack(0.5)
  .decay(1.5)
  .sustain(0.5)
  .release(1.5)
  .lpf(sine.range(200, 800).slow(4))
  .pan(0.5)
  .room(0.45)

// NEW: Descending chromatic line - the fall
$: note("a4 gs4 g4 fs4 f4 e4 eb4 d4")
  .slow(4)
  .sound("sine")
  .gain(0.07)
  .attack(0.02)
