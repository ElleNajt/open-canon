// BWV 1087 Canon 9 - Variation: The Awakening

// From dissolution emerges REBIRTH - the cycle begins anew
let risingVoice = x => x
  .sound("sawtooth")
  .gain(0.09)
  .attack(0.05)
  .decay(0.4)
  .sustain(0.6)
  .release(1)
  .lpf(2200)
  .lpq(3)
  .room(0.4)
  .fmi(2)
  .fmh(2)

// Twilight becomes DAWN - light returning with urgency
let dawnChord = x => x
  .sound("square")
  .gain(0.06)
  .attack(0.1)
  .decay(0.6)
  .sustain(0.5)
  .release(1.2)
  .lpf(1200)
  .room(0.5)

setcps(84/60/4)

// Track 1 - Melody RECONSTITUTES - fragments finding each other
$: note("d5 e5 fs5 g5 a5 fs5 e5 d5 cs5 d5 e5 fs5 g5 a5 b5 a5")
  .slow(4)
  .apply(risingVoice)
  .pan(sine.range(0.3, 0.7).slow(4))
  .delay(0.2)
  .delaytime(0.25)
  .delayfeedback(0.3)

// Track 2 - Harmony RESOLVES - questions become answers
$: note("<[d3,fs3,a3] [g3,b3,d4] [a3,cs4,e4] [d3,fs3,a3]>")
  .slow(2)
  .apply(dawnChord)
  .pan(0.55)

// Track 3 - Bass AWAKENS - striding forward with purpose
$: note("d2 a2 d2 e2 fs2 a2 d3 a2")
  .slow(2)
  .sound("triangle")
  .gain(0.12)
  .attack(0.02)
  .decay(0.3)
  .sustain(0.5)
  .release(0.8)
  .lpf(180)
  .shape(0.08)

// Wind chimes become BELLS OF ANNOUNCEMENT
$: note("d6 fs6 a6 d7 a6 fs6 d6 a5")
  .euclid(5, 8)
  .slow(2)
  .sound("sine")
  .gain(0.06)
  .attack(0.01)
  .decay(0.8)
  .sustain(0.1)
  .release(1.5)
  .fmi(8)
  .fmh(7)
  .fmdecay(0.1)
  .room(0.5)
  .pan(rand.range(0.3, 0.7))

