// BWV 1087 Canon 9 - Variation: The Breaking Dawn

// The storm has passed - first light emerges through dissipating clouds
let dawnVoice = x => x
  .sound("triangle")
  .gain(0.08)
  .attack(0.15)
  .decay(0.4)
  .sustain(0.5)
  .release(0.8)
  .lpf(2800)
  .room(0.4)

// Hope returns - major inflections pierce the minor veil
let resolutionChord = x => x
  .sound("sine")
  .gain(0.09)
  .attack(0.2)
  .decay(0.8)
  .sustain(0.5)
  .release(1.5)
  .lpf(1800)
  .room(0.45)

setcps(84/60/4)

// Track 1 - Melody BREATHES AGAIN - long phrases, resolved intervals
$: note("d5 e5 fs5 ~ a5 ~ fs5 e5 ~ d5 ~ a4 b4 cs5 d5 ~")
  .slow(4)
  .apply(dawnVoice)
  .pan(sine.range(0.35, 0.65).slow(6))
  .delay(0.3)
  .delaytime(0.25)
  .delayfeedback(0.35)

// Track 2 - Harmony OPENS - major chords bloom from darkness
