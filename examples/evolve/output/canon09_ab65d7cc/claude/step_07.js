// BWV 1087 Canon 9 - Variation: The Machine Dreams of Water

// The gears slow, rust blooms - something organic seeps through cracks
let drowningMachine = x => x
  .sound("sawtooth")
  .gain(0.32)
  .attack(0.08)
  .decay(0.4)
  .sustain(0.5)
  .release(0.8)
  .lpf(sine.range(600, 2200).slow(11))
  .lpq(4)
  .shape(0.15)
  .room(0.6)
  .delay(0.35)
  .delaytime(0.25)
  .delayfeedback(0.55)

// The specter finds its body again - warmer, breathing
let resurrectedVoice = x => x
  .sound("triangle")
  .gain(0.28)
  .attack(0.3)
  .decay(0.8)
  .sustain(0.6)
  .release(1.5)
  .fmi(1.2)
  .fmh(3)
  .fmdecay(2)
  .room(0.8)

setcps(72/60/4)

// Track 1 - Melody remembers itself, but in fragments, reaching upward
$: note("e4 ~ fs4 a4 ~ b4 d5 ~ e5 fs5 ~ ~")
  .slow(8)
  .apply(drowningMachine)
  .pan(0.35)
  .every(4, x => x.transpose(7).slow(2))
  .juxBy(0.4, x => x.late(0.5).transpose(-12))

// Track 2 - Harmony opens into suspended chords - questions without answers
$: note("<[a3,d4,e4] [g3,c4,d4] [f3,bb3,c4] [eb3,ab3,bb3] [d3,g3,a3]>")
  .slow(10)
  .apply(resurrectedVoice)
  .pan(0.65)
  .lpf(perlin.range(800, 3000).slow(13))
  .phaser(0.15)
  .phaserdepth(0.6)

// Track 3 - Bass becomes a slow tide, not a pulse
$: note("a1 ~ ~ ~ e1 ~ ~ ~ d1 ~ ~ ~ g1 ~ ~ ~")
  .slow(8)
  .sound("sine")
  .gain(0.38)
  .attack(0.8)
  .decay(1)
  .sustain(0.9)
  .release(2)
  .lpf(150)
  .fmi(0.3)
  .fmh(2)
  .fmdecay(3)

// Track 4 - Percussion dissolves into texture, rain returning
$: s("~ hh:2 ~ [hh:1 hh:3] ~ hh:2 ~ ~")
  .slow(2)
  .gain(0.18)
  .room(0.7)
  .hpf(3000)
  .speed(rand.range(0.7, 1.4))
  .pan(rand)
  .degradeBy(0.4)

// NEW: Glass bells emerge where metal once clanged
$: note("[e6 b5] [fs6 cs6] [a5 e5] [d6 a5]")
  .slow(6)
  .sound("sine")
  .gain(0.15)
  .attack(0.001)
  .decay(1.5)
  .sustain(0.1)
  .release(2)
  .fmi(8)
  .fmh(11)
  .fmdecay(0.3)
  .hpf(1500)
  .room(0.9)
  .pan(sine.range(0.2, 0.8).slow(7))
  .delay(0.5)
  .delaytime(0.375)
  .delayfeedback(0.6)

// The swarm calms into a distant choir - thirds now, not clusters
$: note("<[a3,cs4] [fs3,a3] [d3,fs3] [e3,gs3] [b2,ds3]>")
  .slow(12)
  .sound("supersaw")
  .gain(0.12)
  .attack(2)
  .decay(1.5)
  .sustain(0.4)
  .release(3)
  .lpf(cosine.range(400, 1600).slow(16))
  .detune(8)
  .room(0.8)
  .pan(0.5)

// NEW: A voice speaks through the static - speech becomes rhythm
$: s("cr ~ ~ rim ~ cr rim ~")
  .slow(4)
  .gain(0.12)
  .speed(0.6)
  .room(0.5)
  .lpf(2000)
  .coarse(4)
