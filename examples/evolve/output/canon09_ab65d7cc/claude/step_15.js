// BWV 1087 Canon 9 - Variation: The Storm Before Peace

// The organ darkens - building tension, searching
let stormOrgan = x => x
  .sound("sawtooth")
  .gain(0.19)
  .attack(0.03)
  .decay(0.4)
  .sustain(0.8)
  .release(0.6)
  .fmi(4)
  .fmh(1.5)
  .fmdecay(0.3)
  .lpf(sine.range(400, 2200).slow(4))
  .lpq(4)
  .room(0.4)
  .delay(0.15)
  .delaytime(0.166)
  .delayfeedback(0.5)

// Voice becomes urgent - pleading, insistent
let urgentVoice = x => x
  .sound("pulse")
  .gain(0.12)
  .attack(0.02)
  .decay(0.2)
  .sustain(0.7)
  .release(0.4)
  .lpf(2400)
  .lpq(3)
  .room(0.3)

setcps(72/60/4)

// Track 1 - Melody becomes DESCENDING LAMENT - falling, grieving
$: note("d5 c5 bb4 a4 g4 f4 eb4 d4 c4 bb3 a3 g3")
  .fast(1.5)
  .apply(stormOrgan)
  .pan(0.4)
  .juxBy(0.6, x => x.late(0.125).transpose(7).gain(0.08))

// Track 2 - Harmony becomes DIMINISHED - unsettled, questioning
$: note("<[g3,bb3,db4] [f3,ab3,c4] [eb3,gb3,bb3] [d3,f3,ab3]>")
  .slow(3)
  .apply(urgentVoice)
  .pan(0.6)
  .every(3, x => x.transpose(-12).gain(0.15))

// Track 3 - Heartbeat becomes GALLOPING - anxious, racing
$: note("[g2 g2 d2] [g2 g2 eb2] [g2 g2 c2] [g2 g2 d2]")
  .slow(2)
  .sound("triangle")
  .gain(0.22)
  .attack(0.01)
  .decay(0.15)
  .sustain(0.4)
  .release(0.2)
  .lpf(180)
  .shape(0.2)

// Track 4 - Percussion becomes THUNDER - rumbling, distant
$: s("[bd bd ~ bd] [~ bd bd ~] [bd ~ bd bd] [bd ~ ~ bd]")
  .slow(2)
  .gain(0.14)
  .room(0.8)
  .lpf(400)
  .shape(0.3)
  .pan(perlin.range(0.1, 0.9))

// NEW: Lightning strikes - piercing, electric
$: note("~ ~ ~ g6 ~ ~ ~ ~ ~ ~ eb6 ~ ~ ~ ~ ~")
  .slow(4)
  .sound("square")
  .gain(0.08)
  .attack(0.001)
  .decay(0.05)
  .sustain(0.02)
  .release(0.8)
  .fmi(8)
  .fmh(7)
  .fmdecay(0.02)
  .hpf(3000)
  .room(0.9)
  .delay(0.6)
  .delaytime(0.083)
  .delayfeedback(0.6)
  .pan(rand)

// Choir becomes WAILING - dissonant, raw
$: note("[g4,ab4,d5] ~ ~ [f4,gb4,c5] ~ ~ [eb4,e4,bb4] ~ ~")
  .slow(6)
  .sound("sawtooth")
  .gain(0.09)
  .attack(0.4)
  .decay(0.3)
  .sustain(0.9)
  .release(1.5)
  .lpf(1200)
  .lpq(5)
  .room(0.7)
  .pan(0.5)

// NEW: Wind howling - spectral, sweeping
$: note("g3 ab3 g3 f3 g3 ab3 bb3 ab3 g3 f3 eb3 f3")
  .fast(2)
  .sound("sine")
  .gain(0.06)
  .attack(0.3)
  .decay(0.5)
  .sustain(0.6)
  .release(0.8)
  .fmi(1)
  .fmh(0.5)
  .lpf(perlin.range(300, 900).slow(3))
  .pan(sine.range(0, 1).slow(2))
  .room(0.5)

// Bass becomes GROANING - tectonic, shifting
$: note("[g1 ab1] [~ g1] [f1 ~] [eb1 d1]")
  .slow(4)
  .sound("sawtooth")
  .gain(0.18)
  .attack(0.2)
  .decay(0.8)
  .sustain(0.8)
  .release(1.5)
  .lpf(90)
  .shape(0.25)
  .fmi(0.5)
  .fmh(0.25)

// NEW: Bells tolling - ominous, counting
$: note("g5 ~ ~ ~ d5 ~ ~ ~ g4 ~ ~ ~")
  .slow(8)
  .sound("triangle")
  .gain(0.11)
  .attack(0.001)
  .decay(1.5)
  .sustain(0.2)
  .release(3)
