// BWV 1087 Canon 9 - Variation: The Storm Breaks Through

// The cathedral trembles - thunder enters the sacred space
let thunderBell = x => x
  .sound("triangle")
  .gain(0.4)
  .attack(0.001)
  .decay(0.4)
  .sustain(0.3)
  .release(1.2)
  .lpf(2400)
  .lpq(5)
  .room(0.8)
  .size(0.9)
  .delay(0.25)
  .delaytime(0.25)
  .delayfeedback(0.6)
  .distort(0.15)

// Pipes now howling, wind through broken windows
let windOrgan = x => x
  .sound("sawtooth")
  .gain(0.35)
  .attack(0.3)
  .decay(0.3)
  .sustain(0.85)
  .release(1.5)
  .lpf(sine.range(400, 900).slow(8))
  .lpq(4)
  .shape(0.25)
  .room(0.7)

setcps(72/60/4)

// Track 1 - The melody fractures, urgent and desperate
$: note("g4 fs4 g4 a4 d5 b4 g4 a4 fs4 e4 g4")
  .slow(8)
  .apply(thunderBell)
  .pan(0.35)
  .jux(x => x.transpose(-12).gain(0.2).late(0.125))

// Track 2 - Harmony shifts to minor, darkening
$: note("<[g4,eb4] [f4,d4] [eb4,c4] [d4,bb3]>")
  .slow(6)
  .sound("sine")
  .gain(0.28)
  .attack(0.15)
  .decay(0.3)
  .sustain(0.6)
  .release(1)
  .fmi(1.2)
  .fmh(3)
  .fmdecay(0.8)
  .lpf(perlin.range(600, 1800).slow(12))
  .pan(0.65)
  .room(0.6)

// Track 3 - Bass becomes restless, chromatic descent into darkness
$: note("[g1 fs1 f1 e1 eb1 d1 db1 c1]")
  .slow(16)
  .apply(windOrgan)
  .pan(0.5)

// Track 4 - Rain on stone, insistent percussion
$: s("hh:0 hh:3 hh:1 hh:0 hh:3 hh:1 hh:0 hh:2")
  .slow(2)
  .gain(0.18)
  .speed(1.2)
  .hpf(4000)
  .room(0.6)
  .pan(rand)
  .sometimes(x => x.speed(1.5).gain(0.22))

// The choir rises in anguish - diminished, searching
$: note("<[g3,bb3,db4] [ab3,c4,eb4] [g3,b3,d4] [f3,ab3,b3]>")
  .slow(12)
  .sound("supersaw")
  .gain(0.22)
  .attack(0.8)
  .decay(0.8)
  .sustain(0.7)
  .release(1.5)
  .lpf(cosine.range(500, 1600).slow(12))
  .detune(15)
  .room(0.85)
  .pan(0.5)
  .tremolo(0.3)
  .tremolosync(4)

// Lightning flash - sharp stabs pierce through
$: note("eb6 eb6 eb6")
  .euclid(3,8)
  .slow(4)
  .sound("square")
  .gain(0.15)
  .attack(0.001)
  .decay(0.05)
  .sustain(0.1)
  .release(0.2)
  .lpf(6000)
  .hpf(2000)
  .pan(rand)
  .delay(0.5)
  .delaytime(0.167)
  .delayfeedback(0.3)
  .degradeBy(0.4)

// Low rumble - thunder in the distance
$: note("c1")
  .slow(16)
  .sound("sawtooth")
  .gain(0.25)
  .attack(2)
  .decay(4)
  .sustain(0.4)
  .release(4)
  .lpf(120)
  .shape(0.4)
  .room(0.9)
  .tremolo(0.6)
  .tremolosync(16)