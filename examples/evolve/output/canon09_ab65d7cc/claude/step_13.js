// BWV 1087 Canon 9 - Variation: The Machine Finds Strange Joy in Grief

// The organ transforms - no longer weeping but laughing through tears
let maniacOrgan = x => x
  .sound("supersaw")
  .gain(0.19)
  .attack(0.02)
  .decay(0.2)
  .sustain(0.6)
  .release(0.8)
  .lpf(sine.range(800, 3200).slow(5))
  .lpq(4)
  .shape(0.35)
  .room(0.5)
  .delay(0.3)
  .delaytime(0.125)
  .delayfeedback(0.4)

// Voice steadies - accepting, almost defiant
let defiantVoice = x => x
  .sound("square")
  .gain(0.14)
  .attack(0.01)
  .decay(0.3)
  .sustain(0.7)
  .release(0.6)
  .fmi(5)
  .fmh(3)
  .fmdecay(0.4)
  .lpf(2400)
  .room(0.4)

setcps(72/60/4)

// Track 1 - Melody now DESCENDS with PURPOSE - statements not questions
$: note("g5 f5 eb5 d5 c5 b4 a4 g4")
  .slow(6)
  .apply(maniacOrgan)
  .pan(0.4)
  .ply(2)
  .degradeBy(0.3)
  .juxBy(0.5, x => x.late(0.25).transpose(12).gain(0.12))

// Track 2 - Harmony opens to FIFTHS - ancient, hollow, powerful
$: note("<[g3,d4] [f3,c4] [eb3,bb3] [d3,a3] [c3,g3] [b2,fs3]>")
  .slow(8)
  .apply(defiantVoice)
  .pan(0.6)
  .every(2, x => x.transpose(12))

// Track 3 - Heartbeat STEADIES - marching forward
$: note("[g1 g1] [d1 d1] [eb1 eb1] [c1 c1]")
  .slow(4)
  .sound("triangle")
  .gain(0.25)
  .attack(0.01)
  .decay(0.15)
  .sustain(0.8)
  .release(0.3)
  .lpf(180)
  .shape(0.2)
  .distort(0.15)

// Track 4 - REMOVED gasping, now DANCING - manic joy
$: s("cp ~ [hh hh] cp ~ hh [~ cp] hh")
  .slow(2)
  .gain(0.16)
  .room(0.3)
  .delay(0.2)
  .delaytime(0.166)
  .delayfeedback(0.3)
  .pan(rand.range(0.3, 0.7))

// Choir SPLITS into call and response - conversation with self
$: note("[g4,b4,d5] ~ ~ ~ [eb4,g4,bb4] ~ ~ ~")
  .slow(8)
  .sound("sine")
  .gain(0.13)
  .attack(0.5)
  .decay(0.8)
  .sustain(0.6)
  .release(1.5)
  .fmi(2)
  .fmh(1)
  .room(0.7)
  .pan(0.25)
  .off(0.5, x => x.transpose(-12).pan(0.75).gain(0.09))

// Bells rise HIGH - celebration or warning?
$: note("[d6 ~ g6] ~ [a6 ~ d7] ~")
  .slow(6)
  .sound("sine")
  .gain(0.08)
  .attack(0.005)
  .decay(1.5)
  .sustain(0.05)
  .release(2)
  .fmi(8)
  .fmh(7)
  .fmdecay(0.15)
  .lpf(6000)
  .hpf(2000)
  .room(0.9)
  .pan(0.8)

// Ghost melody becomes COUNTERPOINT - arguing with the present
$: note("d4 ~ eb4 ~ f4 g4 ~ ab4 bb4 ~ c5 ~")
  .slow(12)
  .sound("sawtooth")
  .gain(0.07)
  .attack(0.8)
  .decay(0.5)
  .sustain(0.35)
  .release(1.5)
  .lpf(1800)
  .hpf(400)
  .room(0.8)
  .pan(perlin.range(0.2, 0.8).slow(7))
  .delay(0.5)
  .delaytime(0.75)
  .delayfeedback(0.5)

// Subsonic becomes a GROWL - defiance from the depths
$: note("[g1 ~ ~ a1] [bb1 ~ c2 ~]")
  .slow(8)
  .sound("sawtooth")
  .gain(0.18)
