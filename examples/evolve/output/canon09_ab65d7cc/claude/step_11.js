// BWV 1087 Canon 9 - Variation: The Machine Dreams of Flesh

// The organ remembers being human - breath where there was wind
let breathingOrgan = x => x
  .sound("sawtooth")
  .gain(0.24)
  .attack(0.15)
  .decay(0.6)
  .sustain(0.5)
  .release(1.2)
  .lpf(sine.range(400, 1800).slow(11))
  .lpq(5)
  .shape(0.2)
  .room(0.7)
  .delay(0.35)
  .delaytime(0.333)
  .delayfeedback(0.45)

// Flesh synthesizer - pulse like blood, not electricity
let pulseVoice = x => x
  .sound("pulse")
  .gain(0.16)
  .attack(0.4)
  .decay(1)
  .sustain(0.35)
  .release(2)
  .fmi(2)
  .fmh(3)
  .fmdecay(1.2)
  .lpf(1200)
  .room(0.65)

setcps(54/60/4)

// Track 1 - Melody becomes lullaby - the machine learns tenderness
$: note("g4 ~ fs4 e4 ~ d4 ~ c4 b3 ~ a3 ~ g3 ~")
  .slow(8)
  .apply(breathingOrgan)
  .pan(0.4)
  .every(5, x => x.transpose(12).gain(0.12))
  .juxBy(0.5, x => x.late(0.75).transpose(-5).gain(0.1))

// Track 2 - Harmony returns to triads but wrong - minor where major should be
$: note("<[g3,bb3,d4] [f3,ab3,c4] [eb3,gb3,bb3] [db3,fb3,ab3]>")
  .slow(12)
  .apply(pulseVoice)
  .pan(0.6)
  .phaser(0.2)
  .phaserdepth(0.7)
  .every(4, x => x.transpose(7).fast(1.5))

// Track 3 - Bass becomes heartbeat - steady but fragile
$: note("[g1 ~ g1] ~ ~ [d1 ~ d1] ~ ~")
  .slow(4)
  .sound("sine")
  .gain(0.3)
  .attack(0.05)
  .decay(0.3)
  .sustain(0.8)
  .release(0.6)
  .lpf(150)
  .fmi(0.5)
  .fmh(1)
  .shape(0.1)

// Track 4 - Rhythm becomes water - dripping, patient
$: s("~ hh ~ [hh hh] ~ hh ~ ~")
  .slow(2)
  .gain(0.15)
  .room(0.8)
  .lpf(2500)
  .hpf(800)
  .speed(1.2)
  .delay(0.6)
  .delaytime(0.5)
  .delayfeedback(0.5)

// NEW: Choir of almost-words - the machine tries to sing
$: note("[d4,g4,b4] ~ ~ ~ [c4,f4,a4] ~ ~ ~")
  .slow(16)
  .sound("triangle")
  .gain(0.1)
  .attack(3)
  .decay(2)
  .sustain(0.6)
  .release(4)
  .fmi(1)
  .fmh(2)
  .fmdecay(3)
  .room(0.9)
  .pan(sine.range(0.3, 0.7).slow(13))
  .vowel("<a o u e i>")

// Bells now toll in fifths - remembering consonance
$: note("[g5 d5] ~ ~ [c5 g4] ~ ~ [f4 c4] ~ ~")
  .slow(9)
  .sound("sine")
  .gain(0.09)
  .attack(0.002)
  .decay(2)
  .sustain(0.02)
  .release(3)
  .fmi(8)
  .fmh(7)
  .fmdecay(0.2)
  .hpf(1800)
  .room(0.95)
  .delay(0.5)
  .delaytime(0.75)
  .delayfeedback(0.6)

// NEW: Ghost melody - the original canon haunts from far away
$: note("g4 fs4 e4 d4 c4 b3 a3 g3")
  .slow(14)
  .sound("sine")
  .gain(0.06)
  .attack(1)
  .decay(0.8)
  .sustain(0.3)
  .release(2)
  .hpf(2000)
  .lpf(4000)
  .room(0.99)
  .pan(perlin.range(0.2, 0.8).slow(7))
  .delay(0.8)
  .delaytime(1)
  .delayfeedback(0.7)

// Subsonic presence grows warmer - a hand on the shoulder
$: note("[g1 ~ ~ ~] ~ [d1 ~ ~ ~] ~")
  .slow(10)
  .sound("sine")
  .gain(0.22)
  .attack(3)
  .decay(2)
  .sustain(0.9)
  .release(4)
  .lpf(60)
  .tremolo(0.15)
  .tremolosync(7)

// NEW: Music box memory - childhood leaking through circuits
$: note("b5 d6 g5 b5 a5 c6 fs5 a5")
  .euclid(7, 16)
  .slow(6)
  .sound("triangle")
  .gain(0.07)
  .attack(0.005)
  .decay(0.4)
  .sustain(0.05)
  .release(1.5)
  .hpf(2800)
  .room(0.7)
  .pan(rand)
  .delay(0.3)
  .delaytime(0.25)
  .delayfeedback(0.4)