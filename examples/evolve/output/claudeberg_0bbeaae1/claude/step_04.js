// Goldberg Variation - Gigue (A spirited, leaping dance)
// Compound time transforms the bass into bounding 6/8, feet barely touching ground

setcps(72/60/4)

// Ground bass - transformed into leaping intervals, octave displacements
$: note("[g2 g3 g2] [fs2 fs3 fs2] [e2 e3 e2] [eb2 eb3 eb2] [d2 d3 d2] [c2 c3 c2] [b1 b2 b1] [d2 d3 d2]")
  .fast(1.5)
  .sound("triangle")
  .gain(0.35)
  .attack(0.01)
  .decay(0.15)
  .sustain(0.3)
  .release(0.3)
  .lpf(1200)
  .room(0.25)

// First dancing voice - syncopated leaps and runs
$: note("[g4 b4 d5] [~ d5 b4] [g4 a4 b4] [c5 ~ a4] [fs4 a4 d5] [~ c5 a4] [fs4 g4 a4] [b4 ~ g4]")
  .fast(1.5)
  .sound("sawtooth")
  .lpf(saw.range(1600, 3200).slow(4))
  .lpq(4)
  .gain(0.28)
  .attack(0.005)
  .decay(0.12)
  .sustain(0.25)
  .release(0.2)
  .pan(0.35)
  .room(0.2)
  .delay(0.1)
  .delaytime(0.22)
  .delayfeedback(0.15)

// Second dancing voice - imitative canon at the fifth, one beat behind
$: note("[~ ~ d4] [g4 b4 d5] [~ d5 b4] [g4 a4 b4] [c5 ~ a4] [fs4 a4 d5] [~ c5 a4] [fs4 g4 a4]")
  .fast(1.5)
  .sound("sawtooth")
  .lpf(2400)
  .lpq(3)
  .gain(0.25)
  .attack(0.005)
  .decay(0.12)
  .sustain(0.25)
  .release(0.2)
  .pan(0.65)
  .room(0.2)

// Thirds in parallel motion - sweet rustic charm
$: note("[<b3 d4> <d4 fs4> <g4 b4>] [<a3 c4> <c4 e4> <fs4 a4>]")
  .fast(1.5)
  .sound("pulse")
  .lpf(1800)
  .gain(0.18)
  .attack(0.01)
  .decay(0.1)
  .sustain(0.2)
  .release(0.15)
  .pan(0.5)

// Percussive accents - heel strikes on strong beats
$: note("[g5 ~ ~] [~ ~ ~] [e5 ~ ~] [~ ~ ~] [d5 ~ ~] [~ ~ ~] [b4 ~ ~] [~ ~ ~]")
  .fast(1.5)
  .sound("sine")
  .gain(0.22)
  .attack(0.001)
  .decay(0.05)
  .sustain(0.05)
  .release(0.1)
  .pan(rand.range(0.4, 0.6))
  .room(0.15)

// Low drone pedal - bagpipe suggestion beneath the dance
$: note("<g2 g2 g2 d2>")
  .slow(4)
  .sound("sawtooth")
  .lpf(400)
  .lpq(2)
  .gain(0.12)
  .attack(0.1)
  .decay(0.3)
  .sustain(0.8)
  .release(0.5)

// Sparkling upper register - bells and ornaments
$: note("[~ g6 ~] [~ ~ d6] [~ e6 ~] [~ ~ c6] [~ d6 ~] [~ ~ a5] [~ b5 ~] [~ ~ d6]")
  .fast(1.5)
  .sound("sine")
  .gain(0.12)
  .attack(0.001)
  .decay(0.15)
  .sustain(0.1)
  .release(0.3)
  .delay(0.25)
  .delaytime(0.15)
  .delayfeedback(0.3)
  .room(0.3)
  .pan(sine.range(0.3, 0.7).slow(2))