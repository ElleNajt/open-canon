// Goldberg Variation - Gigue (A spirited, leaping dance)
// The bass becomes springy, the voices chase each other in joyful counterpoint

setcps(96/60/4)

// Bouncing bass - transformed into leaping intervals
$: note("[g2 ~ d3] [~ g3 ~] [fs2 ~ cs3] [~ fs3 ~] [e2 ~ b2] [~ e3 ~] [d2 ~ a2] [~ d3 ~]")
  .fast(1.5)
  .sound("triangle")
  .gain(0.45)
  .decay(0.15)
  .sustain(0.2)
  .release(0.1)
  .lpf(1200)
  .room(0.2)

// First voice of the gigue - leaping theme
$: note("[g5 b5 d6] [~ d6 b5] [g5 a5 fs5] [~ e5 ~] [e5 g5 b5] [~ b5 g5] [e5 fs5 d5] [~ c5 ~]")
  .fast(1.5)
  .sound("sawtooth")
  .lpf(2800)
  .lpq(2)
  .gain(0.32)
  .attack(0.005)
  .decay(0.12)
  .sustain(0.3)
  .release(0.15)
  .pan(0.35)
  .room(0.25)

// Second voice - chasing in canon
$: note("[~ ~ g4] [b4 d5 ~] [~ d5 b4] [g4 a4 fs4] [~ ~ e4] [g4 b4 ~] [~ b4 g4] [e4 fs4 d4]")
  .fast(1.5)
  .sound("sawtooth")
  .lpf(2200)
  .lpq(2)
  .gain(0.28)
  .attack(0.005)
  .decay(0.12)
  .sustain(0.3)
  .release(0.15)
  .pan(0.65)
  .room(0.25)

// Rhythmic punctuation - crisp harpsichord-like attacks
$: note("[g3,b3,d4] ~ ~ [g3,b3,d4] ~ [fs3,a3,d4] ~ ~")
  .fast(1.5)
  .sound("square")
  .lpf(1600)
  .gain(0.18)
  .attack(0.001)
  .decay(0.08)
  .sustain(0.05)
  .release(0.1)

// Sparkling high register - dancing ornaments
$: note("<[d6 ~ g6 ~ d6 ~] [b5 ~ e6 ~ b5 ~] [g5 ~ c6 ~ g5 ~] [fs5 ~ a5 ~ fs5 ~]>")
  .fast(1.5)
  .sound("sine")
  .gain(0.22)
  .attack(0.002)
  .decay(0.1)
  .sustain(0.15)
  .release(0.2)
  .pan(saw.range(0.25, 0.75).fast(2))
  .delay(0.2)
  .delaytime(0.166)
  .delayfeedback(0.3)
  .room(0.3)