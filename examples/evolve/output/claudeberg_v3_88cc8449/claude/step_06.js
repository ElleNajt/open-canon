// Goldberg Variations - Dissolving Cathedral
// Bold shift: moving to F minor, polymetric pulses, granular decay

setcps(66/60/4)

// Bass becomes arpeggiated minor 9th figure
$: note("[f1 ~ c2 ~] [ab1 ~ ~ eb2] [db2 ~ f1 ~] [~ c2 ab1 ~]")
  .slow(5)
  .sound("sawtooth")
  .lpf(280)
  .lpq(4)
  .gain(0.38)
  .attack(0.01)
  .decay(0.15)
  .sustain(0.4)
  .release(0.6)
  .room(0.5)
  .distort(0.2)

// Soprano replaced with descending whole tone cascade
$: note("[gb6 eb6 db6 bb5] [~ ab5 ~ f5] [eb5 ~ ~ ~] [~ ~ gb5 ~]")
  .slow(4)
  .sound("triangle")
  .lpf(4200)
  .gain(0.22)
  .attack(0.08)
  .release(2.2)
  .delay(0.55)
  .delaytime(0.25)
  .delayfeedback(0.55)
  .room(0.7)
  .pan(saw.range(0.15, 0.85).slow(11))

// New: stuttering rhythmic cell in 7
$: note("[f4 ~ ab4 ~ c5 ~ eb5]*7")
  .slow(8)
  .sound("pulse")
  .gain(0.14)
  .lpf(cosine.range(800, 3200).slow(6))
  .lpq(5)
  .attack(0.005)
  .decay(0.1)
  .sustain(0.2)
  .release(0.2)
  .pan(0.3)

// FM bells become detuned choir clusters
$: note("<f5 ab5 c6> <db5 f5 ab5> <eb5 gb5 bb5>")
  .slow(6)
  .sound("sine")
  .fm(1.5)
  .fmh(2.01)
  .gain(0.13)
  .attack(0.3)
  .decay(0.8)
  .sustain(0.3)
  .release(3)
  .room(0.85)
  .detune(rand.range(-15, 15))

// Sub drone shifts to minor second tension
$: note("<f0 gb0>")
  .slow(12)
  .sound("sine")
  .gain(0.22)
  .lpf(90)
  .attack(3)
  .release(5)

// New: pizzicato contrary motion figure
$: note("[c5 db5 eb5 f5] [ab4 gb4 f4 eb4]")
  .slow(3)
  .sound("triangle")
  .gain(0.18)
  .lpf(2600)
  .attack(0.002)
  .decay(0.08)
  .sustain(0)
  .release(0.3)
  .room(0.3)
  .pan(0.6)

// Chord stabs replaced with bitcrushed noise bursts
$: s("[~ hh:3 ~ ~] [~ ~ cp ~] [~ hh:3 hh:3 ~] [~ ~ ~ rim]")
  .slow(2)
  .gain(0.12)
  .crush(6)
  .lpf(2200)
  .room(0.35)
  .delay(0.25)
  .delaytime(0.375)
  .delayfeedback(0.4)

// New: ghostly high harmonic glide
$: note("[~ ~ c7 ~] [~ db7 ~ ~] [eb7 ~ ~ f7] [~ ~ ~ ~]")
  .slow(16)
  .sound("sine")
  .gain(0.08)
  .lpf(6000)
  .hpf(2000)
  .attack(0.5)
  .release(4)
  .room(0.9)
  .slide(0.3)