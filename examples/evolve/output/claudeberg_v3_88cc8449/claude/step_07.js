// Goldberg Variations - Collapsing into Lydian Light
// Bold shift: modulating to Db Lydian, fragmenting rhythms, adding metallic resonance

setcps(72/60/4)

// Bass transforms into wide lydian fourths, syncopated
$: note("[db1 ~ ~ gb1] [~ ab1 ~ ~] [~ ~ db2 ~] [ab1 ~ ~ ~]")
  .slow(6)
  .sound("sawtooth")
  .lpf(320)
  .lpq(5)
  .gain(0.35)
  .attack(0.02)
  .decay(0.2)
  .sustain(0.35)
  .release(0.8)
  .room(0.45)
  .distort(0.15)

// Soprano becomes pointillist lydian fragments
$: note("[~ g6 ~ ~] [ab6 ~ ~ bb6] [~ ~ c7 ~] [~ db7 ~ ~]")
  .slow(5)
  .sound("sine")
  .lpf(5500)
  .gain(0.19)
  .attack(0.15)
  .release(2.8)
  .delay(0.6)
  .delaytime(0.333)
  .delayfeedback(0.5)
  .room(0.75)
  .pan(tri.range(0.2, 0.8).slow(9))

// Stuttering cell now in 5, phrygian color
$: note("[db4 eb4 ~ fb4 ~]*5")
  .slow(6)
  .sound("square")
  .gain(0.12)
  .lpf(sine.range(600, 2800).slow(7))
  .lpq(6)
  .attack(0.003)
  .decay(0.08)
  .sustain(0.15)
  .release(0.15)
  .pan(0.7)

// Choir clusters become metallic FM stabs
$: note("<db4 g4 c5> <ab4 db5 g5>")
  .slow(4)
  .sound("sine")
  .fm(3.2)
  .fmh(1.414)
  .gain(0.11)
  .attack(0.01)
  .decay(0.4)
  .sustain(0.1)
  .release(1.5)
  .room(0.6)
  .hpf(400)

// Sub drone opens to tritone breath
$: note("<db0 g0>")
  .slow(14)
  .sound("triangle")
  .gain(0.2)
  .lpf(75)
  .attack(4)
  .release(6)

