$: note("<c4 eb4 g4 bb4 ~ ab4 f4 db4 e4 gb4 a4>/3")
  .sound("triangle")
  .lpf(sine.range(180, 3800).slow(13))
  .gain(sine.range(0.09, 0.28).slow(11))
  .room(0.88)

$: note("c2 ~ ~ g2 ~ <eb2 f2 ~ ab2 bb1>/2")
  .sound("sawtooth")
  .lpf(sine.range(35, 1800).slow(11))
  .gain(0.09)
  .slow(4)

$: s("hh ~ hh*2 ~ hh ~ hh*3 ~")
  .gain(sine.range(0.05, 0.12).slow(7))
  .pan(sine.range(0.15, 0.85).slow(13))
  .hpf(6200)
  .delay(0.32)

