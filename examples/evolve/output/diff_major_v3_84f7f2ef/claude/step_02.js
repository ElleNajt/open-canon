$: note("c2 ~ g2 <eb2 f2>")
  .sound("sawtooth")
  .lpf(sine.range(200, 900).slow(5))
  .gain(0.22)
  .slow(2)

$: s("hh*8")
  .gain(sine.range(0.06, 0.15).fast(3))
  .pan(sine.range(0.2, 0.8).fast(7))

