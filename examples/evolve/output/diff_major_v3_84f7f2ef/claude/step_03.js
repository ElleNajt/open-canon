$: note("<c4 ds4 g4 b4 c5 as4 fs4 eb4>")
  .sound("triangle")
  .lpf(sine.range(400, 2200).slow(13))
  .gain(0.33)
  .room(0.45)

$: note("c2 ~ g2 <eb2 f2 ab2 bb1>")
  .sound("sawtooth")
  .lpf(sine.range(180, 750).slow(7))
  .gain(0.2)
  .slow(2)

$: s("hh*8")
  .gain(sine.range(0.07, 0.18).fast(5))
  .pan(sine.range(0.15, 0.85).fast(9))
  .hpf(6000)

$: note("<e5 fs5 bb5 db6> <~ g5 ~ ab5>")
  .sound("sine")
  .delay(0.4)
  .gain(0.14)
  .slow(4)

$: note("~ <g4 ab4 bb4> ~ <eb5 d5 c5>")
  .sound("pulse")
  .lpf(sine.range(800, 1600).slow(11))
  .gain(0.11)

