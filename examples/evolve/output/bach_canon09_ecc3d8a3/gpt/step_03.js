// BWV 1087 Canon 9

// Baroque style voices
let upperVoice = x => x
  .sound("triangle")
  .gain(0.44)
  .attack(0.018)
  .decay(0.15)
  .sustain(0.23)
  .lpf(2450)
  .room(0.21)
  .delay(0.13)
  .delaytime(0.25)
  .delayfeedback(0.17)

let lowerVoice = x => x
  .sound("square")
  .gain(0.5)
  .attack(0.022)
  .decay(0.13)
  .sustain(0.19)
  .lpf(1620)
  .room(0.17)
  .delay(0.1)
  .delaytime(0.22)
  .delayfeedback(0.13)

let bassVoice = x => x
  .sound("sine")
  .gain(0.35)
  .attack(0.011)
  .decay(0.31)
  .sustain(0.2)
  .lpf(900)
  .room(0.28)
  .octave(-1)

setcps(119/60/4)

// Track 1 (occasionally airy and crisp)
$: note("g5 ~ b5 ~ d6 ~ g6 ~ d6 ~ b5 ~ g5 ~ d6 ~ d5 ~ gb5 ~ a5 ~ db5 ~ e5 ~ g5 ~ db6 ~!3 d6 ~ a5 ~ gb5 ~ d5 ~ g5 ~ b5 ~ d6 ~ g5 ~ e6 ~ c6 ~ a5 ~ c6 ~ gb5 ~ a5 ~ d6 c6 b5 a5 g5 ~ b5 ~ d6 ~ g6 ~ d6 ~ b5 ~ g5 ~ d6 ~ d5 ~ gb5 ~ a5 ~ db5 ~ e5 ~ g5 ~ db6 ~!3 d6 ~ a5 ~ gb5 ~ d5 ~ g5 ~ b5 ~ d6 ~ g5 ~ e6 ~ c6 ~ a5 ~ c6 ~ gb5 ~ a5 ~ d6 c6 b5 a5 g5 ~ b5 ~ d6 ~ g6 ~ d6 ~ b5 ~ g5 ~ d6 ~ d5 ~ gb5 ~ a5 ~ db5 ~ e5 ~ g5 ~ db6 ~!3 d6 ~ a5 ~ gb5 ~ d5 ~ g5 ~ b5 ~ d6 ~ g5 ~ e6 ~ c6 ~ a5 ~ c6 ~ gb5 ~ a5 ~ d6 c6 b5 a5 g5 ~ b5 ~ d6 ~ g6 ~ d6 ~ b5 ~ g5 ~ d6 ~ d5 ~ gb5 ~ a5 ~ db5 ~ e5 ~ g5 ~ db6 ~!3 d6 ~ a5 ~ gb5 ~ d5 ~ g5 ~ b5 ~ d6 ~ g5 ~ e6 ~ c6 ~ a5 ~ c6 ~ gb5 ~ a5 ~ d6 c6 b5 a5 g5 ~!7")
  .slow(264/8/4)
  .apply(upperVoice)
  .pan(0.18)
  .every(8, x => x.rev())
  .every(12, x => x.hpf(600).room(0.31))
  .sometimes(x => x.lpf(1200).gain(0.39))

// Track 2 (glassy, subtly detuned, more airy with lpf mods)
$: note("~!2 g5 ~ b5 ~ d6 ~ g6 ~ d6 ~ b5 ~ g5 ~ d6 ~ d5 ~ gb5 ~ a5 ~ db5 ~ e5 ~ g5 ~ db6 ~!3 d6 ~ a5 ~ gb5 ~ d5 ~ g5 ~ b5 ~ d6 ~ g5 ~ e6 ~ c6 ~ a5 ~ c6 ~ gb5 ~ a5 ~ d6 c6 b5 a5 g5 ~ b5 ~ d6 ~ g6 ~ d6 ~ b5 ~ g5 ~ d6 ~ d5 ~ gb5 ~ a5 ~ db5 ~ e5 ~ g5 ~ db6 ~!3 d6 ~ a5 ~ gb5 ~ d5 ~ g5 ~ b5 ~ d6 ~ g5 ~ e6 ~ c6 ~ a5 ~ c6 ~ gb5 ~ a5 ~ d6 c6 b5 a5 g5 ~ b5 ~ d6 ~ g6 ~ d6 ~ b5 ~ g5 ~ d6 ~ d5 ~ gb5 ~ a5 ~ db5 ~ e5 ~ g5 ~ db6 ~!3 d6 ~ a5 ~ gb5 ~ d5 ~ g5 ~ b5 ~ d6 ~ g5 ~ e6 ~ c6 ~ a5 ~ c6 ~ gb5 ~ a5 ~ d6 c6 b5 a5 g5 ~ b5 ~ d6 ~ g6 ~ d6 ~ b5 ~ g5 ~ d6 ~ d5 ~ gb5 ~ a5 ~ db5 ~ e5 ~ g5 ~ db6 ~!3 d6 ~ a5 ~ gb5 ~ d5 ~ g5 ~ b5 ~ d6 ~ g5 ~ e6 ~ c6 ~ a5 ~ c6 ~ gb5 ~ a5 ~ d6 c6 b5 a5 g5 ~!5")
  .slow(264/8/4)
  .apply(upperVoice)
  .detune(perlin.range(-7, 8).slow(8))
  .pan(0.35)
  .every(16, x => x.lpf(1400).room(0.24))
  .every(6, x => x.rev())
  .sometimes(x => x.lpf(900))

// Track 3 (Lower Counterpoint, sometimes palindromic)
$: note("~!8 g4 ~!7 gb4 ~!7 e4 ~!7 d4 ~!7 b3 ~!7 c4 ~!7 d4 ~!7 g3 ~!7 g4 ~!7 gb4 ~!7 e4 ~!7 d4 ~!7 b3 ~!7 c4 ~!7 d4 ~!7 g3 ~!7 g4 ~!7 gb4 ~!7 e4 ~!7 d4 ~!7 b3 ~!7 c4 ~!7 d4 ~!7 g3 ~!7 g4 ~!7 gb4 ~!7 e4 ~!7 d4 ~!7 b3 ~!7 c4 ~!7 d4 ~!7 g3 ~!7")
  .slow(264/8/4)
  .apply(lowerVoice)
  .pan(0.62)
  .every(24, x => x.distort(0.15).room(0.16))
  .sometimes(x => x.rev())
  .every(12, x => x.palindrome())

// Track 4 (Evolving bass, warming up)
$: note("g2 ~ gb2 ~ e2 ~ d2 ~ b1 ~ c2 ~ d2 ~ g1 ~ g2 ~ gb2 ~ e2 ~ d2 ~ b1 ~ c2 ~ d2 ~ g1")
  .slow(264/8/4)
  .apply(bassVoice)
  .pan(0.75)
  .every(32, x => x.gain(0.4).lpf(650).room(0.39))
  .sometimes(x => x.lpf(800).room(0.16))
  .every(16, x => x.lpf(1200).room(0.32))

// Track 5 (gentle brush hats, sprinkles of silence, lpf movement)
$: s("hh(3,8) ~ hh ~!2 hh ~ cp(2,8) ~ hh ~!3")
  .gain(0.14)
  .pan(0.51)
  .delay(0.06)
  .delaytime(0.19)
  .delayfeedback(0.07)
  .room(0.19)
  .slow(2)
  .every(8, x => x.degradeBy(0.33))
  .sometimes(x => x.lpf(9500))
  .every(6, x => x.lpf(sine.range(5000, 13000).slow(10)))
  .every(16, x => x.rev())