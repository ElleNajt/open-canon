// Goldberg Variation - Gigue Furioso (Fiery Dance)
// A wild 12/8 compound dance with perpetual motion and leaping intervals

setcps(72/60/4)

// Ground bass - compressed and driving
$: note("[g2 g2 g2] [fs2 fs2 fs2] [e2 e2 e2] [d2 d2 d2] [b1 b1 b1] [c2 c2 c2] [d2 d2 d2] [g1 ~ g2]")
  .slow(4)
  .sound("sawtooth")
  .gain(0.3)
  .lpf(600)
  .attack(0.005)
  .decay(0.1)
  .sustain(0.3)
  .release(0.2)
  .room(0.15)

// Perpetual motion treble - leaping sixths and octaves
$: note("[g4 e5 d5] [fs4 d5 c5] [e4 c5 b4] [d4 b4 a4] [b3 g4 fs4] [c4 a4 g4] [d4 b4 a4] [g4 d5 g5]")
  .slow(4)
  .sound("pulse")
  .gain(0.22)
  .lpf(3500)
  .attack(0.002)
  .decay(0.08)
  .sustain(0.2)
  .release(0.15)
  .pan(0.55)

// Hocketing response - answering leaps
$: note("[~ d5 b4] [~ c5 a4] [~ b4 g4] [~ a4 fs4] [~ fs4 d4] [~ g4 e4] [~ a4 fs4] [~ b4 ~]")
  .slow(4)
  .sound("pulse")
  .gain(0.18)
  .lpf(2800)
  .attack(0.002)
  .release(0.12)
  .pan(0.45)

// Stomping bass accents - downbeat emphasis
$: note("[g2 ~ ~] [fs2 ~ ~] [e2 ~ ~] [d2 ~ ~] [b1 ~ ~] [c2 ~ ~] [d2 ~ ~] [g1 ~ ~]")
  .slow(4)
  .sound("triangle")
  .gain(0.35)
  .lpf(400)
  .attack(0.001)
  .decay(0.2)
  .sustain(0)
  .release(0.3)
  .distort(0.15)

// Wild violin-like figuration - chromatic runs
$: note("[g4 gs4 a4] [a4 as4 b4] [b4 c5 cs5] [d5 ds5 e5] [e5 ds5 d5] [d5 cs5 c5] [c5 b4 as4] [a4 gs4 g4]")
  .slow(4)
  .fast(2)
  .every(2, x => x.rev())
  .sound("sawtooth")
  .gain(0.12)
  .lpf(sine.range(1800, 4000).slow(2))
  .lpq(3)
  .attack(0.001)
  .release(0.08)
  .pan(rand.range(0.3, 0.7))
  .room(0.1)

// Rhythmic drone fifths - bagpipe energy
$: note("<[g3 d4]>")
  .slow(4)
  .sound("square")
  .gain(0.08)
  .lpf(900)
  .attack(0.01)
  .sustain(0.8)
  .release(0.5)
  .tremolo(0.4)
  .tremolosync(6)