// Goldberg Variation - Gigue Infernale (Hellish Jig)
// A wild, virtuosic 12/8 gigue with driving energy and devilish chromaticism

setcps(138/60/4)

// Ground bass - propulsive, accented, with chromatic neighbor tones
$: note("[g2 g2 a2] [b2 b2 c3] [d3 d3 cs3] [d3 e3 fs3] [g3 fs3 f3] [e3 eb3 d3] [c3 b2 a2] [d3 d2 g2]")
  .slow(4)
  .sound("sawtooth")
  .gain(0.22)
  .lpf(600)
  .attack(0.005)
  .decay(0.1)
  .sustain(0.4)
  .release(0.2)
  .distort(0.15)

// Fiery melodic line - leaping, angular, relentless
$: note("[g5 d5 b4] [g4 b4 d5] [fs5 a5 d5] [cs5 e5 a5] [g5 e5 cs5] [a4 cs5 e5] [d5 a4 fs4] [g4 b4 d5]")
  .slow(4)
  .sound("square")
  .gain(0.16)
  .lpf(3500)
  .lpq(3)
  .attack(0.002)
  .decay(0.08)
  .sustain(0.3)
  .release(0.15)
  .pan(sine.range(0.3, 0.7).fast(2))

// Counter-melody - chasing, imitative, displaced
$: note("[~ g4 d4] [b3 ~ b4] [d5 ~ fs4] [a4 cs5 ~] [e5 ~ g4] [cs5 a4 ~] [fs4 ~ d4] [~ g4 b4]")
  .slow(4)
  .sound("square")
  .gain(0.13)
  .lpf(2800)
  .attack(0.003)
  .decay(0.1)
  .sustain(0.35)
  .release(0.2)
  .pan(0.35)

// Percussion - driving compound meter, accented
$: s("[bd ~ ~] [~ ~ bd] [~ bd ~] [bd ~ ~] [~ ~ bd] [~ bd ~] [bd ~ bd] [~ bd ~]")
  .slow(4)
  .gain(0.28)
  .lpf(200)
  .shape(0.2)

$: s("[~ hh hh] [hh ~ hh] [hh hh ~] [~ hh hh] [hh ~ hh] [hh hh ~] [hh hh hh] [hh hh hh]")
  .slow(4)
  .gain(0.18)
  .hpf(6000)
  .pan(rand.range(0.4, 0.6))

// Snarling inner voice - chromatic, biting
$: note("[d4 ds4 e4] [f4 fs4 g4] [a4 as4 b4] [c5 cs5 d5] [eb5 d5 cs5] [c5 b4 bb4] [a4 gs4 g4] [fs4 f4 e4]")
  .slow(4)
  .sound("pulse")
  .gain(0.11)
  .lpf(2000)
  .lpenv(4)
  .lpdecay(0.1)
  .attack(0.001)
  .decay(0.12)
  .sustain(0.2)
  .release(0.1)
  .pan(0.6)

// Stamping chords - rhythmic punctuation
$: note("<[g3 b3 d4] [g3 c4 e4] [fs3 a3 d4] [g3 b3 e4]>")
  .slow(4)
  .sound("sawtooth")
  .struct("[x ~ ~] [~ ~ x] [~ x ~] [x ~ x]")
  .gain(0.14)
  .lpf(1500)
  .attack(0.001)
  .decay(0.15)
  .sustain(0.1)
  .release(0.2)
  .room(0.15)

// Devilish trill - flickering ornament
$: note("[fs5 g5]*6")
  .slow(4)
  .sometimes(x => x.note("[a5 bb5]*6"))
  .sound("triangle")
  .gain(0.09)
  .lpf(4000)
  .attack(0.001)
  .decay(0.05)
  .sustain(0.4)
  .release(0.1)
  .pan(0.7)
  .degradeBy(0.4)

// Rumbling pedal point - ominous undertone
$: note("d2")
  .slow(4)
  .sound("sawtooth")
  .gain(0.12)
  .lpf(300)
  .attack(0.01)
  .sustain(0.8)
  .release(0.5)
  .room(0.2)