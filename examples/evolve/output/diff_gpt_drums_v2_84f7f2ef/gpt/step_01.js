setcps(140/60/4)

samples('shabda/speech:keep_listening,im_here,not_yet')

$: s("bd ~ sn ~ bd sn").fast(2)
  .every(4, p => p.palindrome())
  .sometimes(p => p.hurry(2))
  .swing(0.12)
  .lpf(8000)
  .compressor("-18:4:6:0.01:0.2")
  .gain(0.9)

$: s("hh").euclid(11,16).fast(2)
  .sometimes(p => p.degradeBy(0.25))
  .hpf(5000)
  .delay(0.18)
  .dt(0.125)
  .pan(sine.range(0.25,0.75).slow(4))
  .gain(0.22)

$: note("<c2 c2 c2 eb2> ~ <g1 g1 bb1> ~").s("pulse").slow(2)
  .every(6, p => p.transpose(12))
  .lpf(2000)
  .lpq(6)
  .drive(0.4)
  .release(0.2)
  .gain(0.35)

$: note("<c4 eb4 g4 bb4> <ab3 c4 eb4 g4> <bb3 d4 f4 ab4> <g3 bb3 d4 f4>").s("supersaw").slow(4)
  .lpf(sine.range(450, 3200).slow(8))
  .room(0.3)
  .size(0.6)
  .release(2)
  .gain(0.16)

$: s("keep_listening ~ im_here ~ not_yet ~").slow(2)
  .chop(8)
  .speed(rand.range(0.9, 1.1))
  .delay(0.35)
  .dt(0.25)
  .gain(0.12)