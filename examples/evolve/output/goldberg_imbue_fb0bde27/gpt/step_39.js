setcps(93/60/4)

$: stack(
  note("g3 gb3 e3 <d3 b2> c3 d3 g2").slow(3)
    .sound("triangle")
    .gain(0.37)
    .lpf(sine.range(890, 3500).slow(10))
    .lpq(7.2)
    .every(5, x => x.rev())
    .every(4, x => x.pan(sine.range(0.21,0.63).slow(8))),
  s("bd*3 <bd bd~>")
    .gain(0.19)
    .room(0.36)
    .cutoff(970)
    .every(6, x => x.echo(0.19,0.13,0.19))
)

$: s("hh cp <cp [cp~]> hh").slow(3)
