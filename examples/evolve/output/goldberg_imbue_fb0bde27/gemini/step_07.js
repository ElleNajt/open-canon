setcps(72/60/4)

$: note("[g3 fs3 e3 d3]/2 [b2 c3 g2 g2]")
  .slow(4)
  .sound("pulse")
  .gain(0.25)
  .lpf(perlin.range(200, 1500).slow(8))
  .lpq(4)
  .shape(perlin.range(0.1, 0.9).slow(4))
  .room(0.2)
  .crush(8)

$: note("<[d5 a5] fs5> <c5 g5 e5> <[b4 fs5] d5>")
  .fast(2)
  .sound("triangle")
  .gain(0.2)
  .slide(0.05)
  .delay(0.5)
  .pan(perlin.range(0.2, 0.8).slow(5))
  .room(0.3)
  .fm(sine.range(0.1, 4).slow(7))

$: s("[bd ~ bd] [~ bd bd ~]")
  .gain(0.8)
  .drive(0.6)
  .shape(0.2)
  .crush(7)
  .lpf(1200)
  .compressor()

$: s("<[hh hh oh]*2 hh*2> <[oh hh]*4>")
  .fast(2)
  .gain(0.3)
  .crush(8)
  .pan(perlin.range(0.2, 0.8).slow(6))
  .hpf(5000)
  .speed(perlin.range(1, 1.4).slow(3))
