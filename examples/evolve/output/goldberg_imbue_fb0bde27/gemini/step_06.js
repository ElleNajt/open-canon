$: note("[g3 fs3 e3 d3]/2 [b2 c3 ~ g2]")
  .slow(4)
  .sound("pulse")
  .gain(0.25)
  .lpf(perlin.range(200, 1500).slow(8))
  .lpq(5)
  .shape(perlin.range(0.1, 0.9).slow(4))
  .room(0.2)
