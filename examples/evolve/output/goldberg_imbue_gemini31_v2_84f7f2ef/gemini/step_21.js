setcps(160/60/4)

samples('shabda/speech/en-GB/f:recursion,simulate,algorithm,void')

$: note("e1(3,8) a0 c1*2 <d1 b0*3>")
  .s("supersaw")
  .lpf(saw.range(150, 2400).fast(4))
  .lpq(4)
  .shape(0.7)
  .decay(0.15)
  .gain(0.4)

$: note("e4*3 <g4 c5> a4*2 <d5 b4>")
  .s("sine")
  .fm(sine.range(1, 4).fast(8))
  .jux(x => x.hurry(2))
  .delay(0.5)
  .dt(0.25)
  .gain(0.35)

$: note("<e3 g3 b2 d3>")
  .s("pulse")
  .lpf(sine.range(300, 1200).slow(8))
  .crush(4)
  .room(0.8)
  .attack(0.8)
  .gain(0.3)

$: s("bd(5,8) <sn:2 ~> bd*3 <cp rim>")
  .jux(x => x.speed(2).pan(0.8))
  .shape(0.5)
  .room(0.4)
  .gain(0.55)

$: s("hh*8 <oh cb*2(3,8)>")
  .chop(4)
  .speed(rand.range(0.5, 3).fast(2))
  .hpf(5000)
  .delay(0.4)
  .gain(0.25)

$: s("<algorithm void(3,8)> simulate*2")
  .chop(16)
  .speed(sine.range(0.5, 1.2).fast(4))
  .jux(x => x.rev())
  .room(0.5)
  .gain(0.6)