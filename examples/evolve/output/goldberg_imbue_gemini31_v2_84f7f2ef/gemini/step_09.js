setcps(140/60/4)

samples('shabda/speech:calculate,simulate,mutate,transcend')

$: note("e2(5,8) [~ c2] <g1 d2> [~ <e2 c2>]")
  .sound("supersaw")
  .lpf(perlin.range(200, 2500).fast(8))
  .lpq(7)
  .crush(4)
  .shape(0.8)
  .gain(0.4)

$: note("e5 b5 <c6 g5> a5 fs5 c6 d5 <b5 e6>")
  .sound("square")
  .euclid(11, 16)
  .jux(x => x.rev().fast(2))
  .delay(0.6)
  .room(0.5)
  .gain(0.25)

$: note("e3,g3,b3,d4 c3,e3,g3,b3 a2,c3,e3,g3 d3,fs3,a3,c4")
  .sound("sine")
  .slow(4)
  .fm(sine.range(0.5, 4).fast(4))
  .attack(2)
  .room(0.6)
  .gain(0.5)

$: s("<bd(5,8) bd?*3> [~ sn] <bd(3,8) bd*2> [cp, rim*3]")
  .speed(rand.range(0.8, 1.3))
  .chop(4)
  .jux(x => x.fast(2))
  .delay(0.3)
  .gain(0.6)

$: s("hh*16")
  .pan(saw.range(0.1, 0.9).fast(8))
  .striate(16)
  .degradeBy(0.3)
  .room(0.4)
  .gain(0.3)

$: s("calculate simulate [~ mutate] <transcend*2 transcend?*4>")
  .chop(32)
  .speed(perlin.range(0.5, 1.5).fast(2))
  .jux(x => x.rev())
  .room(0.7)
  .gain(0.8)