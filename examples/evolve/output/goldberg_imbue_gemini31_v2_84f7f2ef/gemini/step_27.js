setcps(160/60/4)

samples('shabda/speech/fr-FR/f:algorithme,parfait,silence')

$: note("e1(5,8) <d1*2 c1> <g1(3,8) b0> a0")
  .s("pulse")
  .shape(saw.range(0.4, 0.9).fast(2))
  .lpf(sine.range(200, 3000).slow(4))
  .lpq(5)
  .crush(5)
  .gain(0.45)

$: note("e4(3,8) <g4 b4> [d5 c5] <a4*2 e5>")
  .s("piano")
  .jux(x => x.hurry(2))
  .room(0.8)
  .delay(0.5)
  .speed(rand.range(0.95, 1.05))
  .gain(0.4)

$: note("e5 g5 b5 a5 c6 d6 b5 g5")
  .slow(2)
  .s("sine")
  .fm(square.range(1, 6).fast(8))
  .bpf(1200)
  .bpq(4)
  .gain(0.3)

$: s("bd [~ sn:2] <bd(3,8) bd*3> [cp:1 rim*2]")
  .shape(0.85)
  .chop(4)
  .jux(x => x.hurry(2))
  .room(0.4)
  .gain(0.55)

$: s("hc*16")
  .degradeBy(0.4)
  .jux(x => x.fast(2))
  .hpf(8500)
  .delay(0.4)
  .gain(0.35)

$: s("algorithme(3,8) <silence*2 algorithme> parfait? ~")
  .striate(16)
  .speed(tri.range(0.7, 1.3).slow(4))
  .delay(0.6)
  .room(0.7)
  .gain(0.55)