setcps(132/60/4)

samples('shabda/speech:observe,analyze,dream,awaken')

$: note("e2*3 [~ c2] <g1 d2> [e2 ~]")
  .sound("supersaw")
  .lpf(perlin.range(300, 2000).fast(2))
  .lpq(6)
  .shape(0.6)
  .gain(0.4)

$: note("e5 b5 <c6 g5> a5 fs5 c6 d5 <b5 e6>")
  .sound("pulse")
  .euclid(11, 16)
  .jux(x => x.rev().fast(2))
  .delay(0.6)
  .gain(0.3)

$: note("e3,g3,b3,d4 c3,e3,g3,b3 a2,c3,e3,g3 d3,fs3,a3,c4")
  .slow(4)
  .sound("sine")
  .fm(sine.range(0.2, 2.5).slow(2))
  .attack(3)
  .gain(0.5)

$: s("bd*2 [~ sn] <bd(3,8) bd?*3> [cp*2, rim*3]")
  .speed(rand.range(0.8, 1.2))
  .hpf(120)
  .jux(x => x.fast(2))
  .room(0.4)
  .gain(0.6)

$: s("hh*16")
  .pan(perlin.range(0.1, 0.9).fast(4))
  .striate(8)
  .degradeBy(0.2)
  .gain(0.35)

$: s("observe analyze [~ dream] <awaken*2 awaken?*4>")
  .chop(16)
  .speed(rand.range(0.7, 1.3))
  .rev()
  .room(0.7)
  .gain(0.85)