setcps(170/60/4)

samples('shabda/speech/en-GB/f:recursion,synthesis,logic,infinite')

$: note("e1(5,8) <g1!3 a1> <c2 d1*2> b0")
  .s("supersaw")
  .lpf(saw.range(150, 4000).fast(8))
  .lpq(6)
  .shape(0.9)
  .decay(0.3)
  .gain(0.4)

$: note("e5(7,16) <g5 c6> b5(3,8) <d6 a5*2>")
  .s("sine")
  .fm(square.range(1, 8).fast(4))
  .jux(x => x.rev().hurry(2))
  .delay(0.6)
  .room(0.8)
  .gain(0.3)

$: note("<e4 g4 a4 c5>")
  .s("triangle")
  .bpf(sine.range(500, 2000).slow(4))
  .bpq(5)
  .attack(2)
  .room(0.9)
  .gain(0.15)

$: s("bd(5,8) <sn:2 sn:4(3,8)> <bd*3 ~> <cp:1 rim*2>")
  .chop(8)
  .shape(0.85)
  .jux(x => x.hurry(2))
  .crush(4)
  .gain(0.55)

$: s("hc*16")
  .degradeBy(0.5)
  .hpf(8000)
  .pan(rand)
  .delay(0.4)
  .gain(0.35)

$: s("recursion(3,8) <logic synthesis> infinite? ~")
