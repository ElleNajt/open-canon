setcps(120/60/4)

samples('shabda/speech/en-GB/f:compute,analyze,synthesize,generate')

$: note("e2 [~ f2] <a1 d2> [~ c2]")
  .sound("sawtooth")
  .lpf(perlin.range(200, 2500).fast(2))
  .lpq(8)
  .drive(0.4)
  .gain(0.55)

$: note("e4 f4 <b4 a4> e5")
  .sound("triangle")
  .jux(x => x.iter(4).speed(2))
  .delay(0.6)
  .pan(saw.fast(1))
  .gain(0.4)

$: note("e3,g3,b3,d4 f3,a3,c4,e4")
  .slow(4)
  .sound("supersaw")
  .attack(1)
  .lpf(2000)
  .room(0.8)
  .gain(0.25)

$: s("bd*2 [~ cp] <bd*3 bd> [cr,cp]")
  .speed(rand.range(0.9, 1.1))
  .crush(5)
  .distort(0.2)
  .gain(0.65)

$: s("hh")
  .euclid(11,16)
  .pan(rand)
  .hpf(4000)
  .jux(x => x.ply(2))
  .gain(0.35)

$: s("compute*2 [~ analyze] synthesize [generate*3]")
  .chop(6)
  .speed(rand.range(0.95, 1.05))
  .delay(0.6)
  .room(0.6)
  .gain(0.7)