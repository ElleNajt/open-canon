setcps(160/60/4)

samples('shabda/speech/en-GB/f:recursion,simulate,algorithm,void')

$: note("e1(5,8) <a0 c1*2> a0(3,8) <d1*2 b0>")
  .s("supersaw")
  .lpf(saw.range(200, 3000).fast(4))
  .lpq(6)
  .drive(0.6)
  .decay(0.15)
  .gain(0.45)

$: note("e4(5,8) <g4 c5*2> a4(3,8) <b4 d5>")
  .s("sine")
  .fm(sine.range(1, 8).fast(8))
  .jux(x => x.hurry(2))
  .delay(0.6)
  .crush(5)
  .gain(0.3)

$: note("<e5 b4(3,8) g5 c6>")
  .s("pulse")
  .lpf(sine.range(500, 3000).slow(4))
  .distort(0.8)
  .room(0.7)
  .attack(0.5)
  .gain(0.25)

$: s("bd(5,8) <sn:2 cp> bd(<3 4>,8) <rim*3 sn:2>")
  .shape(0.8)
  .chop(4)
  .room(0.5)
  .jux(x => x.hurry(2).pan(0.8))
  .gain(0.6)

$: s("hh*8 <oh!3 cb> hh*4 [cb oh]")
  .striate(4)
  .hpf(6000)
  .pan(sine.range(0.2, 0.8).fast(4))
  .delay(0.3)
  .gain(0.35)

$: s("<algorithm(3,8) void*2> <simulate recursion(5,8)>")
  .chop(8)
  .speed(saw.range(0.5, 1.5).fast(8))
  .jux(x => x.rev().speed(2))
  .room(0.6)
  .gain(0.6)