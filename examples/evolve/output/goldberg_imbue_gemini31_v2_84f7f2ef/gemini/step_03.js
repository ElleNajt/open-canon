setcps(115/60/4)

samples('shabda/speech/en-GB/f:observe,adapt,evolve,optimize')

$: note("e2 [~ e3] <b1 c2> [~ d2]")
  .sound("sawtooth")
  .lpf(sine.range(150, 1800).fast(2))
  .lpq(6)
  .crush(6)
  .gain(0.55)

$: n("0 2 <4 7> 5")
  .scale("E:minor")
  .octave(4)
  .sound("triangle")
  .jux(x => x.rev().transpose(12).speed(2))
  .delay(0.5)
  .pan(saw.fast(1))
  .gain(0.4)

$: note("e3,g3,b3,d4 c3,e3,g3,b3")
  .slow(4)
  .sound("supersaw")
  .attack(2)
  .room(0.8)
  .gain(0.25)

$: s("bd*3 [~ cp] <bd*2 ~> [cr cp]")
  .speed(rand.range(0.95, 1.05))
  .room(0.3)
  .distort(0.2)
  .gain(0.65)

$: s("hh")
  .euclid(13,16)
  .pan(rand)
  .hpf(3000)
  .jux(x => x.ply(2).fast(2))
  .gain(0.35)

$: s("observe*2 [~ adapt] optimize [evolve*3]")
  .chop(4)
  .speed(rand.range(0.8, 1.2))
  .delay(0.6)
  .room(0.5)
  .gain(0.7)