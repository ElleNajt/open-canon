setcps(128/60/4)

samples('shabda/speech:compute,learn,synthesize,dream,awake')

$: note("e2*2 [~ a1] <c2 g1> [d2 <e1 c2>]")
  .s("sawtooth")
  .lpf(sine.range(150, 2000).fast(2))
  .lpq(8)
  .crush(5)
  .gain(0.4)

$: note("e5 fs5 g5 b5 d6 e6")
  .s("pulse")
  .euclid(13, 16)
  .juxBy(0.5, x => x.add(12).rev())
  .delay(0.6)
  .gain(0.15)

$: note("<e3 c3 a2 d3>")
  .chord("<minor major minor major>")
  .s("supersaw")
  .slow(2)
  .lpf(perlin.range(300, 3000).slow(4))
  .room(0.7)
  .gain(0.25)

$: s("bd(5,8) [~ <sn cp>] <bd(3,8) bd(3,5)> [rim*2, hh*4]")
  .speed(rand.range(0.85, 1.15))
  .juxBy(0.5, x => x.fast(2))
  .shape(0.8)
  .gain(0.6)

$: s("cr(3,8) ~ <oh!3 ~> ~")
  .jux(x => x.fast(3).pan(rand))
  .delay(0.4)
  .room(0.6)
  .gain(0.35)

$: s("compute [~ learn] <synthesize dream> [awake? awake*2]")
  .chop(16)
  .speed(0.85)
  .jux(x => x.rev())
  .delay(0.5)
  .gain(0.75)