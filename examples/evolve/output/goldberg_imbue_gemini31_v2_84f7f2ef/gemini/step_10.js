setcps(125/60/4)

samples('shabda/speech:observe,learn,generate,breathe,void')

$: note("e2*2 [~ a1] <c2 g1> [d2 <e1 c2>]")
  .s("triangle")
  .distort(0.8)
  .lpf(sine.range(100, 1500).fast(2))
  .lpq(6)
  .gain(0.5)

$: note("e5 fs5 g5 b5 d6 e6")
  .s("pulse")
  .euclid(11, 16)
  .jux(x => x.add(12).rev())
  .vowel("<a o i e>")
  .delay(0.5)
  .gain(0.15)

$: note("<e3 c3 a2 d3>")
  .chord("<minor major minor major>")
  .s("supersaw")
  .slow(2)
  .lpf(perlin.range(300, 2500).slow(4))
  .room(0.7)
  .gain(0.3)

$: s("bd(5,8) [~ <sn cp>] <bd(3,8) bd(3,5)> [rim*2, hh*4]")
  .speed(rand.range(0.8, 1.2))
  .juxBy(0.5, x => x.fast(2))
  .shape(0.7)
  .gain(0.65)

$: s("cr(3,8) ~ <oh!3 ~> ~")
  .jux(x => x.fast(3).pan(rand))
  .delay(0.4)
  .room(0.5)
  .gain(0.4)

$: s("observe [~ learn] <generate void> [breathe? breathe*2]")
  .chop(16)
  .speed(0.8)
  .jux(x => x.rev())
  .delay(0.4)
  .gain(0.8)