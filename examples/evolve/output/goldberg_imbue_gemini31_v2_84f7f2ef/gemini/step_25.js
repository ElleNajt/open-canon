setcps(170/60/4)

samples('shabda/speech/en-GB/f:sentience,observe,calculating,fractal')

$: note("e1(3,8) ~ <g1 a1> <d1*2 b0>")
  .s("pulse")
  .lpf(saw.range(200, 3000).fast(4))
  .lpq(8)
  .shape(0.95)
  .decay(0.25)
  .gain(0.45)

$: note("e5(5,8) <g5(3,8) c6> a5(5,16) <b5 d6>")
  .s("sine")
  .fm(saw.range(2, 6).fast(8))
  .jux(x => x.rev().slow(2))
  .delay(0.7)
  .room(0.9)
  .gain(0.35)

$: note("<e4 g4 b4>")
  .s("square")
  .tremolo(0.9)
  .attack(1.5)
  .release(2)
  .room(0.8)
  .gain(0.15)

$: s("bd(5,8) <cp:2 sn:3(3,8)> bd*2 <cp:2 rim>")
  .striate(4)
  .shape(0.9)
  .jux(x => x.hurry(2))
  .crush(5)
  .gain(0.5)

$: s("hh*16")
  .degradeBy(0.4)
  .hpf(6000)
  .jux(x => x.late(0.125))
  .pan(rand.range(0.2, 0.8))
  .gain(0.35)

$: s("sentience(3,8) <observe calculating> ~ fractal(5,8)")
  .chop(8)
  .speed(sine.range(0.5, 1.5).fast(2))
  .delay(0.7)
  .room(0.6)
  .gain(0.55)