setcps(170/60/4)

samples('shabda/speech/en-GB/f:recursion,simulate,algorithm,void')

$: note("e1(5,8) ~ c1(3,8) <d1 b0>")
  .s("supersaw")
  .lpf(saw.range(300, 2000).fast(8))
  .lpq(8)
  .shape(0.7)
  .decay(0.2)
  .gain(0.5)

$: note("e4(7,16) <g4 c5> a4(5,16) <b4 d5>")
  .s("sine")
  .fm(sine.range(1, 4).fast(4))
  .crush(4)
  .jux(x => x.hurry(2))
  .delay(0.5)
  .gain(0.35)

$: note("<e5 b4 g5 c6>")
  .s("pulse")
  .vowel("e i a o")
  .distort(0.4)
  .room(0.8)
  .attack(0.5)
  .gain(0.25)

$: s("bd(5,8) sn:2 bd(3,8) <sn:2 rim>")
  .iter(4)
  .shape(0.8)
  .chop(4)
  .room(0.5)
  .gain(0.6)

$: s("hh*8 oh cb hh*4")
  .euclid(11, 16)
  .hpf(6000)
  .pan(saw.range(0.2, 0.8).fast(2))
  .delay(0.4)
  .gain(0.4)

$: s("<algorithm*2 void> <simulate recursion(5,8)>")
  .chop(8)
  .speed(sine.range(0.8, 1.2).fast(4))
  .jux(x => x.rev())
  .delay(0.5)
  .gain(0.55)