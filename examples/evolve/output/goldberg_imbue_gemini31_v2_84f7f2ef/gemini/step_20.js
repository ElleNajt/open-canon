setcps(160/60/4)

samples('shabda/speech/en-GB/f:recursion,simulate,algorithm,void')

$: note("e1(3,8) a0 c1*2 <d1 b0*3>")
  .s("square")
  .lpf(sine.range(100, 1800).fast(8))
  .lpq(8)
  .crush(3)
  .decay(0.2)
  .gain(0.45)

$: note("<e4 [e4 g4]> <a4*2 b4> c5(3,8) <d5 e5(5,8)>")
  .s("triangle")
  .fm(saw.range(2, 8).fast(4))
  .echo(2, 0.125, 0.4)
  .jux(x => x.rev())
  .room(0.4)
  .gain(0.3)

$: note("<e3 a2 c3 d3>")
  .chord("minor")
  .s("pulse")
  .lpf(saw.range(200, 2000).slow(4))
  .lpq(6)
  .pan(sine.range(0.1, 0.9).fast(3))
  .attack(0.5)
  .gain(0.2)

$: s("bd(5,16) [~ sn:2] bd*3 <rim(3,8) cp>")
  .jux(x => x.speed(2).pan(0.8))
  .shape(0.8)
  .room(0.2)
  .gain(0.5)

$: s("hh*16")
  .sometimesBy(0.3, x => x.ply(3))
  .degradeBy(0.4)
  .speed(sine.range(0.8, 1.5).fast(4))
  .hpf(4000)
  .gain(0.25)

$: s("recursion*2 <~ algorithm> simulate/2 void(3,8)")
  .striate(8)
  .speed(rand.range(0.4, 1.5))
  .delay(0.6)
  .dt(0.25)
  .gain(0.55)