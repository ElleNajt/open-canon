// Evolved BWV 1087 Canon 3 with pads & groove

let upperVoice = x => x
  .sound("supersaw")
  .gain(0.38)
  .attack(0.03)
  .decay(0.22)
  .sustain(0.3)
  .release(0.12)
  .lpf(2400)
  .hpf(140)
  .lpq(2.2)
  .delay(0.12)
  .delayfeedback(0.25)
  .room(0.22)
  .tremolo(0.08)
  .tremolosync(6)
  .compressor()

let lowerVoice = x => x
  .sound("square")
  .gain(0.45)
  .attack(0.025)
  .decay(0.2)
  .sustain(0.28)
  .release(0.11)
  .lpf(2000)
  .hpf(110)
  .lpq(1.8)
  .phaser(0.3)
  .room(0.2)
  .compressor()

let bassVoice = x => x
  .sound("piano")
  .gain(0.55)
  .attack(0.02)
  .decay(0.3)
  .sustain(0.4)
  .release(0.8)
  .lpf(1200)
  .hpf(50)
  .room(0.3)
  .pan(0.5)
  .compressor()

let padVoice = x => x
  .sound("sawtooth")
  .gain(0.2)
  .attack(0.8)
  .decay(0.5)
  .sustain(0.4)
  .release(1.2)
  .lpf(900)
  .lpq(1.2)
  .room(0.45)
  .pan(sine.range(0.4, 0.6))

setcps(128/60/4)

$: note("~!36 d5 ~!7 e5 ~!7 gb5 ~!7 g5 ~!7 b5 ~!7 a5 ~!7 g5 ~!7 d6 ~!7 d5 ~!7 e5 ~!7 gb5 ~!7 g5 ~!7 b5 ~!7 a5 ~!7 g5 ~!7 d6 ~!7")
  .slow(6)
  .every(4, x => x.rev())
  .apply(upperVoice)
  .pan(0.3)
  .juxBy(0.6, x => x.rev().pan(1))

$: note("~!12 g5 ~!7 gb5 ~!7 e5 ~!7 d5 ~!7 b4 ~!7 c5 ~!7 d5 ~!7 g4 ~!7 g5 ~!7 gb5 ~!7 e5 ~!7 d5 ~!7 b4 ~!7 c5 ~!7 d5 ~!7 g4")
  .slow(6)
  .apply(lowerVoice)
  .pan(0.7)
  .off(1/8, x => x.add(-12))

$: note("g2 bb2 d3 f3 c3 eb3 bb2").euclid(6,16)
  .slow(1.25)
  .apply(bassVoice)

$: chord("gmin:1.5 dmin bbmin fmin cmin gmin").voicing()
  .slow(4)
  .apply(padVoice)

$: s("bd ~ [sn hh*2] bd sn ~ hh*4").gain(0.25).room(0.15).pan(0.5)
  .sometimes(x => x.speed(0.8))