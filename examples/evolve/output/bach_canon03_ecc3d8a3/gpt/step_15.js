// Track 5 — Sparse harpsichord, slightly more shifted
$: note("<d4 g4 b4> ~ ~ <c4 e4 g4> ~ <fs4 b4 d5> ~ <a3 ds4 f4> ~")
  .slow(20/8/4)
  .apply(harpsiAccent)
  .degradeBy(0.15)
  .velocity(rand.range(0.15,0.27))
  .pan(rand.range(0.14,0.72))
  .lpf(sine.range(4200,5100).slow(15))
  .sustain(0.04)
  .every(12,x=>x.rev())

// Ghost sine: expanded intervals, shimmering delay
