// Baroque style voices refined for clarity and blend
let upperVoice = x => x
  .sound("triangle")
  .gain(0.36)
  .attack(0.013)
  .decay(0.12)
  .sustain(0.24)
  .lpf(2340)
  .pan(sine.range(0.09,0.52).slow(14))
  .room(sine.range(0.17,0.29).slow(9))

let lowerVoice = x => x
  .sound("square")
  .gain(0.14)
  .attack(0.014)
  .decay(0.15)
  .sustain(0.14)
  .lpf(940)
  .room(sine.range(0.18,0.24).slow(12))
  .pan(sine.range(0.57,0.88).slow(13))

let bassVoice = x => x
  .sound("sawtooth")
  .gain(0.12)
  .attack(0.015)
  .decay(0.13)
  .lpf(sine.range(410,721).slow(8))
  .release(0.21)
  .room(0.18)
  .octave(-1)
  .pan(sine.range(0.19,0.41).slow(12))

let harpsiAccent = x => x
  .sound("piano")
  .gain(0.10)
  .attack(0.002)
  .decay(0.07)
  .sustain(0.03)
  .lpf(sine.range(4100,5300).slow(14))
  .room(sine.range(0.13,0.23).slow(9))
  .pan(sine.range(0.18,0.83).slow(12))

setcps(116/60/4)

// Track 1 — upper canon: slightly more motion, more vowel variety
$: note("~!37 d5 ~!4 e5 ~!7 gb5 ~!7 g5 ~!4 b5 ~!8 a5 ~!3 g5 ~!7 d6 ~!6 d5 ~!7 e5 ~!5 gb5 ~!6 g5 ~!9 b5 ~!8 a5 ~!5 g5 ~!7 d6 ~!5 d5 ~!8 e5 ~!4 gb5 ~!8 g5 ~!7")
  .slow(187/8/5)
  .apply(upperVoice)
  .pan(sine.range(0.10,0.44).slow(14))
  .degradeBy(0.07)
  .lpf(sine.range(1670, 2450).slow(10))
  .room(sine.range(0.21, 0.33).slow(7))
  .every(4, x => x.vowel("a e o i u"))
  .every(8, x => x.palindrome())
  .rarely(x=>x.delay(0.23).delayfeedback(0.18))

// Track 2 — Lower canon: gentle bpf, subtle formant, rhythmic contrast
$: note("~!10 g5 ~!8 gb5 ~!5 e5 ~!7 d5 ~!5 b4 ~!9 c5 ~!4 d5 ~!6 g4 ~!6 g5 ~!6 gb5 ~!4 e5 ~!5 d5 ~!7 b4 ~!6 c5 ~!4 d5 ~!5 g4 ~!6 g5 ~!4 gb5 ~!6 e5 ~!5 d5 ~!7 b4 ~!4 c5 ~!6 d5 ~!5 g4 ~!8")
  .slow(187/8/5)
  .apply(lowerVoice)
  .pan(sine.range(0.65,0.85).slow(12))
  .room(sine.range(0.17,0.21).slow(11))
  .degradeBy(0.07)
  .swing(0.10)
  .every(3, x => x.bpf(sine.range(790,1480).slow(10)))
  .sometimesBy(0.18, x => x.vowel("o a u"))

// Track 3 — Bass: rare 7th/downward, lush lpf
$: note("~!16 d3 ~!7 g3 ~!6 b2 ~!8 a2 ~!5 g3 ~!5 d3 ~!9 g2 ~!7 b2 ~!7 a2 ~!7 e3 ~!6 d3 ~!7 g2 ~!7 b2 ~!7 e3 ~!7 d3 ~!7 g2 ~!4 b2 ~!6 a2 ~!7 e3 ~!9")
  .slow(187/8/5)
  .apply(bassVoice)
  .degradeBy(0.13)
  .shape(sine.range(0,0.12).slow(11))
  .every(23, x => x.transpose(-5))
  .rarely(x => x.lpf(280))
  .sometimesBy(0.16, x => x.sustain(0.33))

// Track 4 — Triangle accent: more syncopated
$: note("[g4] ~ [e4] [ds4] ~ [b4] ~ [a4] ~ [g4] ~")
