// BWV 1087 Canon 3 — Evolved REVISED 5 (Strudel evolved by AI, curated clarity/contrast)

// Baroque style voices
let upperVoice = x => x
  .sound("triangle")
  .gain(0.42)
  .attack(0.011)
  .decay(0.13)
  .sustain(0.19)
  .lpf(2170)
  .pan(sine.range(0.18,0.54).slow(12))
  .room(sine.range(0.13,0.27).slow(8))

let lowerVoice = x => x
  .sound("square")
  .gain(0.16)
  .attack(0.013)
  .decay(0.14)
  .sustain(0.12)
  .lpf(880)
  .room(sine.range(0.17,0.23).slow(10))
  .pan(sine.range(0.59,0.91).slow(13))

let bassVoice = x => x
  .sound("sawtooth")
  .gain(0.13)
  .attack(0.013)
  .decay(0.11)
  .lpf(sine.range(420,730).slow(9))
  .release(0.17)
  .room(0.16)
  .octave(-1)
  .pan(sine.range(0.27,0.49).slow(10))

let harpsiAccent = x => x
  .sound("piano")
  .gain(0.10)
  .attack(0.001)
  .decay(0.06)
  .sustain(0.04)
  .lpf(sine.range(3850,5400).slow(13))
  .room(sine.range(0.12,0.19).slow(9))
  .pan(sine.range(0.17,0.87).slow(14))

setcps(122/60/4)

// Track 1 — upper canon: simpler vowel motion, sparse delay
$: note("~!37 d5 ~!4 e5 ~!6 gb5 ~!7 g5 ~!4 b5 ~!8 a5 ~!3 g5 ~!7 d6 ~!6 d5 ~!7 e5 ~!5 gb5 ~!6 g5 ~!9 b5 ~!8 a5 ~!5 g5 ~!7 d6 ~!5 d5 ~!8 e5 ~!4 gb5 ~!8 g5 ~!10")
  .slow(189/8/5)
  .apply(upperVoice)
  .pan(sine.range(0.13,0.44).slow(14))
  .degradeBy(0.06)
  .lpf(sine.range(1670, 2350).slow(10))
  .room(sine.range(0.19, 0.29).slow(7))
  .every(5, x => x.vowel("a e o i"))
  .every(9, x => x.palindrome())
  .rarely(x=>x.delay(0.19).delayfeedback(0.14))

// Track 2 — Lower canon: clearer bpf sweep, more rest space
$: note("~!10 g5 ~!9 gb5 ~!5 e5 ~!8 d5 ~!5 b4 ~!9 c5 ~!4 d5 ~!7 g4 ~!6 g5 ~!6 gb5 ~!5 e5 ~!5 d5 ~!8 b4 ~!6 c5 ~!4 d5 ~!6 g4 ~!7 g5 ~!4 gb5 ~!7 e5 ~!5 d5 ~!8 b4 ~!4 c5 ~!7 d5 ~!5 g4 ~!8")
  .slow(189/8/5)
  .apply(lowerVoice)
  .pan(sine.range(0.6,0.83).slow(13))
  .room(sine.range(0.15,0.18).slow(10))
  .degradeBy(0.05)
  .swing(0.10)
  .every(2, x => x.bpf(sine.range(760,1390).slow(11)))
  .sometimesBy(0.17, x => x.vowel("o a"))

// Track 3 — Counterpoint bass: less detune, crisp lpf sweep, rare octave jumps
$: note("~!19 d3 ~!8 g3 ~!7 b2 ~!9 a2 ~!6 g3 ~!6 d3 ~!10 g2 ~!7 b2 ~!8 a2 ~!8 e3 ~!6 d3 ~!8 g2 ~!7 b2 ~!8 e3 ~!7 d3 ~!8 g2 ~!4 b2 ~!6 a2 ~!7 e3 ~!11")
  .slow(189/8/5)
  .apply(bassVoice)
  .degradeBy(0.12)
  .shape(sine.range(0,0.09).slow(10))
  .every(21, x => x.transpose(12))
  .rarely(x => x.lpf(230))
  .sometimesBy(0.22, x => x.sustain(0.29))

// Track 4 — Accent rhythm: single layer, more sync to groove, drive on offbeats
$: note("g4 ~ e4 ~ ds4 ~ b4 ~ a4 ~ g4 ~")
  .sound("triangle")
  .gain(0.091)
  .lpf(sine.range(890,1490).slow(8))
  .room(sine.range(0.13,0.21).slow(8))
  .pan(sine.range(0.14,0.40).slow(13))
  .release(0.18)
  .degradeBy(0.13)
  .every(9, x=>x.palindrome())
  .rarely(x=>x.hpf(670))
  .sometimesBy(0.42, x=>x.drive(0.11))

// Track 5 — Harpsichord accent: more sparse, more room for polyphony, hold modulation
$: note("<d4 g4 b4> ~ <c4 e4 g4> ~ <fs4 b4 d5> <a3 ds4 f4> ~")
  .slow(22/8/4)
  .apply(harpsiAccent)
  .degradeBy(0.12)
  .velocity(rand.range(0.15,0.27))
  .pan(rand.range(0.13,0.81))
  .lpf(sine.range(4000,5200).slow(13))
  .sustain(0.1)
  .every(8,x=>x.rev())

// Ghost sine: even longer, sparser, more evolving delay
$: note("g6 ~ b5 ~ d6 ~ e6 ~ gs6 ~")
    .sound("sine")
    .gain(0.035)
    .attack(0.22)
    .release(0.75)
    .room(0.72)
    .pan(sine.range(0.03,0.91).slow(15))
    .slow(98/8/4)
    .degradeBy(0.19)
    .tremolo(sine.range(0.10,0.25).slow(13))
    .every(23, x => x.vowel("u o"))
    .delay(0.26).delayfeedback(sine.range(0.17,0.36).slow(13))
    .rarely(x=>x.rev())

// Percussive metallic/noise: minimal, punchy clap, rare delays
$: s("cp:1 ~ ~ cp:1 ~ cp:1 ~")
    .gain(0.048)
    .pan(sine.range(0.72,0.96).slow(9))
    .room(sine.range(0.26,0.44).slow(10))
    .decay(0.13)
    .sometimes(x=>x.delay(0.14))
    .rarely(x=>x.crush(2))
    .velocity(rand.range(0.15,0.28))
    .slow(13/8/4)
    .degradeBy(sine.range(0.31,0.48).slow(9))