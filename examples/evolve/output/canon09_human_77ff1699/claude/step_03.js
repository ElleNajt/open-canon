// BWV 1087 Canon 9 - Cathedral at Dawn

// Upper voice emerges from darkness with growing intensity
let upperVoice = x => x
  .sound("triangle")
  .gain(sine.range(0.28, 0.52).slow(6))
  .attack(0.06)
  .decay(0.35)
  .sustain(0.25)
  .release(0.7)
  .lpf(sine.range(1400, 5000).slow(10))
  .lpq(3)
  .room(0.4)
  .delay(0.25)
  .delaytime(0.25)
  .delayfeedback(0.4)
  .phaser(0.3)
  .phaserdepth(0.4)

// Canon voice with subtle shimmer
let lowerVoice = x => x
  .sound("sine")
  .gain(0.35)
  .attack(0.08)
  .decay(0.3)
  .sustain(0.4)
  .release(0.6)
  .lpf(2200)
  .lpq(1.5)
  .room(0.45)
  .delay(0.3)
  .delaytime(0.375)
  .delayfeedback(0.35)
  .detune(sine.range(-8, 8).slow(7))

// Warm resonant bass with movement
let bassVoice = x => x
  .sound("sawtooth")
  .gain(0.28)
  .attack(0.12)
  .decay(0.5)
  .sustain(0.55)
  .release(1.0)
  .lpf(sine.range(200, 500).slow(14))
  .lpq(2)
  .room(0.35)

setcps(96/60/4)

// Track 1 - Ascending upper melody with breath
$: note("g5 ~ b5 ~ d6 ~ g6 ~ d6 ~ b5 ~ g5 ~ d6 ~ d5 ~ fs5 ~ a5 ~ cs5 ~ e5 ~ g5 ~ cs6 ~!3 d6 ~ a5 ~ fs5 ~ d5 ~ g5 ~ b5 ~ d6 ~ g5 ~ e6 ~ c6 ~ a5 ~ c6 ~ fs5 ~ a5 ~ d6 c6 b5 a5 g5 ~ b5 ~ d6 ~ g6 ~ d6 ~ b5 ~ g5 ~ d6 ~ d5 ~ fs5 ~ a5 ~ cs5 ~ e5 ~ g5 ~ cs6 ~!3 d6 ~ a5 ~ fs5 ~ d5 ~ g5 ~ b5 ~ d6 ~ g5 ~ e6 ~ c6 ~ a5 ~ c6 ~ fs5 ~ a5 ~ d6 c6 b5 a5 g5 ~!7")
  .slow(8)
  .apply(upperVoice)
  .pan(sine.range(0.15, 0.4).slow(8))
  .sometimes(x => x.add(12))

// Track 2 - Spectral canon follower
$: note("~!2 g5 ~ b5 ~ d6 ~ g6 ~ d6 ~ b5 ~ g5 ~ d6 ~ d5 ~ fs5 ~ a5 ~ cs5 ~ e5 ~ g5 ~ cs6 ~!3 d6 ~ a5 ~ fs5 ~ d5 ~ g5 ~ b5 ~ d6 ~ g5 ~ e6 ~ c6 ~ a5 ~ c6 ~ fs5 ~ a5 ~ d6 c6 b5 a5 g5 ~ b5 ~ d6 ~ g6 ~ d6 ~ b5 ~ g5 ~ d6 ~ d5 ~ fs5 ~ a5 ~ cs5 ~ e5 ~ g5 ~ cs6 ~!3 d6 ~ a5 ~ fs5 ~ d5 ~ g5 ~ b5 ~ d6 ~ g5 ~ e6 ~ c6 ~ a5 ~ c6 ~ fs5 ~ a5 ~ d6 c6 b5 a5 g5 ~!5")
  .slow(8)
  .apply(lowerVoice)
  .pan(sine.range(0.6, 0.85).slow(12))
  .octave(4)
  .juxBy(0.3, x => x.late(0.02).lpf(1400))

// Track 3 - Grounding bass with pulse
$: note("~!8 g3 ~!7 fs3 ~!7 e3 ~!7 d3 ~!7 b2 ~!7 c3 ~!7 d3 ~!7 g2 ~!7 g3 ~!7 fs3 ~!7 e3 ~!7 d3 ~!7 b2 ~!7 c3 ~!7 d3 ~!7 g2 ~!7")
  .slow(8)
  .apply(bassVoice)
  .pan(0.5)
  .off(0.5, x => x.add(7).gain(0.15).lpf(350))

// Track 4 - Crystalline bells cascading
$: note("g6 ~ b6 ~ d7 ~ ~ ~ b6 ~ g6 ~ d7 ~ ~ ~ g7 ~ ~ ~")
  .slow(4)
  .sound("sine")
  .gain(perlin.range(0.08, 0.22).slow(6))
  .attack(0.1)
  .decay(1.0)
  .sustain(0.08)
  .release(1.5)
  .lpf(4500)
  .room(0.55)
  .pan(sine.range(0.2, 0.8).slow(5))
  .delay(0.45)
  .delaytime(0.5)
  .delayfeedback(0.5)
  .rarely(x => x.add(12))

// Track 5 - Breathing drone with fifths
$: note("g2 d3 a2 e3")
  .slow(8)
  .sound("triangle")
  .gain(sine.range(0.12, 0.24).slow(10))
  .attack(0.4)
  .decay(0.6)
  .sustain(0.65)
  .release(1.5)
  .lpf(320)
  .lpq(1.5)
  .room(0.45)
  .pan(0.5)

// Track 6 - Ethereal choir with motion
$: note("<g4 b4 d5> <d4 fs4 a4> <e4 g4 b4> <d4 g4 b4> <c4 e4 g4> <d4 fs4 a4>")
  .slow(12)
  .sound("sine")
  .gain(0.15)
  .attack(0.6)
  .decay(0.4)
  .sustain(0.75)
  .release(2.0)
  .lpf(sine.range(900, 1600).slow(16))
  .room(0.55)
  .pan(sine.range(0.3, 0.7).slow(14))
  .delay(0.35)
  .delaytime(0.667)
  .delayfeedback(0.4)
  .juxBy(0.5, x => x.add(7).gain(0.08))

// Track 7 - Distant responding voice (new counterpoint)
