setcps(72/60/4)

$: note("g3 fs3 e3 d3 b2 c3 d3 g2")
  .slow(4)
  .sound("triangle")
  .gain(0.3)
  .lpf(sine.range(300, 1400).slow(12))
  .room(0.4)

$: note("g4 fs4 e4 d4 b3 c4 d4 g3")
  .slow(4)
  .sound("sine")
  .gain(0.18)
  .delay(0.5).delaytime(0.375).delayfeedback(0.52)
  .pan(sine.range(0.25, 0.75).slow(7))

$: note("<g5 b5 d5 fs5 g5 e5 a5 fs5>")
  .slow(4)
  .sound("sawtooth")
  .lpf(sine.range(500, 1600).slow(14)).lpq(5)
  .gain(0.14)
  .attack(0.4).release(1.8)

$: note("g3 fs3 e3 d3 b2 c3 d3 g2")
  .slow(4)
  .add(note("<0 12 7 5>"))
  .sound("square")
  .gain(0.09)
  .lpf(500)
  .jux(x => x.detune(7).gain(0.07))

$: s("bd:3 ~ [~ bd:3] sn:3 ~ bd:3 [~ rim] sn:3")
  .slow(4)
  .gain(0.2)
  .shape(0.35)
  .room(0.25)
  .sometimes(x => x.speed(0.9))

$: n("0 4 7 11 9 7 4 2")
  .scale("G:minor")
  .slow(2)
  .sound("sine")
  .gain(sine.range(0.06, 0.2).slow(10))
  .pan(sine.range(0.15, 0.85).slow(5))