setcps(72/60/4)

$: note("g3 fs3 e3 d3 b2 c3 d3 g2")
  .slow(4)
  .sound("triangle")
  .gain(0.25)
  .lpf(sine.range(400, 1800).slow(16))
  .room(0.5)
  .release(0.8)

$: note("g4 fs4 e4 d4 b3 c4 d4 g3")
  .slow(4)
  .sound("sine")
  .gain(0.16)
  .delay(0.45).delaytime(0.375).delayfeedback(0.48)
  .fmi(sine.range(0.1, 1.2).slow(12))

$: note("<[g5,b5] [d5,fs5] [e5,g5] [a5,c6]>")
  .slow(4)
  .sound("sawtooth")
  .lpf(sine.range(600, 2200).slow(14)).lpq(6)
  .gain(0.12)
  .attack(0.6).release(2.2)

$: note("g3 ~ e3 ~ b2 ~ d3 ~")
  .slow(4)
  .add(note("<0 7 12 5>"))
  .sound("square")
  .gain(0.08)
  .lpf(tri.range(300, 900).slow(10))
  .jux(x => x.detune(9).slow(2))

$: s("bd:3 ~ [~ bd:3] sn:3 ~ bd:3 [~ rim] sn:3")
  .slow(4)
  .gain(0.18)
  .shape(0.3)
  .room(0.2)
  .every(4, x => x.speed(0.85).gain(0.13))

$: n("<[0,7] [4,11] [7,14] [2,9]>")
  .scale("G:minor")
  .slow(4)
  .sound("sine")
  .gain(perlin.range(0.07, 0.18).slow(8))
  .pan(sine.range(0.1, 0.9).slow(6))