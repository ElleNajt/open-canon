setcps(72/60/4)

$: note("g3 fs3 e3 d3 b2 c3 d3 g2")
  .slow(4)
  .sound("triangle")
  .gain(0.22)
  .lpf(sine.range(350, 2400).slow(14))
  .release(1.2)
  .sometimes(x => x.add(note("12")).gain(0.11))

$: note("g4 fs4 e4 d4 b3 c4 d4 g3")
  .slow(4)
  .sound("sine")
  .gain(0.15)
  .fmi(perlin.range(0.2, 2.8).slow(8))
  .fmh(1.5)
  .delay(0.4).delaytime(0.375).delayfeedback(0.52)

$: note("<[g5,b5,d6] [d5,fs5,a5] [e5,g5,b5] [a5,c6,e6]>")
  .slow(4)
  .sound("sawtooth")
  .lpf(perlin.range(500, 3200).slow(10)).lpq(4)
  .gain(0.1)
  .attack(0.8).release(2.8)

$: note("g3 ~ e3 ~ b2 ~ d3 ~")
  .slow(4)
  .add(note("<0 7 12 5>"))
  .sound("square")
  .gain(0.09)
  .lpf(tri.range(280, 1100).slow(12))
  .jux(x => x.detune(11).late(0.125))

$: s("bd:3 ~ [~ bd:3] sn:3 ~ bd:3 [~ rim] sn:3")
  .slow(4)
  .gain(0.17)
  .shape(0.35)
  .room(0.15)
  .every(3, x => x.speed(0.8).crush(10))

$: n("<[0,7,11] [4,7,14] [7,11,16] [2,9,14]>")
  .scale("G:minor")
  .slow(4)
  .sound("sine")
  .gain(perlin.range(0.06, 0.16).slow(6))
  .pan(sine.range(0.15, 0.85).slow(5))