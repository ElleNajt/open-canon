setcps(72/60/4)

$: note("g3 fs3 e3 d3 b2 c3 d3 g2")
  .slow(4)
  .sound("triangle")
  .gain(0.19)
  .lpf(sine.range(600, 2800).slow(11))
  .release(2.5)
  .every(4, x => x.add(note("7")).rev())
  .every(7, x => x.palindrome())

$: note("g4 fs4 e4 d4 b3 c4 d4 g3")
  .slow(4)
  .sound("sine")
  .gain(0.14)
  .fmi(perlin.range(3, 18).slow(7))
  .fmh(1.5)
  .fmdecay(perlin.range(0.15, 1.8).slow(9))
  .off(0.125, x => x.add(note("12")).gain(0.07))

$: note("<[g5,b5,d6,fs6] [d5,fs5,a5,c6] [e5,g5,b5,d6] [a4,c5,e5,g5]>")
  .slow(4)
  .sound("sawtooth")
  .lpf(perlin.range(320, 5500).slow(10)).lpq(8)
  .gain(0.11)
  .attack(1.8).release(4.5)

$: note("g3 ~ e3 ~ b2 ~ d3 ~")
  .slow(4)
  .add(note("<0 7 12 5>"))
  .sound("square")
  .gain(0.1)
  .lpf(tri.range(220, 1900).slow(11))
  .jux(x => x.detune(40).late(0.1875))

$: s("[bd:3 ~ ~ sn:3] [~ bd:3 rim ~]")
  .slow(2)
  .gain(0.17)
  .shape(0.6)
  .room(0.25)
  .sometimes(x => x.speed(0.65).crush(7))

$: n("<[0,7,11,16] [4,7,14,19] [7,11,16,21] [2,9,14,19]>")
  .scale("G:minor")
  .slow(4)
  .sound("sine")
  .gain(perlin.range(0.08, 0.17).slow(5))
  .delay(0.5).delaytime(0.375).delayfeedback(0.6)