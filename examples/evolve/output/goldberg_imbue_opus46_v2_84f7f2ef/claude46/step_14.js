setcps(72/60/4)

$: note("g3 fs3 e3 d3 b2 c3 d3 g2")
  .slow(4)
  .sound("triangle")
  .gain(0.14)
  .lpf(sine.range(600, 3200).slow(11))
  .release(4)
  .every(4, x => x.add(note("7")).rev())
  .every(7, x => x.palindrome())

$: note("g4 fs4 e4 d4 b3 c4 d4 g3")
  .slow(4)
  .sound("sine")
  .gain(0.11)
  .fmi(perlin.range(4, 22).slow(7))
  .fmh(1.5)
  .fmdecay(perlin.range(0.15, 2.2).slow(9))
  .off(0.125, x => x.add(note("12")).gain(0.06))

$: note("<[g5,b5,d6] [d5,fs5,c6] [e5,b5,d6] [a4,e5,g5]>")
  .slow(4)
  .sound("sawtooth")
  .lpf(perlin.range(280, 5000).slow(10)).lpq(8)
  .gain(0.1)
  .attack(3.5)

$: note("g2 ~ ~ b2 ~ ~ d3 ~ ~ e3 ~ ~ fs3 ~ g3 ~")
  .slow(8)
  .add(note("<0 5 -5 7>"))
  .sound("pulse")
  .gain(0.09)
  .lpf(tri.range(180, 2200).slow(13))
  .jux(x => x.detune(50).late(0.25))

$: s("[bd:3 ~ ~ sn:3] [~ bd:3 rim ~]")
  .slow(2)
  .gain(0.12)
  .shape(0.55)
  .room(0.4)
  .sometimes(x => x.speed(0.65).crush(6))

$: n("<[0,7,16] [4,14,19] [7,16,21] [2,9,14]>")
  .scale("G:minor")
  .slow(4)
  .sound("sine")
  .gain(perlin.range(0.06, 0.13).slow(5))
  .delay(0.65).delaytime(0.375).delayfeedback(0.55)