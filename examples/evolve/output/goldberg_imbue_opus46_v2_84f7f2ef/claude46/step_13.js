setcps(72/60/4)

$: note("g3 fs3 e3 d3 b2 c3 d3 g2")
  .slow(4)
  .sound("triangle")
  .gain(0.15)
  .lpf(sine.range(500, 2800).slow(11))
  .release(5)
  .every(4, x => x.add(note("7")).rev())
  .every(7, x => x.palindrome())

$: note("g4 fs4 e4 d4 b3 c4 d4 g3")
  .slow(4)
  .sound("sine")
  .gain(0.12)
  .fmi(perlin.range(3, 18).slow(7))
  .fmh(1.5)
  .fmdecay(perlin.range(0.2, 1.8).slow(9))
  .off(0.125, x => x.add(note("12")).gain(0.07))

$: note("<[g5,b5,d6] [d5,fs5,c6] [e5,b5,d6] [a4,e5,g5]>")
  .slow(4)
  .sound("sawtooth")
  .lpf(perlin.range(320, 4200).slow(10)).lpq(6)
  .gain(0.11)
  .attack(3.5).release(8)

$: note("g2 ~ ~ b2 ~ ~ d3 ~ ~ e3 ~ ~ fs3 ~ g3 ~")
  .slow(8)
  .add(note("<0 5 -5 7>"))
  .sound("pulse")
  .gain(0.1)
  .lpf(tri.range(220, 1800).slow(13))
  .jux(x => x.detune(40).late(0.25))

$: s("[bd:3 ~ ~ sn:3] [~ bd:3 rim ~]")
  .slow(2)
  .gain(0.13)
  .shape(0.5)
  .room(0.35)
  .sometimes(x => x.speed(0.7).crush(7))

$: n("<[0,7,16] [4,14,19] [7,16,21] [2,9,14]>")
  .scale("G:minor")
  .slow(4)
  .sound("sine")
  .gain(perlin.range(0.06, 0.14).slow(5))
  .delay(0.6).delaytime(0.375).delayfeedback(0.5)