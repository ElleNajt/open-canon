setcps(72/60/4)

$: note("g3 fs3 e3 d3 b2 c3 d3 g2")
  .slow(4)
  .sound("triangle")
  .gain(0.18)
  .lpf(sine.range(700, 3200).slow(13))
  .release(2.2)
  .every(4, x => x.add(note("7")).rev())
  .every(7, x => x.palindrome())

$: note("g4 fs4 e4 d4 b3 c4 d4 g3")
  .slow(4)
  .sound("sine")
  .gain(0.13)
  .fmi(perlin.range(2, 12).slow(7))
  .fmh(1.5)
  .fmdecay(perlin.range(0.3, 2.2).slow(9))
  .off(0.125, x => x.add(note("12")).gain(0.06))

$: note("<[g5,b5,d6,fs6] [d5,fs5,a5,c6] [e5,g5,b5,d6] [a4,c5,e5,g5]>")
  .slow(4)
  .sound("sawtooth")
  .lpf(perlin.range(380, 4200).slow(10)).lpq(7)
  .gain(0.1)
  .attack(2.0).release(5)

$: note("g3 ~ e3 ~ b2 ~ d3 ~")
  .slow(4)
  .add(note("<0 7 12 5>"))
  .sound("square")
  .gain(0.09)
  .lpf(tri.range(280, 1600).slow(11))
  .jux(x => x.detune(30).late(0.1875))

$: s("[bd:3 ~ ~ sn:3] [~ bd:3 rim ~]")
  .slow(2)
  .gain(0.16)
  .shape(0.55)
  .room(0.22)
  .sometimes(x => x.speed(0.7).crush(8))

$: n("<[0,7,11,16] [4,7,14,19] [7,11,16,21] [2,9,14,19]>")
  .scale("G:minor")
  .slow(4)
  .sound("sine")
  .gain(perlin.range(0.07, 0.16).slow(5))
  .delay(0.45).delaytime(0.375).delayfeedback(0.55)