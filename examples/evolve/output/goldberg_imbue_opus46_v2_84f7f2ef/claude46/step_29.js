setcps(72/60/4)

$: note("g3 fs3 e3 d3 b2 c3 d3 g2")
  .slow(4)
  .sound("triangle")
  .gain(0.13)
  .lpf(sine.range(500, 2800).slow(11))
  .release(3.5)
  .every(4, x => x.add(note("7")).rev())
  .off(0.5, x => x.add(note("<0 12 -12 5>")).gain(0.08))

$: note("g4 fs4 e4 d4 b3 c4 d4 g3")
  .slow(4)
  .sound("sine")
  .gain(0.1)
  .fmi(perlin.range(5, 18).slow(9))
  .fmh(perlin.range(1, 3).slow(13))
  .fmdecay(perlin.range(0.1, 0.7).slow(7))
  .pan(sine.range(0.15, 0.85).slow(11))

$: note("<[g5,b5,d6] [d5,fs5,c6] [e5,b5,d6] [a4,e5,g5]>")
  .slow(4)
  .sound("sawtooth")
  .lpf(perlin.range(350, 1900).slow(10)).lpq(7)
  .gain(0.08)
  .attack(2.5)
  .sometimes(x => x.add(note("-12")).vowel("<a e o u i>"))

$: note("g2 ~ ~ b2 ~ ~ d3 ~ ~ e3 ~ ~ fs3 ~ g3 ~")
  .slow(8)
  .add(note("<0 5 -5 7>"))
  .sound("pulse")
  .gain(0.1)
  .lpf(tri.range(400, 1800).slow(14))
  .jux(x => x.detune(25).late(0.25))

$: s("[~ bd:3 ~ sn:3] [bd:3 ~ rim ~]")
  .slow(2)
  .gain(0.12)
  .shape(0.5)
  .room(0.35)
  .sometimes(x => x.speed(perlin.range(0.75, 1.15)))

$: n("<[0,7,16] [4,14,19] [7,16,21] [2,9,14]>")
  .scale("G:minor")
  .slow(4)
  .sound("sine")
  .gain(perlin.range(0.06, 0.11).slow(7))
  .delay(0.8).delaytime(perlin.range(0.18, 0.5).slow(11)).delayfeedback(0.6)