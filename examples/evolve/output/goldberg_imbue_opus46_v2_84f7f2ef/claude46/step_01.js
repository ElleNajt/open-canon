setcps(72/60/4)

$: note("g3 fs3 e3 d3 b2 c3 d3 g2")
  .slow(4)
  .sound("triangle")
  .gain(0.35)
  .lpf(sine.range(400, 1200).slow(16))

$: note("g4 fs4 e4 d4 b3 c4 d4 g3")
  .slow(4)
  .sound("sine")
  .gain(0.2)
  .delay(0.4).delaytime(0.375).delayfeedback(0.45)

$: note("<g5 b5 d5 fs5 g5 e5 a5 fs5>")
  .slow(4)
  .sound("sawtooth")
  .lpf(800).lpq(4)
  .gain(0.15)
  .attack(0.3).release(1.2)

$: note("g3 fs3 e3 d3 b2 c3 d3 g2")
  .slow(4)
  .add(note("<0 12 7 5>"))
  .sound("square")
  .gain(0.08)
  .lpf(600)

$: s("bd:3 ~ ~ sn:3 ~ bd:3 ~ sn:3")
  .slow(4)
  .gain(0.18)
  .shape(0.3)
  .room(0.3)

$: n("0 2 4 7 11 9 7 4")
  .scale("G:minor")
  .slow(2)
  .sound("sine")
  .gain(sine.range(0.05, 0.18).slow(8))
  .pan(sine.range(0.2, 0.8).slow(6))