setcps(0.4)

$: s("bd:3 [~ bd:1] sn:4 [bd:0 ~ bd:3]")
.gain(.88)
.shape(.25)
.room(.3)
.lpf(sine.range(800, 3000).slow(12))

$: s("~ [cp:3 ~] ~ cp:1")
.gain(.35)
.delay(.4)
.dt(.333)
.dfb(.45)
.pan(sine.range(.2, .8).slow(7))

$: note("<[c2 ~ eb2 ~] [f2 ~ g2 ab2] [c2 bb1 ~ ab1] [g1 ~ ~ eb2]>")
.sound("sawtooth")
.lpf(600)
.decay(.18)
.sustain(0)
.gain(.55)

$: note("[c4 eb4 g4 bb4]/2")
.sound("triangle")
.attack(.05)
.release(1.2)
.gain(.22)
.pan(cosine.range(.3, .7).slow(5))
.room(.5)

$: s("[hh:2 hh:0 [hh:3 hh:1] hh:2]*2")
.gain(".5 .35 .6 .3 .45 .35 .55 .4")
.hpf(6000)
.shape(.15)
.pan(rand.range(.25, .75))
.sometimes(x => x.speed(1.5))

$: note("<eb5 d5 c5 bb4>")
.sound("sine")
.gain(.15)
.fmi(sine.range(1, 6).slow(16))
.fmh(3)
.release(1.8)
.delay(.35)
.dt(.5)