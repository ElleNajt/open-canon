setcps(0.48)

$: s("bd:3 [~ bd:1] sn:4 [bd:0 ~ bd:3]")
.gain(".92 .7 .95 .78")
.shape(.35)
.lpf(sine.range(500, 3200).slow(14))
.room(.3)
.orbit(0)

$: s("~ [cp:3 ~] ~ cp:1")
.gain(.3)
.delay(.55)
.dt("<.333 .25 .166 .333>")
.dfb(.55)

$: note("<[c2 ~ eb2 ~] [f2 ~ g2 ab2] [bb1 ~ ab1 ~] [g1 ~ f1 ~]>")
.sound("sawtooth")
.lpf(saw.range(350, 1400).slow(11))
.decay(.18)
.sustain(0)
.gain(.55)

$: note("<[c4 eb4 g4 bb4] [ab3 c4 eb4 g4] [f3 ab3 c4 eb4] [g3 bb3 d4 f4]>/2")
.sound("triangle")
.attack(.12)
.release(2.2)
.gain(.18)
.juxBy(.6, x => x.note("<[eb4 g4 bb4 d5] [c4 eb4 g4 bb4] [ab3 c4 eb4 g4] [bb3 d4 f4 ab4]>/2"))

$: s("[hh:2 hh:0 [hh:3 hh:1] hh:2]*2")
.gain(".52 .28 .6 .25 .45 .3 .55 .35")
.hpf(6000)
.pan(rand.range(.15, .85))
.delay(.12)
.sometimes(x => x.speed("1.6 0.75"))

$: note("<eb5 [d5 ~] [~ c5] [bb4 c5]>")
.sound("sine")
.gain(.12)
.fmi(sine.range(1, 12).slow(11))
.fmh("<3 5 7 2>")
