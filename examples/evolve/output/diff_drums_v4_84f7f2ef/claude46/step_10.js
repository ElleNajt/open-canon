setcps(0.51)

$: s("bd:3 [~ bd:1] sn:4 [bd:0 ~ bd:3]")
.gain(".93 .46 .97 .55")
.shape(.62)
.lpf(sine.range(180, 5200).slow(11))
.room(.48)

$: s("~ [cp:3 ~] ~ cp:1")
.gain(.21)
.delay(.88)
.dt("<.333 .166 .25 .125>")
.dfb(.78)

$: note("<[c2 ~ eb2 ~] [f2 ~ g2 ab2] [bb1 ~ ab1 ~] [g1 ~ f1 eb1]>")
.sound("sawtooth")
.lpf(saw.range(90, 3800).slow(11))
.decay(sine.range(.02, .28).slow(9))
.sustain(.15)

$: note("<[c4 eb4 g4 bb4] [ab3 c4 eb4 g4] [f3 ab3 c4 eb4] [bb3 d4 f4 ab4]>/2")
.sound("triangle")
.attack(.7)
.release(8.4)
.gain(sine.range(.07, .19).slow(14))
.juxBy(.65, x => x.note("<[eb4 g4 bb4 d5] [c4 eb4 g4 bb4] [ab3 c4 eb4 g4] [d4 f4 ab4 c5]>/2"))

$: s("[hh:2 hh:0 [hh:3 hh:1] hh:2]*2")
