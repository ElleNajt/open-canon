setcps(0.48)

$: s("bd:3 [~ bd:1] sn:4 [bd:0 ~ bd:3]")
.gain(".96 .62 .99 .68")
.shape(.48)
.lpf(sine.range(320, 3200).slow(14))
.room(.42)

$: s("~ [cp:3 ~] ~ cp:1")
.gain(.24)
.delay(.7)
.dt("<.333 .166 .25 .5>")
.dfb(.68)

$: note("<[c2 ~ eb2 ~] [f2 ~ g2 ab2] [bb1 ~ ab1 ~] [g1 ~ f1 eb1]>")
.sound("sawtooth")
.lpf(saw.range(220, 2200).slow(11))
.sustain(0)
.decay(sine.range(.08, .32).slow(7))

$: note("<[c4 eb4 g4 bb4] [ab3 c4 eb4 g4] [f3 ab3 c4 eb4] [g3 bb3 d4 f4]>/2")
.sound("triangle")
.attack(.2)
.release(3.6)
.gain(.14)
.juxBy(.7, x => x.note("<[eb4 g4 bb4 d5] [c4 eb4 g4 bb4] [ab3 c4 eb4 g4] [bb3 d4 f4 ab4]>/2"))

$: s("[hh:2 hh:0 [hh:3 hh:1] hh:2]*2")
.gain(".44 .22 .54 .18 .38 .24 .48 .26")
