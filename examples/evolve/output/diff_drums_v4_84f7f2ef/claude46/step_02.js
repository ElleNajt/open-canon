setcps(0.45)

$: s("bd:3 [~ bd:1] sn:4 [bd:0 ~ bd:3]")
.gain(".88 .75 .9 .82")
.shape(.3)
.lpf(sine.range(600, 2800).slow(16))
.sometimes(x => x.room(.45))
.orbit(0)

$: s("~ [cp:3 ~] ~ cp:1")
.gain(.33)
.delay(.5)
.dt("<.333 .25 .333 .166>")
.dfb(.5)
.pan(sine.range(.15, .85).slow(7))

$: note("<[c2 ~ eb2 ~] [f2 ~ g2 ab2] [c2 bb1 ~ ab1] [g1 ~ f1 eb2]>")
.sound("sawtooth")
.lpf(saw.range(400, 1100).slow(8))
.decay(.22)
.sustain(0)
.gain(.58)

$: note("<[c4 eb4 g4 bb4] [ab3 c4 eb4 g4] [f3 ab3 c4 eb4] [g3 bb3 d4 f4]>/2")
.sound("triangle")
.attack(.08)
.release(1.6)
.gain(.2)
.room(.55)

$: s("[hh:2 hh:0 [hh:3 hh:1] hh:2]*2")
.gain(".48 .3 .58 .28 .42 .32 .52 .38")
.hpf(5500)
.pan(rand.range(.2, .8))
.sometimes(x => x.speed("1.5 0.8"))
.delay(.15)

