samples('shabda/speech:ghost,machine,error,collapse')

setcps(142/60/4)

$: note("c2 <eb2*2 d2*2> [c2 f2] [~ g1] c2*2 <d1 b1> [~ c2]")
  .sound("sawtooth")
  .lpf(saw.range(150, 2500).fast(8))
  .resonance(8)
  .crush(5)
  .shape(0.7)
  .gain(0.7)

$: note("c5 eb5 g5 f5 <b4 d5> c6*2").euclid(11, 16)
  .sound("triangle")
  .jux(x => x.rev().hurry(1.5).transpose(12))
  .delay(0.6)
  .room(0.6)
  .pan(perlin.range(0.2, 0.8).fast(2))
  .gain(0.35)

$: s("bd(5,8) <cp [~ cp]> bd(3,8) <[~ rim*2] cr>")
  .distort(0.4)
  .djf(0.3)
  .drive(0.8)
  .room(0.3)
  .gain(0.85)

$: s("[hh*16, [~ oh]*4]")
  .juxBy(0.5, x => x.rev().hurry(2))
  .vowel("<i e a o>")
  .room(0.4)
  .pan(sine.range(0.1, 0.9).fast(4))
  .gain(0.45)

$: s("<ghost!3 machine> <error(3,8) [~ collapse]>")
  .chop(16)
  .speed(perlin.range(0.5, 2.5).slow(8))
  .delay(0.8)
  .room(0.8)
  .gain(0.65)

$: note("<[c3,eb3,g3,c4] [ab2,c3,eb3,g3] [f2,ab2,c3,f3] [g2,b2,d3,g3]>")
  .sound("supersaw")
  .lpf(sine.range(300, 2000).slow(4))
  .resonance(3)
  .delay(0.5)
  .room(0.9)
  .gain(0.4)