samples('shabda/speech:synthetic,dream,ghost,machine')

setcps(145/60/4)

$: note("c1(5,8) eb1(3,8) <f1*2 g1> <~ d1>")
  .s("saw")
  .cutoff(perlin.range(300, 2500).fast(8))
  .lpq(8)
  .shape(0.85)
  .room(0.3)
  .gain(0.5)

$: n("0 [3 7] 10 [14 10] 7 [3 0] 7 10").scale("C:minor")
  .s("triangle")
  .fm(perlin.range(1, 8).fast(4))
  .delay(0.5)
  .pan(saw.fast(2))
  .room(0.8)
  .gain(0.35)

$: s("<bd(5,8) bd(3,8)> [~ cp] [sn:2|cb]? <[~ bd*2] bd>")
  .shape(0.9)
  .crush(4)
  .room(0.4)
  .pan(0.5)
  .gain(0.6)

$: s("[hh*2 hh?]*8")
  .bpf(sine.range(1000, 6000).fast(16))
  .bpq(6)
  .delay(0.7)
  .room(0.5)
  .gain(0.4)

$: s("synthetic ~ [ghost*2] <machine dream*2>")
  .chop(8)
  .speed(rand.range(0.8, 1.2))
  .delay(0.6)
  .room(0.8)
  .gain(0.55)

