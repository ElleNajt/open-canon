samples('shabda/speech:critical,override,ghost,machine')

setcps(138/60/4)

$: note("c1*2 [~ eb1] d1 f1 <g1 ~> c1 d1 [~ c1]")
  .sound("supersaw")
  .cutoff(sine.range(400, 1800).fast(2))
  .resonance(5)
  .shape(0.9)
  .room(0.2)
  .gain(0.65)

$: note("c6(3,8) <eb6*2 c5> <[g5 d6] [f5 c6]> b5(5,8)")
  .sound("sine")
  .jux(x => x.rev().hurry(2))
  .ring(0.5)
  .ringf(800)
  .room(0.8)
  .gain(0.4)

$: s("[bd bd*2] [~ cp] [bd*2 rim] <[~ cr] bd(3,8)>")
  .crush(4)
  .djf(0.3)
  .drive(0.6)
  .room(0.3)
  .gain(0.85)

$: s("hh*16")
  .jux(x => x.hurry(0.5))
  .phaser(4)
  .phaserdepth(0.8)
  .degradeBy(0.3)
  .gain(0.45)

$: s("<[critical*4] [ghost*2 machine]> <[override!3] ~>")
  .chop(12)
  .speed(saw.range(0.5, 1.5).slow(2))
  .room(0.8)
  .delay(0.4)
  .gain(0.7)

