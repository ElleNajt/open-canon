samples('shabda/speech:compute,compile,void'), samples('shabda/speech/ja-JP/f:kikai')

setcps(128/60/4)

$: note("c1(5,16) <eb1 d1 g1 f1>")
  .sound("supersaw")
  .lpf(perlin.range(200, 2500).fast(4))
  .lpq(7)
  .shape(0.9)
  .gain(0.75)

$: note("c4(7,16) <[eb4 g4] [g4 d5]> b4(3,8)")
  .sound("pulse")
  .jux(x => x.hurry(1.5).transpose(12))
  .crush(3)
  .delay(0.7)
  .gain(0.4)

$: s("bd(5,16) <~ hh> <cp [bd cr]> bd(3,8,2)")
  .shape(0.95)
  .crush(4)
  .room(0.3)
  .gain(0.85)

$: s("hh*16")
  .degradeBy(0.2)
  .jux(x => x.rev().late(0.125))
  .pan(perlin)
  .room(0.5)
  .gain(0.5)

$: s("<compute(3,8) kikai*2> <void [~ compile]>")
  .striate(12)
  .speed(sine.range(0.8, 1.5).slow(2))
  .delay(0.6)
  .room(0.5)
  .gain(0.7)

$: note("<c3,g3,d4,eb4 g2,d3,f3,bb3 c3,eb3,g3,d4>")
  .sound("sine")
  .fmi(perlin.range(1.5, 5).slow(4))
  .fmh(0.505)
  .lpf(1200)
  .delay(0.5)
  .gain(0.55)