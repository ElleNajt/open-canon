samples('shabda/speech:algorithm,calculate,process,void')

setcps(140/60/4)

$: note("c2 [~ cb2] <f1*3 db2> [bb1 eb2] ~ f2*2 g1 <~ bb1*2>")
  .s("pulse")
  .cutoff(saw.range(200, 3000).fast(4))
  .lpq(7)
  .crush(4)
  .gain(0.6)

$: n("0 3 7 10 14").euclid(9, 16).scale("C:minor")
  .s("sine")
  .fm(sine.range(1, 4).slow(4))
  .fmh(2.5)
  .delay(0.5)
  .gain(0.45)

$: s("bd <~ cp> bd(5,8) sn:2")
  .ply("<1 2 1 4>")
  .shape(0.8)
  .djf(saw.range(0.2, 0.8).slow(2))
  .room(0.4)
  .gain(0.8)

$: s("hh*8 [hh*4 oh*2]")
  .jux(x => x.hurry(1.5))
  .bpf(6000)
  .bpq(5)
  .pan(rand)
  .gain(0.4)

$: s("<algorithm void> ~ calculate <process void>")
  .chop(16)
  .speed(perlin.range(0.8, 1.2).fast(2))
  .delay(0.6)
  .room(0.6)
  .gain(0.7)

$: note("<[c3,eb3,g3,d4] [ab2,c3,eb3,g3]>/2")
  .s("supersaw")
  .lpf(sine.range(400, 2000).slow(8))
  .phaser(3)
  .room(0.9)
  .gain(0.3)