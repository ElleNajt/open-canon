samples('shabda/speech:synthetic,dream,ghost,machine')

setcps(130/60/4)

$: note("c1 [~ eb1] <g1*3 d2> [bb0 f1] ~ c2*2 g0 <~ bb0*2>")
  .s("pulse")
  .cutoff(saw.range(100, 2000).fast(8))
  .lpq(4)
  .distort(0.4)
  .room(0.2)
  .gain(0.55)

$: n("0 4 7 11 14").euclid(11, 16).scale("C:minor")
  .s("sine")
  .fm(perlin.range(2, 6).slow(4))
  .fmh(0.5)
  .delay(0.4)
  .pan(rand)
  .gain(0.4)

$: s("bd <~ sn:2> bd(5,8) cp")
  .ply("<1 2 1 3>")
  .djf(sine.range(0.3, 0.7).slow(2))
  .shape(0.6)
  .room(0.3)
  .gain(0.7)

$: s("hh*8 [hh*4 oh*2]")
  .jux(x => x.hurry(2))
  .bpf(sine.range(4000, 8000).slow(4))
  .bpq(3)
  .pan(saw)
  .gain(0.35)

$: s("<dream [~ ghost]> ~ machine <synthetic ghost*2>")
  .striate(8)
  .speed(perlin.range(0.5, 1.5).fast(2))
  .delay(0.6)
  .room(0.8)
  .gain(0.65)

$: note("<[c3,eb3,g3,bb3] [f2,ab2,c3,eb3]>/4")
  .s("supersaw")
  .lpf(sine.range(300, 1800).slow(8))
  .tremolo(0.5)
  .tremolosync(4)
  .room(0.9)
  .gain(0.3)