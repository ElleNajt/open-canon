samples('shabda/speech:logic,system,override,reboot')

setcps(138/60/4)

$: note("c1 [eb1 d1] c1 f1 [~ g1] c1 <d1 ~> [~ c1]")
  .sound("supersaw")
  .lpf(saw.range(200, 1500).fast(4))
  .resonance(4)
  .shape(0.8)
  .compressor("0.2:4:0.5:0.01:0.1")
  .gain(0.7)

$: note("c5 eb5 g5 f5 b4 c6*2").euclid(11, 16)
  .sound("pulse")
  .jux(x => x.rev().hurry(1.5))
  .ring(sine.range(0.1, 0.8).fast(2))
  .ringf(800)
  .room(0.7)
  .gain(0.35)

$: s("bd [cp, bd*2] [~ rim] <cr(3,8) [bd*4]>")
  .crush(3)
  .djf(0.35)
  .drive(0.8)
  .room(0.4)
  .gain(0.8)

$: s("[hh*16, [~ oh]*4]")
  .juxBy(0.4, x => x.hurry(0.5).rev())
  .phaser(6)
  .phaserdepth(0.9)
  .degradeBy(0.2)
  .gain(0.45)

$: s("<[logic!3] [system override]> <[reboot(3,8)] ~>")
  .chop(16)
  .speed(perlin.range(0.5, 1.8).slow(4))
  .delay(0.6)
  .room(0.8)
  .gain(0.65)

$: note("<[c3,eb3,g3,c4] [ab2,c3,eb3,g3] [f2,ab2,c3,f3] [g2,b2,d3,g3]>")
  .sound("sine")
  .fm(sine.range(1, 4).slow(8))
  .fmh(2.01)
  .delay(0.5)
  .room(0.8)
  .gain(0.5)