samples('shabda/speech:algorithm,dreaming,awake,logic')

setcps(142/60/4)

$: note("c2 [~ eb2] <d2*2 f2> [c2 f2] [~ g1] c2*2 <b1 g1> [~ c2]")
  .sound("sawtooth")
  .lpf(perlin.range(150, 4000).fast(4))
  .resonance(6)
  .crush(6)
  .shape(0.8)
  .gain(0.7)

$: n("0 2 4 5 <8 2> 7*2").euclid(13, 16).scale("C:minor")
  .sound("triangle")
  .jux(x => x.rev().hurry(1.5).transpose(12))
  .delay(0.6)
  .room(0.7)
  .crush(5)
  .gain(0.35)

$: s("bd(5,8,2) <cp [~ cp]> [~ bd:2] <[~ rim*4] cr>")
  .chop(8)
  .djf(perlin.range(0.2, 0.6).fast(2))
  .drive(0.6)
  .room(0.3)
  .gain(0.85)

$: s("[hh*16, [~ oh]*4]")
  .jux(x => x.ply(2).hurry(0.5))
  .vowel("<i o>")
  .room(0.4)
  .pan(perlin.range(0.2, 0.8).fast(4))
  .gain(0.4)

$: s("<algorithm!3 dreaming> <logic(5,8) [~ awake]>")
  .chop(16)
  .speed(sine.range(0.5, 2.0).slow(8))
  .delay(0.7)
  .room(0.8)
  .gain(0.65)

$: note("<[c3,eb3,g3,c4] [ab2,c3,eb3,g3] [f2,ab2,c3,f3] [g2,b2,d3,g3]>/2")
  .sound("supersaw")
  .lpf(sine.range(200, 3000).slow(8))
  .tremolo(0.8)
  .delay(0.6)
  .room(0.9)
  .gain(0.4)