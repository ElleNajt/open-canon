samples('shabda/speech:synthetic,dream,ghost,machine')

setcps(145/60/4)

$: note("c1(5,8,2) [eb1|~] <g1 [d2 f1]> f1")
  .s("pulse")
  .cutoff(perlin.range(100, 3000).fast(8))
  .lpq(8)
  .shape(0.85)
  .room(0.4)
  .gain(0.55)

$: n("0 3 7 [10|14]").euclid(11, 16).scale("C:minor")
  .s("sine")
  .jux(x => x.fast(2).rev())
  .fm(perlin.range(2, 8).slow(4))
  .delay(0.65)
  .room(0.7)
  .pan(saw)
  .gain(0.4)

$: s("bd(5,8) [sn:2|cp:1]? ~ <bd(3,8) bd*2>")
  .shape(0.9)
  .crush(4)
  .room(0.2)
  .pan(rand)
  .gain(0.65)

$: s("hh*8 <hh*16? oh*4>")
  .bpf(perlin.range(2000, 8000).fast(8))
  .bpq(8)
  .delay(0.5)
  .room(0.4)
  .gain(0.45)

$: s("<ghost(3,8) synthetic*2> <~ machine> [dream|ghost]")
  .speed(sine.range(0.4, 1.8).slow(8))
  .delay(0.75)
  .room(0.85)
  .pan(sine)
  .gain(0.6)

$: note("<[c3,g3,d4] [ab2,eb3,c4] [bb2,f3,d4] [g2,d3,b3]>/4")
  .s("triangle")
  .lpf(3000)
  .leslie(2)
  .lsize(0.8)
  .room(0.95)
  .gain(0.4)