samples('shabda/speech:synthetic,dream,ghost,machine')

setcps(145/60/4)

$: note("c1(5,8) <eb1 [~ g1]> f1 <~ d1>")
  .s("saw")
  .cutoff(sine.range(400, 2000).fast(4))
  .lpq(6)
  .shape(0.8)
  .room(0.2)
  .gain(0.45)

$: n("0 3 7 10 14 10 7 3").scale("C:minor")
  .s("triangle")
  .fm(perlin.range(2, 6).fast(2))
  .delay(0.6)
  .pan(saw)
  .room(0.7)
  .gain(0.35)

$: s("<bd*3 bd(5,8)> ~ [sn:2|cp]? <~ bd>")
  .crush(3)
  .speed(rand.range(0.8, 1.2))
  .room(0.3)
  .pan(0.5)
  .gain(0.6)

$: s("[hh?]*16")
  .bpf(perlin.range(1500, 8000).fast(8))
  .bpq(7)
  .delay(0.5)
  .room(0.5)
  .gain(0.45)

$: s("synthetic*2 [~ ghost(3,8)] <machine dream> ~")
