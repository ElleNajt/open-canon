samples('shabda/speech:phantom,algorithm,void'), samples('shabda/speech/ru-RU/m:pustota')

setcps(140/60/4)

$: note("g1 [~ g1] bb1 [c2 eb2] ~ d2 [~ f1] g1")
  .fast(2)
  .sound("triangle")
  .crush(4)
  .lpf(saw.range(300, 2500).slow(4))
  .lpq(6)
  .gain(0.8)

$: note("g4*2 <bb4!2 d5> [c5*3] f5")
  .sound("pulse")
  .jux(x => x.rev().transpose(12))
  .delay(0.7)
  .dt(0.375)
  .room(0.6)
  .gain(0.65)

$: s("bd(<5 3>,8) [~ <cp sn>] bd <cb(3,8) sn>")
  .shape(0.8)
  .room(0.4)
  .pan(0.5)
  .gain(0.85)

$: s("hh*16")
  .degradeBy(0.3)
  .vowel("i <e o>")
  .delay(0.3)
  .dt(0.25)
  .gain(0.55)

$: s("phantom ~ <pustota algorithm> void")
  .slow(2)
  .striate(8)
  .jux(x => x.hurry(2).rev())
  .room(0.7)
  .gain(0.75)

$: note("g3,bb3,d4,f4 c3,eb3,g3,bb3")
  .sound("supersaw")
  .slow(4)
  .lpf(800)
  .phaser(2)
  .room(0.8)
  .gain(0.65)