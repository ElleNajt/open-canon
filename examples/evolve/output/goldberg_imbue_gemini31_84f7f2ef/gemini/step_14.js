samples('shabda/speech:processing,system,failure,logic'), samples('shabda/speech/ru-RU/m:mashina')

setcps(135/60/4)

$: note("c1(5,16) <eb1 d1> f1(3,8) <g1 [~ d1]>")
  .sound("supersaw")
  .lpf(sine.range(150, 2200).fast(4))
  .lpq(6)
  .shape(0.9)
  .drive(0.4)
  .gain(0.7)

$: note("c5(7,16) <eb5*2 g5> <[g4*2 d5] [f5 c5]> b4(3,8)")
  .sound("pulse")
  .jux(x => x.hurry(2).transpose(7))
  .delay(0.5)
  .pan(perlin.range(0.2, 0.8).slow(4))
  .room(0.5)
  .gain(0.35)

$: s("bd(3,8) <rim*2 cp> <[~ bd] [bd*2 hh]> <cr bd(3,8,2)>")
  .shape(0.9)
  .crush(4)
  .drive(0.5)
  .gain(0.85)

$: s("hh*16")
  .jux(x => x.hurry(1.5))
  .degradeBy(perlin.range(0.2, 0.7).slow(8))
  .pan(saw.range(0.1, 0.9).fast(2))
  .gain(0.4)

$: s("<[processing*2] [mashina! system]> <[logic!3] [failure?]>")
  .chop(4)
  .speed(rand.range(0.8, 1.3))
  .jux(x => x.rev())
  .room(0.6)
  .gain(0.7)

$: note("<[c3,g3,eb4,b4] [a2,e3,c4,g4] [f2,c3,a3,e4] [g2,d3,bb3,f4]>")
  .sound("sine")
  .fmi(sine.range(0.5, 4).slow(12))
  .fmh(2.01)
  .attack(0.8)
  .room(0.8)
  .gain(0.55)