samples('shabda/speech:synthetic,dream,ghost,machine')

setcps(140/60/4)

$: note("c1(5,8) eb1 <g1 d2> f1")
  .s("square")
  .cutoff(saw.range(200, 1800).fast(4))
  .lpq(6)
  .drive(0.6)
  .room(0.3)
  .gain(0.5)

$: n("0 3 7 10 14").euclid(9, 16).scale("C:minor")
  .s("sine")
  .fm(perlin.range(3, 9).slow(4))
  .delaytime(0.125)
  .delay(0.5)
  .room(0.6)
  .gain(0.45)

$: s("bd*2 [~ cp] <bd*3 bd> sn:2")
  .djf(sine.range(0.2, 0.8).slow(4))
  .shape(0.8)
  .room(0.3)
  .pan(saw)
  .gain(0.65)

$: s("[hh*4 oh*2] <hh*8 oh*4>")
  .bpf(saw.range(4000, 8000).fast(2))
  .bpq(4)
  .delay(0.4)
  .room(0.2)
  .gain(0.4)

$: s("<synthetic ghost> <dream machine*2>")
  .chop(8)
  .speed(rand.range(0.5, 1.5))
  .delay(0.6)
  .room(0.8)
  .gain(0.7)

$: note("<[c3,eb3,g3] [ab2,c3,eb3] [bb2,d3,f3] [g2,b2,d3]>/4")
  .s("supersaw")
  .lpf(sine.range(400, 2500).slow(8))
  .tremolo(0.75)
  .tremolosync(8)
  .room(0.9)
  .gain(0.3)