samples('shabda/speech:phantom,algorithm,void'), samples('shabda/speech/ru-RU/m:pustota')

setcps(132/60/4)

$: note("g1 [~ d2] ~ <bb1 c2> e2 f1 [~ d2] g1")
  .fast(2)
  .sound("sawtooth")
  .lpf(sine.range(400, 2000).slow(4))
  .lpq(6)
  .shape(0.8)
  .gain(0.7)

$: note("g4*2 <bb4!2 d5> [c5*3] f5")
  .sound("pulse")
  .jux(x => x.rev().transpose(12))
  .delay(0.7)
  .dt(0.3)
  .room(0.5)
  .gain(0.65)

$: s("bd*2 [~ <cp sn>] bd <cb(3,8) sn>")
  .crush(3)
  .shape(0.7)
  .room(0.4)
  .pan(0.4)
  .gain(0.85)

$: s("hh*8 <[oh hh*2] [hh*4 oh]>")
  .pan(sine.slow(3))
  .vowel("i <a e>")
  .delay(0.4)
  .room(0.2)
  .gain(0.6)

$: s("phantom ~ <pustota algorithm> void")
  .slow(2)
  .chop(16)
  .jux(x => x.hurry(1.5).rev())
  .room(0.7)
  .gain(0.75)

$: note("g3,bb3,d4 f3,a3,c4")
  .sound("supersaw")
  .slow(4)
  .tremolo(0.8)
  .tremolosync(2)
  .lpf(800)
  .room(0.8)
  .gain(0.6)