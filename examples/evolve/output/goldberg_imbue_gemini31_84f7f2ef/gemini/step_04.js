samples('shabda/speech:digital,ghosts,memory'), samples('shabda/speech/ja-JP/f:kioku')

setcps(125/60/4)

$: note("g1 g2 ~ <d2 bb1> c2 e2 f1 d2")
  .fast(2)
  .sound("supersaw")
  .lpf(sine.range(300, 1500).slow(4))
  .lpq(5)
  .drive(0.6)
  .gain(0.65)

$: note("g4 <bb4 d5> c5 f5")
  .sound("triangle")
  .jux(x => x.rev().transpose(7))
  .delay(0.6)
  .dt(0.25)
  .room(0.5)

$: s("bd(5,8,1) [~ <cp cb*2>]")
  .crush(4)
  .shape(0.7)
  .lpf(2000)
  .room(0.3)
  .gain(0.8)

$: s("hh*8 <oh hh*4>")
  .pan(sine.slow(2))
  .phaser(2)
  .room(0.2)
  .gain(0.5)

$: s("digital ~ <kioku ghosts> memory")
  .slow(2)
  .chop(8)
  .jux(x => x.hurry(1.5).rev())
  .room(0.6)
  .gain(0.7)

$: note("g3,bb3,d4 f3,a3,c4")
