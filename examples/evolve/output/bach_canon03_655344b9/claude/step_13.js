// BWV 1087 Canon 3 - Variation: The Breaking Point

// Shattered voice - fragments of what was
let shatteredVoice = x => x
  .sound("pulse")
  .gain(0.09)
  .attack(0.005)
  .decay(0.1)
  .sustain(0.4)
  .release(0.3)
  .lpf(2200)
  .room(0.3)

// Abyss voice - the void opens
let abyssVoice = x => x
  .sound("sawtooth")
  .gain(0.1)
  .attack(0.1)
  .decay(0.6)
  .sustain(0.6)
  .release(0.8)
  .lpf(600)
  .room(0.6)

setcps(92/60/4)

// Track 1 - Theme FRACTURES into stuttering repetitions
$: note("d5 d5 ~ cs5 cs5 cs5 ~ ~ c5 ~ c5 c5 ~ b4 ~ b4")
  .slow(4)
  .apply(shatteredVoice)
  .pan(rand.range(0.3, 0.7))
  .delay(0.5)
  .delaytime(0.125)
  .delayfeedback(0.6)

// Track 2 - Pulsing becomes aggressive stabs
$: note("[d4,fs4,a4] ~ ~ [eb4,g4,bb4]! ~ [d4,f4,ab4] ~ ~")
  .fast(2)
  .sound("sawtooth")
  .gain(0.08)
  .attack(0.002)
  .decay(0.08)
  .sustain(0.3)
  .release(0.15)
  .lpf(1800)
  .distort(0.2)
  .pan(0.5)

// Track 3 - Harmony collapses to bare tritones
$: note("<[d2,ab2]> <[eb2,a2]> <[d2,ab2]> <[db2,g2]>")
  .slow(8)
  .apply(abyssVoice)
  .lpq(6)
  .pan(0.5)

// Track 4 - Heartbeat becomes erratic, panicked
$: note("d2 d2 ~ d2 ~ ~ d2 d2 d2 ~ d2 ~ ~ ~ d2 d2")
  .fast(1.5)
  .sound("sine")
  .gain(0.13)
  .attack(0.005)
  .decay(0.15)
  .sustain(0.6)
  .release(0.2)
  .lpf(280)
  .distort(0.15)
  .pan(0.5)

// Track 5 - Wind becomes SCREAMING cluster
$: note("[fs5,g5,ab5,a5]")
  .slow(4)
  .sound("sawtooth")
  .gain(0.07)
  .attack(0.5)
  .decay(1)
  .sustain(0.8)
  .release(0.5)
  .lpf(sine.range(1500, 4000).slow(2))
  .hpf(800)
  .room(0.5)
  .pan(0.5)

// Track 6 - NEW: Descending chromatic doom
$: note("ab3 g3 fs3 f3 e3 eb3 d3 db3")
  .slow(16)
  .sound("triangle")
  .gain(0.1)
  .attack(0.05)
  .decay(0.3)
  .sustain(0.7)
  .release(0.5)
  .lpf(1100)
  .room(0.4)
  .pan(0.6)

// Track 7 - Bells become tolling death knell
$: note("d3 ~ ~ ~ a2 ~ ~ ~ d3 ~ ~ ~ a2 ~ ~ ~")
  .slow(4)
  .sound("triangle")
  .gain(0.11)
  .attack(0.01)
  .decay(1.2)
  .sustain(0.2)
  .release(2)
  .lpf(900)
  .room(0.7)
  .delay(0.3)
  .delaytime(0.5)
  .delayfeedback(0.4)
  .pan(0.5)

// Track 8 - Thunder now constant, oppressive
$: note("d1 ~ eb1 ~ d1 ~ db1 ~ d1 ~ eb1 ~ e1 ~ d1 ~")
  .slow(8)
  .sound("sawtooth")
  .gain(0.08)
  .attack(0.2)
  .decay(0.8)
  .sustain(0.5)
  .release(1)
  .lpf(150)
  .distort(0.2)
  .room(0.6)
  .pan(0.5)

// Track 9 - Fleeing voice now TRAPPED, repeating figure
$: note("a5 bb5 a5 g5 a5 bb5 a5 g5")
  .slow(2)
  .ply(2)
  .sometimesBy(0.3, x => x.add(12))
  .sound("sine")
  .gain(0.07)
  .attack(0.01)
  .decay(0.1)
  .sustain(0.2)
  .release(0.2)
  .lpf(3000)
  .hpf(2000)
  .room(0.3)
  .pan(sine.range(0.2, 0.8).fast(2))