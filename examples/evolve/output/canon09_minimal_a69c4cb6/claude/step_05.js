// BWV 1087 Canon 9 - Fracturing Ice Cathedral

// The crystalline structure shatters into prismatic shards
// Each fragment carries harmonic memory as it falls

let shardVoice = x => x
  .sound("triangle")
  .gain(0.24)
  .attack(0.005)
  .decay(0.4)
  .sustain(0.08)
  .release(1.8)
  .lpf(perlin.range(1200, 5000).slow(6))
  .lpq(7)
  .hpf(400)
  .room(0.7)
  .delay(0.5)
  .delaytime(0.166)
  .delayfeedback(0.65)

let ghostVoice = x => x
  .sound("sine")
  .gain(0.2)
  .attack(0.3)
  .decay(1.2)
  .sustain(0.4)
  .release(2.5)
  .fmi(sine.range(0.5, 4).slow(14))
  .fmh(1.5)
  .room(0.8)
  .delay(0.55)
  .delaytime(0.416)
  .delayfeedback(0.5)

let fractureVoice = x => x
  .sound("pulse")
  .gain(0.14)
  .attack(0.002)
  .decay(0.08)
  .sustain(0.01)
  .release(0.5)
  .lpf(rand.range(2000, 6000))
  .hpf(800)
  .crush(10)
  .room(0.5)

let resonanceVoice = x => x
  .sound("sawtooth")
  .gain(0.12)
  .attack(0.8)
  .decay(1.5)
  .sustain(0.3)
  .release(3)
  .lpf(tri.range(200, 900).slow(10))
  .lpq(8)
  .shape(0.12)
  .room(0.65)

setcps(84/60/4)

// Primary melodic shards - fragmenting and scattering
$: note("g5 ~ b5 ~ d6 ~ g6 ~ d6 ~ b5 ~ g5 ~ d6 ~ d5 ~ gb5 ~ a5 ~ db5 ~ e5 ~ g5 ~ db6 ~!3 d6 ~ a5 ~ gb5 ~ d5 ~ g5 ~ b5 ~ d6 ~ g5 ~ e6 ~ c6 ~ a5 ~ c6 ~ gb5 ~ a5 ~ d6 c6 b5 a5 g5 ~ b5 ~ d6 ~ g6 ~ d6 ~ b5 ~ g5 ~ d6 ~ d5 ~ gb5 ~ a5 ~ db5 ~ e5 ~ g5 ~ db6 ~!3 d6 ~ a5 ~ gb5 ~ d5 ~ g5 ~ b5 ~ d6 ~ g5 ~ e6 ~ c6 ~ a5 ~ c6 ~ gb5 ~ a5 ~ d6 c6 b5 a5 g5 ~!7")
  .slow(8)
  .apply(shardVoice)
  .sometimes(x => x.chop(4).speed(rand.range(0.8, 1.4)))
  .off(0.0625, x => x.transpose(12).gain(0.08).lpf(8000))
  .off(0.125, x => x.transpose(19).gain(0.06).attack(0.2))
  .pan(perlin.range(0.15, 0.85).slow(5))

// Canonic ghost - echo of what was
$: note("~!2 g5 ~ b5 ~ d6 ~ g6 ~ d6 ~ b5 ~ g5 ~ d6 ~ d5 ~ gb5 ~ a5 ~ db5 ~ e5 ~ g5 ~ db6 ~!3 d6 ~ a5 ~ gb5 ~ d5 ~ g5 ~ b5 ~ d6 ~ g5 ~ e6 ~ c6 ~ a5 ~ c6 ~ gb5 ~ a5 ~ d6 c6 b5 a5 g5 ~ b5 ~ d6 ~ g6 ~ d6 ~ b5 ~ g5 ~ d6 ~ d5 ~ gb5 ~ a5 ~ db5 ~ e5 ~ g5 ~ db6 ~!3 d6 ~ a5 ~ gb5 ~ d5 ~ g5 ~ b5 ~ d6 ~ g5 ~ e6 ~ c6 ~ a5 ~ c6 ~ gb5 ~ a5 ~ d6 c6 b5 a5 g5 ~!5")
  .slow(8)
  .apply(ghostVoice)
  .degradeBy(0.3)
  .every(4, x => x.rev())
  .pan(cosine.range(0.2, 0.8).slow(11))

// Harmonic pillars - slowly crumbling
$: note("~!8 g3 ~!7 gb3 ~!7 e3 ~!7 d3 ~!7 b2 ~!7 c3 ~!7 d3 ~!7 g2 ~!7 g3 ~!7 gb3 ~!7 e3 ~!7 d3 ~!7 b2 ~!7 c3 ~!7 d3 ~!7 g2 ~!7")
  .slow(8)
  .apply(resonanceVoice)
  .off(0.5, x => x.transpose(12).gain(0.08).fmi(2).fmh(2))
  .sometimes(x => x.slide(0.4))
  .pan(0.5)

// Fracture debris - stochastic glitter
$: note("g6 b6 d7 g7 d7 b6 g6 d6 b5 g5 d5 b4 g4")
  .struct("t(11,16)")
  .slow(3)
  .apply(fractureVoice)
  .iter(8)
  .degradeBy(0.4)
  .sometimesBy(0.3, x => x.transpose(rand.range(-7, 7)))
  .juxBy(0.7, x => x.rev().late(0.03))
  .pan(rand)

// Falling resonances - spectral descent
$: note("g5 e5 c5 a4 gb4 d4 b3 g3")
  .euclid(5,8)
  .slow(6)
  .sound("triangle")
  .gain(0.18)
  .attack(0.15)
  .decay(0.6)
  .sustain(0.2)
  .release(1.5)
  .lpf(saw.range(600, 3500).slow(8))
  .lpq(5)
  .accelerate(-0.3)
  .room(0.7)
  .delay(0.45)
  .delaytime(0.333)
  .delayfeedback(0.55)
  .pan(sine.range(0.3, 0.7).slow(7))

// Subterranean drone - the frozen depths
$: note("<g1 d1 e1 b0>")
  .sound("sawtooth")
  .gain(0.1)
  .attack(4)
  .decay(2)
  .sustain(0.6)
  .release(6)
  .lpf(sine.range(80, 250).slow(16))
  .lpq(6)
  .fmi(perlin.range(0.1, 0.8).slow(12))
  .fmh(0.25)
  .shape(0.06)
  .room(0.85)
  .slow(16)
  .pan(0.5)

// Spectral overtones - cathedral bells
$: note("<g4 d4 b3 e4> <b4 g4 d4 c5>")
  .slow(8)
  .sound("sine")
  .gain(0.15)
  .attack(0.01)
  .decay(2)
  .sustain(0.1)
  .release(4)
  .fmi(cosine.range(2, 8).slow(9))
  .fmh(4)
  .fmdecay(1.5)
  .room(0.75)
  .delay(0.6)
  .delaytime(0.583)
  .delayfeedback(0.5)
  .jux(x => x.transpose(12).late(0.125).gain(0.08))
  .pan(0.5)