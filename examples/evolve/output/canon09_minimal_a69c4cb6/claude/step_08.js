setcps(72/60/4)

// Main channel spreading - slower, wider, meditative
$: note("g4 a4 b4 d5 ~ e5 g5 ~ a5 g5 ~ d5 c5 b4 ~ g4 a4 ~ d5 e5 ~ d4 e4 gb4 ~ a4 b4 ~ db5 e5 ~ e4 gb4 g4 ~ a4 db5 d5 ~ e5 d5 ~ d5 c5 ~ a4 b4 gb4 ~ e4 d4 ~")
