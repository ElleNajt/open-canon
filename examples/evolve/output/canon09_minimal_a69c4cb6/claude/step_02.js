// BWV 1087 Canon 9 - Dissolving into Vapor

// Voices become increasingly unstable and granular
let upperVoice = x => x
  .sound("triangle")
  .gain(0.35)
  .attack(0.05)
  .decay(0.3)
  .sustain(0.15)
  .release(0.6)
  .lpf(sine.range(800, 2800).slow(12))
  .lpq(3)
  .room(0.4)
  .delay(0.25)
  .delaytime(0.333)
  .delayfeedback(0.45)

let lowerVoice = x => x
  .sound("pulse")
  .gain(0.3)
  .decay(0.3)
  .sustain(0.2)
  .lpf(cosine.range(600, 1400).slow(10))
  .room(0.3)
  .distort(0.08)

let ghostVoice = x => x
  .sound("sine")
  .gain(0.18)
  .attack(0.2)
  .decay(0.6)
  .sustain(0.05)
  .release(1.2)
  .room(0.65)
  .delay(0.5)
  .delaytime(0.625)
  .delayfeedback(0.6)

let grainVoice = x => x
  .sound("sawtooth")
  .gain(0.12)
  .attack(0.01)
  .decay(0.1)
  .sustain(0)
  .lpf(rand.range(1200, 3000))
  .crush(10)
  .room(0.5)

setcps(96/60/4)

$: note("g5 ~ b5 ~ d6 ~ g6 ~ d6 ~ b5 ~ g5 ~ d6 ~ d5 ~ gb5 ~ a5 ~ db5 ~ e5 ~ g5 ~ db6 ~!3 d6 ~ a5 ~ gb5 ~ d5 ~ g5 ~ b5 ~ d6 ~ g5 ~ e6 ~ c6 ~ a5 ~ c6 ~ gb5 ~ a5 ~ d6 c6 b5 a5 g5 ~ b5 ~ d6 ~ g6 ~ d6 ~ b5 ~ g5 ~ d6 ~ d5 ~ gb5 ~ a5 ~ db5 ~ e5 ~ g5 ~ db6 ~!3 d6 ~ a5 ~ gb5 ~ d5 ~ g5 ~ b5 ~ d6 ~ g5 ~ e6 ~ c6 ~ a5 ~ c6 ~ gb5 ~ a5 ~ d6 c6 b5 a5 g5 ~!7")
  .slow(8)
  .apply(upperVoice)
  .degradeBy(0.15)
  .juxBy(0.4, x => x.detune(12).late(0.02))
  .pan(0.3)

$: note("~!2 g5 ~ b5 ~ d6 ~ g6 ~ d6 ~ b5 ~ g5 ~ d6 ~ d5 ~ gb5 ~ a5 ~ db5 ~ e5 ~ g5 ~ db6 ~!3 d6 ~ a5 ~ gb5 ~ d5 ~ g5 ~ b5 ~ d6 ~ g5 ~ e6 ~ c6 ~ a5 ~ c6 ~ gb5 ~ a5 ~ d6 c6 b5 a5 g5 ~ b5 ~ d6 ~ g6 ~ d6 ~ b5 ~ g5 ~ d6 ~ d5 ~ gb5 ~ a5 ~ db5 ~ e5 ~ g5 ~ db6 ~!3 d6 ~ a5 ~ gb5 ~ d5 ~ g5 ~ b5 ~ d6 ~ g5 ~ e6 ~ c6 ~ a5 ~ c6 ~ gb5 ~ a5 ~ d6 c6 b5 a5 g5 ~!5")
  .slow(8)
  .apply(upperVoice)
  .sometimes(x => x.speed(0.5).octave(4))
  .leslie(0.4)
  .lrate(3)
  .pan(0.7)

$: note("~!8 g3 ~!7 gb3 ~!7 e3 ~!7 d3 ~!7 b2 ~!7 c3 ~!7 d3 ~!7 g2 ~!7 g3 ~!7 gb3 ~!7 e3 ~!7 d3 ~!7 b2 ~!7 c3 ~!7 d3 ~!7 g2 ~!7")
  .slow(8)
  .apply(lowerVoice)
  .off(0.125, x => x.transpose(12).gain(0.15))
  .pan(0.5)

$: note("g4 ~ ~ ~ d5 ~ ~ ~ b4 ~ ~ ~ e5 ~ ~ ~ c5 ~ ~ ~ a4 ~ ~ ~ gb4 ~ ~ ~ g4 ~ ~ ~")
  .slow(8)
  .apply(ghostVoice)
  .every(3, x => x.transpose(7))
  .often(x => x.detune(rand.range(-25, 25)))
  .pan(perlin.range(0.15, 0.85).slow(8))

$: note("g5 b5 d6 g6 d6 b5 g5 a5 c6 e6 c6 a5 gb5 a5 d6")
  .struct("t(5,16)")
  .slow(4)
  .apply(grainVoice)
  .ply(2)
  .degradeBy(0.4)
  .pan(rand)

$: note("<g2 g1>")
  .sound("sine")
  .gain(0.12)
  .attack(3)
  .sustain(1)
  .release(3)
  .lpf(sine.range(200, 500).slow(16))
  .fmi(0.5)
  .fmh(0.5)
  .room(0.7)
  .slow(16)
  .pan(0.5)

