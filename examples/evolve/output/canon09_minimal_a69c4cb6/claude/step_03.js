// BWV 1087 Canon 9 - Crystalline Collapse

// The vapor condenses into sharp crystalline structures, then shatters
let crystalVoice = x => x
  .sound("triangle")
  .gain(0.3)
  .attack(0.01)
  .decay(0.4)
  .sustain(0.1)
  .release(0.8)
  .lpf(perlin.range(1200, 4000).slow(6))
  .lpq(5)
  .room(0.5)
  .delay(0.3)
  .delaytime(0.25)
  .delayfeedback(0.5)

let shardVoice = x => x
  .sound("pulse")
  .gain(0.25)
  .attack(0.005)
  .decay(0.15)
  .sustain(0.05)
  .release(0.3)
  .lpf(sine.range(800, 2400).slow(8))
