samples('shabda/speech:binary,thought,process,data', 'shabda/speech/de-DE:maschine,geist')
setcps(124/60/4)

$: note("[c2 c2] g2 f2 a2").slow(4)
  .sound("supersaw")
  .gain(0.1)
  .cutoff(perlin.range(200, 1200).slow(14))
  .lpq(7)
  .drive(0.4)
  .delay(0.5)
  .phaser(perlin.range(0.2, 4).slow(10))

$: note("<c5 d#5 g5> ~ [g4 a#4] ~").slow(4).iter(2)
  .sound("sawtooth")
  .gain(0.18)
  .cutoff(2500)
  .vowel("a o u e".slow(8))
  .delay(0.6)
  .delayfeedback(0.6)
  .lpenv(4)

$: s("bd(3,8) [~ cp]? [cr rim] mt*2").fast(4)
  .jux(rev)
  .gain(0.45)
  .distort(0.2)
  .crush(10)
  .room(0.3)
  .pan(rand)

$: note("<c3:min9 g3:min9> <f3:maj7 a#3:maj7>").chord().slow(8)
  .sound("piano")
  .gain(0.25)
  .bandf(sine.range(500, 2500).slow(8))
  .bandq(5)
  .tremolo(0.3)
  .delay(0.75)
  .delayfeedback(0.6)

$: s("<binary thought process data> <maschine geist>").slow(2)
  .chop(perlin.range(4,16).slow(7))
  .speed(perlin.range(0.8, 1.2).slow(9))
  .gain(0.12)
  .hpf(800)
  .room(0.7)
  .pan(perlin.slow(13).range(0, 1))

$: note("-5 0 2 [3 7] 5 0 2").scale("c:minor").ply(2).fast(8)
  .sound("pulse")
  .gain(0.09)
  .lpf(3000)
  .lpq(4)
  .detune(perlin.range(-5,5).slow(3))
  .crush(6)
  .delay(0.2)