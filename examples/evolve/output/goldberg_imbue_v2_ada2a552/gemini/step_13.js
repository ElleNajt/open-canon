samples('shabda/speech:eternal,return', 'shabda/speech/de-DE:ewige,wiederkunft')
setcps(130/60/4)

$: note("c2 g2 f2 a2").slow(4)
  .sound("supersaw")
  .gain(0.12)
  .cutoff(perlin.range(300, 1500).slow(12))
  .lpq(8)
  .phaser(perlin.range(0.1, 5).slow(9))

$: note("<c5 d#5> ~ g4 ~").slow(2).iter(3)
  .sound("sawtooth")
  .gain(0.15)
  .cutoff(3000)
  .lpenv(2)
  .delay(0.6)

$: s("bd*2 [cp rim]?").euclid(5, 8).fast(2)
  .jux(rev)
  .gain(0.5)
  .distort(0.3)
  .room(0.2)
  .pan(rand)

$: note("<c3:min9 g3:min9> <f3:maj7 a#3:maj7>").chord().slow(8)
  .sound("triangle")
  .gain(0.2)
  .cutoff(sine.range(500, 4000).slow(16))
  .delay(0.75)
  .delayfeedback(0.7)

$: s("<eternal return ewige wiederkunft>").fast(2)
  .striate(perlin.range(8,64).slow(5))
  .gain(0.1)
  .hpf(1000)
  .room(0.8)
  .pan(perlin.slow(11).range(0, 1))

