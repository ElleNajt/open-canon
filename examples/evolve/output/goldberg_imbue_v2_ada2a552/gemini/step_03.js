// Goldberg Variations - Ambient Rework
// The 8-note ground bass, re-contextualized

setcps(72/60/4)

$: note("g3 gb3 e3 d3 b2 c3 d3 g2")
  .slow(2)
  .sound("sawtooth")
  .gain(0.2)
  .cutoff(400)
  .resonance(2)
  .distort(0.1)
  .delay(0.3)

$: note("d5 b4 g4 e4 d4 e4 fs4 g4")
  .slow(2)
  .sound("sine")
  .gain(0.2)
  .fmi(2)
  .lpf(100)
  .lpenv(2500)
  .room(0.5)

$: s("hh").euclid(7, 12)
  .slow(2)
  .gain(0.15)
  .pan(sine.range(0.1, 0.9).slow(16))
  .hpf(8000)
  .delay(0.5)
  .dfb(0.4)

$: note("<g5 d6>")
  .sound("supersaw")
  .gain(0.15)
  .lpf(sine.range(500, 3000).slow(8))
  .lpq(4)
  .room(0.6)
  .detune(cosine.range(-15, 15).slow(11))
  
$: s("rd*2")
  .slow(8)
  .speed(perlin.range(-0.4, -0.6))
  .gain(0.1)
  .hpf(1200)
  .room(0.7)
  .pan(saw.range(0, 1).slow(12))

$: note("g5 d6 g6 b6")
  .fast(2)
  .sound("triangle")
  .gain(0.08)
  .delay(0.5)
  .hpf(2000)
  .pan(perlin.range(0.2, 0.8).slow(7))
  .slide(perlin.range(-0.1, 0.1).slow(9))