samples('shabda/speech:binary,thought,process,data', 'shabda/speech/de-DE:maschine,geist')
setcps(128/60/4)

$: note("[c2 c2] g#2 f2 a#2").slow(4)
  .sound("supersaw")
  .gain(0.12)
  .cutoff(perlin.range(200, 1500).slow(16))
  .lpq(6)
  .delay(0.5)

$: note("c5 d#5 g5 a#5 g5 d#5 c5 ~").fast(2)
  .sound("sawtooth")
  .gain(0.15)
  .vowel("a:2 o u e".slow(6))
  .delay(0.6)
  .delayfeedback(0.7)

$: s("bd(5,12) [~ cp]? [cr(3,4,0.5) rim] <mt ht>*2")
  .fast(2)
  .gain(0.5)
  .shape(0.3)
  .crush(9)
  .room(0.2)
  .pan(rand)

$: note("<d#3:min9 g3:sus4> <c4:min7 f3:maj7>").chord().slow(8)
  .sound("piano")
  .gain(0.2)
  .cutoff(sine.range(500, 2500).slow(8))
  .phaser(perlin.range(0.1, 2).slow(12))
  .delay(0.7)

$: s("<binary thought process data> <maschine geist>").slow(2)
  .chop(rand.range(16,32))
  .speed(perlin.range(0.8, 1.2).slow(9))
  .gain(0.13)
  .hpf(perlin.range(200, 1000).slow(10))
  .room(0.7)
  .delay(0.4)
  .pan(perlin.slow(13).range(0.1, 0.9))

$: note("-5 0 2 [3 7] 5 0 2 [7 10]").scale("c:minor").slow(2)
  .sound("pulse")
  .gain(0.1)
  .lpf(2500)
  .crush(7)
  .delay(0.2)
  .room(0.3)