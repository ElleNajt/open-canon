// Goldberg Variations - Ambient Rework
// The 8-note ground bass, re-contextualized

setcps(72/60/4)

$: note("g3 gb3 e3 d3 b2 c3 d3 g2")
  .slow(4)
  .sound("sawtooth")
  .gain(0.18)
  .shape(perlin.range(0.1, 0.9).slow(8))
  .cutoff(sine.range(400, 1200).slow(8))
  .resonance(5)
  .drive(0.4)

$: note("d5 c5 ~ g4 eb4 ~ d4 fs4 g4")
  .slow(2)
  .sound("sine")
  .gain(0.15)
  .fmi(perlin.range(0, 5).slow(8))
  .lpenv(2000)
  .room(0.5)
  .delay(0.4)

$: s("<hh rim sn:4>").euclid(5, 8)
  .slow(2)
  .gain(0.1)
  .pan(perlin.range(0.1, 0.9).slow(12))
  .bandf(3000)
  .bandq(5)
  .degradeBy(0.15)
  .delay(0.5)
  
$: note("g4 d5").euclid(3, 8)
  .sound("supersaw")
  .gain(0.12)
  .tremolo(sine.range(0.2, 0.8).slow(5))
  .lpf(sine.range(800, 2500).slow(8))
  .lpq(6)
  .room(0.7)
  .detune(cosine.range(-10, 10).slow(11))

$: s("cr*4")
  .slow(16)
  .chop(perlin.range(8, 32).slow(5))
  .speed(perlin.range(-0.5, -1.5).slow(9))
  .gain(0.08)
  .hpf(1000)
  .room(0.8)

$: note("<g5 af5> <d6 ef6> g6 b6")
  .fast(2)
  .sound("piano")
  .gain(0.09)
  .crush(7)
  .distort(0.1)
  .delay(0.25)
  .pan(perlin.range(0.2, 0.8).slow(7))