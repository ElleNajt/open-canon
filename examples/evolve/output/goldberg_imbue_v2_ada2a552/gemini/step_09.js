samples('shabda/speech:gold,berg')
setcps(72/60/4)

$: note("[g3 gb3] e3 d3 b2 c3 d3 g2")
  .slow(2).ply(2).iter(1)
  .sound("pulse")
  .gain(0.15)
  .cutoff(sine.range(100, 900).slow(8))
  .lpq(5)
  .crush(6)
  .shape(0.4)
  .room(0.6)

$: note("eb5 ~ c5 ~ <g4 a4> ~ d4?").slow(2)
  .sound("sawtooth")
  .gain(0.16)
  .fmi(perlin.range(1, 6).slow(9))
  .bandf(perlin.range(500, 3000).slow(10))
  .distort(0.3)
  .delay(0.5)
  .pan(perlin.range(0, 1).slow(11))

$: s("[bd cp, hh*2] sn?").euclid(5, 8).fast(2)
  .gain(0.3)
  .crush(4)
  .delay(0.3)
  .compressor()
  .pan(rand)
  .postgain(1.2)

$: note("g4:min7 c5:maj7").chord().euclid(5, 13)
  .sound("piano")
  .gain(0.08)
  .vowel("a e o u").slow(16)
  .crush(8)
  .room(0.8)
  .delay(0.2)
  .pan(sine.range(0.1, 0.9).slow(16))

$: s("gold berg").chop(16).fast(2)
  .gain(0.1)
  .speed(perlin.range(0.5, 1.5).slow(13))
  .bandf(1500)
  .bandq(6)
  .delay(0.6)
  .pan(perlin.range(0, 1).slow(7))

