samples('shabda/speech:gold,berg,variation')
setcps(60/60/4)

$: note("[g3 gb3] e3 d3 b2 c3 d3 g2")
  .slow(4)
  .sound("pulse")
  .gain(0.15)
  .cutoff(sine.range(200, 1200).slow(8))
  .lpq(4)
  .crush(perlin.range(4, 7).slow(6))
  .delay(0.4)
  .room(0.5)

$: note("eb5 ~ c5 ~ <g4 a4> ~ d4?").slow(2).euclid(5,8)
  .sound("sawtooth")
  .gain(0.15)
  .fmi(perlin.range(0.5, 8).slow(9))
  .bandf(perlin.range(500, 3000).slow(10))
  .phaser(perlin.range(1, 8).slow(12))
  .pan(perlin.range(0, 1).slow(11))
  .jux(x => x.late(1/3).gain(0.7))

$: s("[<bd bd*2> cp, [hh oh]*2] sn?").euclid(5, 8).fast(2)
  .gain(0.4)
  .crush(5)
  .striate(perlin.range(8, 32).slow(4))
  .speed(perlin.range(0.8, 1.2).slow(3))
  .delay(0.3)
  .pan(rand)

$: note("<g4:min7 c4:maj7> <f4:maj7 bb3:maj7>").chord().euclid(5, 13)
  .sound("piano")
  .gain(0.1)
  .vowel("i o u a").slow(12)
  .crush(6)
  .tremolo(perlin.slow(16).range(0.1, 0.7))
  .room(0.7)
  .pan(sine.range(0.1, 0.9).slow(16))

$: s("<gold berg variation>*2").chop(8).fast(4)
  .gain(0.12)
  .speed(perlin.range(0.75, 1.25).slow(13))
  .bandf(perlin.range(1000, 2500).slow(5))
  .bandq(5)
  .crush(6)
  .pan(perlin.range(0, 1).slow(7))

$: note("0 2 4 5 7 9 11 12").scale("g:minor").fast(8).palindrome()
  .sound("sine")
  .gain(0.09)
  .fmi(perlin.range(0.1, 4).slow(7))
  .hpf(perlin.range(500,2500).slow(8))
  .hpq(8)
  .detune(perlin.range(-15, 15).slow(4))
  .room(0.4)