samples('shabda/speech:gold,berg,variation')
setcps(60/60/4)

$: note("[g3 gb3] e3 d3 b2 c3 d3 g2").ply(2).slow(8)
  .sound("pulse")
  .gain(0.15)
  .cutoff(sine.range(200, 1200).slow(8))
  .crush(perlin.range(4, 7).slow(6))
  .delay(0.4)

$: note("<eb5 eb6> ~ c5 ~ <g4 a4> ~ d4?").slow(2).euclid(5,8)
  .sound("sawtooth")
  .gain(0.18)
  .fmi(perlin.range(0.5, 8).slow(9))
  .bandf(perlin.range(500, 3000).slow(10))
  .pan(perlin.range(0, 1).slow(11))

$: s("bd sn? [hh hh oh]?").euclid(7, 12).fast(2)
  .gain(0.4)
  .crush(5)
  .striate(perlin.range(8, 32).slow(4))
  .speed(perlin.range(0.8, 1.2).slow(3))
  .pan(rand)

$: note("<d4:min7 g3:dom7> <c4:maj7 f3:maj7>").chord().euclid(7, 13)
  .sound("piano")
  .gain(0.12)
  .vowel("i o u a").slow(12)
  .tremolo(perlin.slow(16).range(0.1, 0.7))
  .room(0.7)

$: s("<gold berg variation>*2").chop(perlin.range(4,16).slow(4)).fast(4)
  .gain(0.12)
  .speed(perlin.range(0.75, 1.25).slow(13))
  .bandf(perlin.range(1000, 2500).slow(5))
  .delay(0.5)
  .pan(perlin.range(0, 1).slow(7))

$: note("0 1 3 5 7 8 10").scale("g:phrygian").fast(12).palindrome()
  .sound("sine")
  .gain(0.1)
  .distort(perlin.range(0.1, 0.5).slow(5))
  .hpf(perlin.range(700,3000).slow(8))
  .room(0.4)