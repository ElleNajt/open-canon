// Goldberg Variations - Ambient Rework
// The 8-note ground bass, re-contextualized

setcps(72/60/4)

$: note("g3 gb3 e3 d3 b2 c3 d3 g2")
  .slow(4)
  .sound("pulse")
  .gain(0.2)
  .shape(perlin.range(0,1).slow(8))
  .cutoff(600)
  .resonance(8)
  .distort(0.15)

$: note("d5 b4 ~ g4 e4 ~ d4 fs4 g4")
  .slow(2)
  .sound("sine")
  .gain(0.15)
  .fmi(perlin.range(0, 5).slow(8))
  .lpenv(3000)
  .penv(100)
  .pattack(0.05)
  .room(0.5)

$: s("<hh sn:4>").euclid(5, 8)
  .slow(2)
  .gain(0.1)
  .pan(perlin.range(0.1, 0.9).slow(12))
  .hpf(7000)
  .degradeBy(0.25)
  .delay(0.5)

$: note("<[g4,g5] [d5,d6]>")
  .sound("supersaw")
  .gain(0.1)
  .phaser(perlin.range(0.1, 2).slow(13))
  .lpf(sine.range(800, 2500).slow(8))
  .lpq(6)
  .room(0.7)
  .detune(cosine.range(-10, 10).slow(11))
  
$: s("cr*4")
  .slow(16)
  .striate(perlin.range(2, 16).slow(4))
  .speed(perlin.range(0.5, 1.5).slow(9))
  .gain(0.08)
  .hpf(1000)
  .room(0.8)

$: note("g5 d6 g6 b6")
  .fast(2)
  .sound("piano")
  .gain(0.1)
  .crush(6)
  .distort(0.2)
  .phaser(perlin.range(0.2,2).slow(11))
  .pan(perlin.range(0.2, 0.8).slow(7))