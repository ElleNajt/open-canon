setcps(72/60/4)

$: note("g3 fs3 e3 d3 b2 c3 d3 g2")
  .slow(2)
  .sound("triangle")
  .gain(0.22)
  .lpf(sine.range(280, 2200).slow(16))
  .room(0.5)

$: note("g4 fs4 e4 d4 b3 c4 d4 g3")
  .slow(2)
  .sound("sine")
  .gain(0.14)
  .delay(0.6).delaytime(0.375).delayfeedback(0.55)
  .pan(sine.range(0.25, 0.75).slow(12))

$: note("<g5 b5 d6 fs6> <fs5 a5 cs6 e6> <e5 gs5 b5 d6> <d5 fs5 a5 cs6> <b4 ds5 g5 b5> <c5 e5 a5 c6> <d5 fs5 b5 d6> <g4 b4 d5 g5>")
  .slow(2)
  .sound("sawtooth")
  .gain(0.07)
  .lpf(perlin.range(500, 3000).slow(8))
  .attack(0.2).release(1.1)

$: note("g6 [~ fs6] [e6 d6] ~ [b5 ~] c6 [~ d6] [g5 ~]")
  .slow(2)
  .sound("square")
  .gain(0.055)
  .lpf(perlin.range(600, 1200).slow(5)).lpq(4)
  .tremolo(0.4).tremolosync(3)

