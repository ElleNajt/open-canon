setcps(72/60/4)

$: note("g3 fs3 e3 d3 b2 c3 d3 g2")
  .slow(2)
  .sound("triangle")
  .gain(0.24)
  .lpf(sine.range(320, 1800).slow(14))
  .room(0.45)

$: note("g4 fs4 e4 d4 b3 c4 d4 g3")
  .slow(2)
  .sound("sine")
  .gain(0.16)
  .delay(0.55).delaytime(0.5).delayfeedback(0.5)
  .pan(sine.range(0.3, 0.7).slow(10))

$: note("<g5 b5 d6> <fs5 a5 cs6> <e5 gs5 b5> <d5 fs5 a5> <b4 ds5 g5> <c5 e5 a5> <d5 fs5 b5> <g4 b4 d5>")
  .slow(2)
  .sound("sawtooth")
  .gain(0.09)
  .lpf(perlin.range(600, 2600).slow(6))
  .attack(0.15).release(0.9)

$: note("g6 [~ fs6] [e6 ~] d6 [~ b5] c6 [d6 ~] [~ g5]")
  .slow(2)
  .sound("square")
  .gain(0.065)
  .lpf(850).lpq(6)
  .tremolo(0.35).tremolosync(4)

$: note("~ [d4 ~] ~ [a3 ~] ~ [e4 ~] ~ [b3 ~]")
  .slow(2)
  .sound("sine")
  .gain(0.13)
  .attack(0.25).release(1.6)
  .room(0.55)

