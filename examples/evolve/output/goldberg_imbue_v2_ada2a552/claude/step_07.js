setcps(72/60/4)

$: note("g3 fs3 e3 d3 b2 c3 d3 g2")
  .slow(2)
  .sound("triangle")
  .gain(0.24)
  .lpf(sine.range(320, 1800).slow(12))
  .room(0.55)

$: note("g4 fs4 e4 d4 b3 c4 d4 g3")
  .slow(2)
  .sound("sine")
  .gain(0.16)
  .delay(0.55).delaytime(0.375).delayfeedback(0.48)
  .pan(sine.range(0.2, 0.8).slow(10))

$: note("<g5 b5 d6> <fs5 a5 e6> <e5 b5 d6> <d5 a5 cs6> <b4 g5 b5> <c5 e5 c6> <d5 b5 d6> <g4 d5 g5>")
  .slow(2)
  .sound("sawtooth")
  .gain(0.08)
  .lpf(perlin.range(600, 2400).slow(6))
  .attack(0.25).release(1.3)

$: note("g6 ~ [e6 ~] d6 ~ [b5 c6] ~ [g5 d6]")
  .slow(2)
  .sound("square")
  .gain(0.06)
  .lpf(1100).lpq(3)
  .tremolo(0.35).tremolosync(4)

$: note("~ [d4 g4] ~ ~ ~ [e4 b4] ~ [g3 d4]")
  .slow(2)
  .sound("sine")
  .gain(0.13)
  .attack(0.35).release(2.0)
  .room(0.5)

$: s("~ hh:1 ~ hh:0 ~ hh:2 ~ hh:1")
  .slow(2)
  .gain(0.06)
  .delay(0.4).delaytime(0.25).delayfeedback(0.35)
  .pan(rand.range(0.2, 0.8))