setcps(72/60/4)

$: note("g3 fs3 e3 d3 b2 c3 d3 g2")
  .slow(2)
  .sound("triangle")
  .gain(0.28)
  .lpf(sine.range(300, 1400).slow(12))
  .room(0.35)

$: note("g4 fs4 e4 d4 b3 c4 d4 g3")
  .slow(2)
  .sound("sine")
  .gain(0.2)
  .delay(0.55).delaytime(0.375).delayfeedback(0.5)

$: note("<g5 b5 d6> <fs5 a5 c6> <e5 g5 b5> <d5 fs5 a5> <b4 d5 g5> <c5 e5 a5> <d5 fs5 b5> <g4 b4 d5>")
  .slow(2)
  .sound("sawtooth")
  .gain(0.11)
  .lpf(perlin.range(600, 2200).slow(6))
  .attack(0.08)

$: note("g6 [~ fs6] [e6 ~] d6 [~ b5] c6 [d6 ~] [~ g5]")
  .slow(2)
  .sound("square")
  .gain(0.08)
  .lpf(1100).lpq(6)
  .pan(sine.range(0.3, 0.7).slow(8))

