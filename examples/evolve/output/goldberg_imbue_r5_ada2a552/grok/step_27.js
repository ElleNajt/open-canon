$: n("[0*2 3 5 ~] [7 9 11 ~] [2 4 6 ~]").euclid(4,16)
  .slow(3.5)
  .every(4, x => x.rev().add(12))
  .degradeBy(0.3)
  .scale("G:mixolydian")
  .sound("supersaw")
  .lpf(sine.range(400,3000).slow(6))
  .pan(cosine.range(0,1).slow(3))
  .room(0.45)
  .tremolo(0.4)
  .gain(0.6)

$: n("[5 ~ 10*3 ~] [2 4 7 ~] [0 9 11]").euclid(6,16)
