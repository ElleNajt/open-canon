setcps(108/60/4)
samples('shabda/speech:tidal_cycles,strudel,realtime,code_as_you_think,live,code,groove')

$: note("g3 [f3 d3] bb2 [a2 c3] [d3 g2] [f2 d2] bb1")
  .slow(2)
  .every(4, x => x.rev().add(12))
  .degradeBy(0.25)
  .scale("G:dorian")
  .sound("sawtooth")
  .lpf(sine.range(400, 3000).slow(4))
  .fmi(2)
  .gain(0.6)

$: note("g2 [f2 d2] bb1 [a1 c2] [d2 g1] [f1 d1] bb0")
  .slow(2)
  .sometimes(rev)
  .degradeBy(0.25)
  .sound("sine")
  .detune(rand.range(-20, 30).slow(3))
  .hpf(180)
  .delay(0.2)
  .room(0.3)
  .gain(0.4)

$: stack(
  s("bd ~ bd bd").euclid(7, 16).fast(1.5),
  s("~ sn [sn ~]").euclid(5, 16).fast(1.5).hpf(280),
  s("hh*8 [oh*16 ~]? [cp*4 rd*8]").pan(saw.range(0.1, 0.9)).degradeBy(0.35),
  s("lt*4 ~").gain(0.5)
)
.swing(0.3)
.phaser(0.5)
.delay(0.25)
.room(0.35)
.gain(0.8)

$: n("~0 [7 5] 2~[9 12] [14 16], [7 9] 0~12, [2 4] ~[7 9] [0 5]")
