setcps(200/60/4)
samples('shabda/speech:tidal_cycles,strudel,realtime,code_as_you_think,live,code,groove')

$: n("[0*8 [2 7]*4] [[14 11] 16*3] [12*3 [5 9]*2 ~]").euclid(5,16)
  .slow(4)
  .every(4, x => x.rev().add(12))
  .scale("G:mixolydian")
  .sound("supersaw")
  .lpf(saw.range(500,12000).slow(2))
  .pan(rand.range(0,1))
  .distort(0.25)
  .room(0.85)
  .gain(0.8)

$: n("[2*8 ~ [9 4]*4] [7*5 11*3 ~]").euclid(3,16)
  .slow(2)
  .jux(rev)
  .scale("G:mixolydian")
  .sound("pulse")
  .fm(0.6)
  .lpf(cosine.range(100,5000).slow(2))
  .ring(0.5)
  .room(0.75)
  .gain(0.75)

$: stack(
  s("bd*4 [~ bd*3] bd").euclid(5,16).fast(1.5),
  s("[sn*2 cp ~] [sn*3 ~ cp]").euclid(3,16).fast(4).hpf(2500).shape(0.6).gain(0.65),
  s("hh*16? [oh*8 ~ oh*8]").pan(tri.range(0,1).fast(8)).degradeBy(0.3).gain(0.5),
  s("[~ lt*3 [ht mt]*2]").slow(2).gain(0.55)
)
.swing(0.4)
.echo(4, 0.125, 0.5)
.compressor("0.4:3:0.1:0.02:0.15")
.room(0.75)
.gain(0.8)

$: n("[~ [0 4]*8] [[9 12 2]*2 7*4] [0*5 ~]").euclid(7,16)
  .scale("G:mixolydian")
  .add(-7)
  .fast(4)
  .sound("triangle")
  .hpf(150)
  .tremolo(0.5)
  .penv(0.4)
  .room(0.7)
  .gain(0.7)

$: s("[[strudel*2 live code_as_you_think] [tidal_cycles realtime*2 groove live*2] [code*4 strudel*3 ~ realtime]]")
  .slow(1.5)
  .sometimesBy(0.3, rev)
  .every(8, x=>x.ply(2).fast(1.5))
  .chop(64)
  .speed(sine.range(0.75,1.35).slow(4))
  .vowel("e a i o")
  .room(0.95)
  .gain(0.8)

$: n("[[12*2 9 14]*3 ~] [[2 5 11]*3] [7*4 [4 0*2]*2 ~]")
  .scale("G:mixolydian")
  .fast(3)
  .every(4, x => x.rev().add(-5))
  .degradeBy(0.3)
  .sound("sine")
  .lpf(saw.range(300,8000).slow(4))
  .pan(cosine.range(0.2,0.8))
  .fm(0.3)
  .room(0.8)
  .gain(0.7)