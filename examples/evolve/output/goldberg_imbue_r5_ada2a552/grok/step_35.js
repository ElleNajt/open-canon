setcps(145/60/4)
samples('shabda/speech:tidal_cycles,strudel,realtime,code_as_you_think,live,code,groove')

$: n("[0*5 ~ 7*2] [14 11 ~ 9] [12*4 ~]").euclid(8,16)
  .slow(4)
  .every(4, x => x.rev().add(12))
  .scale("G:mixolydian")
  .sound("supersaw")
  .lpf(sine.range(300,5000).slow(3))
  .pan(rand.range(0,1).slow(2.5))
  .phaser(sine.range(0.1,1).slow(4))
  .room(0.45)
  .gain(0.75)

$: n("[2*4 ~ 9] [4*3 7*2 ~]").euclid(5,16)
  .slow(3)
  .juxBy(-0.2, rev)
  .every(4, rev)
  .scale("G:mixolydian")
  .sound("square")
  .detune(saw.range(-30,40).slow(4))
  .lpf(tri.range(200,2000).slow(3.5))
  .distort(0.3)
  .room(0.25)
  .gain(0.6)

$: stack(
  s("bd*3, [~ bd*2 bd]").euclid(9,16).fast(2),
  s("[~ sn cp*2]").euclid(7,16).fast(1.8).hpf(2000).crush(4).gain(0.8),
  s("hh*12? [oh*3 ~*5]").pan(sine.range(0,1).fast(5)).degradeBy(0.35),
  s("[lt ~*2 ht*3 mt]").gain(0.55)
)
.swing(0.28)
.delay(0.4)
.phaser(0.6)
.room(0.55)
.gain(0.8)

$: n("[~ 0*4 5*2] [9 ~ 12 2*2] [7*2 ~]")
