setcps(150/60/4)
samples('shabda/speech:tidal_cycles,strudel,realtime,code_as_you_think,live,code,groove')

$: n("[0*4 ~ 7*3] [14 11 9 ~] [12*3 ~]").euclid(7,16)
  .slow(3.5)
  .every(5, x => x.rev().add(7))
  .scale("G:mixolydian")
  .sound("supersaw")
  .lpf(sine.range(400,6000).slow(2.5))
  .pan(rand.range(0,1).slow(3))
  .tremolo(sine.range(0.3,0.8).slow(4))
  .room(0.5)
  .gain(0.8)

$: n("[2*3 ~ 9*2] [4*4 7 ~]").euclid(6,16)
  .slow(2.5)
  .juxBy(-0.3, rev)
  .every(3, rev)
  .scale("G:mixolydian")
  .sound("square")
  .detune(saw.range(-20,50).slow(3))
  .lpf(tri.range(300,2500).slow(4))
  .crush(4)
  .room(0.3)
  .gain(0.65)

$: stack(
  s("bd*3, [~ bd*3]").euclid(8,16).fast(1.5),
  s("[~ sn*2 cp]").euclid(6,16).fast(1.9).hpf(1800).crush(4).gain(0.85),
  s("hh*10? [oh*4 ~*4]").pan(sine.range(0,1).fast(4.5)).degradeBy(0.4),
  s("[lt*2 ~ ht mt]").gain(0.6)
)
.swing(0.3)
.delay(0.35)
.crush(3)
.room(0.6)
.gain(0.85)

