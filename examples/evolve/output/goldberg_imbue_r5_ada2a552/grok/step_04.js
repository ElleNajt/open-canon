setcps(80/60/4)

$: note("g3 gb3 e3 d3 bb2 c3 d3 g2")
  .slow(2)
  .every(4, rev())
  .sound("triangle")
  .lpf(perlin.range(600, 1200))
  .lpq(3)
  .gain(0.55)

$: note("g2 gb2 e2 d2 bb1 c2 d2 g1")
  .slow(2)
  .sound("sine")
  .detune(sine.range(-20, 20).slow(4))
  .lpf(350)
  .delay(0.2)
  .gain(0.28)

$: stack(
  s("bd").euclid(5,16),
  s("sn").euclid(3,16).fast(2).hpf(250),
  s("hh*8? oh*4").pan(rand.range(0.2,0.8)).degradeBy(0.2)
)
.swing(0.08)
.phaser(0.3)
.gain(0.7)
.room(0.2)

