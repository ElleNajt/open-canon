setcps(98/60/4)
samples('shabda/speech:tidal_cycles,strudel,realtime,code_as_you_think,live,code,groove')

$: note("ab3 [g3 eb3] c3 [bb2 d3] [f3 ab2] [g2 eb2] bb1")
  .slow(1.5)
  .every(4, rev)
  .degradeBy(0.25)
  .sound("triangle")
  .lpf(saw.range(350, 3000).slow(4))
  .lpq(4)
  .tremolo(0.3)
  .gain(0.6)

$: note("ab2 [g2 eb2] c2 [bb1 d2] [f2 ab1] [g1 eb1] bb0")
  .slow(1.5)
  .sometimes(rev)
  .degradeBy(0.15)
  .sound("sine")
  .detune(sine.range(-20, 30).slow(3))
  .hpf(180)
  .delay(0.3)
  .room(0.3)
  .gain(0.3)

$: stack(
  s("bd bd ~ bd").euclid(6, 16).fast(2),
  s("~ sn sn").euclid(4, 16).fast(2).hpf(300),
  s("hh*16 [oh*8 cp*4]? ~ [rd*8 cp*8]").pan(tri.range(0.2, 0.8)).degradeBy(0.35)
)
.swing(0.2)
.phaser(0.5)

.room(0.4)
.gain(0.7)

