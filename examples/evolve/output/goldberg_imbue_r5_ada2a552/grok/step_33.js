setcps(145/60/4)
samples('shabda/speech:tidal_cycles,strudel,realtime,code_as_you_think,live,code,groove')

$: n("[0*3 ~ 5 9] [12 ~ 7 10] [14*2 ~]").euclid(8,16)
  .slow(2.5)
  .every(4, x => x.rev().add(12))
  .scale("G:mixolydian")
  .sound("supersaw")
  .lpf(sine.range(500,4500).slow(3))
  .pan(rand.range(0,1).slow(4))
  .phaser(sine.range(0.2,1.5).slow(2))
  .room(0.35)
  .gain(0.65)

$: n("[2*4 ~ 7 9] [11*2 4 ~]").euclid(5,16)
  .slow(3)
  .juxBy(-0.2, rev)
  .every(4, rev)
  .degradeBy(0.3)
  .scale("G:mixolydian")
  .sound("square")
  .detune(perlin.range(-30,60).slow(4))
  .lpf(saw.range(400,2000).fast(3))
  .drive(0.3)
  .room(0.25)
  .gain(0.5)

$: stack(
  s("bd*4, [bd bd ~]").euclid(7,16).fast(2.2),
  s("[sn cp*2 sn ~]").euclid(5,16).fast(1.8).hpf(2000).crush(4).gain(0.8),
  s("hh*8? [oh*16 ~]").pan(sine.range(0,1).fast(8)).degradeBy(0.5),
  s("[ht ~ mt*2 lt]").gain(0.45)
)
.swing(0.25)
.delay(0.4)
.leslie(0.4)
.room(0.45)
.gain(0.8)

