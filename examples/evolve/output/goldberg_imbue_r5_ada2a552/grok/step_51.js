$: n("[0*4,2*3 7*5] [14*3 11*2 16*4] [12*3 5*4 9*2 ~]").euclid(7,16)
  .slow(4)
  .every(3, x => x.rev().add(7))
  .scale("G:mixolydian")
  .sound("sawtooth")
  .lpf(sine.range(400,12000).slow(3))
  .distort(0.25)
  .pan(sine.range(0.2,0.8).slow(6))
  .room(0.85)
  .gain(0.8)

