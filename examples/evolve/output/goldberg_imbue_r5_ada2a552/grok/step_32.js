setcps(140/60/4)
samples('shabda/speech:tidal_cycles,strudel,realtime,code_as_you_think,live,code,groove')

$: n("[0*2 ~ 5 7] [9 12 ~ 3] [10*2 14 ~]").euclid(7,16)
  .slow(3)
  .every(4, x => x.rev().add(12))
  .scale("G:mixolydian")
  .sound("supersaw")
  .lpf(sine.range(400,4000).slow(2))
  .pan(rand.range(0,1).slow(2))
  .fmi(cosine.range(0.5,2).slow(4))
  .room(0.3)
  .gain(0.6)

$: n("[2*3 7 ~ 9] [4 11 ~]").euclid(3,16)
  .slow(2.5)
  .juxBy(-0.15, rev)
  .every(4, rev)
  .degradeBy(0.4)
  .scale("G:mixolydian")
  .sound("square")
  .detune(perlin.range(-40,80).slow(3))
  .lpf(saw.range(500,1500).fast(4))
  .shape(0.25)
  .room(0.25)
  .gain(0.45)

$: stack(
  s("bd*4, [bd ~ bd]").euclid(6,16).fast(2.1),
  s("[sn cp*2 ~ sn]").euclid(8,16).fast(2).hpf(2500).crush(3).gain(0.85),
  s("hh*16, oh*8?").pan(sine.range(0,1).fast(6)).degradeBy(0.65),
  s("[ht mt lt*2 ~] cb?").gain(0.5)
)
.swing(0.3)
.delay(0.35)
.leslie(0.3)
.room(0.4)
.gain(0.75)

$: n("[~ 0*4 5] [3*2 7 10 ~] [2 12 ~]")
  .scale("G:mixolydian")
  .add(-12)
  .fast(1.8)
  .sound("triangle")
  .lpf(350)
  .detune(sine.range(-20,20).slow(4))
  .pan(rand.range(0,1))
  .room(0.3)
  .gain(0.55)

$: s("[strudel*3 live ~] [tidal_cycles code_as_you_think] [realtime*2 groove] [code*4 live]")
  .slow(1.05)
  .sometimesBy(0.6, rev)
  .sometimesBy(0.25, x=>x.ply(3))
  .chop(24)
  .speed(perlin.range(0.7,1.4).slow(2.5))
  .pan(sine.range(0.1,0.9))
  .vowel("a e i o")
  .gain(0.5)

$: n("[9*3 ~ 12] [14*2 4 8 ~] [5 2 11] [7*2 10 3 ~]")
  .scale("G:mixolydian")
  .fast(4)
  .every(4, x => x.palindrome().add(5))
  .degradeBy(0.15)
  .sound("pulse")
  .lpf(tri.range(600,2500).slow(4))
  .shape(0.4)
  .fmi(sine.range(1,3).slow(3))
  .room(0.25)
  .gain(0.55)