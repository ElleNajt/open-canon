setcps(168/60/4)
samples('shabda/speech:tidal_cycles,strudel,realtime,code_as_you_think,live,code,groove')

$: n("[0*4 5 ~] [9*2 12 ~] [3 7 10]").euclid(5,16)
  .slow(4)
  .every(4, x => x.rev().add(7))
  .scale("G:mixolydian")
  .sound("supersaw")
  .lpf(sine.range(300,3000).slow(4))
  .pan(rand.range(0,1))
  .tremolo(0.4)
  .gain(0.55)

$: n("[4 9*3 ~] [2 7 11 ~]").euclid(5,16)
  .slow(2)
  .every(5, rev)
  .degradeBy(0.25)
  .scale("G:mixolydian")
  .sound("square")
  .detune(perlin.range(-30,60).slow(4))
  .lpf(cosine.range(400,800))
  .distort(0.25)
  .gain(0.5)

$: stack(
  s("bd*3 [~ bd] bd").euclid(7,16).fast(1.75),
  s("[~ sn*2 cp*2] ~").euclid(9,16).fast(2.25).hpf(2000).crush(4).gain(0.8),
  s("hh*14?").pan(sine.range(0,1).fast(4)).degradeBy(0.6),
  s("[~ ht*3 lt mt]").gain(0.45)
)
.swing(0.3)
.delay(0.3)

.leslie(0.4)
.gain(0.7)

$: n("~ [5*3 10 3] [7*2 0 9] [2 ~ 12]")
  .scale("G:mixolydian")
  .add(-12)
  .fast(1.5)
  .sound("triangle")
  .lpf(450)
  .hpf(50)
  .pan(sine.slow(4))
  .room(0.35)
  .gain(0.6)

$: s("[tidal_cycles*4 strudel*3] [live*3 code_as_you_think] [realtime*2 ~] [groove*2 live code]")
  .slow(1.25)
  .sometimesBy(0.5, rev)
  .sometimesBy(0.3, x=>x.ply(2))
  .chop(16)
  .speed(perlin.range(0.8,1.3).slow(3))
  .pan(rand.range(0.2,0.8))
  .hpf(200)
  .gain(0.45)

$: n("[12*4 9 ~] [14 4*3 8] [5 11 2 ~] [7 10 3]")
  .scale("G:mixolydian")
  .fast(4)
  .every(4, x => x.rev().add(5))
  .degradeBy(0.15)
  .sound("pulse")
  .lpf(saw.range(500,2000).slow(3))
  .shape(0.3)
  .fmi(1.2)
