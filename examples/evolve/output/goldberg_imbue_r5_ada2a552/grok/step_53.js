$: n("[0*4,2*3 7*5] [14*3 11*2 16*4] [12*3 5*4 9*2 ~]").euclid(3,16)
  .slow(2)
  .every(4, x => x.rev().add(7))
  .scale("G:mixolydian")
  .sound("supersaw")
  .lpf(sine.range(300,14000).slow(4))
  .pan(rand.range(0.1,0.9))
  .phaser(0.3)
  .room(0.8)
  .gain(0.85)

$: n("[2*4 ~ 9*5] [4*3 7*4 11*2]").euclid(7,16)
  .slow(3)
