setcps(120/60/4)

// Baroque style voices
let upperVoice = x => x
  .sound("triangle")
  .gain(0.45)
  .attack(0.02)
  .decay(0.15)
  .sustain(0.2)
  .lpf(sine.range(1200, 2600).slow(32))
  .room(0.4)
  .size(0.7)

let midVoice = x => x
  .sound("sine")
  .gain(0.36)
  .attack(0.04)
  .decay(0.2)
  .sustain(0.25)
  .lpf(1600)
  .room(0.28)
  .size(0.55)

let lowerVoice = x => x
  .sound("square")
  .gain(0.28)
  .decay(0.25)
  .sustain(0.18)
  .lpf(sine.range(400, 900).slow(20))
  .lpq(4)
  .room(0.22)
  .size(0.6)

// Track 1 - upper voice, ornamental line — thinned delay, subtle echo tail
$: note("g5 ~ b5 ~ d6 ~ g6 ~ d6 ~ b5 ~ g5 ~ d6 ~ d5 ~ gb5 ~ a5 ~ db5 ~ e5 ~ g5 ~ db6 ~!3 d6 ~ a5 ~ gb5 ~ d5 ~ g5 ~ b5 ~ d6 ~ g5 ~ e6 ~ c6 ~ a5 ~ c6 ~ gb5 ~ a5 ~ d6 c6 b5 a5 g5 ~ b5 ~ d6 ~ g6 ~ d6 ~ b5 ~ g5 ~ d6 ~ d5 ~ gb5 ~ a5 ~ db5 ~ e5 ~ g5 ~ db6 ~!3 d6 ~ a5 ~ gb5 ~ d5 ~ g5 ~ b5 ~ d6 ~ g5 ~ e6 ~ c6 ~ a5 ~ c6 ~ gb5 ~ a5 ~ d6 c6 b5 a5 g5 ~!7")
  .slow(132/8/4)
  .apply(upperVoice)
  .pan(0.28)
  .penv(0.4)
  .pattack(0.01)
  .pdecay(0.12)
  .delay(0.18)
  .delaytime(0.375)
  .delayfeedback(0.22)
  .tremolo(0.09)
  .tremolosync(16)
  .tremoloshape("sine")
  .off(0.25, x => x.gain(0.12).transpose(7).pan(0.72).lpf(1400).delay(0.04).delaytime(0.75))
  .juxBy(0.18, x => x.rev().lpf(900).gain(0.08))

// Track 2 - canonic entry, one octave lower, vowel morph, phaser separates timbre
$: note("~!2 g5 ~ b5 ~ d6 ~ g6 ~ d6 ~ b5 ~ g5 ~ d6 ~ d5 ~ gb5 ~ a5 ~ db5 ~ e5 ~ g5 ~ db6 ~!3 d6 ~ a5 ~ gb5 ~ d5 ~ g5 ~ b5 ~ d6 ~ g5 ~ e6 ~ c6 ~ a5 ~ c6 ~ gb5 ~ a5 ~ d6 c6 b5 a5 g5 ~ b5 ~ d6 ~ g6 ~ d6 ~ b5 ~ g5 ~ d6 ~ d5 ~ gb5 ~ a5 ~ db5 ~ e5 ~ g5 ~ db6 ~!3 d6 ~ a5 ~ gb5 ~ d5 ~ g5 ~ b5 ~ d6 ~ g5 ~ e6 ~ c6 ~ a5 ~ c6 ~ gb5 ~ a5 ~ d6 c6 b5 a5 g5 ~!5")
  .slow(132/8/4)
  .apply(midVoice)
  .pan(0.68)
  .transpose(-12)
  .lpf(sine.range(500, 1800).slow(44))
  .vowel("<a e i o u>".slow(16))
  .phaser(0.14)
  .phaserdepth(0.35)
  .phasercenter(800)
  .room(0.42)
  .size(0.6)
  .echo(2, 0.125, 0.18)

// Track 3 - inner voice, FM shimmer, fmh slowly walks harmonic series
$: note("<d4 c4 b3 a3> ~ <b4 a4 g4 gb4> ~ <g4 gb4 e4 d4> ~ <e4 d4 c4 b3>")
  .slow(18)
  .sound("sine")
  .gain(0.22)
  .attack(0.22)
  .decay(0.7)
  .sustain(0.24)
  .release(1.6)
  .lpf(sine.range(350, 1100).slow(36))
  .fmi(sine.range(0.3, 4.2).slow(40))
  .fmh("<2 3 5 7 5 3 2>".slow(48))
  .fmdecay(1.1)
  .fmsustain(0.12)
  .phaser(0.12)
  .phaserdepth(0.8)
  .phasercenter(sine.range(400, 900).slow(29))
  .pan(sine.range(0.32, 0.68).slow(23))
  .room(0.65)
  .size(0.9)
  .delay(0.12)
  .delaytime(0.5)
  .delayfeedback(0.3)

// Track 4 - bass, pedal drone with walking fifth
$: note("g2 ~!7 gb2 ~!7 e2 ~!7 d2 ~!7 b1 ~!7 c2 ~!7 d2 ~!7 g2 ~!7 g2 ~!7 gb2 ~!7 e2 ~!7 d2 ~!7 b1 ~!7 c2 ~!7 d2 ~!7 g2 ~!7")
  .slow(132/8/4)
  .apply(lowerVoice)
  .pan(0.5)
  .shape(0.12)
  .drive(0.06)
  .off(0.5, x => x.transpose(7).gain(0.16).lpf(480).pan(0.38).attack(0.08))
  .off(1, x => x.transpose(19).gain(0.07).lpf(300).pan(0.62).sound("triangle").room(0.6).decay(0.55))
  .room(0.32)
  .size(0.72)
  .hpf(40)
  .every(4, x => x.sometimes(y => y.transpose(-12).gain(0.18).lpf(200)))