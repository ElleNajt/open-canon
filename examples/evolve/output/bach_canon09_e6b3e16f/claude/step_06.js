setcps(120/60/4)

// Baroque style voices
let upperVoice = x => x
  .sound("triangle")
  .gain(0.45)
  .attack(0.02)
  .decay(0.15)
  .sustain(0.2)
  .lpf(sine.range(1200, 2600).slow(32))
  .room(0.4)
  .size(0.7)

let midVoice = x => x
  .sound("sine")
  .gain(0.36)
  .attack(0.04)
  .decay(0.2)
  .sustain(0.25)
  .lpf(1600)
  .room(0.28)
  .size(0.55)

let lowerVoice = x => x
  .sound("square")
  .gain(0.32)
  .decay(0.25)
  .sustain(0.18)
  .lpf(sine.range(400, 900).slow(20))
  .lpq(4)
  .room(0.22)
  .size(0.6)

// Track 1 - upper voice, ornamental line — narrowed trem, richer echo shadow
$: note("g5 ~ b5 ~ d6 ~ g6 ~ d6 ~ b5 ~ g5 ~ d6 ~ d5 ~ gb5 ~ a5 ~ db5 ~ e5 ~ g5 ~ db6 ~!3 d6 ~ a5 ~ gb5 ~ d5 ~ g5 ~ b5 ~ d6 ~ g5 ~ e6 ~ c6 ~ a5 ~ c6 ~ gb5 ~ a5 ~ d6 c6 b5 a5 g5 ~ b5 ~ d6 ~ g6 ~ d6 ~ b5 ~ g5 ~ d6 ~ d5 ~ gb5 ~ a5 ~ db5 ~ e5 ~ g5 ~ db6 ~!3 d6 ~ a5 ~ gb5 ~ d5 ~ g5 ~ b5 ~ d6 ~ g5 ~ e6 ~ c6 ~ a5 ~ c6 ~ gb5 ~ a5 ~ d6 c6 b5 a5 g5 ~!7")
  .slow(132/8/4)
  .apply(upperVoice)
  .pan(0.28)
  .delay(0.2)
  .delaytime(0.375)
  .delayfeedback(0.28)
  .tremolo(0.15)
  .tremolosync(8)
  .tremoloshape("sine")
  .off(0.25, x => x.gain(0.18).transpose(7).pan(0.72).lpf(2200).delay(0.08).delaytime(0.75))

// Track 2 - canonic entry, dropped octave for density, vowel morph retained
$: note("~!2 g5 ~ b5 ~ d6 ~ g6 ~ d6 ~ b5 ~ g5 ~ d6 ~ d5 ~ gb5 ~ a5 ~ db5 ~ e5 ~ g5 ~ db6 ~!3 d6 ~ a5 ~ gb5 ~ d5 ~ g5 ~ b5 ~ d6 ~ g5 ~ e6 ~ c6 ~ a5 ~ c6 ~ gb5 ~ a5 ~ d6 c6 b5 a5 g5 ~ b5 ~ d6 ~ g6 ~ d6 ~ b5 ~ g5 ~ d6 ~ d5 ~ gb5 ~ a5 ~ db5 ~ e5 ~ g5 ~ db6 ~!3 d6 ~ a5 ~ gb5 ~ d5 ~ g5 ~ b5 ~ d6 ~ g5 ~ e6 ~ c6 ~ a5 ~ c6 ~ gb5 ~ a5 ~ d6 c6 b5 a5 g5 ~!5")
  .slow(132/8/4)
  .apply(midVoice)
  .pan(0.68)
  .transpose(-12)
  .lpf(sine.range(500, 1600).slow(44))
  .vowel("<a e i o u>".slow(12))
  .room(0.42)
  .size(0.6)

// Track 3 - inner voice, FM shimmer with slow phaser sweep, more harmonic motion
$: note("<d4 c4 b3 a3> ~ <b4 a4 g4 gb4> ~ <g4 gb4 e4 d4> ~ <e4 d4 c4 b3>")
  .slow(14)
  .sound("sine")
  .gain(0.28)
  .attack(0.1)
  .decay(0.4)
  .sustain(0.35)
  .release(0.6)
  .lpf(sine.range(500, 1600).slow(30))
  .fmi(sine.range(0.4, 3.2).slow(22))
  .fmh("<2 3 5 7>".slow(28))
  .fmdecay(0.6)
  .phaser(0.25)
  .phaserdepth(0.7)
  .phasercenter(800)
  .pan(sine.range(0.38, 0.62).slow(19))
  .room(0.45)
  .size(0.75)

// Track 4 - bass, pedal motion with fifth drone and gentle distortion warmth
$: note("g2 ~!7 gb2 ~!7 e2 ~!7 d2 ~!7 b1 ~!7 c2 ~!7 d2 ~!7 g2 ~!7 g2 ~!7 gb2 ~!7 e2 ~!7 d2 ~!7 b1 ~!7 c2 ~!7 d2 ~!7 g2 ~!7")
  .slow(132/8/4)
  .apply(lowerVoice)
  .pan(0.5)
  .shape(0.12)
  .off(0.5, x => x.transpose(7).gain(0.18).lpf(520).pan(0.4).attack(0.06))
  .off(1, x => x.transpose(19).gain(0.09).lpf(400).pan(0.6).sound("triangle").room(0.45))
  .room(0.3)
  .size(0.65)
  .hpf(48)