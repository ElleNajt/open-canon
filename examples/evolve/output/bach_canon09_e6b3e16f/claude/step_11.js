setcps(120/60/4)

// Baroque style voices
let upperVoice = x => x
  .sound("triangle")
  .gain(0.45)
  .attack(0.02)
  .decay(0.15)
  .sustain(0.2)
  .lpf(sine.range(1200, 2600).slow(32))
  .room(0.4)
  .size(0.7)

let midVoice = x => x
  .sound("sine")
  .gain(0.36)
  .attack(0.04)
  .decay(0.2)
  .sustain(0.25)
  .lpf(1600)
  .room(0.28)
  .size(0.55)

let lowerVoice = x => x
  .sound("square")
  .gain(0.28)
  .decay(0.25)
  .sustain(0.18)
  .lpf(sine.range(400, 900).slow(20))
  .lpq(4)
  .room(0.22)
  .size(0.6)

// Track 1 - upper voice, ornamental line
$: note("g5 ~ b5 ~ d6 ~ g6 ~ d6 ~ b5 ~ g5 ~ d6 ~ d5 ~ gb5 ~ a5 ~ db5 ~ e5 ~ g5 ~ db6 ~!3 d6 ~ a5 ~ gb5 ~ d5 ~ g5 ~ b5 ~ d6 ~ g5 ~ e6 ~ c6 ~ a5 ~ c6 ~ gb5 ~ a5 ~ d6 c6 b5 a5 g5 ~ b5 ~ d6 ~ g6 ~ d6 ~ b5 ~ g5 ~ d6 ~ d5 ~ gb5 ~ a5 ~ db5 ~ e5 ~ g5 ~ db6 ~!3 d6 ~ a5 ~ gb5 ~ d5 ~ g5 ~ b5 ~ d6 ~ g5 ~ e6 ~ c6 ~ a5 ~ c6 ~ gb5 ~ a5 ~ d6 c6 b5 a5 g5 ~!7")
  .slow(132/8/4)
  .apply(upperVoice)
  .pan(0.28)
  .penv(0.5)
  .pattack(0.01)
  .pdecay(0.18)
  .delay(0.22)
  .delaytime(0.375)
  .delayfeedback(0.28)
  .tremolo(0.12)
  .tremolosync(16)
  .tremoloshape("sine")
  .off(0.25, x => x.gain(0.1).transpose(7).pan(0.72).lpf(1100).delay(0.05).delaytime(0.75))
  .every(6, x => x.juxBy(0.3, y => y.rev().lpf(800).gain(0.07)))

// Track 2 - canonic entry, octave lower, vowel morph
$: note("~!2 g5 ~ b5 ~ d6 ~ g6 ~ d6 ~ b5 ~ g5 ~ d6 ~ d5 ~ gb5 ~ a5 ~ db5 ~ e5 ~ g5 ~ db6 ~!3 d6 ~ a5 ~ gb5 ~ d5 ~ g5 ~ b5 ~ d6 ~ g5 ~ e6 ~ c6 ~ a5 ~ c6 ~ gb5 ~ a5 ~ d6 c6 b5 a5 g5 ~ b5 ~ d6 ~ g6 ~ d6 ~ b5 ~ g5 ~ d6 ~ d5 ~ gb5 ~ a5 ~ db5 ~ e5 ~ g5 ~ db6 ~!3 d6 ~ a5 ~ gb5 ~ d5 ~ g5 ~ b5 ~ d6 ~ g5 ~ e6 ~ c6 ~ a5 ~ c6 ~ gb5 ~ a5 ~ d6 c6 b5 a5 g5 ~!5")
  .slow(132/8/4)
  .apply(midVoice)
  .pan(0.68)
  .transpose(-12)
  .lpf(sine.range(400, 1800).slow(52))
  .vowel("<a e i o u a>".slow(20))
  .phaser(0.22)
  .phaserdepth(0.7)
  .phasercenter(sine.range(500, 1400).slow(31))
  .room(0.55)
  .size(0.7)
  .echo(2, 0.125, 0.12)

// Track 3 - inner voice, FM shimmer, slowly walking harmonic series
$: note("<d4 c4 b3 a3> ~ <b4 a4 g4 gb4> ~ <g4 gb4 e4 d4> ~ <e4 d4 c4 b3>")
  .slow(18)
  .sound("sine")
  .gain(0.22)
  .attack(0.5)
  .decay(1.2)
  .sustain(0.18)
  .release(3.0)
  .lpf(sine.range(200, 1100).slow(42))
  .fmi(sine.range(0.3, 4.2).slow(56))
  .fmh("<2 3 5 7 5 3 4>".slow(60))
  .fmdecay(1.8)
  .fmsustain(0.06)
  .phaser(0.11)
  .phaserdepth(1.4)
  .phasercenter(sine.range(300, 950).slow(37))
  .pan(sine.range(0.22, 0.78).slow(29))
  .room(0.78)
  .size(0.95)
  .delay(0.18)
  .delaytime(0.667)
  .delayfeedback(0.38)
  .juxBy(0.4, x => x.slow(1.5).lpf(600).gain(0.1))

// Track 4 - bass, pedal drone with walking fifth
$: note("g2 ~!7 gb2 ~!7 e2 ~!7 d2 ~!7 b1 ~!7 c2 ~!7 d2 ~!7 g2 ~!7 g2 ~!7 gb2 ~!7 e2 ~!7 d2 ~!7 b1 ~!7 c2 ~!7 d2 ~!7 g2 ~!7")
  .slow(132/8/4)
  .apply(lowerVoice)
  .pan(0.5)
  .shape(0.18)
  .drive(0.12)
  .off(0.5, x => x.transpose(7).gain(0.16).lpf(500).pan(0.36).attack(0.08))
  .off(1, x => x.transpose(19).gain(0.07).lpf(280).pan(0.64).sound("triangle").room(0.75).decay(0.9))
  .room(0.4)
  .size(0.8)
  .hpf(42)
  .every(5, x => x.sometimes(y => y.transpose(-12).gain(0.16).lpf(180)))
  .every(7, x => x.rarely(y => y.crush(10).gain(0.22)))
  .every(12, x => x.juxBy(0.25, y => y.lpf(200).gain(0.08).pan(0.8)))