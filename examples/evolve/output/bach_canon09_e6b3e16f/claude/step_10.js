setcps(120/60/4)

// Baroque style voices
let upperVoice = x => x
  .sound("triangle")
  .gain(0.45)
  .attack(0.02)
  .decay(0.15)
  .sustain(0.2)
  .lpf(sine.range(1200, 2600).slow(32))
  .room(0.4)
  .size(0.7)

let midVoice = x => x
  .sound("sine")
  .gain(0.36)
  .attack(0.04)
  .decay(0.2)
  .sustain(0.25)
  .lpf(1600)
  .room(0.28)
  .size(0.55)

let lowerVoice = x => x
  .sound("square")
  .gain(0.28)
  .decay(0.25)
  .sustain(0.18)
  .lpf(sine.range(400, 900).slow(20))
  .lpq(4)
  .room(0.22)
  .size(0.6)

// Track 1 - upper voice, ornamental line
$: note("g5 ~ b5 ~ d6 ~ g6 ~ d6 ~ b5 ~ g5 ~ d6 ~ d5 ~ gb5 ~ a5 ~ db5 ~ e5 ~ g5 ~ db6 ~!3 d6 ~ a5 ~ gb5 ~ d5 ~ g5 ~ b5 ~ d6 ~ g5 ~ e6 ~ c6 ~ a5 ~ c6 ~ gb5 ~ a5 ~ d6 c6 b5 a5 g5 ~ b5 ~ d6 ~ g6 ~ d6 ~ b5 ~ g5 ~ d6 ~ d5 ~ gb5 ~ a5 ~ db5 ~ e5 ~ g5 ~ db6 ~!3 d6 ~ a5 ~ gb5 ~ d5 ~ g5 ~ b5 ~ d6 ~ g5 ~ e6 ~ c6 ~ a5 ~ c6 ~ gb5 ~ a5 ~ d6 c6 b5 a5 g5 ~!7")
  .slow(132/8/4)
  .apply(upperVoice)
  .pan(0.28)
  .penv(0.5)
  .pattack(0.01)
  .pdecay(0.18)
  .delay(0.22)
  .delaytime(0.375)
  .delayfeedback(0.28)
  .tremolo(0.12)
  .tremolosync(16)
  .tremoloshape("sine")
  .off(0.25, x => x.gain(0.1).transpose(7).pan(0.72).lpf(1100).delay(0.05).delaytime(0.75))
  .every(6, x => x.juxBy(0.3, y => y.rev().lpf(800).gain(0.07)))

// Track 2 - canonic entry, octave lower, vowel morph
$: note("~!2 g5 ~ b5 ~ d6 ~ g6 ~ d6 ~ b5 ~ g5 ~ d6 ~ d5 ~ gb5 ~ a5 ~ db5 ~ e5 ~ g5 ~ db6 ~!3 d6 ~ a5 ~ gb5 ~ d5 ~ g5 ~ b5 ~ d6 ~ g5 ~ e6 ~ c6 ~ a5 ~ c6 ~ gb5 ~ a5 ~ d6 c6 b5 a5 g5 ~ b5 ~ d6 ~ g6 ~ d6 ~ b5 ~ g5 ~ d6 ~ d5 ~ gb5 ~ a5 ~ db5 ~ e5 ~ g5 ~ db6 ~!3 d6 ~ a5 ~ gb5 ~ d5 ~ g5 ~ b5 ~ d6 ~ g5 ~ e6 ~ c6 ~ a5 ~ c6 ~ gb5 ~ a5 ~ d6 c6 b5 a5 g5 ~!5")
  .slow(132/8/4)
  .apply(midVoice)
  .pan(0.68)
  .transpose(-12)
  .lpf(sine.range(400, 1600).slow(52))
  .vowel("<a e i o u a>".slow(20))
  .phaser(0.18)
  .phaserdepth(0.55)
  .phasercenter(sine.range(600, 1200).slow(31))
  .room(0.5)
  .size(0.65)
  .echo(2, 0.125, 0.15)

// Track 3 - inner voice, FM shimmer, slowly walking harmonic series
$: note("<d4 c4 b3 a3> ~ <b4 a4 g4 gb4> ~ <g4 gb4 e4 d4> ~ <e4 d4 c4 b3>")
  .slow(18)
  .sound("sine")
  .gain(0.19)
  .attack(0.35)
  .decay(0.9)
  .sustain(0.2)
  .release(2.2)
  .lpf(sine.range(280, 950).slow(42))
  .fmi(sine.range(0.2, 3.6).slow(56))
  .fmh("<2 3 5 7 5 3>".slow(60))
  .fmdecay(1.4)
  .fmsustain(0.08)
  .phaser(0.09)
  .phaserdepth(1.1)
  .phasercenter(sine.range(350, 850).slow(37))
  .pan(sine.range(0.28, 0.72).slow(29))
  .room(0.72)
  .size(0.92)
  .delay(0.15)
  .delaytime(0.667)
  .delayfeedback(0.35)

// Track 4 - bass, pedal drone with walking fifth
$: note("g2 ~!7 gb2 ~!7 e2 ~!7 d2 ~!7 b1 ~!7 c2 ~!7 d2 ~!7 g2 ~!7 g2 ~!7 gb2 ~!7 e2 ~!7 d2 ~!7 b1 ~!7 c2 ~!7 d2 ~!7 g2 ~!7")
  .slow(132/8/4)
  .apply(lowerVoice)
  .pan(0.5)
  .shape(0.15)
  .drive(0.08)
  .off(0.5, x => x.transpose(7).gain(0.14).lpf(420).pan(0.36).attack(0.1))
  .off(1, x => x.transpose(19).gain(0.06).lpf(260).pan(0.64).sound("triangle").room(0.7).decay(0.7))
  .room(0.36)
  .size(0.76)
  .hpf(38)
  .every(5, x => x.sometimes(y => y.transpose(-12).gain(0.16).lpf(180)))
  .every(8, x => x.rarely(y => y.crush(10).gain(0.22)))