// BWV 1087 Canon 9

// Baroque style voices
let upperVoice = x => x
  .sound("triangle")
  .gain(0.45)
  .attack(0.02)
  .decay(0.15)
  .sustain(0.2)
  .lpf(2100)
  .room(0.18)

let lowerVoice = x => x
  .sound("square")
  .gain(0.44)
  .decay(0.15)
  .sustain(0.19)
  .lpf(950)
  .room(0.18)

setcps(120/60/4)

// Track 1
$: note("g5 ~ b5 ~ d6 ~ g6 ~ d6 ~ b5 ~ g5 ~ d6 ~ d5 ~ gb5 ~ a5 ~ db5 ~ e5 ~ g5 ~ db6 ~!3 d6 ~ a5 ~ gb5 ~ d5 ~ g5 ~ b5 ~ d6 ~ g5 ~ e6 ~ c6 ~ a5 ~ c6 ~ gb5 ~ a5 ~ d6 c6 b5 a5 g5 ~ b5 ~ d6 ~ g6 ~ d6 ~ b5 ~ g5 ~ d6 ~ d5 ~ gb5 ~ a5 ~ db5 ~ e5 ~ g5 ~ db6 ~!3 d6 ~ a5 ~ gb5 ~ d5 ~ g5 ~ b5 ~ d6 ~ g5 ~ e6 ~ c6 ~ a5 ~ c6 ~ gb5 ~ a5 ~ d6 c6 b5 a5 g5 ~ b5 ~ d6 ~ g6 ~ d6 ~ b5 ~ g5 ~ d6 ~ d5 ~ gb5 ~ a5 ~ db5 ~ e5 ~ g5 ~ db6 ~!3 d6 ~ a5 ~ gb5 ~ d5 ~ g5 ~ b5 ~ d6 ~ g5 ~ e6 ~ c6 ~ a5 ~ c6 ~ gb5 ~ a5 ~ d6 c6 b5 a5 g5 ~ b5 ~ d6 ~ g6 ~ d6 ~ b5 ~ g5 ~ d6 ~ d5 ~ gb5 ~ a5 ~ db5 ~ e5 ~ g5 ~ db6 ~!3 d6 ~ a5 ~ gb5 ~ d5 ~ g5 ~ b5 ~ d6 ~ g5 ~ e6 ~ c6 ~ a5 ~ c6 ~ gb5 ~ a5 ~ d6 c6 b5 a5 g5 ~!7")
  .slow(264/8/4)
  .apply(upperVoice)
  .pan(0.13)
  .lpf(sine.range(1100, 2700).slow(16))
  .room(0.23)
  .every(16, x => x.hpf(380))
  .every(32, x => x.rev())
  .degradeBy(0.07)
  .every(48, x => x.distort(0.18))
  .every(64, x => x.delay(0.11).delaytime(0.14).delayfeedback(0.13))
  .every(24, x => x.vowel("e"))
  .every(96, x => x.pan(0.86))
  .every(128, x => x.vowel("i"))
  .every(80, x => x.hpf(550))
  .every(56, x => x.lpf(1800))
  .every(40, x => x.vowel("o"))

// Track 3 — more subtle reverb, bolder timbre automation
$: note("g2 ~!7 g3 ~!7 gb3 ~!7 e3 ~!7 d3 ~!7 b2 ~!7 c3 ~!7 d3 ~!7 g2 ~!7 g3 ~!7 gb3 ~!7 e3 ~!7 d3 ~!7 b2 ~!7 c3 ~!7 d3 ~!7")
  .slow(264/8/4)
  .apply(
    x => lowerVoice(x)
      .attack(0.05)
      .release(0.18)
      .decay(0.21)
      .sustain(0.22)
      .room(0.29)
      .lpf(sine.range(200, 1400).slow(18))
      .vowel("<a u o e>")
  )
  .pan(0.48)
  .degradeBy(0.1)
  .every(28, x => x.distort(0.18))
  .every(20, x => x.rev())
  .every(36, x => x.vowel("u"))
  .every(44, x => x.hpf(340))
  .every(72, x => x.delay(0.08).delaytime(0.16).delayfeedback(0.21))

// Track 4 — evolving, drifting upwards, reduction for clarity
$: note("e6 ~!4 b5 ~!4 d6 ~!4 g6 ~!4 b6 ~!4 e7 ~!4")
  .slow(264/42)
  .sound("supersaw")
  .attack(0.36)
  .release(2.34)
  .decay(1.02)
  .sustain(0.16)
  .gain(0.05)
  .pan(0.53)
  .room(0.82)
  .lpf(cosine.range(2300, 3900).slow(24))
  .degradeBy(0.26)
  .every(8, x => x.vowel("i"))
  .every(10, x => x.rev())