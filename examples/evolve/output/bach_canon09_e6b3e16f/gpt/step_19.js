// BWV 1087 Canon 9

// Baroque style voices
let upperVoice = x => x
  .sound("triangle")
  .gain(0.45)
  .attack(0.02)
  .decay(0.15)
  .sustain(0.2)
  .lpf(2100)
  .room(0.18)

let lowerVoice = x => x
  .sound("square")
  .gain(0.44)
  .decay(0.15)
  .sustain(0.19)
  .lpf(950)
  .room(0.18)

setcps(120/60/4)

// Track 1
$: note("g5 ~ b5 ~ d6 ~ g6 ~ d6 ~ b5 ~ g5 ~ d6 ~ d5 ~ gb5 ~ a5 ~ db5 ~ e5 ~ g5 ~ db6 ~!3 d6 ~ a5 ~ gb5 ~ d5 ~ g5 ~ b5 ~ d6 ~ g5 ~ e6 ~ c6 ~ a5 ~ c6 ~ gb5 ~ a5 ~ d6 c6 b5 a5 g5 ~ b5 ~ d6 ~ g6 ~ d6 ~ b5 ~ g5 ~ d6 ~ d5 ~ gb5 ~ a5 ~ db5 ~ e5 ~ g5 ~ db6 ~!3 d6 ~ a5 ~ gb5 ~ d5 ~ g5 ~ b5 ~ d6 ~ g5 ~ e6 ~ c6 ~ a5 ~ c6 ~ gb5 ~ a5 ~ d6 c6 b5 a5 g5 ~ b5 ~ d6 ~ g6 ~ d6 ~ b5 ~ g5 ~ d6 ~ d5 ~ gb5 ~ a5 ~ db5 ~ e5 ~ g5 ~ db6 ~!3 d6 ~ a5 ~ gb5 ~ d5 ~ g5 ~ b5 ~ d6 ~ g5 ~ e6 ~ c6 ~ a5 ~ c6 ~ gb5 ~ a5 ~ d6 c6 b5 a5 g5 ~ b5 ~ d6 ~ g6 ~ d6 ~ b5 ~ g5 ~ d6 ~ d5 ~ gb5 ~ a5 ~ db5 ~ e5 ~ g5 ~ db6 ~!3 d6 ~ a5 ~ gb5 ~ d5 ~ g5 ~ b5 ~ d6 ~ g5 ~ e6 ~ c6 ~ a5 ~ c6 ~ gb5 ~ a5 ~ d6 c6 b5 a5 g5 ~!7")
  .slow(264/8/4)
  .apply(upperVoice)
  .pan(rand.range(0.1, 0.9).slow(32))
  .lpf(sine.range(1100, 2800).slow(17))
  .room(0.27)
  .every(16, x => x.hpf(380))
  .every(32, x => x.rev())
  .degradeBy(0.13)
  .every(48, x => x.distort(0.21))
  .every(64, x => x.delay(0.11).delaytime(0.14).delayfeedback(0.13))
  .every(24, x => x.vowel("e"))
  .every(96, x => x.pan(0.86))
  .every(128, x => x.vowel("i"))
  .every(80, x => x.hpf(650))
  .every(56, x => x.lpf(1600))
  .every(40, x => x.vowel("o"))
  .every(20, x => x.lpf(cosine.range(700, 1800).slow(8)))
  .every(72, x => x.vowel("a"))
  .every(36, x => x.tremolo(0.19).tremolosync(0.16))

// Track 3 — evolving weight, sparse bass, deeper filter sweep
$: note("g2 ~!7 g3 ~!7 e3 ~!7 d3 ~!7 b2 ~!7 c3 ~!7 d3 ~!7")
  .slow(264/6/4)
  .apply(
    x => lowerVoice(x)
      .attack(0.11)
      .release(0.31)
      .decay(0.34)
      .sustain(0.15)
      .room(0.58)
      .lpf(sine.range(100, 750).slow(28))
      .vowel("<u o>")
      .drive(0.23)
      .phaser(0.24)
      .phaserdepth(0.33)
  )
  .pan(rand.range(0.09, 0.27).slow(30))
  .degradeBy(0.22)
  .every(32, x => x.distort(0.17))
  .every(22, x => x.rev())
  .every(18, x => x.lpf(320))
  .every(28, x => x.vowel("u"))
  .every(44, x => x.hpf(120))
  .every(40, x => x.delay(0.13).delaytime(0.14).delayfeedback(0.11))
  .every(18, x => x.tremolo(0.1).tremolosync(0.07))

// Track 4 — evolving to bell-like, longer tails, with less filter motion
$: note("e6 ~!4 b5 ~!4 d6 ~!4 g6 ~!4 b6 ~!4 e7 ~!4")
  .slow(264/36)
  .sound("sine")
  .attack(0.7)
  .release(4.2)
  .decay(1.9)
  .sustain(0.03)
  .gain(0.031)
  .pan(0.33)
  .room(0.97)
  .lpf(1200)
  .degradeBy(0.14)
  .every(12, x => x.vowel("i"))
  .every(36, x => x.lpf(1050))
  .every(22, x => x.rev())
  .every(34, x => x.distort(0.16))