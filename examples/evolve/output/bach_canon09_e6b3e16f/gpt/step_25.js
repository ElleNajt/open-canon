// BWV 1087 Canon 9

// Baroque style voices
let upperVoice = x => x
  .sound("triangle")
  .gain(0.44)
  .attack(0.03)
  .decay(0.12)
  .sustain(0.2)
  .lpf(2100)
  .room(0.24)

let lowerVoice = x => x
  .sound("square")
  .gain(0.41)
  .decay(0.18)
  .sustain(0.19)
  .lpf(790)
  .room(0.19)

setcps(120/60/4)

// Track 1 — upper melody, evolving towards more air/glass, less tail
$: note("g5 ~ b5 ~ d6 ~ g6 ~ d6 ~ b5 ~ g5 ~ d6 ~ d5 ~ gb5 ~ a5 ~ db5 ~ e5 ~ g5 ~ db6 ~!3 d6 ~ a5 ~ gb5 ~ d5 ~ g5 ~ b5 ~ d6 ~ g5 ~ e6 ~ c6 ~ a5 ~ c6 ~ gb5 ~ a5 ~ d6 c6 b5 a5")
  .slow(264/8/4)
  .apply(upperVoice)
  .pan(rand.range(0.09, 0.65).slow(25))
  .lpf(sine.range(1800, 5500).slow(12))
  .hpf(sine.range(370, 970).slow(27))
  .room(0.34)
  .degradeBy(0.09)
  .every(17, x => x.vowel("<i u a>"))
  .every(24, x => x.rev())
  .every(29, x => x.distort(0.37))
  .every(35, x => x.delay(0.25).delaytime(0.21).delayfeedback(0.16))
  .every(43, x => x.pan(0.60))
  .every(23, x => x.tremolo(0.15).tremolosync(0.13))

// Track 2 — lower voice, more enveloped, rounder
$: note("g3 ~ d4 ~ b3 ~ d4 ~ g4 ~ d4 ~ b3 ~ d4 ~ g3 ~ d3 ~ e3 ~ c3 ~ b2 ~ d3 ~ g3 ~!3 d3 ~ a2 ~ g3 ~ d3 ~ g2 ~ g3 ~ b3 ~ d4 ~ g3 ~ e4 ~ c4 ~ a3 ~ c4 ~ g3 ~ a3 ~ d4 c4 b3 a3")
  .slow(264/8/4)
  .apply(lowerVoice)
  .pan(sine.range(0.58, 0.9).slow(21))
  .lpf(sine.range(390, 1310).slow(15))
  .hpf(40)
  .room(0.22)
  .degradeBy(0.24)
  .every(18, x => x.vowel("<o u>"))
  .every(33, x => x.rev())
  .every(39, x => x.distort(0.27))
  .every(37, x => x.tremolo(0.11).tremolosync(0.11))

// Track 3 — subtle plucked accent, new, gently vanishing in reverb
$: note("c5 ~!6 e4 ~!12 b4 ~!6 g4 ~!8")
  .slow(264/24)
  .sound("piano")
  .attack(0.03)
  .release(2.6)
  .gain(0.08)
  .room(0.71)
  .pan(sine.range(0.11,0.78).slow(21))
  .lpf(2400)
  .every(8, x => x.vowel("a"))
  .every(16, x => x.distort(0.07))
  .every(19, x => x.delay(0.16).delaytime(0.17).delayfeedback(0.11))

// Track 4 — shimmer, more glasslike, spaced out
$: note("e6 ~!4 b5 ~!7 d6 ~!6 g6 ~!8 b6 ~!6 e7 ~!9")
  .slow(264/32)
  .sound("sine")
  .attack(1.1)
  .release(7.2)
  .decay(2.9)
  .sustain(0.02)
  .gain(0.029)
  .pan(sine.range(0.17, 0.83).slow(20))
  .room(0.93)
  .lpf(sine.range(420, 760).slow(15))
  .every(11, x => x.vowel("i"))
  .every(21, x => x.rev())
  .every(17, x => x.distort(0.15))
  .every(18, x => x.tremolo(0.23).tremolosync(0.12))
  .every(29, x => x.hpf(340))
  .every(45, x => x.delay(0.26).delaytime(0.31).delayfeedback(0.18))