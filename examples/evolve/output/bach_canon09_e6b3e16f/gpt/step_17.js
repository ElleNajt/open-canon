// BWV 1087 Canon 9

// Baroque style voices
let upperVoice = x => x
  .sound("triangle")
  .gain(0.45)
  .attack(0.02)
  .decay(0.15)
  .sustain(0.2)
  .lpf(2100)
  .room(0.18)

let lowerVoice = x => x
  .sound("square")
  .gain(0.44)
  .decay(0.15)
  .sustain(0.19)
  .lpf(950)
  .room(0.18)

setcps(120/60/4)

// Track 1
$: note("g5 ~ b5 ~ d6 ~ g6 ~ d6 ~ b5 ~ g5 ~ d6 ~ d5 ~ gb5 ~ a5 ~ db5 ~ e5 ~ g5 ~ db6 ~!3 d6 ~ a5 ~ gb5 ~ d5 ~ g5 ~ b5 ~ d6 ~ g5 ~ e6 ~ c6 ~ a5 ~ c6 ~ gb5 ~ a5 ~ d6 c6 b5 a5 g5 ~ b5 ~ d6 ~ g6 ~ d6 ~ b5 ~ g5 ~ d6 ~ d5 ~ gb5 ~ a5 ~ db5 ~ e5 ~ g5 ~ db6 ~!3 d6 ~ a5 ~ gb5 ~ d5 ~ g5 ~ b5 ~ d6 ~ g5 ~ e6 ~ c6 ~ a5 ~ c6 ~ gb5 ~ a5 ~ d6 c6 b5 a5 g5 ~ b5 ~ d6 ~ g6 ~ d6 ~ b5 ~ g5 ~ d6 ~ d5 ~ gb5 ~ a5 ~ db5 ~ e5 ~ g5 ~ db6 ~!3 d6 ~ a5 ~ gb5 ~ d5 ~ g5 ~ b5 ~ d6 ~ g5 ~ e6 ~ c6 ~ a5 ~ c6 ~ gb5 ~ a5 ~ d6 c6 b5 a5 g5 ~ b5 ~ d6 ~ g6 ~ d6 ~ b5 ~ g5 ~ d6 ~ d5 ~ gb5 ~ a5 ~ db5 ~ e5 ~ g5 ~ db6 ~!3 d6 ~ a5 ~ gb5 ~ d5 ~ g5 ~ b5 ~ d6 ~ g5 ~ e6 ~ c6 ~ a5 ~ c6 ~ gb5 ~ a5 ~ d6 c6 b5 a5 g5 ~!7")
  .slow(264/8/4)
  .apply(upperVoice)
  .pan(rand.range(0.1, 0.9).slow(32))
  .lpf(sine.range(1400, 3200).slow(12))
  .room(0.23)
  .every(16, x => x.hpf(380))
  .every(32, x => x.rev())
  .degradeBy(0.07)
  .every(48, x => x.distort(0.18))
  .every(64, x => x.delay(0.11).delaytime(0.14).delayfeedback(0.13))
  .every(24, x => x.vowel("e"))
  .every(96, x => x.pan(0.86))
  .every(128, x => x.vowel("i"))
  .every(80, x => x.hpf(550))
  .every(56, x => x.lpf(1800))
  .every(40, x => x.vowel("o"))
  .every(20, x => x.lpf(cosine.range(900, 2100).slow(10)))
  .every(72, x => x.vowel("a"))

// Track 3 — lower voice with evolving timbre, phaser, and reduction
$: note("g2 ~!7 g3 ~!7 gb3 ~!7 e3 ~!7 d3 ~!7 b2 ~!7 c3 ~!7 d3 ~!7 g2 ~!7 g3 ~!7 gb3 ~!7 e3 ~!7 d3 ~!7 b2 ~!7 c3 ~!7 d3 ~!7")
  .slow(264/8/4)
  .apply(
    x => lowerVoice(x)
      .attack(0.05)
      .release(0.18)
      .decay(0.21)
      .sustain(0.22)
      .room(0.38)
      .lpf(sine.range(200, 1400).slow(18))
      .vowel("<a u o e>")
      .drive(0.13)
      .phaser(0.21)
      .phaserdepth(0.33)
  )
  .pan(rand.range(0.15, 0.6).slow(28))
  .degradeBy(0.21)
  .every(28, x => x.distort(0.22))
  .every(20, x => x.rev())
  .every(18, x => x.lpf(450))
  .every(36, x => x.vowel("u"))
  .every(44, x => x.hpf(340))
  .every(72, x => x.delay(0.13).delaytime(0.14).delayfeedback(0.21))
  .every(60, x => x.vowel("i"))
  .every(24, x => x.tremolo(0.16).tremolosync(0.12))

// Track 4 — evolving texture, more reverb, subtle slow vibrato
$: note("e6 ~!4 b5 ~!4 d6 ~!4 g6 ~!4 b6 ~!4 e7 ~!4")
  .slow(264/42)
  .sound("supersaw")
  .attack(0.41)
  .release(2.8)
  .decay(1.28)
  .sustain(0.06)
  .gain(0.05)
  .pan(0.34)
  .room(0.87)
  .lpf(sine.range(1100, 3700).slow(33))
  .degradeBy(0.23)
  .tremolo(0.25)
  .tremolosync(0.07)
  .every(8, x => x.vowel("i"))
  .every(18, x => x.vowel("a"))
  .every(11, x => x.rev())
  .every(16, x => x.distort(0.19))
  .every(22, x => x.delay(0.16).delaytime(0.28).delayfeedback(0.16))
  .every(30, x => x.lpf(2100))
  .every(36, x => x.vowel("u"))
  .every(14, x => x.hpf(800))