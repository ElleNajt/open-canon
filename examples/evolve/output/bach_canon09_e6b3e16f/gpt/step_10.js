// BWV 1087 Canon 9

// Baroque style voices
let upperVoice = x => x
  .sound("triangle")
  .gain(0.45)
  .attack(0.02)
  .decay(0.15)
  .sustain(0.2)
  .lpf(2100)
  .room(0.18)

let lowerVoice = x => x
  .sound("square")
  .gain(0.44)
  .decay(0.15)
  .sustain(0.19)
  .lpf(950)
  .room(0.18)

setcps(120/60/4)

