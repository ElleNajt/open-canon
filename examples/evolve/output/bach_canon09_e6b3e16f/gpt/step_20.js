// BWV 1087 Canon 9

// Baroque style voices
let upperVoice = x => x
  .sound("triangle")
  .gain(0.47)
  .attack(0.03)
  .decay(0.13)
  .sustain(0.23)
  .lpf(2200)
  .room(0.22)

let lowerVoice = x => x
  .sound("square")
  .gain(0.42)
  .decay(0.19)
  .sustain(0.22)
  .lpf(880)
  .room(0.19)

setcps(120/60/4)

// Track 1
$: note("g5 ~ b5 ~ d6 ~ g6 ~ d6 ~ b5 ~ g5 ~ d6 ~ d5 ~ gb5 ~ a5 ~ db5 ~ e5 ~ g5 ~ db6 ~!3 d6 ~ a5 ~ gb5 ~ d5 ~ g5 ~ b5 ~ d6 ~ g5 ~ e6 ~ c6 ~ a5 ~ c6 ~ gb5 ~ a5 ~ d6 c6 b5 a5 g5 ~ b5 ~ d6 ~ g6 ~ d6 ~ b5 ~ g5 ~ d6 ~ d5 ~ gb5 ~ a5 ~ db5 ~ e5 ~ g5 ~ db6 ~!3 d6 ~ a5 ~ gb5 ~ d5 ~ g5 ~ b5 ~ d6 ~ g5 ~ e6 ~ c6 ~ a5 ~ c6 ~ gb5 ~ a5 ~ d6 c6 b5 a5 g5 ~ b5 ~ d6 ~ g6 ~ d6 ~ b5 ~ g5 ~ d6 ~ d5 ~ gb5 ~ a5 ~ db5 ~ e5 ~ g5 ~ db6 ~!3 d6 ~ a5 ~ gb5 ~ d5 ~ g5 ~ b5 ~ d6 ~ g5 ~ e6 ~ c6 ~ a5 ~ c6 ~ gb5 ~ a5 ~ d6 c6 b5 a5 g5 ~ b5 ~ d6 ~ g6 ~ d6 ~ b5 ~ g5 ~ d6 ~ d5 ~ gb5 ~ a5 ~ db5 ~ e5 ~ g5 ~ db6 ~!3 d6 ~ a5 ~ gb5 ~ d5 ~ g5 ~ b5 ~ d6 ~ g5 ~ e6 ~ c6 ~ a5 ~ c6 ~ gb5 ~ a5 ~ d6 c6 b5 a5 g5 ~!7")
  .slow(264/8/4)
  .apply(upperVoice)
  .pan(rand.range(0.05, 0.4).slow(40))
  .lpf(sine.range(1300, 3200).slow(21))
  .room(0.27)
  .every(20, x => x.hpf(480))
  .every(48, x => x.rev())
  .degradeBy(0.17)
  .every(56, x => x.distort(0.15))
  .every(64, x => x.delay(0.15).delaytime(0.2).delayfeedback(0.15))
  .every(36, x => x.vowel("o"))
  .every(32, x => x.lpf(cosine.range(1000, 2000).slow(11)))
  .every(84, x => x.pan(0.78))
  .every(112, x => x.vowel("u"))
  .every(70, x => x.hpf(780))
  .every(60, x => x.tremolo(0.14).tremolosync(0.18))

// Track 3 — evolving weight, sparse bass, deeper filter sweep
$: note("g2 ~!7 g3 ~!7 e3 ~!7 d3 ~!7 b2 ~!7 c3 ~!7 d3 ~!7")
  .slow(264/6/4)
  .apply(
    x => lowerVoice(x)
      .attack(0.17)
      .release(0.43)
      .decay(0.24)
      .sustain(0.10)
      .room(0.61)
      .lpf(sine.range(80, 550).slow(22))
      .vowel("<o a>")
      .drive(0.19)
      .phaser(0.15)
      .phaserdepth(0.21)
  )
  .pan(rand.range(0.10, 0.32).slow(38))
  .degradeBy(0.3)
  .every(27, x => x.distort(0.13))
  .every(20, x => x.rev())
  .every(36, x => x.lpf(210))
  .every(20, x => x.vowel("o"))
  .every(48, x => x.hpf(160))
  .every(44, x => x.delay(0.16).delaytime(0.18).delayfeedback(0.13))

// Track 4 — evolving to atmospheric with shimmer, bell timbre, less reverb
$: note("e6 ~!4 b5 ~!4 d6 ~!4 g6 ~!4 b6 ~!4 e7 ~!4")
  .slow(264/36)
  .sound("sine")
  .attack(1.1)
  .release(5.2)
  .decay(2.6)
  .sustain(0.03)
  .gain(0.039)
  .pan(0.43)
  .room(0.68)
  .lpf(1100)
  .every(18, x => x.vowel("i"))
  .every(42, x => x.lpf(950))
  .every(27, x => x.rev())
  .every(46, x => x.distort(0.12))
  .every(14, x => x.tremolo(0.21).tremolosync(0.13))