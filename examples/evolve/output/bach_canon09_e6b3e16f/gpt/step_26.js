// BWV 1087 Canon 9

// Baroque style voices
let upperVoice = x => x
  .sound("triangle")
  .gain(0.44)
  .attack(0.03)
  .decay(0.12)
  .sustain(0.2)
  .lpf(2100)
  .room(0.24)

let lowerVoice = x => x
  .sound("square")
  .gain(0.41)
  .decay(0.18)
  .sustain(0.19)
  .lpf(790)
  .room(0.19)

setcps(120/60/4)

// Track 1 — upper melody, more ethereal, more air
$: note("g5 ~ b5 ~ d6 ~ g6 ~ d6 ~ b5 ~ g5 ~ d6 ~ d5 ~ gb5 ~ a5 ~ db5 ~ e5 ~ g5 ~ db6 ~!3 d6 ~ a5 ~ gb5 ~ d5 ~ g5 ~ b5 ~ d6 ~ g5 ~ e6 ~ c6 ~ a5 ~ c6 ~ gb5 ~ a5 ~ d6 c6 b5 a5")
  .slow(264/8/4)
  .apply(upperVoice)
  .pan(rand.range(0.09, 0.65).slow(25))
  .lpf(sine.range(2400, 6100).slow(10))
  .hpf(sine.range(670, 1300).slow(17))
  .room(0.42)
  .degradeBy(0.12)
  .every(13, x => x.vowel("<i u a>"))
  .every(21, x => x.rev())
  .every(25, x => x.distort(0.29))
  .every(32, x => x.delay(0.35).delaytime(0.18).delayfeedback(0.12))
  .every(29, x => x.pan(0.74))
  .every(14, x => x.tremolo(0.17).tremolosync(0.17))

// Track 2 — lower voice, more enveloped, slightly smoother, more movement
$: note("g3 ~ d4 ~ b3 ~ d4 ~ g4 ~ d4 ~ b3 ~ d4 ~ g3 ~ d3 ~ e3 ~ c3 ~ b2 ~ d3 ~ g3 ~!3 d3 ~ a2 ~ g3 ~ d3 ~ g2 ~ g3 ~ b3 ~ d4 ~ g3 ~ e4 ~ c4 ~ a3 ~ c4 ~ g3 ~ a3 ~ d4 c4 b3 a3")
  .slow(264/8/4)
  .apply(lowerVoice)
  .pan(sine.range(0.38, 0.8).slow(15))
  .lpf(sine.range(390, 1620).slow(13))
  .hpf(55)
  .room(0.26)
  .degradeBy(0.19)
  .every(15, x => x.vowel("<o u>"))
  .every(21, x => x.rev())
  .every(27, x => x.distort(0.19))
  .every(19, x => x.tremolo(0.13).tremolosync(0.15))

// Track 3 — shimmer, glasslike, spaced out (moved from Track 4; no piano accent)
$: note("e6 ~!4 b5 ~!7 d6 ~!6 g6 ~!8 b6 ~!6 e7 ~!9")
  .slow(264/32)
  .sound("sine")
  .attack(0.7)
  .release(5.5)
  .decay(1.8)
  .sustain(0.03)
  .gain(0.032)
  .pan(sine.range(0.27, 0.76).slow(18))
  .room(0.97)
  .lpf(sine.range(520, 910).slow(10))
  .every(7, x => x.vowel("i"))
  .every(18, x => x.rev())
  .every(15, x => x.distort(0.12))
  .every(15, x => x.tremolo(0.28).tremolosync(0.09))
  .every(23, x => x.hpf(420))
  .every(34, x => x.delay(0.22).delaytime(0.25).delayfeedback(0.19))