// Goldberg Variations - Ground Bass (BWV 988)
// The 8-note descending bass that underlies all 30 variations

setcps(72/60/4)

$: note("g3 fs3 e3 d3 b2 c3 d3 g2")
  .slow(2)
  .sound("triangle")
  .gain(0.4)
  .attack(0.02)
  .decay(0.3)
  .sustain(0.6)
  .release(0.8)
  .lpf(sine.range(400, 1200).slow(8))
  .room(0.25)

$: note("g4 fs4 e4 d4 b3 c4 d4 g3")
  .slow(2)
  .sound("sine")
  .gain(0.2)
  .late(0.5)
  .attack(0.1)
  .release(1.2)
  .pan(sine.range(0.3, 0.7).slow(4))
  .room(0.3)

$: note("<g5 d5 b4 g4>")
  .slow(4)
  .sound("triangle")
  .gain(0.15)
  .attack(0.2)
  .release(2)
  .lpf(800)
  .room(0.4)
  .delay(0.3)
  .delaytime(0.375)
  .delayfeedback(0.4)