setcps(0.48)

$: note("<e2 d2 b1 [c2 cs2]> <e2 [fs2 g2] b1 d2>")
  .sound("sawtooth")
  .lpf(sine.range(80, 1800).slow(13))
  .shape(0.62)
  .gain(0.44)
  .every(4, x => x.add(note("<12 -5>")).shape(0.85))

$: note("e3 [g3 b3] <a3 fs3> [e3 ~ d3]")
  .sound("triangle")
  .delay(0.6).delaytime(0.375).delayfeedback(0.62)
  .gain(0.24)
  .palindrome()
  .sometimes(x => x.add(note("<7 -12 5>")))

$: note("<[e4 b4] [g4 d5] [a4 e5] [fs4 cs5 gs4]>")
  .sound("sine")
  .attack(4).release(7)
  .gain(0.17)
  .room(0.93).size(0.88)

$: s("bd:2 [~ bd:5] [~ cp:1] <rim:3 [~ rim]>, [hh:2 hh:1]*4 <oh:1 [~ oh:3]>")
