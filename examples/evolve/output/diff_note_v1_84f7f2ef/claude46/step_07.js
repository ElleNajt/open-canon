setcps(0.48)

$: note("<e2 d2 b1 [c2 cs2]> <e2 [fs2 g2] b1 d2>")
  .sound("sawtooth")
  .lpf(sine.range(140, 1800).slow(13))
  .shape(0.62)
  .gain(0.37)
  .every(8, x => x.add(note("12")).lpf(3200))

$: note("e3 [g3 b3] <a3 fs3> [e3 ~ d3]")
  .sound("triangle")
  .delay(0.6).delaytime(0.375).delayfeedback(0.62)
  .gain(0.24)
  .every(3, x => x.rev())
  .sometimes(x => x.add(note("7")))

$: note("<[e4 b4] [g4 d5] [a4 e5] [fs4 ~ gs4]>")
  .sound("sine")
  .attack(1.8).release(5)
  .gain(0.16)
  .pan(sine.range(0.05, 0.95).slow(11))
  .room(0.82)

$: s("bd [~ bd] [~ cp] <~ rim>, [hh hh:1]*4 oh")
  .gain("0.48 0.40 0.44 0.18")
  .shape(0.32)
  .room(0.18)
  .sometimes(x => x.speed(0.62))
  .every(7, x => x.crush(5))

$: note("[e5 ~] [~ b4] <[g5 a5] [~ fs5]> [~ d5]")
  .sound("pulse")
  .gain(0.13)
  .lpf(perlin.range(400, 4200).slow(11))
  .delay(0.45).delaytime(0.25)
  .degradeBy(0.32)

$: note("<e3 b2 [cs3 d3] a2>")
  .sound("sine")
  .fmi(sine.range(0.8, 14).slow(9))
  .fmh(3)
  .gain(perlin.range(0.07, 0.22).slow(7))
  .pan(cosine.range(0.1, 0.9).slow(11))