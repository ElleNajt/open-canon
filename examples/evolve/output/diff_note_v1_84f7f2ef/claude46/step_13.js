setcps(0.48)

$: note("<e2 d2 b1 [c2 cs2]> <e2 [fs2 g2] b1 d2>")
  .sound("sawtooth")
  .lpf(sine.range(90, 1800).slow(13))
  .shape(0.62)
  .gain(0.5)
  .every(5, x => x.add(note("<12 -5 7>")).shape(0.78))

$: note("e3 [g3 b3] <a3 fs3> [e3 ~ d3]")
  .sound("triangle")
  .delay(0.6).delaytime(0.375).delayfeedback(0.62)
  .gain(0.28)
  .every(3, x => x.rev())
  .sometimes(x => x.add(note("<7 -12 5>")))

$: note("<[e4 b4] [g4 d5] [a4 e5] [fs4 cs5 gs4]>")
  .sound("sine")
  .attack(4).release(8)
  .gain(0.17)
  .room(0.93).size(0.88)

$: s("bd [~ bd:3] [~ cp] <rim [~ rim]>, [hh hh:1]*4 <oh [~ oh:2]>")
  .gain("0.48 0.36 0.44 0.19")
  .shape(0.38)
  .room(0.12)
  .often(x => x.speed(perlin.range(0.55, 1.3)))
  .every(5, x => x.ply(2).gain(0.25))

$: note("[e5 ~] [~ b4] <[g5 a5] [~ fs5]> [~ d5 ~]")
  .sound("pulse")
  .gain(0.14)
  .lpf(perlin.range(280, 5200).slow(11))
  .delay(0.52).delaytime(0.1875)
  .degradeBy(0.42)

$: note("<e3 b2 [cs3 d3] a2>")
