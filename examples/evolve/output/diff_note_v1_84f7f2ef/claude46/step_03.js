setcps(0.48)

$: note("<e2 d2 b1 [c2 cs2]>")
  .sound("sawtooth")
  .lpf(sine.range(140, 1800).slow(13))
  .shape(0.52)
  .gain(0.37)
  .room(0.6)

$: note("e3 [g3 b3] <a3 fs3> [e3 ~ d3]")
  .sound("triangle")
  .delay(0.6).delaytime(0.375).delayfeedback(0.6)
  .gain(0.28)
  .every(5, x => x.add(note("12")).lpf(2200))

$: note("<[e4 b4] [g4 d5] [a4 e5] [fs4 cs5 gs4]>")
  .sound("sine")
  .attack(0.5).release(2.2)
  .gain(0.24)
  .pan(sine.range(0.1, 0.9).slow(7))
  .room(0.45)

$: s("bd [~ bd] [~ cp] <~ rim>, hh*8")
  .gain("0.52 0.46 0.48 0.32")
  .sometimes(x => x.speed(0.82))
  .room(0.18)
  .delay(0.12).delaytime(0.187)

$: note("[e5 ~] [~ b4] <[g5 a5] [~ fs5]> [~ d5]")
  .sound("pulse")
  .gain(0.16)
  .lpf(perlin.range(900, 4200).slow(11))
  .delay(0.55).delaytime(0.25)
  .pan(cosine.range(0.2, 0.8).slow(9))

$: note("<e3 b2 [cs3 d3] a2>")
