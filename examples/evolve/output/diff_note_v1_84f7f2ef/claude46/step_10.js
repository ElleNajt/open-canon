setcps(0.51)

$: note("<e2 d2 b1 [c2 cs2]> <e2 [fs2 g2] b1 d2>")
  .sound("sawtooth")
  .lpf(sine.range(110, 2200).slow(11))
  .shape(0.58)
  .gain(0.43)
  .every(8, x => x.add(note("12")).lpf(3800))

$: note("e3 [g3 b3] <a3 fs3> [e3 ~ d3]")
  .sound("triangle")
  .delay(0.55).delaytime(0.375).delayfeedback(0.58)
  .gain(0.26)
  .every(3, x => x.rev())
  .sometimes(x => x.add(note("7")))

$: note("<[e4 b4] [g4 d5] [a4 e5] [fs4 ~ gs4]>")
  .sound("sine")
  .attack(3.2).release(8)
  .gain(0.19)
  .pan(sine.range(0.08, 0.92).slow(15))
  .room(0.91)

$: s("bd [~ bd] [~ cp] <~ rim>, [hh hh:1]*4 oh")
