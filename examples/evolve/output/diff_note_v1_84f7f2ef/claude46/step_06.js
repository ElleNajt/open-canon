setcps(0.52)

$: note("<e2 d2 b1 [c2 cs2]> <e2 [fs2 g2] b1 d2>")
  .sound("sawtooth")
  .lpf(sine.range(180, 2400).slow(11))
  .shape(0.58)
  .gain(0.39)
  .every(8, x => x.add(note("12")).lpf(3200))

$: note("e3 [g3 b3] <a3 fs3> [e3 ~ d3]")
  .sound("triangle")
  .delay(0.55).delaytime(0.375).delayfeedback(0.58)
  .gain(0.26)
  .every(3, x => x.rev())
  .sometimes(x => x.add(note("7")))

$: note("<[e4 b4] [g4 d5] [a4 e5] [fs4 ~ gs4]>")
  .sound("sine")
  .attack(1.2).release(4)
  .gain(0.18)
  .pan(sine.range(0.08, 0.92).slow(13))
  .room(0.75)

$: s("bd [~ bd] [~ cp] <~ rim>, [hh hh:1]*4 oh")
  .gain("0.50 0.42 0.46 0.20")
  .shape(0.28)
  .room(0.15)
  .sometimes(x => x.speed(0.68))
  .every(5, x => x.crush(6))

$: note("[e5 ~] [~ b4] <[g5 a5] [~ fs5]> [~ d5]")
  .sound("pulse")
  .gain(0.15)
  .lpf(perlin.range(500, 5000).slow(9))
  .delay(0.5).delaytime(0.25)
  .degradeBy(0.25)

$: note("<e3 b2 [cs3 d3] a2>")
  .sound("sine")
  .fmi(sine.range(1.2, 12).slow(7))
  .fmh(3)
  .gain(perlin.range(0.09, 0.25).slow(5))
  .pan(cosine.range(0.15, 0.85).slow(9))