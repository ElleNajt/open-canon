$: note("<e2 d2 b1 [c2 cs2]>")
  .sound("sawtooth")
  .lpf(sine.range(180, 2200).slow(11))
  .shape(0.58)
  .gain(0.39)
  .room(0.55)

$: note("e3 [g3 b3] <a3 fs3> [e3 ~ d3]")
  .sound("triangle")
  .delay(0.55).delaytime(0.375).delayfeedback(0.55)
  .gain(0.30)
  .every(4, x => x.add(note("7")).lpf(2800))

$: note("<[e4 b4] [g4 d5] [a4 e5] [fs4 cs5 gs4]>")
  .sound("sine")
  .attack(0.6).release(2.8)
  .gain(0.22)
  .pan(sine.range(0.1, 0.9).slow(7))

$: s("bd [~ bd] [~ cp] <~ rim>, hh*8")
  .gain("0.55 0.48 0.50 0.28")
  .sometimes(x => x.speed(0.78))
  .room(0.15)
  .shape(0.2)
  .delay(0.1)

$: note("[e5 ~] [~ b4] <[g5 a5] [~ fs5]> [~ d5]")
