setcps(0.51)

$: note("<e2 d2 b1 [c2 cs2]> <e2 [fs2 g2] b1 d2>")
  .sound("sawtooth")
  .lpf(sine.range(120, 2200).slow(11))
  .shape(0.58)
  .gain(0.48)
  .every(4, x => x.add(note("<12 -5>")).shape(0.74))

$: note("e3 [g3 b3] <a3 fs3> [e3 ~ d3]")
  .sound("triangle")
  .delay(0.55).delaytime(0.375).delayfeedback(0.58)
  .gain(0.26)
  .palindrome()
  .sometimes(x => x.add(note("<7 -12 5>")))

$: note("<[e4 b4] [g4 d5] [a4 e5] [fs4 cs5 gs4]>")
  .sound("sine")
  .attack(3).release(6)
  .gain(0.19)
  .room(0.91).size(0.85)

$: s("bd [~ bd:3] [~ cp] <rim [~ rim]>, [hh hh:1]*4 <oh [~ oh:2]>")
