setcps(0.45)

$: note("<e2 d2 b1 [c2 cs2]>")
  .sound("sawtooth")
  .lpf(sine.range(180, 1400).slow(11))
  .shape(0.45)
  .gain(0.35)
  .room(0.5)

$: note("e3 [g3 b3] <a3 fs3> [e3 ~ d3]")
  .sound("triangle")
  .delay(0.55).delaytime(0.375).delayfeedback(0.55)
  .gain(0.26)
  .every(7, x => x.add(note("7")))

$: note("<[e4 b4] [g4 d5] [a4 e5] [fs4 cs5 gs4]>")
  .sound("sine")
  .attack(0.4).release(1.5)
  .gain(0.22)
  .pan(sine.range(0.15, 0.85).slow(7))

$: s("bd [~ bd] [~ cp] <~ rim>, hh*8")
  .gain("0.5 0.45 0.45 0.3")
  .sometimes(x => x.speed(0.85))
  .room(0.15)
  .orbit(1)

$: note("[e5 ~] [~ b4] <[g5 a5] [~ fs5]> [~ d5]")
  .sound("pulse")
  .gain(0.14)
  .lpf(sine.range(1200, 3800).slow(13))
  .delay(0.6).delaytime(0.25)

$: note("<e3 b2 [cs3 d3] a2>")
  .sound("sine")
  .fmi(sine.range(0.5, 3.5).slow(9))
  .fmh(2)
  .gain(perlin.range(0.08, 0.19).slow(6))
  .attack(0.15).release(0.8)