setcps(0.51)

$: note("<e2 d2 b1 [c2 cs2]> <e2 [fs2 g2] b1 d2>")
  .sound("sawtooth")
  .lpf(sine.range(120, 2400).slow(11))
  .shape(0.58)
  .gain(0.48)
  .every(7, x => x.add(note("<12 7>")).lpf(3800))

$: note("e3 [g3 b3] <a3 fs3> [e3 ~ d3]")
  .sound("triangle")
  .delay(0.55).delaytime(0.375).delayfeedback(0.58)
  .gain(0.26)
  .every(3, x => x.rev())
  .sometimes(x => x.add(note("<7 12 -5>")))

$: note("<[e4 b4] [g4 d5] [a4 e5] [fs4 ~ gs4]>")
  .sound("sine")
  .attack(3).release(7)
  .gain(0.19)
  .room(0.91).size(0.85)

$: s("bd [~ bd] [~ cp] <~ rim>, [hh hh:1]*4 <oh [~ oh]>")
  .gain("0.46 0.38 0.42 0.17")
  .shape(0.35)
  .room(0.15)
  .often(x => x.speed(perlin.range(0.6, 1.25)))
  .every(4, x => x.ply(2).gain(0.28))

$: note("[e5 ~] [~ b4] <[g5 a5] [~ fs5]> [~ d5]")
  .sound("pulse")
  .gain(0.15)
  .lpf(perlin.range(350, 4800).slow(9))
  .delay(0.48).delaytime(0.25)
  .degradeBy(0.38)

