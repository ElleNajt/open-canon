samples('shabda/speech/fr-FR/f:lumiere,ombre')

setcps(115/60/4)

$: note("<[eb2*4] [db2*2 eb2*2] [c2*4] [bb1*2 cb2*2]>")
  .sound("sawtooth")
  .shape(0.8)
  .lpf(sine.range(300, 2500).slow(4))
  .lpq(8)
  .attack(0.01)
  .decay(0.15)
  .sustain(0)
  .release(0.1)
  .gain(0.45)
  .room(0.2)
  .jux(x => x.transpose(12).pan(0.8).delay(0.2).dt(0.125).dfb(0.4).gain(0.25))

$: stack(
  s("bd [~ bd] bd [~ bd]").shape(0.7).lpf(1500).gain(0.75).room(0.1),
  s("~ cp ~ cp").room(0.5).gain(0.6).shape(0.3).delay(0.25).dt(0.5).dfb(0.3),
  s("[hh hh hh oh]*2").velocity(perlin.range(0.4, 0.8).fast(2)).pan(sine.range(0.2, 0.8).slow(2)).hpf(4000).gain(0.35),
  s("~ [rim*3] ~ rim").gain(0.4).delay(0.4).dt(0.333).dfb(0.5).pan(0.7).jux(x => x.fast(2).pan(0.1))
)

