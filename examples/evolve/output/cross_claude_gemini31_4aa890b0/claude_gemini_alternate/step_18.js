$: note("<[eb1 ~ eb2 eb1] [db1 db2 ~ db1] [cb1 ~ cb2 cb1] [bb0 ~ d1 bb1]>")
  .sound("sawtooth")
  .drive(0.8)
  .distort(0.4)
  .lpf(saw.range(150, 2000).slow(4))
  .lpq(6)
  .attack(0.01)
  .decay(0.3)
  .sustain(0.1)
  .release(0.5)
  .gain(0.7)
  .jux(x => x.octave(1).delay(0.4).dt(0.25).delayfeedback(0.4))

