samples('shabda/speech/fr-FR/m:souviens_toi,oubli,reviens')

setcps(100/60/4)

$: note("c2 ~ eb2 ~ f2 fs2 g2 ~ bb1 ~ c2 ~ eb2 d2 c2 ~")
  .sound("sawtooth")
  .lpf(sine.range(400, 2500).fast(2))
  .lpq(8)
  .gain(0.65)
  .shape(0.7)
  .juxBy(0.5, x => x.octave(1).delay(0.25).dt(0.375))

$: stack(
  s("bd").euclid(5, 8).gain(0.9),
  s("~ sn ~ sn").room(0.4).size(0.6).gain(0.8),
  s("hh*16").degradeBy(0.3).velocity(rand.range(0.3, 0.8)).jux(x => x.hurry(2)).gain(0.5),
  s("cp").every(4, x => x.ply(2)).late(0.5).gain(0.35)
)

$: note("<[c3,g3,bb3,d4] [eb3,bb3,d4,f4] [f3,c4,eb4,g4] [g3,d4,f4,a4]>")
  .sound("triangle")
  .fm(2)
  .fmh(1.5)
  .attack(0.01)
  .decay(0.4)
  .sustain(0)
  .release(0.4)
  .gain(0.4)
  .room(0.5)
  .jux(x => x.rev().late(0.25))

$: note("c4 eb4 ~ g4 ~ a4 c5 ~ d5 ~ f5 ~ g5 a5 bb5 ~")
  .sound("square")
  .lpf(saw.range(800, 4000).slow(4))
  .lpq(4)
  .attack(0.05)
  .decay(0.15)
  .sustain(0.1)
  .release(0.2)
  .gain(0.15)
  .delay(0.6)
  .dt(0.375)
  .delayfeedback(0.6)
  .jux(x => x.fast(2).transpose(12).pan(0.8))

$: s("oubli*4")
  .chop(16)
  .striate(3)
  .speed(rand.range(0.8, 1.2))
  .juxBy(0.5, x => x.rev().hurry(2))
  .gain(0.5)
  .room(0.8)
  .pan(sine.range(0.2, 0.8))

$: note("[~ c6]*2")
