setcps(172/60/4)
samples('shabda/speech:system,failure,override')
samples('shabda/speech/de-DE/m:achtung,maschine')

$: note("c1(5,16) eb1(3,8) fs1(5,16) <g0!3 c1>")
  .sound("supersaw")
  .lpf(saw.range(150, 3000).fast(8))
  .lpq(8)
  .shape(0.8)
  .gain(0.7)

$: note("c4*2 ~ <eb4 g4> ~")
  .chord("minor")
  .sound("pulse")
  .jux(x => x.rev().transpose(-12).fast(2))
  .lpf(cosine.range(300, 2500).slow(4))
  .room(0.8)
  .gain(0.35)

$: s("bd(5,8) , [~ sn:2] , <hh*16 oh*8>")
  .cut(1)
  .distort(0.5)
  .djf(0.6)
  .room(0.2)
  .gain(0.8)

$: s("<system achtung> <maschine*3? failure> override ~")
  .chop(16)
  .speed(saw.range(0.5, 2).fast(4))
  .crush(4)
  .delay(0.6)
  .gain(0.8)

$: note("<c6(3,8) eb6(5,16) fs5(7,16) c7>")
  .sound("square")
  .fm(sine.range(0.5, 5).fast(12))
  .fmh(2)
  .delay(0.7)
  .gain(0.4)

$: s("~ <mt(3,8) cb*4>")
  .speed(rand.range(0.5, 4))
  .crush(2)
  .pan(sine.fast(8))
  .delay(0.5)
  .gain(0.65)