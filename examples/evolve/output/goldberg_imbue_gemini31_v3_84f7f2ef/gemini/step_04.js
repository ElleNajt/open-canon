setcps(90/60/4)
samples('shabda/speech/fr-FR/m:abime,fragments,murmure')

$: note("c2 ~ eb2 ~ g1 d2 ~ <c2 b1>")
  .sound("pulse")
  .lpf(sine.range(200, 800).slow(8))
  .lpq(4)
  .distort(0.3)
  .room(0.5)
  .gain(0.55)

$: note("[c4 eb4 g4 [ab4 b4]?]/2")
  .sound("triangle")
  .off(0.25, x => x.add(7))
  .delay(0.7)
  .room(0.6)
  .gain(0.35)

$: s("[bd(5,8), ~ <hh*8 [hh*3 mt]>, cp(3,8,2)]")
  .shape(0.6)
