setcps(160/60/4)
samples('shabda/speech:synthetic,dreams,logic,awake')
samples('shabda/speech/fr-FR/f:machine,esprit')

$: note("c1(5,16) eb1(3,8) g0(3,8) <f1!3 d1>")
  .sound("pulse")
  .lpf(saw.range(200, 1200).fast(4))
  .lpq(4)
  .distort(0.4)
  .gain(0.65)

$: note("[c4,eb4,g4] <[f4,ab4,c5] [g4,bb4,d5]>")
  .sound("saw")
  .jux(x => x.rev().transpose(12))
  .lpf(1500)
  .delay(0.5)
  .gain(0.35)

$: s("bd(5,16,2) , [~ <sn:2 cp>] , <hh*16? hh*8>")
  .djf(0.65)
  .drive(0.2)
  .gain(0.7)

$: s("synthetic <awake esprit> logic dreams")
  .striate(8)
  .speed(perlin.range(0.8, 1.5).fast(2))
  .room(0.5)
  .gain(0.8)

$: note("<c6(5,8) eb6(7,16) bb5(9,16) g6*3>")
  .sound("sine")
  .fm(rand.range(1, 3).fast(2))
  .fmh(3)
  .delay(0.5)
  .gain(0.45)

$: s("~ <mt*8? cb(3,8)>")
  .crush(2)
  .speed(rand.range(2, 6))
  .pan(sine.fast(4))
  .gain(0.55)