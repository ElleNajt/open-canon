setcps(112/60/4)
samples('shabda/speech/fr-FR/m:spectre,machine,reve,abime')

$: note("c1(5,8,2) <eb1*3 [~ g1]> <c1 [~ d1]> <ab0 f1>")
  .sound("supersaw")
  .lpf(saw.range(200, 2500).fast(2))
  .lpq(5)
  .shape(0.9)
  .gain(0.35)

$: note("c4 [eb4, g4]*2 <b4, d5> c5")
  .sound("triangle")
  .jux(x => x.add(12).rev())
  .bpf(sine.range(800, 3000).slow(4))
  .delay(0.6)
  .gain(0.2)

$: s("[bd(5,8,1), <~ cp> <sn(3,8)>?, <hh*8 [~ hh*3] cb(5,8)>]")
  .crush(2)
  .room(0.3)
  .speed(0.85)
  .gain(0.45)

$: s("<abime spectre> machine*2 reve <spectre ~>")
  .striate(16)
  .speed(perlin.range(0.5, 1.5).slow(8))
  .room(0.6)
  .pan(perlin)
  .gain(0.55)

$: note("<c5 eb5> [g5, d4] <eb5 f5> <c5 b4>")
  .sound("sine")
  .fm(sine.range(0.5, 3).slow(4))
  .echo(2, 0.25, 0.4)
  .room(0.7)
  .gain(0.15)

$: s("rim(5,8) <lt(3,8) mt(5,8)>")
  .speed(rand.range(1.5, 3))
  .pan(saw.slow(2))
  .degradeBy(0.25)
  .delay(0.5)
  .gain(0.25)