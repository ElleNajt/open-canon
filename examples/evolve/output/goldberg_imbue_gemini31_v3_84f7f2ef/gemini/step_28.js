setcps(175/60/4)
samples('shabda/speech:system,chaos,memory')
samples('shabda/speech/ja-JP/f:mirai,kioku')

$: note("c1(5,8) ~ [<g1*3 bb0> <g0 c2>] <eb1(3,8) ~>")
  .sound("supersaw")
  .lpf(perlin.range(200, 3000).fast(8))
  .lpq(8)
  .crush(4)
  .shape(0.8)
  .gain(0.65)

$: note("<c4 eb4 g4 bb4>(<5 7>,8)")
  .sound("triangle")
  .jux(x => x.transpose(12).rev())
  .phaser(4)
  .delay(0.5)
  .room(0.4)
  .gain(0.4)

$: s("<bd(5,8) bd(3,8)> , [~ sn:2] , <hh*16 [hh*4 oh]*2>")
  .ply("<1 2 4 1>")
  .jux(x => x.speed(2))
  .shape(0.4)
  .compressor("0.1:4:0.1:0.01:0.1")
  .gain(0.8)

$: s("system(3,8) memory(5,8) [~ mirai] kioku*2")
  .chop(8)
  .jux(x => x.rev())
  .room(0.6)
  .pan(sine.slow(4))
  .gain(0.85)

$: note("<c6 eb6 g6 c7 bb6>(11,16)")
  .sound("sine")
  .fm(saw.range(1, 15).fast(4))
  .fmh(2.5)
  .delay(0.8)
  .pan(rand)
  .gain(0.4)

$: s("mt(3,8) ~ [rim*2 cb] ~")
  .speed(perlin.range(0.5, 2).fast(8))
  .crush(3)
  .delay(0.5)
  .room(0.6)
  .gain(0.55)