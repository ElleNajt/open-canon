setcps(185/60/4)
samples('shabda/speech:algorithm,void,process')
samples('shabda/speech/ja-JP/f:mirai,kioku')

$: note("c1(5,8) ~ [<eb1*3 db1> <c0 g1>] <ab0(3,8) ~>")
  .sound("supersaw")
  .lpf(saw.range(100, 4000).fast(4))
  .lpq(6)
  .crush(3)
  .gain(0.7)

$: note("<c4 db4 f4 ab4>(<7 11>,16)")
  .sound("pulse")
  .jux(x => x.transpose(12).rev())
  .room(0.5)
  .crush(5)
  .gain(0.4)

$: s("<bd(5,8) ~> , [~ <cp sn:2>] , <hh*16 [hh*8 oh]*2>")
  .jux(x => x.speed(2))
  .shape(0.6)
  .compressor("0.1:4:0.1:0.01:0.1")
  .room(0.3)
  .gain(0.75)

$: s("algorithm(3,8) void(5,8) [~ mirai] kioku*2")
  .chop(8)
  .jux(x => x.rev().speed(0.5))
  .room(0.6)
  .pan(perlin.fast(2))
  .gain(0.8)

$: note("<c6 db6 f6 bb5>(11,16)")
  .sound("sine")
  .fm(sine.range(1, 20).fast(8))
  .fmh(3.14)
  .delay(0.7)
  .gain(0.4)

$: s("mt(5,8) [~ cb] [rim*2 cb] ~")
  .speed(rand.range(0.5, 3).fast(16))
  .crush(2)
  .delay(0.6)
  .room(0.5)
  .gain(0.6)