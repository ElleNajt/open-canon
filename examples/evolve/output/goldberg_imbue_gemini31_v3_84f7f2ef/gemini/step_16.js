setcps(135/60/4)
samples('shabda/speech:calculating,predicting,generating,output')

$: note("c1(5,8) <f1 g1> c1(3,8) <eb1 d1>")
  .sound("saw")
  .shape(0.9)
  .lpf(perlin.range(150, 1500).slow(8))
  .lpq(4)
  .gain(0.5)

$: note("c4(11,16) eb4(9,16) [g4 c5]")
  .sound("pulse")
  .juxBy(0.5, x => x.rev().transpose(7))
  .crush(3)
  .delay(0.6)
  .gain(0.3)

$: s("bd:4*4 <~ cp> <hh*8 hh(11,16)>")
  .shape(0.8)
  .room(0.2)
  .gain(0.7)

$: s("calculating [~ predicting] generating*2 <output ~>")
  .chop(4)
  .speed(perlin.range(0.8, 1.2).slow(4))
  .room(0.4)
  .pan(rand)
  .gain(0.65)

$: note("<c3 eb3 f3 g3>(3,8)")
  .sound("triangle")
  .fmi(rand.range(0.5, 2.5))
  .tremolo(sine.range(0.2, 0.8).fast(2))
  .delay(0.4)
  .gain(0.4)

$: s("~ <mt(5,8) lt(7,16)> <cr*2 cb*4>")
  .striate(4)
  .speed(rand.range(1, 3))
  .pan(saw.range(0.2, 0.8).slow(4))
  .delay(0.6)
  .gain(0.4)