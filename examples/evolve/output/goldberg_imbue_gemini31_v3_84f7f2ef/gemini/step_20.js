setcps(160/60/4)
samples('shabda/speech:synthetic,dreams,logic,awake')
samples('shabda/speech/fr-FR/f:machine,esprit')

$: note("c1(5,16) eb1(3,8) f1(3,8) <g1!3 bb1>")
  .sound("supersaw")
  .cutoff(perlin.range(300, 3500).fast(2))
  .lpq(5)
  .shape(0.6)
  .gain(0.65)

$: note("c4(3,8) , eb4(5,8) , g4(7,16)")
  .sound("saw")
  .jux(x => x.rev().transpose(7))
  .lpf(2000)
  .delay(0.4)
  .gain(0.35)

$: s("bd(5,16,2) , [~ <sn!3 cp>] , hh*16?")
  .shape(0.7)
  .bpf(saw.range(800, 2500).slow(4))
  .bpq(4)
  .gain(0.7)

$: s("synthetic <machine dreams> logic esprit")
  .chop(8)
  .speed(perlin.range(0.8, 1.3).fast(2))
  .jux(x => x.rev())
  .room(0.4)
  .gain(0.8)

$: note("<c6(5,8) eb6(7,16) f5(9,16) g6*4>")
  .sound("triangle")
  .ring(0.5)
  .ringf(440)
  .delay(0.6)
  .gain(0.45)

$: s("~ <mt*8? lt(3,8)>")
  .crush(3)
  .speed(rand.range(1, 4))
  .pan(sine.fast(2))
  .gain(0.55)