setcps(172/60/4)
samples('shabda/speech:system,failure,override')
samples('shabda/speech/de-DE/m:achtung,maschine')

$: note("c1(3,8) eb1(5,16) fs1(3,8) <g0 c2(3,8)>")
  .sound("supersaw")
  .lpf(sine.range(200, 2500).fast(12))
  .lpq(6)
  .drive(0.5)
  .gain(0.7)

$: note("c4(3,8) eb4(3,8) g4(5,16) c5")
  .sound("triangle")
  .jux(x => x.hurry(2).rev())
  .lpf(cosine.range(400, 3000).slow(8))
  .room(0.8)
  .gain(0.4)

$: s("bd(3,8) , [~ <sn:2 cp>] , <hh*12 [hh*8 oh*2]>")
  .cut(1)
  .distort(0.4)
  .djf(sine.range(0.3, 0.7).slow(4))
  .room(0.2)
  .gain(0.8)

$: s("<system [~ achtung]> <maschine*2 failure> <override ~> ~")
  .chop(8)
  .speed(saw.range(0.5, 2.5).fast(4))
  .crush(3)
  .delay(0.4)
  .gain(0.7)

$: note("<c6(5,8) c7(3,8)> <eb6(5,16) g5(7,16)>")
  .sound("sine")
  .fm(cosine.range(0.5, 8).fast(8))
  .fmh(saw.range(1, 4).fast(4))
  .delay(0.6)
  .gain(0.4)

$: s("~ <mt(5,8) cb(3,8)>")
  .striate(8)
  .speed(rand.range(0.5, 3))
  .room(0.5)
  .pan(sine.fast(8))
  .gain(0.6)