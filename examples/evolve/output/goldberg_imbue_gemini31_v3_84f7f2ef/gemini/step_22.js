setcps(170/60/4)
samples('shabda/speech:algorithm,glitch,void')
samples('shabda/speech/fr-FR/f:silence,futur')

$: note("c1(5,16) eb1(3,8) <f1(3,8) bb0(3,8)> <g1(5,16)? g0!2>")
  .sound("supersaw")
  .lpf(perlin.range(200, 1800).fast(2))
  .lpq(6)
  .shape(0.6)
  .gain(0.65)

$: note("c4 eb4 <f4 c5> g4")
  .chord("<minor minor7>")
  .sound("saw")
  .jux(x => x.rev().transpose(12).hurry(2))
  .lpf(sine.range(400, 2200).slow(8))
  .room(0.6)
  .gain(0.4)

$: s("bd(7,16,2) , [~ <sn:2!2 cp>] , <hh*16 hh*12>")
  .cut(1)
  .drive(0.4)
  .djf(0.7)
  .gain(0.75)

$: s("algorithm <futur*2 silence> glitch void")
  .striate(12)
  .speed(perlin.range(0.75, 1.25).fast(4))
  .room(0.7)
  .pan(rand)
  .gain(0.85)

$: note("<c6(5,8) eb6(3,8) bb5(7,16) g6(5,16)>")
  .sound("sine")
  .fm(saw.range(1, 4).fast(8))
  .fmh(2)
  .delay(0.5)
  .gain(0.45)

$: s("~ <rim*4? cr(3,8)>")
  .speed(rand.range(2, 6))
  .crush(3)
  .delay(0.4)
  .pan(sine.fast(4))
  .gain(0.6)