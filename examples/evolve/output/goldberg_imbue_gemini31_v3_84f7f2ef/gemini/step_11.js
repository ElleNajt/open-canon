setcps(95/60/4)
samples('shabda/speech/fr-FR/m:spectre,machine,reve,abime')

$: note("[c1, c2](5,8) <eb1*3 g0> [~ f0] <f1(3,8) d1>")
  .sound("pulse")
  .lpf(sine.range(200, 1800).slow(4))
  .lpq(8)
  .shape(0.7)
  .gain(0.4)

$: note("c4(5,8) eb4(3,8) [g4, c5] <d5, f5(3,8)>")
  .sound("square")
  .jux(x => x.add(12).rev())
  .lpf(sine.range(800, 3000).slow(6))
  .delay(0.6)
  .gain(0.2)

$: s("<bd bd*2> [~ cp] <sn(3,8) ~> hh(7,16)")
  .crush(4)
  .room(0.5)
  .djf(0.8)
  .gain(0.45)

$: s("<spectre reve> machine(3,8) <abime ~> spectre(5,8)?")
  .striate(16)
  .speed(perlin.range(0.6, 1.3).slow(8))
  .pan(rand)
  .delay(0.5)
  .gain(0.65)

$: note("c3~ <eb3 g3> <f3 d3> c3")
  .sound("supersaw")
  .room(0.9)
  .size(0.8)
  .crush(5)
  .lpf(800)
  .gain(0.25)

$: s("rim*3 <mt(5,8) cb(3,8)>")
  .speed(rand.range(2, 4))
  .pan(sine.fast(2))
  .jux(x => x.hurry(2))
  .delay(0.5)
  .gain(0.25)