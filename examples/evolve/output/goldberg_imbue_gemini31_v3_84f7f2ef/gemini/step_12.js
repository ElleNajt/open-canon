setcps(90/60/4)
samples('shabda/speech/fr-FR/m:spectre,machine,reve,abime')

$: note("c1(5,8) <eb1(3,8) g1(3,8)> [~ f1] <d2*2 c2(3,8)>")
  .sound("pulse")
  .lpf(sine.range(150, 1200).slow(8))
  .lpq(6)
  .shape(0.8)
  .gain(0.45)

$: note("c4(7,16) eb4(5,16) <g4 d5>(3,8)")
  .sound("square")
  .jux(x => x.add(12).iter(4))
  .lpf(saw.range(400, 3000).slow(16))
  .delay(0.7)
  .gain(0.25)

$: s("bd(5,8) [~ <cp cp*2>] <sn(5,16) sn(3,8)> hh(11,16)")
  .crush(3)
  .djf(0.75)
  .room(0.4)
  .gain(0.55)

$: s("machine*2 <spectre reve(3,8)> [~ abime] spectre(5,8)?")
  .striate(32)
  .speed(perlin.range(0.8, 1.2).slow(4))
  .delay(0.6)
  .room(0.7)
  .gain(0.8)

$: note("<c3 eb3 g3 f3>")
  .chord("minor")
  .sound("supersaw")
  .lpf(sine.range(400, 2000).slow(8))
  .room(0.9)
  .gain(0.35)

$: s("rim([5 7],16) <cb(3,8)? mt*3>")
  .speed(saw.range(1.5, 4).slow(2))
  .crush(3)
  .delay(0.5)
  .pan(perlin)
  .gain(0.3)