setcps(174/60/4)
samples('shabda/speech:neural,pattern,shift,dream')
samples('shabda/speech/ja-JP/f:kirei,kowai')

$: note("c1(5,8) <eb1 ~> [<g1*2 bb0> g0] <c2(3,8) eb0>")
  .sound("supersaw")
  .lpf(saw.range(150, 2000).fast(4))
  .lpq(6)
  .shape(0.95)
  .drive(0.8)
  .gain(0.7)

$: note("c4(3,8) <g4 c5> eb5 <bb5*2 g5>")
  .sound("triangle")
  .off(0.125, x => x.transpose(7))
  .bpf(perlin.range(200, 4000).slow(8))
  .bpq(8)
  .room(0.5)
  .gain(0.35)

$: s("<bd(5,8)*2 bd> , [~ <sn:2 sn:1>] , <[hh*4 oh <hh*3 hh*6>] hh*16>")
  .jux(x => x.rev())
  .compressor("0.1:5:0.1:0.05:0.1")
  .room(0.3)
  .gain(0.85)

$: s("kirei(3,8) neural(5,8) [~ kowai] pattern*2")
  .striate(8)
  .speed(rand.range(0.9, 1.4).fast(4))
  .delay(0.75)
  .pan(perlin.slow(2))
  .gain(0.75)

$: note("<c6 eb6> <g6 c7> <bb6 g6> c7")
  .euclid(7, 16)
  .sound("sine")
  .fm(sine.range(1, 15).fast(8))
  .delay(0.6)
  .pan(rand)
  .gain(0.4)

$: s("mt(5,8) ~ rim(3,8) cb*2")
  .ring(1)
  .ringf(saw.range(50, 1000).fast(4))
  .delay(0.4)
  .room(0.5)
  .gain(0.6)