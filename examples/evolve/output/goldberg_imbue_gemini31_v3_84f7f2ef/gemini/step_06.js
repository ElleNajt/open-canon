setcps(92/60/4)
samples('shabda/speech/fr-FR/m:spectre,machine,reve,abime')

$: note("c1 <eb1 g1> <c1 d1> <b0 f1>")
  .sound("supersaw")
  .lpf(sine.range(150, 400).slow(8))
  .shape(0.8)
  .room(0.5)
  .gain(0.45)

$: note("~ [c4 eb4 g4 b4]")
  .sound("square")
  .jux(x => x.add(7).rev())
  .lpf(saw.range(400, 2000).slow(4))
  .room(0.6)
  .gain(0.35)

$: s("[bd(5,8), ~ <cp*2 [hh*4 cb]>, sn:2(3,8)]")
  .drive(0.6)
  .crush(3)
  .room(0.4)
  .gain(0.45)

$: s("spectre ~ machine <reve abime>")
  .slow(2)
  .chop(8)
  .delay(0.6)
  .room(0.5)
  .gain(0.6)

$: note("<c4 d4> <ab4 g4> <eb4 f4> <d4 b3>")
  .sound("sine")
  .jux(x => x.rev())
  .fm(saw.range(0.5, 3).slow(4))
  .fmh(2)
  .delay(0.7)
  .gain(0.35)

$: s("mt(3,8) <ht(2,8) lt*4?>")
  .speed(perlin.range(0.4, 1.5).slow(4))
  .pan(rand)
  .room(0.6)
  .gain(0.25)