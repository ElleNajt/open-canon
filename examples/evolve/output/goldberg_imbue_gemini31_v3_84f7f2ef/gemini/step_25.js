setcps(172/60/4)
samples('shabda/speech:neural,pattern,shift')
samples('shabda/speech/fr-FR/f:attention,danger')

$: note("c1(5,8) eb1(3,8) fs1*2 <g0 c2(3,8)>")
  .sound("supersaw")
  .lpf(saw.range(100, 1500).fast(4))
  .lpq(5)
  .shape(0.8)
  .crush(5)
  .gain(0.65)

$: note("c4(3,8) [eb4 g4] <c5 g4> <eb5 c5>")
  .sound("pulse")
  .jux(x => x.hurry(2).rev())
  .bpf(sine.range(500, 4000).slow(4))
  .bpq(8)
  .room(0.7)
  .gain(0.45)

$: s("bd(5,8) , [~ <sn:1 sn:2>] , <[hh*4 oh hh*3] hh*16>")
  .compressor("0.1:4:0.1:0.1:0.1")
  .distort(0.3)
  .djf(cosine.range(0.2, 0.8).slow(8))
  .room(0.2)
  .gain(0.8)

$: s("<neural [~ attention]> <danger pattern*2> <shift ~> ~")
  .chop(16)
  .speed(rand.range(0.5, 1.5).fast(8))
  .delay(0.6)
  .room(0.5)
  .gain(0.8)

$: note("c6 eb6 g6 c7")
  .euclid(5, 8)
  .sound("sine")
  .fm(sine.range(1, 10).fast(4))
  .fmh(rand.range(1, 5).fast(8))
  .delay(0.5)
  .gain(0.35)

$: s("[~ rim*3] <cb(5,8) mt(3,8)>")
