setcps(132/60/4)
samples('shabda/speech:system,reboot,memory,fade')

$: note("c1(3,8) <eb1 f1>(5,8) c1*2")
  .sound("pulse")
  .shape(0.8)
  .lpf(sine.range(200, 1800).slow(8))
  .lpq(5)
  .gain(0.6)

$: note("c4(7,16) g4(5,8) [eb5 c6]")
  .sound("triangle")
  .jux(x => x.transpose(7).rev())
  .crush(4)
  .delay(0.6)
  .gain(0.35)

$: s("bd:2*4 [~ cp] hh*8")
  .room(0.2)
  .shape(0.7)
  .gain(0.65)

$: s("system [~ reboot(3,8)] memory*2 <fade ~>")
  .chop(4)
  .speed(perlin.range(0.5, 1.5).slow(4))
  .room(0.6)
  .gain(0.6)

$: note("<c3 eb3 g3 f3>*2")
  .sound("sine")
  .fmi(saw.range(0.5, 3).slow(8))
  .tremolo(saw.range(0.2, 0.9).slow(4))
  .lpf(1500)
  .gain(0.4)

$: s("~ <mt(5,8) rim(7,16)> cb*2")
  .striate(4)
  .speed(rand.range(0.8, 2.5))
  .pan(sine.range(0.2, 0.8).slow(6))
  .delay(0.7)
  .gain(0.4)