setcps(140/60/4)
samples('shabda/speech:calculating,predicting,generating,output')
samples('shabda/speech/ja-JP/f:watashi,mirai')

$: note("c1(5,8) <f1 eb1> c1(3,8) <gb1 d1>")
  .sound("supersaw")
  .drive(0.5)
  .lpf(perlin.range(200, 2500).slow(8))
  .lpq(6)
  .gain(0.6)

$: note("c4(11,16) , eb4(9,16) , g4(5,8)")
  .sound("pulse")
  .iter(4)
  .juxBy(0.6, x => x.rev().transpose(7))
  .crush(5)
  .delay(0.7)
  .gain(0.35)

$: s("[bd:4*2 ~ bd:4 ~] , [~ cp:2] , <hh*8 hh(11,16)>")
  .shape(0.85)
  .compressor("0.2:4:0.1:0.01:0.1")
  .room(0.3)
  .gain(0.7)

$: s("watashi calculating mirai [generating output]")
  .striate(4)
  .speed(perlin.range(0.8, 1.4).slow(4))
  .pan(saw.range(0.2, 0.8).slow(2))
  .room(0.5)
  .gain(0.7)

$: note("<c3 eb3 f3 g3>(3,8)")
  .sound("sine")
  .fmi(rand.range(1, 4))
  .sometimes(x => x.octave(1))
  .delay(0.5)
  .gain(0.5)

$: s("~ <rim(5,8) lt(7,16)>")
  .crush(3)
  .speed(rand.range(1.5, 3))
  .pan(sine.range(0.1, 0.9).slow(4))
  .room(0.3)
  .gain(0.45)