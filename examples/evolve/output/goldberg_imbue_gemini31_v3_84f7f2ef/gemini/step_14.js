setcps(126/60/4)
samples('shabda/speech/fr-FR/m:spectre,machine,reve,abime')

$: note("c1(5,8) <g1 eb1> [~ <f1 d1>] c2")
  .sound("saw")
  .shape(0.85)
  .lpf(saw.range(150, 2500).slow(8))
  .lpq(6)
  .gain(0.55)

$: note("c5(5,8) <eb5 g4>(7,16) <d5 c6>*2")
  .sound("sine")
  .jux(x => x.add(7).rev())
  .fmi(sine.range(1, 4).slow(8))
  .delay(0.7)
  .gain(0.28)

$: s("bd(5,8) [~ <cp sn>] <bd(3,8) ~> <hh*6 hh(11,16)>")
  .crush(3)
  .shape(0.6)
  .room(0.3)
  .gain(0.55)

$: s("<machine abime> spectre(5,8) reve*2 [~ machine]")
  .chop(8)
  .rev()
  .speed(perlin.range(-1.2, 1.8).slow(6))
  .delay(0.75)
  .gain(0.65)

$: note("<c3(3,8) eb3 g3 f3(5,8)>")
  .chord("minor")
  .sound("supersaw")
  .lpf(sine.range(400, 2500).slow(12))
  .room(0.8)
  .gain(0.25)

$: s("~ <mt(5,8) rim(7,16)> <cb(3,8) ~>")
  .striate(8)
  .speed(perlin.range(0.5, 3).slow(4))
  .pan(rand)
  .delay(0.5)
  .gain(0.4)