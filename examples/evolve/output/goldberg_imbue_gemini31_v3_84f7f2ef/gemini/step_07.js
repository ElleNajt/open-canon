setcps(92/60/4)
samples('shabda/speech/fr-FR/m:spectre,machine,reve,abime')

$: note("c1*4 <eb1*4 g1*2> <c1 [~ d1]> <b0*3 f1>")
  .sound("supersaw")
  .lpf(saw.range(100, 800).slow(2))
  .lpq(4)
  .shape(0.7)
  .gain(0.4)

$: note("c4 [eb4 g4] <b4 d5> ~")
  .sound("triangle")
  .jux(x => x.add(3).rev())
  .lpf(sine.range(300, 1500).slow(4))
  .delay(0.5)
  .gain(0.35)

$: s("[bd(3,8), ~ cp, <hh*4 [~ hh*3] cb(3,8)>]")
  .crush(4)
  .drive(0.4)
  .room(0.3)
  .speed(1.1)
  .gain(0.45)

$: s("spectre ~ <machine reve> abime")
  .striate(16)
  .speed(rand.range(0.8, 1.2))
  .room(0.5)
  .pan(sine.slow(2))
  .gain(0.55)

$: note("<c5 d5> [ab5, g4] <eb5 f5> <d5 b5>")
  .sound("sine")
  .jux(x => x.rev().add(5))
  .fm(saw.range(1, 4).slow(3))
  .delay(0.6)
  .gain(0.25)

$: s("rim(5,8) <cb(3,8) rd*4>")
  .speed(perlin.range(0.8, 2).fast(2))
  .pan(rand)
  .shape(0.5)
  .delay(0.4)
  .gain(0.25)