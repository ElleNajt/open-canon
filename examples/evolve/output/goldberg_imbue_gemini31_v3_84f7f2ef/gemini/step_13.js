setcps(115/60/4)
samples('shabda/speech/fr-FR/m:spectre,machine,reve,abime')

$: note("c1(5,8) eb1(3,8) [~ f1] <d2 c2>")
  .sound("saw")
  .lpf(saw.range(100, 2000).slow(4))
  .lpq(8)
  .shape(0.8)
  .gain(0.45)

$: note("c4(3,8) <eb4 g4>(5,8) d5*2")
  .sound("square")
  .jux(x => x.add(12).rev())
  .bpf(sine.range(500, 3000).slow(8))
  .delay(0.6)
  .gain(0.25)

$: s("bd([5 7],8) [~ cp] <sn(5,16) sn(3,8)> <hh*4 hh(7,16)>")
  .crush(2)
  .djf(0.8)
  .room(0.5)
  .gain(0.5)

$: s("<machine spectre> reve(5,8) [~ abime] spectre*2")
  .chop(16)
  .speed(perlin.range(0.8, 1.5).slow(8))
  .delay(0.8)
  .room(0.6)
  .gain(0.7)

$: note("<c3 eb3 g3 f3>")
  .chord("minor")
  .sound("supersaw")
  .drive(0.2)
  .lpf(sine.range(800, 3000).slow(12))
  .room(0.8)
  .gain(0.3)

$: s("~ rim(3,8) <cb*2 mt(5,16)>")
  .speed(sine.range(1, 4).slow(2))
  .crush(4)
  .pan(perlin)
  .delay(0.5)
  .gain(0.35)