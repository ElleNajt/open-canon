setcps(72/60/4)
samples('shabda/speech/fr-FR/m:souvenir,silence')

$: note("g2 fs2 e2 d2 b1 c2 d2 g1")
  .slow(2)
  .sound("sine")
  .fm(sine.range(1, 4).slow(4))
  .fmh(2)
  .fmenv(0.2)
  .room(0.3)
  .gain(0.7)

$: note("g4 fs4 e4 d4 b3 c4 d4 g3")
  .slow(2)
  .off(0.25, x => x.add(7))
  .sound("supersaw")
  .lpf(sine.range(600, 2400).slow(8))
  .decay(0.8)
  .delay(0.4)
  .room(0.5)
  .gain(0.25)

$: s("[bd(5,8), ~ hh*4?, <~ rim>]")
  .shape(0.2)
  .hpf(150)
  .room(0.2)
  .gain(0.6)

$: s("souvenir silence")
  .slow(4)
  .chop(8)
  .speed(rand.range(0.85, 1.15))
  .room(0.8)
  .gain(0.65)

$: note("g6*3 fs6 e6 d6*2 b5 c6*2 d6 g5")
  .slow(2)
  .sound("piano")
  .jux(rev)
  .delay(0.6)
  .dt(0.375)
  .gain(0.35)