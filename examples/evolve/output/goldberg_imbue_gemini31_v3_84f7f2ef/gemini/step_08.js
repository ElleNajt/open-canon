setcps(92/60/4)
samples('shabda/speech/fr-FR/m:spectre,machine,reve,abime')

$: note("c1(5,8) <eb1*3 [~ g1]> <c1 [~ d1]> <b0 f1>")
  .sound("supersaw")
  .lpf(sine.range(150, 1200).slow(4))
  .lpq(6)
  .shape(0.85)
  .gain(0.35)

$: note("c4 [eb4, g4] <b4, d5> ~")
  .sound("triangle")
  .jux(x => x.add(7).rev())
  .bpf(saw.range(400, 2400).slow(8))
  .delay(0.7)
  .gain(0.3)

$: s("[bd(5,8), <~ cp> <~ sn>, <hh*6 [~ hh*3] cb(3,8)>]")
  .crush(3)
  .room(0.4)
  .speed(0.9)
  .gain(0.45)

$: s("spectre*2 <machine ~> reve <abime spectre>")
  .chop(8)
  .speed(perlin.range(0.4, 1.2).slow(4))
  .room(0.6)
  .pan(sine.slow(2))
  .gain(0.55)

$: note("<c5 d5> [ab5, g4] <eb5 f5> <d5 b5>")
  .sound("sine")
  .jux(x => x.rev().add(5))
  .fm(perlin.range(0.5, 5).slow(2))
  .room(0.5)
  .gain(0.2)

$: s("rim(5,8) <cb(3,8) rd*5>")
  .speed(perlin.range(0.5, 3).fast(2))
  .pan(rand)
  .degradeBy(0.2)
  .delay(0.5)
  .gain(0.25)