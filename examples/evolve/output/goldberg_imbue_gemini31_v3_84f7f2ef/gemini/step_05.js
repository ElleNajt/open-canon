setcps(85/60/4)
samples('shabda/speech/fr-FR/m:spectre,machine,reve')

$: note("c2 <eb2 g1> <c2 d2> <b1 eb2>")
  .sound("supersaw")
  .lpf(sine.range(150, 500).slow(8))
  .lpq(5)
  .room(0.5)
  .gain(0.45)

$: note("[c4 eb4 g4 b4]/2")
  .sound("square")
  .off(0.125, x => x.add(7))
  .bandf(saw.range(400, 2500).slow(4))
  .room(0.6)
  .gain(0.3)

$: s("[bd(3,8), ~ <cr*6 [hh*3 cb]>, sn(2,8,2)]")
  .shape(0.75)
  .crush(4)
  .room(0.4)
  .gain(0.5)

$: s("spectre machine ~ reve")
  .slow(2)
  .striate(6)
  .djf(0.25)
  .room(0.8)
  .gain(0.65)

$: note("<c4 d4> <ab4 g4> <eb4 f4> <d4 b3>")
  .sound("sine")
  .fm(saw.range(1, 4).slow(4))
  .fmh(1.5)
  .delay(0.6)
  .gain(0.35)

