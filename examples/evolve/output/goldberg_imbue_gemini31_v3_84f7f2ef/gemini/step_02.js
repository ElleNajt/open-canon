setcps(72/60/4)
samples('shabda/speech/fr-FR/m:souvenir,silence')

$: note("g2 fs2 <e2 c2> d2 b1 c2 d2 g1")
  .slow(2)
  .sound("triangle")
  .lpf(sine.range(200, 800).slow(4))
  .room(0.4)
  .gain(0.6)

$: note("g4 fs4 e4 d4 b3 c4 d4 g3")
  .slow(2)
  .off(0.25, x => x.add(7))
  .sound("sine")
  .crush(5)
  .delay(0.4)
  .room(0.6)
  .gain(0.35)

$: s("[bd(5,8,2), ~ <hh*4 hh*6>?, <~ [cp rim]>]")
  .shape(0.3)
  .djf(0.6)
  .room(0.2)
  .gain(0.6)

$: s("souvenir silence")
  .slow(4)
  .chop(16)
  .speed(sine.range(0.8, 1.1).slow(2))
  .jux(rev)
  .room(0.8)
  .gain(0.65)

$: note("g5 ~ fs5 ~ <e5 d5> ~ c5*2 g4")
  .slow(2)
  .sound("piano")
  .juxBy(0.5, rev)
  .delay(0.6)
  .dt(0.375)
  .gain(0.45)

$: s("cr*4?")
  .slow(2)
  .speed(rand.range(0.2, 0.6))
  .pan(sine.slow(4))
  .delay(0.8)
  .room(0.6)
  .gain(0.15)