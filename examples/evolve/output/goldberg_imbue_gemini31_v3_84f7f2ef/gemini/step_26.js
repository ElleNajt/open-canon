setcps(175/60/4)
samples('shabda/speech:neural,pattern,shift,dream')
samples('shabda/speech/ja-JP/f:kirei,kowai')

$: note("c1(5,8) <eb1 ~> [<g1*2 bb0> g0] <c2(3,8) eb0>")
  .sound("supersaw")
  .lpf(saw.range(100, 2500).fast(4))
  .lpq(8)
  .shape(0.9)
  .crush(4)
  .gain(0.65)

$: note("c4(3,8) <eb4 g4(5,8)> c5 <eb5*2 g5>")
  .sound("pulse")
  .jux(x => x.rev())
  .bpf(sine.range(400, 4000).slow(8))
  .bpq(9)
  .gain(0.35)

$: s("<bd(5,8)*2 bd(3,8)> , [~ <sn:2 sn:1*2>] , <[hh*4 oh hh*3] hh*16>")
  .every(3, x => x.ply(2))
  .degradeBy(0.05)
  .compressor("0.2:4:0.1:0.1:0.1")
  .room(0.2)
  .gain(0.85)

$: s("<neural [~ kowai]> <kirei pattern*2> <shift ~> <dream? kowai>")
  .chop(8)
  .speed(rand.range(0.8, 1.2).fast(4))
  .delay(0.6)
  .room(0.5)
  .gain(0.85)

$: note("<c6 eb6> <g6 c7> <bb6 g6> c7")
  .euclid(5, 8)
  .sound("sine")
  .fm(sine.range(1, 10).fast(4))
  .delay(0.5)
  .gain(0.4)

$: s("[~ rim*3] <cb(5,8) mt(3,8)>")
  .striate(4)
  .speed(sine.range(0.5, 2).fast(4))
  .room(0.4)
  .pan(perlin.fast(2))
  .gain(0.6)