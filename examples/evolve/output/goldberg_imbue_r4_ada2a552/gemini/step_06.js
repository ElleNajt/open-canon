setcps(84/60/4)

$: note("[g3, gb3] e3 ~ d3 b2 [c3 d3 g2]")
  .slow(2)
  .sound("pulse")
  .lpf(sine.range(100, 1500).slow(8))
  .lpq(5)
  .delay(0.3).delaytime(0.75).delayfeedback(0.4)
  .gain(0.25)

$: note("<b4 a4 g4> [fs4 d5 cs5] <e5 g5>")
  .slow(2)
  .sound("square")
  .lpf(2500).lpq(3)
  .attack(0.02).release(0.4)
  .room(0.5)
  .gain(0.2)

$: s("[cp, ~] cp [~ cp] cp?").ply(2)
  .speed(perlin.range(0.8, 1.5).slow(12))
  .hpf(800)
  .distort(0.3)
  .crush(6)
  .pan(rand.slow(4))
  .gain(0.25)

$: note("[g4, fs4] e4 [d4, b3] [c4 d4] g4")
  .slow(4)
  .sound("supersaw")
  .release(4)
  .vowel("a e i o u".slow(16))
  .off(0.015, x => x.detune(10))
  .phaser(0.1)
  .gain(0.15)

