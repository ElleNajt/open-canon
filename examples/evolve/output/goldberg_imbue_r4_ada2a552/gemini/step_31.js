setcps(120/60/4)
samples('shabda/speech:evolve,personality,imbue,random,glitch,change,become')

$: note("[g3,d4,eb4] [b3,g4,f4,d4]").palindrome().scale("g:minor").slow(2)
  .sound("sawtooth").release(0.1)
  .bpf(perlin.range(500, 2500).slow(8)).bpq(8)
  .vowel("a e o".slow(1))
  .delay(0.3).dt(1/6).dfb(0.6)
  .room(0.4)
  .pan(saw.slow(4).range(0.1, 0.9))
  .gain(0.08)

$: note("<g5 eb5 c5> <d5 b4 g4?>").scale("g:minor").slow(8).rev()
  .sound("triangle")
  .lpf(500).lpenv(1800).lpdecay(0.6)
  .fmi(saw.range(1, 8).slow(8)).fmh(1.2)
  .phaser(sine.range(0.1, 8).slow(12))
  .room(0.5)
  .gain(0.08)

$: s("[imbue, evolve?] <personality change> [glitch random] become").slow(4)
  .striate(perlin.slow(8).range(4, 20))
  .chop(perlin.range(16, 64).slow(10))
  .crush(9)
  .shape(perlin.range(0.3, 0.9).slow(4))
  .delay(0.4).dt(1/3).dfb(0.55)
  .gain(0.10)

$: note("<g3m7 c4m7> f3m9 eb3maj7").chord().slow(16).release(6)
  .sound("supersaw")
  .lpf(cosine.range(500, 2200).slow(12))
  .crush(perlin.range(6, 12).slow(11))
  .leslie(sine.range(0.2, 0.7).slow(5))
  .delay(0.5).dt(3/8).dfb(0.6)
  .room(0.5)
  .gain(0.07)

$: s("[bd*2] [~ sn] [bd sn] [sn,bd?]").slow(2).degradeBy(0.05)
