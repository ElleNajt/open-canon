setcps(120/60/4)
samples('shabda/speech:evolve,personality,imbue,random,glitch,change,become')

$: note("[g3,b3,d4] [d4 f4? <~ g4> g4]").degradeBy(0.1).scale("g:minor").slow(4)
  .sound("sawtooth").release(0.1)
  .lpf(saw.range(600, 3000).slow(8)).lpq(4)
  .shape(perlin.range(0.2, 0.8).slow(8))
  .delay(0.4).dt(1/3).dfb(0.55)
  .room(0.2)
  .pan(sine.slow(5).range(0.2, 0.8))
  .gain(0.11)

$: note("<b4 d5 g5?> <c5 f5>").scale("g:minor").slow(2).palindrome()
