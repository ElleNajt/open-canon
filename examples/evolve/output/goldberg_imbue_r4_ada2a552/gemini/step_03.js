setcps(90/60/4)

$: note("[g3 gb3] e3 d3 [b2 c3 d3] g2")
  .slow(2)
  .sound("pulse")
  .lpf(sine.range(100, 1000).slow(8)).lpq(6)
  .distort(0.1)
  .gain(0.25)

$: note("<b4 a4> g4 fs4 <d5 e5 fs5> g5")
  .slow(2)
  .sound("triangle")
  .phaser(sine.range(0.1, 4).slow(9))
  .room(0.4).size(0.8)
  .gain(0.3)

$: s("<cp ~ [cp cp] cp? >*2")
  .striate(cosine.range(16, 64).slow(13))
  .crush(10)
  .pan(saw.range(0.1, 0.9).slow(9))
  .gain(0.15)

$: note("g4 gb4 e4 d4 b3 c4 d4 g3")
  .ply(2).slow(4)
  .sound("supersaw")
  .release(2)
  .lpf(sine.range(600, 2500).slow(16))
  .pan(perlin.range(0.3, 0.7).slow(10))
  .gain(0.12)

$: s("<bd [bd sn]> ~ bd sn?")
  .distort(0.2)
  .crush(8)
  .lpf(4000)
  .gain(0.6)

$: s("[hh hh*2] [~ hh]?")
  .slow(2)
  .striate(tri.range(10, 80).slow(11))
  .crush(9)
  .hpf(6000)
  .pan(perlin.range(0,1).slow(15))
  .gain(0.12)