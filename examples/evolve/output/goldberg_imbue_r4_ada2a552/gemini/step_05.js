setcps(90/60/4)

$: note("[g3, gb3 e3] ~ d3 b2 [c3 d3] g2")
  .slow(2)
  .sound("triangle")
  .lpf(sine.range(100, 1200).slow(8))
  .delay(0.4).delaytime(1.5)
  .gain(0.2)

$: note("<b4 a4 g4> [fs4 d5] <cs5 e5> g5")
  .slow(2)
  .sound("sine")
  .fm(perlin.range(0.2, 3).slow(16))
  .phaser(sine.range(0.1, 4).slow(9))
  .room(0.4)
  .gain(0.2)

$: s("<cp ~ [cp cp] cp? >*2")
  .striate(8)
  .speed(perlin.range(0.5, 2).slow(8))
  .crush(9)
  .gain(0.25)

$: note("[g4, gb4] e4 d4 [b3, c4] d4 g3")
  .slow(4)
  .sound("supersaw")
  .release(3)
  .lpf(sine.range(400, 2500).slow(12))
  .off(0.015, x => x.detune(12))
  .gain(0.15)

$: s("[bd sn] [bd bd] [~ sn] sn?")
  .degradeBy(0.1)
  .distort(0.4)
  .crush(7)
  .shape(0.3)
  .gain(0.4)

$: s("hh").euclid(7, 12).fast(4)
  .hpf(9000)
  .delay(0.5)
  .pan(sine.slow(10).range(0.1,0.9))
  .gain(0.1)