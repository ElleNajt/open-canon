setcps(120/60/4)
samples('shabda/speech:evolve,personality,imbue,random')

$: note("[g3,gb3] [d3,eb3] [b2,c3] [d3,eb3]").slow(4)
  .sound("sawtooth").release(0.15)
  .shape(0.4)
  .coarse(8)
  .crush(12)
  .lpf(sine.range(200, 1200).slow(8)).lpq(4)
  .delay(0.3).dt(1/6).dfb(0.5)
  .gain(0.18)

$: note("<b4 d5 g5>").scale("g:minor").slow(4).palindrome()
  .sound("triangle").release(0.8)
  .fm(perlin.slow(12).range(0.5, 3))
  .vowel("a e i o").slow(8)
  .room(0.3)
  .delay(0.4).dt(1/4).dfb(0.4)
  .pan(perlin.slow(6).range(0,1))
  .gain(0.19)

$: s("<evolve personality> [imbue random?]").slow(8).sometimes(rev)
  .chop(perlin.range(8, 32).slow(4))
  .speed(rand.range(0.8, 1.2))
  .bpf(perlin.range(800, 3000).slow(16)).bpq(3)
  .delay(0.5).dt(1/3).dfb(0.6)
  .room(0.4)
  .gain(0.18)

$: note("g3maj7 eb3maj7 c3m7 bb2maj7").chord().slow(16)
  .sound("piano").release(6)
  .lpf(perlin.range(300, 2000).slow(12)).lpq(5)
  .distort(0.2)
  .trem(cosine.range(0, 0.5).slow(8))
  .room(0.6)
  .delay(0.4).dt(3/4).dfb(0.4)
  .gain(0.14)

$: s("[bd,sn] [bd,sn]? [bd,bd] [sn,bd/2]").swing(0.08)
  
  .drive(0.8)
  .crush(10)
  .lpf(6000)
  .hpf(40)
  .gain(0.25)

