setcps(140/60/4)
samples('shabda/speech:future,system,corrupt,data,binary,stream,protocol')

$: note("<d4 f4 e4 g4> <a#4 c5 ~ d4>").scale("d:phrygian").slow(4)
  .sound("supersaw").release(0.2)
  .fm(perlin.range(0.1, 1).slow(6))
  .lpf(perlin.range(800, 3000).slow(8)).lpq(5)
  .delay(0.4).dt("1/3").dfb(0.6)
  .room(0.4)
  .gain(0.09)

$: note("<g5 d5 ~ g5> <gs4 d5 c5>").iter(1).scale("d:phrygian").slow(2)
  .sound("pulse").release(0.1)
  .penv(10).pdecay(0.1)
  .lpf(800).lpenv(2000).lpdecay(0.15).lpq(7)
  .phaser(sine.range(0.1, 5).slow(8))
  .pan(saw.slow(7))
  .gain(0.08)

$: s("<protocol system> binary corrupt <future [data,stream]>").every(4, palindrome).slow(4)
  .chop(perlin.range(8, 32).slow(9))
  .crush(perlin.range(4, 9).slow(10))
  .speed(perlin.range(0.7, 1.3).slow(6))
  .bandf(perlin.range(400, 4000).slow(7)).bandq(8)
  .delay(0.7).dt("3/16").dfb(0.8)
  .gain(0.11)

$: note("<d3maj7 g3m7> <f3maj7 c4m7>").chord().slow(4).release(6)
  .sound("sawtooth")
  .shape(0.5)
  .lpf(cosine.range(400, 1800).slow(12)).lpq(6)
  .leslie(perlin.range(0.5, 5).slow(8))
  .pan(sine.slow(16))
  .gain(0.07)

$: s("bd [~ bd, sn] [bd cp] sn?").slow(2).every(8, rev)
  .coarse(5)
  .distort(0.3)
  .bandf(150).bandq(1)
  .compressor("-25:8:0:0.01:0.1")
  .room(0.1)
  .gain(0.15)

