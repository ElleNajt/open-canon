setcps(120/60/4)
samples('shabda/speech:evolve,personality,imbue,random,glitch,change,become')

$: note("[g3,b3,d4] [d4,eb4,g4,f4]").palindrome().scale("g:minor").slow(4)
  .sound("sawtooth").release(0.1)
  .lpf(perlin.range(800, 4000).slow(8)).lpq(5)
  .crush(perlin.range(4, 16).slow(10))
  .delay(0.3).dt(1/3).dfb(0.5)
  .room(0.25)
  .pan(sine.slow(5).range(0.2, 0.8))
  .gain(0.1)

$: note("<b4 d5 g5> <c5 f5 a5?>").scale("g:minor").slow(4).rev()
  .sound("triangle")
  .lpf(200).lpenv(3000).lpdecay(0.3)
  .fmi(saw.range(2, 12).slow(8)).fmh(1.5)
  .vowel("<a o i u>")
  .room(0.4)
  .pan(cosine.range(0.1, 0.9).slow(8))
  .gain(0.1)

$: s("[imbue, glitch] <evolve change> personality [random, become]").slow(8).jux(rev)
  .striate(perlin.slow(8).range(4, 16))
  .distort(perlin.slow(12).range(0.1, 0.4))
  .chop(perlin.range(4, 32).slow(16))
  .delay(0.5).dt(3/8).dfb(0.6)
  .room(0.3)
  .gain(0.13)

$: note("g3m7 f3m7 <eb3maj7 c3m7>*2").chord().slow(16).release(8)
  .sound("supersaw")
  .lpf(sine.range(500, 2000).slow(12))
  .drive(perlin.range(0.2, 0.7).slow(9))
  .tremolo(sine.range(0.1, 0.8).slow(6))
  .delay(0.6).dt(1/4).dfb(0.4)
  .room(0.6)
  .gain(0.09)

$: s("bd [~ sn?] bd sn?").slow(2)
  .lpf(100).lpenv(2500).lpdecay(0.05).lpq(2)
  .distort(perlin.range(0.2, 0.6).slow(6))
  .crush(perlin.range(6, 12).slow(7))
  .delay(0.2).dt(3/16).dfb(0.3)
  .room(0.15)
  .gain(0.18)

$: s("[hh*3,oh*1]").fast(4)
  .lpf(perlin.range(6000, 11000).slow(6))
  .sometimesBy(0.4, (s) => s.striate(16))
  .pan(rand)
  .delay(0.4).dt(1/6).dfb(0.45)
  .room(0.4)
  .gain(0.07)