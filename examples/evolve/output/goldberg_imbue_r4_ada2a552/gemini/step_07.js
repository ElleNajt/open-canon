setcps(90/60/4)

$: note("[g3, gb3] e3 ~ d3 b2 [c3 d3 g2]")
  .slow(2)
  .sound("sawtooth")
  .lpf(sine.range(100, 1500).slow(6))
  .lpq(5)
  .delay(0.3).delaytime(1/3).delayfeedback(0.5)
  .gain(0.25)

$: note("<b4 a4 g4> [fs4 d5 cs5] <e5 g5>")
  .slow(2)
  .sound("triangle")
  .lpf(200).lpq(8)
  .lpenv(4000)
  .attack(0.01).release(0.4)
  .room(0.5)
  .gain(0.2)

$: s("<mt [mt, ~]> <~ [~ mt]>?")
  .speed(perlin.range(0.8, 1.5).slow(12))
  .bpf(perlin.range(500, 2000).slow(8)).bpq(7)
  .room(0.4)
  .pan(rand.slow(4))
  .gain(0.25)

$: note("[a4, gs4] fs4 [e4, cs4] [d4 e4] a4")
